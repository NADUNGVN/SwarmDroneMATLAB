    'exp23aq_routed_state_machine_confirmation',R.parentRoutedRun, ...
    'routed_state_verdict.json')));
assert(strcmp(parent.status,R.parentRoutedStatus)&& ...
    parent.gatesPassed==R.parentRoutedGatesPassed&& ...
    parent.gatesTotal==R.parentRoutedGatesTotal&& ...
    parent.managementRelayingValidated&& ...
    ~parent.closedLoopManagementRelayingValidated);
