    R.expectedRuns==120&&numel(unique(R.seeds))==20&& ...
    R.seeds(1)==16096401&&R.seeds(end)==16096420&& ...
    ~ismember(R.smokeSeed,R.seeds)&&R.transactionFrames==11&& ...
    R.repetitionsPerHop==4&&R.prepareAttempts==3&& ...
    R.claimAttempts==4&&R.evidencePrefixAttempts==2&& ...
    R.commitAttempts==2&&R.requiredValidationContracts==27);
