function A=analyzeExp19APosthoc(runDir)
%ANALYZEEXP19APOSTHOC Descriptive mechanism audit; no new promotion claim.

R=exp19aRegistry();
T=readtable(fullfile(runDir,'tidy.csv'),'TextType','string');
G=readtable(fullfile(runDir,'gates.csv'),'TextType','string');
V=jsondecode(fileread(fullfile(runDir,'development_verdict.json')));
if height(T)~=R.expectedRuns || ~all(G.passed==1) || ...
        ~strcmp(V.status,'NO_SERVICE_SCHEDULING_HEADROOM')
    error('analyzeExp19APosthoc: canonical negative EXP19A run required.');
end

pairs={ ...
    'collision-free-tdma-piggyback',R.baselineArm,'access-scheduling'; ...
    'oracle-deficit-maxweight-piggyback', ...
        'collision-free-tdma-piggyback','deficit-priority'; ...
    'oracle-urgency-maxweight-piggyback', ...
        'collision-free-tdma-piggyback','urgency-priority'; ...
    'oracle-urgency-maxweight-piggyback', ...
        'oracle-deficit-maxweight-piggyback','urgency-vs-deficit'; ...
    'periodic-tdma-p12p5','oracle-deficit-maxweight-piggyback', ...
        'periodic-frontier-vs-deficit'; ...
    'periodic-tdma-p12p5','oracle-urgency-maxweight-piggyback', ...
        'periodic-frontier-vs-urgency'};
metrics={ ...
    'RMSE','lower';'OFFERED_UTIL','lower';'MEAN_TRUE_AOI','lower'; ...
    'MEAN_NODE_GOODPUT_HZ','higher';'MIN_NODE_GOODPUT_HZ','higher'; ...
    'MAX_STARVATION_SEC','lower'};
rows=repmat(emptyContrast(),0,1);
failRows=repmat(emptyFailure(),0,1);
for c=R.cells
    for p=1:size(pairs,1)
        Arow=armRows(T,R,c.id,pairs{p,1});
        Brow=armRows(T,R,c.id,pairs{p,2});
        validatePair(Arow,Brow,R,c.id,pairs{p,1},pairs{p,2});
        for m=1:size(metrics,1)
            metric=metrics{m,1}; direction=metrics{m,2};
            a=Arow.(metric); b=Brow.(metric);
            diverged=logical(Arow.DIVERGED|Brow.DIVERGED);
            a(diverged)=NaN; b(diverged)=NaN;
            q=pairedCI(a,b,numel(R.seeds));
            if strcmp(direction,'lower')
                favorable=q.hi<0;
            else
                favorable=q.lo>0;
            end
            rows(end+1,1)=struct('scenario',c.id,'component',pairs{p,3}, ...
                'armA',pairs{p,1},'armB',pairs{p,2},'metric',metric, ...
                'favorableDirection',direction,'meanA',mean(a,'omitnan'), ...
                'meanB',mean(b,'omitnan'),'differenceAminusB',q.meanD, ...
                'ci95Lo',q.lo,'ci95Hi',q.hi,'nPairs',q.nPairs, ...
                'complete',double(q.complete), ...
                'favorableInterval',double(favorable)); %#ok<AGROW>
        end
        af=logical(Arow.SAFEFAIL); bf=logical(Brow.SAFEFAIL);
        failRows(end+1,1)=struct('scenario',c.id, ...
            'component',pairs{p,3},'armA',pairs{p,1},'armB',pairs{p,2}, ...
            'failuresA',sum(af),'failuresB',sum(bf), ...
            'aOnlyFailures',sum(af & ~bf),'bOnlyFailures',sum(~af & bf), ...
            'bothFail',sum(af & bf),'neitherFail',sum(~af & ~bf)); %#ok<AGROW>
    end
end
contrasts=struct2table(rows);
failures=struct2table(failRows);
S=readtable(fullfile(runDir,'development_summary.csv'),'TextType','string');
pareto=paretoAudit(S,R);

boundaryAccess=contrastRow(contrasts,R.boundaryCell, ...
    'access-scheduling','RMSE').favorableInterval==1 && ...
    contrastRow(contrasts,R.boundaryCell, ...
    'access-scheduling','OFFERED_UTIL').favorableInterval==1;
n10Failure=failures(failures.scenario==string(R.failureCell) & ...
    failures.component=="access-scheduling",:);
accessFailureRepair=n10Failure.failuresA<n10Failure.failuresB;
periodicBoundary=S(S.scenario==string(R.boundaryCell) & ...
    S.arm=="periodic-tdma-p12p5",:);
urgencyBoundary=S(S.scenario==string(R.boundaryCell) & ...
    S.arm=="oracle-urgency-maxweight-piggyback",:);
urgencyReproduced=height(periodicBoundary)==1 && ...
    height(urgencyBoundary)==1 && ...
    periodicBoundary.meanRMSE<=urgencyBoundary.meanRMSE+1e-12 && ...
    periodicBoundary.meanOfferedUtil<= ...
    urgencyBoundary.meanOfferedUtil+1e-12 && ...
    periodicBoundary.safeFailures<=urgencyBoundary.safeFailures && ...
    V.exp19bPermitted==false;
verdict=struct( ...
    'status','ACCESS_HEADROOM_BUT_NO_REGISTERED_SEMANTIC_PROMOTION', ...
    'analysisType','post-hoc descriptive mechanism audit', ...
    'registeredVerdictChanged',false, ...
    'hypothesisTestsRun',false, ...
    'boundaryAccessParetoInterval',logical(boundaryAccess), ...
    'n10ModerateAccessFailureRepair',logical(accessFailureRepair), ...
    'periodicFrontierExplainsMajorGain',logical(urgencyReproduced), ...
    'semanticSchedulerPrimaryNoveltyPermitted',false, ...
    'exp19bPermitted',false, ...
    'manuscriptClaimPermitted',false, ...
    'hardwarePolicyValidationPermitted',false, ...
    'retainedMechanism','collision-free scheduled access', ...
    'retiredMechanism','oracle semantic priority as primary contribution', ...
    'nextResearchQuestion',[ ...
    'Can a causal implementable contention-to-scheduled access mode ' ...
    'achieve the periodic TDMA frontier without receiver-truth oracle state?']);
writetable(contrasts,fullfile(runDir,'posthoc_paired_mechanism_contrasts.csv'));
writetable(failures,fullfile(runDir,'posthoc_paired_failure_counts.csv'));
writetable(pareto,fullfile(runDir,'posthoc_mean_pareto_audit.csv'));
writeJson(fullfile(runDir,'posthoc_mechanism_verdict.json'),verdict);
A=struct('contrasts',contrasts,'failures',failures, ...
    'pareto',pareto,'verdict',verdict);

end


function Q=armRows(T,R,scenario,arm)

Q=T(T.scenario==string(scenario) & T.arm==string(arm),:);
[~,order]=sort(Q.seed); Q=Q(order,:);
if height(Q)~=numel(R.seeds) || ~isequal(Q.seed,R.seeds)
    error('analyzeExp19APosthoc: incomplete arm rows.');
end

end


function validatePair(A,B,R,scenario,armA,armB)

if ~isequal(A.seed,B.seed) || ...
        any(A.TRACE_HASH_EXACT~=B.TRACE_HASH_EXACT) || ...
        any(A.CHANNEL_STATE_HASH~=B.CHANNEL_STATE_HASH) || ...
        any(A.ESTIMATOR_HASH_EXACT~=B.ESTIMATOR_HASH_EXACT)
    error('analyzeExp19APosthoc: unpaired %s %s/%s.', ...
        scenario,armA,armB);
end
if height(A)~=numel(R.seeds)
    error('analyzeExp19APosthoc: wrong pair count.');
end

end


function row=contrastRow(C,scenario,component,metric)

row=C(C.scenario==string(scenario) & ...
    C.component==string(component) & C.metric==string(metric),:);
if height(row)~=1, error('analyzeExp19APosthoc: contrast not unique.'); end

end


function P=paretoAudit(S,R)

P=table();
for c=R.cells
    Q=S(S.scenario==string(c.id),:);
    flag=true(height(Q),1);
    dominatedBy=strings(height(Q),1);
    for i=1:height(Q)
        for j=1:height(Q)
            if i==j, continue; end
            weak=Q.meanRMSE(j)<=Q.meanRMSE(i)+1e-12 && ...
                Q.meanOfferedUtil(j)<=Q.meanOfferedUtil(i)+1e-12 && ...
                Q.safeFailures(j)<=Q.safeFailures(i);
            strict=Q.meanRMSE(j)<Q.meanRMSE(i)-1e-12 || ...
                Q.meanOfferedUtil(j)<Q.meanOfferedUtil(i)-1e-12 || ...
                Q.safeFailures(j)<Q.safeFailures(i);
            if weak && strict
                flag(i)=false;
                dominatedBy(i)=Q.arm(j);
                break;
            end
        end
    end
    block=table(Q.scenario,Q.arm,Q.meanRMSE,Q.meanOfferedUtil, ...
        Q.safeFailures,double(flag),dominatedBy, ...
        'VariableNames',{'scenario','arm','meanRMSE','meanOfferedUtil', ...
        'safeFailures','paretoMean','oneDominatingArm'});
    P=[P;block]; %#ok<AGROW>
end

end


function r=emptyContrast()

r=struct('scenario','','component','','armA','','armB','', ...
    'metric','','favorableDirection','','meanA',NaN,'meanB',NaN, ...
    'differenceAminusB',NaN,'ci95Lo',NaN,'ci95Hi',NaN, ...
    'nPairs',NaN,'complete',NaN,'favorableInterval',NaN);

end


function r=emptyFailure()

r=struct('scenario','','component','','armA','','armB','', ...
    'failuresA',NaN,'failuresB',NaN,'aOnlyFailures',NaN, ...
    'bOnlyFailures',NaN,'bothFail',NaN,'neitherFail',NaN);

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('analyzeExp19APosthoc: cannot write %s.',path); end
cleaner=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));

end
