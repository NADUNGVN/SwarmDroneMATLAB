function exp23s_dynamic_revocation_kernel()
%EXP23S_DYNAMIC_REVOCATION_KERNEL Fresh dynamic lifecycle falsification.

startup; close all;
runScriptIsolated('test_exp23s_dynamic_revocation_study_contracts');
runScriptIsolated('test_elcs_dynamic_revocation_contracts');
runScriptIsolated('test_elcs_coherence_integration_contracts');
runScriptIsolated('test_elcs_cumulative_receipt_contracts');
R=exp23sDynamicRevocationRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23s_dynamic_revocation_kernel', ...
    'Fresh fixed-supergraph self-revocation and reacquisition validation.');
writeJson(fullfile(expRun.dir,'dynamic_registry.json'),R);
writeJson(fullfile(expRun.dir,'dynamic_opened.json'),struct( ...
    'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
    'registryHash',registryHash,'registryLeaves',registryLeaves, ...
    'submissionClaimPermitted',false));
snapshotSource(expRun.dir);

rows=repmat(exp23sDynamicRevocationEmptyRow(),R.expectedRuns,1); q=0;
for seed=R.seeds'
    for N=R.nodeCounts
        for index=1:numel(R.conditions)
            q=q+1;
            rows(q)=runExp23sDynamicRevocationCell( ...
                seed,N,R.conditions(index),index,R);
        end
    end
    seedIndex=find(R.seeds==seed);
    if mod(seedIndex,10)==0
        fprintf('  seeds %3d / %3d; rows %3d / %3d\n', ...
            seedIndex,numel(R.seeds),q,R.expectedRuns);
    end
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'dynamic_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'DYNAMIC_COHERENCE_REVOCATION_KERNEL_VALID', ...
    'DYNAMIC_COHERENCE_REVOCATION_KERNEL_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'fixedSupergraphClosedLoopPermitted',pass, ...
    'onlineGraphMigrationValidated',false, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'dynamic_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','gates','verdict','R');

fprintf('\nEXP23S dynamic revocation-kernel gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-45s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23S DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23s: dynamic revocation kernel invalid.'); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.N)+'|'+string(T.condition);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(unique(T.N)',R.nodeCounts) && isequal( ...
    sort(unique(string(T.condition))), ...
    sort(reshape(string({R.conditions.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '100 fresh seeds, N5/N10 and four channel conditions exact');
paired=true;
for seed=R.seeds'
    for N=R.nodeCounts
        index=T.seed==seed & T.N==N;
        paired=paired && nnz(index)==numel(R.conditions) && ...
            isscalar(unique(T.BASE_TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.DYNAMIC_BASE_HASH_EXACT(index))) && ...
            isscalar(unique(T.WITNESS_HASH_EXACT(index))) && ...
            isscalar(unique(T.REVOKE_FRAME(index))) && ...
            isscalar(unique(T.REACQUIRE_ELIGIBLE_FRAME(index)));
    end
end
add('paired_absolute_realizations',paired, ...
    'packet draws, dynamic graph, event and eligible frame are paired');
a=runExp23sDynamicRevocationCell(R.seeds(1),R.nodeCounts(1), ...
    R.conditions(1),1,R);
b=runExp23sDynamicRevocationCell(R.seeds(1),R.nodeCounts(1), ...
    R.conditions(1),1,R);
add('deterministic_reproduction',isequaln(a,b), ...
    'repeated seed/cell is bit-identical');
add('dynamic_mode_exact',all(T.SELF_REVOCATIONS==1) && ...
    all(T.FINAL_REVOKE_VERSION==2), ...
    'every row executes one local version increment');
format=all(T.CLAIM_PACKET_BYTES==R.claimBytes) && all( ...
    T.CERTIFICATE_HEADER_BYTES==R.certificateHeaderBytes) && all( ...
    T.CERTIFICATE_ENTRY_BYTES==R.certificateEntryBytes) && all( ...
    T.REVOKE_PACKET_BYTES==R.revokeBytes) && all( ...
    T.PACKET_MTU_VIOLATIONS==0) && all( ...
    T.MAX_RESPONSE_PACKET_BYTES<=R.maxControlPacketBytes);
add('packet_format_and_mtu_exact',format,sprintf( ...
    'maximum RESPONSE %.0f bytes under 28/16+10e/24 format', ...
    max(T.MAX_RESPONSE_PACKET_BYTES)));
add('third_party_witness_stimulus',all(T.CONFLICT_EDGES>=4) && ...
    all(T.MAX_WITNESS_LOAD>=2), ...
    'revoker has third-party witness and nontrivial witness load');
add('positive_pre_event_state',all(T.PRE_EVENT_ACTIVE==1),sprintf( ...
    '%d/%d revokers scheduled immediately before event', ...
    nnz(T.PRE_EVENT_ACTIVE),height(T)));
add('one_charged_revoke',all(T.REVOKE_ATTEMPTS==1) && ...
    all(T.REVOKE_BYTES==R.revokeBytes), ...
    'one 24-byte REVOKE attempt per lifecycle');
add('event_frame_local_suppression',all(T.EVENT_FRAME_SUPPRESSED==1), ...
    'local suppression is effective in the REVOKE frame');
add('unsafe_window_suppression',all(T.UNSAFE_WINDOW_SUPPRESSED==1), ...
    'revoker never uses scheduled DATA during outside-supergraph edge');
add('dynamic_edge_transition_stimulus',all( ...
    T.WITHIN_SUPERGRAPH_EDGE_FRAMES>0) && all( ...
    T.OUTSIDE_SUPERGRAPH_EDGE_FRAMES>0) && all( ...
    T.EDGE_REMOVAL_STIMULATED==1) && all( ...
    T.OUTSIDE_SENDER_EDGE_CERTIFIED==0) && all( ...
    T.OUTSIDE_PAIR_SAME_COLOR==1), ...
    'within-edge add/remove plus unsafe same-color outside edge exercised');
add('scheduled_delivery_safety',all(T.SCHEDULED_COLLISION_FRAMES==0), ...
    'zero scheduled collision frames across dynamic graph sequences');
add('certificate_safety',all(T.FALSE_VALID_EDGE_FRAMES==0), ...
    'zero false-valid certified edge frames');
blackout=string(T.condition)==string(R.responseBlackoutCondition);
normal=~blackout;
add('nonblackout_reacquisition_liveness',all( ...
    T.REACQUISITIONS(normal)==1) && all( ...
    T.FINAL_SUPPRESSED(normal)==0) && all(isfinite( ...
    T.FIRST_REACQUIRED_FRAME(normal))),sprintf( ...
    '%d/%d nonblackout rows reacquire',sum(T.REACQUISITIONS(normal)), ...
    nnz(normal)));
reacquired=isfinite(T.FIRST_REACQUIRED_FRAME);
add('old_fence_respected',all(T.FIRST_REACQUIRED_FRAME(reacquired)> ...
    T.CAPTURED_FENCE_FRAME(reacquired)), ...
    'no scheduled reuse before captured old tuple fence');
add('response_blackout_stimulus',any(blackout) && any( ...
    T.RETRY_CLAIM_ATTEMPTS(blackout)>0), ...
    'permanent incident-witness RESPONSE blackout activates retry');
add('response_blackout_fail_silent',all(T.REACQUISITIONS(blackout)==0) && ...
    all(T.FINAL_SUPPRESSED(blackout)==1) && all(isnan( ...
    T.FIRST_REACQUIRED_FRAME(blackout))), ...
    'missing reacquisition receipt never restores scheduled validity');
independent=true;
for seed=R.seeds'
    for N=R.nodeCounts
        zero=T.seed==seed & T.N==N & string(T.condition)=="zero-delivered";
        lost=T.seed==seed & T.N==N & string(T.condition)== ...
            string(R.revokeBlackoutCondition);
        independent=independent && isscalar(find(zero)) && ...
            isscalar(find(lost)) && T.SUPPRESSION_HASH_EXACT(zero)== ...
            T.SUPPRESSION_HASH_EXACT(lost) && ...
            T.REACQUIRED_HASH_EXACT(zero)==T.REACQUIRED_HASH_EXACT(lost);
    end
end
add('revoke_loss_safety_independence',independent && any( ...
    T.REVOKE_RECIPIENT_ERASURE(string(T.condition)== ...
    string(R.revokeBlackoutCondition))>0), ...
    'delivered/lost REVOKE has identical local silence and reuse times');
joint=string(T.condition)=="joint-control-revoke-iid5";
add('loss_retry_stimulus',any(T.RETRY_CLAIM_ATTEMPTS(joint)>0) && any( ...
    T.REVOKE_RECIPIENT_ERASURE(joint)>0), ...
    'joint-loss rows exercise cumulative retry and REVOKE erasure');
account=all(T.CONTROL_ATTEMPTS==T.CLAIM_ATTEMPTS+ ...
    T.CERTIFICATE_ATTEMPTS+T.REVOKE_ATTEMPTS) && all( ...
    T.CONTROL_BYTES==T.CLAIM_BYTES+T.CERTIFICATE_BYTES+T.REVOKE_BYTES) && ...
    all(T.REVOKE_BYTES==T.REVOKE_ATTEMPTS.*T.REVOKE_PACKET_BYTES) && all( ...
    T.MANAGEMENT_RECIPIENT_SUCCESS+T.MANAGEMENT_RECIPIENT_ERASURE+ ...
    T.MANAGEMENT_RECIPIENT_COLLISION==T.MANAGEMENT_RECIPIENT_ATTEMPTS) && ...
    all(T.REVOKE_RECIPIENT_SUCCESS+T.REVOKE_RECIPIENT_ERASURE+ ...
    T.REVOKE_RECIPIENT_COLLISION==T.REVOKE_RECIPIENT_ATTEMPTS);
add('attempt_byte_recipient_accounting',account, ...
    'CLAIM/RESPONSE/REVOKE attempts, bytes and recipients close');
add('absolute_control_bounds',all(T.CONTROL_ATTEMPT_BOUND_RATIO<=1+1e-12) && ...
    all(T.CONTROL_BYTE_BOUND_RATIO<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.CONTROL_ATTEMPT_BOUND_RATIO),max(T.CONTROL_BYTE_BOUND_RATIO)));
D=coherenceRevokeCacheDecision(1,1,2,true);
stale=coherenceRevokeCacheDecision(2,1,2,true);
future=coherenceRevokeCacheDecision(1,2,3,true);
bad=coherenceRevokeCacheDecision(1,1,3,true);
unauth=coherenceRevokeCacheDecision(1,1,2,false);
add('version_bound_revoke_rejection',D.accept && ~D.createsValidity && ...
    ~stale.accept && ~future.accept && ~bad.accept && ~unauth.accept, ...
    'stale, future, malformed and unauthenticated metadata is inert');
add('causal_nonpromotion_scope',all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && ~R.policyOptimizationAllowed && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted, ...
    'causal fixed-supergraph kernel only; no promotion or submission claim');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23s: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'N','condition'}));
S.nRuns=splitapply(@numel,T.CONTROL_ATTEMPTS,group);
S.preEventActiveRate=splitapply(@mean,T.PRE_EVENT_ACTIVE,group);
S.reacquisitionRate=splitapply(@mean,T.REACQUISITIONS,group);
S.meanFirstReacquiredFrame=splitapply(@meanOmitNaN, ...
    T.FIRST_REACQUIRED_FRAME,group);
S.meanControlAttempts=splitapply(@mean,T.CONTROL_ATTEMPTS,group);
S.meanControlBytes=splitapply(@mean,T.CONTROL_BYTES,group);
S.revokeErasureCount=splitapply(@sum,T.REVOKE_RECIPIENT_ERASURE,group);
S.scheduledCollisionFrames=splitapply(@sum, ...
    T.SCHEDULED_COLLISION_FRAMES,group);
end


function value=meanOmitNaN(x)
value=mean(x,'omitnan');
end


function snapshotSource(target)

root=projectRoot();
files={'docs/EXP23S_DYNAMIC_REVOCATION_KERNEL_PLAN.md', ...
    'docs/EXP23S_DYNAMIC_REVOCATION_DESIGN.md', ...
    'docs/EXP23R_COHERENCE_PACKET_GRAPH_REPAIR_RESULTS_2026-09-04.md', ...
    'network/simulateElcsWitnessScheduling.m', ...
    'network/coherenceRevokeCacheDecision.m', ...
    'network/buildSenderConflictGraph.m', ...
    'utils/elcsWitnessTraceHash.m', ...
    'utils/exp23sDynamicRevocationRegistry.m', ...
    'utils/exp23sDynamicRevocationEmptyRow.m', ...
    'utils/runExp23sDynamicRevocationCell.m', ...
    'tests/test_exp23s_dynamic_revocation_study_contracts.m', ...
    'tests/test_elcs_dynamic_revocation_contracts.m', ...
    'tests/test_elcs_coherence_integration_contracts.m', ...
    'tests/test_elcs_cumulative_receipt_contracts.m', ...
    'experiments/exp23s_dynamic_revocation_kernel.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    name=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,name));
end
end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('exp23s: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
