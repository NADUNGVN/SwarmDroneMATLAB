function diagnose_exp23ah_phase_reserved_fixture()
%DIAGNOSE_EXP23AH_PHASE_RESERVED_FIXTURE Calibrate only on prior AG seeds.

startup; R=exp23ahPhaseReservedClosureRegistry();
R.seeds=R.radialValidationSeeds; R.arms=R.arms(2:end);
expRun=startExperiment('exp23ah_phase_reserved_diagnostic', ...
    'Prior-seed diagnosis of persistent QUIET and reserved control phases.');
rows=repmat(exp23afOnlineClosureEmptyRow(), ...
    numel(R.seeds)*numel(R.arms),1); q=0;
for seedIndex=1:numel(R.seeds)
    block=runExp23afOnlineClosureSeed(R.seeds(seedIndex),R);
    rows(q+(1:numel(block)))=block; q=q+numel(block);
    if mod(seedIndex,10)==0
        fprintf('  calibration seed %2d / %2d; rows %3d\n', ...
            seedIndex,numel(R.seeds),q);
    end
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'phase_reserved_diagnostic_tidy.csv'));
normal=string(T.arm)=="closure-iid20-emergency";
response=string(T.arm)=="closure-response-blackout-emergency";
noEmergency=string(T.arm)== ...
    "closure-response-blackout-no-emergency";
prepare=string(T.arm)=="closure-prepare-blackout-emergency";
commit=string(T.arm)=="closure-commit-blackout-emergency";
protected=~noEmergency;
[group,S]=findgroups(T(:,{'arm'}));
S.nRuns=splitapply(@numel,T.seed,group);
S.motionAuthorizationRate=splitapply(@mean,T.motionAuthorized,group);
S.reactivationRate=splitapply(@mean,T.allReactivated,group);
S.radialContractRate=splitapply(@mean,T.radialTheoremCertified,group);
S.maximumRadialRatio=splitapply(@max,T.criticalRadialMaximumRatio,group);
S.maximumReliabilityBound=splitapply( ...
    @max,T.transactionFailureUpperBound,group);
S.meanMissionRmse=splitapply(@mean,T.MISSION_RMSE,group);
S.minimumSeparation=splitapply(@min,T.MINSEP,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);
writetable(S,fullfile(expRun.dir,'summary.csv'));

normalReliable=mean(T.allReactivated(normal))>= ...
    R.minimumEmpiricalNormalCompletionRate&&all( ...
    T.transactionHorizonFeasible(normal)==1)&&all( ...
    T.transactionFailureUpperBound(normal)< ...
    R.maxTransactionFailureProbability);
responseSafe=all((T.motionAuthorized(response)==0)| ...
    (T.finalSuppressedCount(response)==T.affectedCount(response)))&& ...
    all(T.commitReady(response)==0);
commitSafe=all((T.motionAuthorized(commit)==0)| ...
    ((T.commitReady(commit)==0& ...
    T.finalSuppressedCount(commit)==T.affectedCount(commit))| ...
    (T.commitReady(commit)==1&T.reactivatedCount(commit)==1& ...
    T.finalSuppressedCount(commit)==T.affectedCount(commit)-1)));
protectedGeometry=all(T.radialTheoremCertified(protected)==1)&& ...
    all(T.actualPhysicalSubset(protected)==1)&& ...
    all(T.actualSenderSubset(protected)==1)&& ...
    all(T.observedCollisionFrames(protected)==0);
negativeVisible=all(T.radialTheoremCertified(noEmergency)==0)&& ...
    all(T.criticalRadialMaximumRatio(noEmergency)>1)&& ...
    all(T.MISSION_RMSE(noEmergency)>T.MISSION_RMSE(response));
prepareSafe=all(T.motionAuthorized(prepare)==0)&& ...
    all(T.barrierClosed(prepare)==0);
supported=normalReliable&&responseSafe&&commitSafe&&prepareSafe&& ...
    protectedGeometry&&negativeVisible&&all(T.SAFEFAIL(protected)==0);
status=ternary(supported,'PHASE_RESERVED_FIXTURE_SUPPORTED', ...
    'PHASE_RESERVED_FIXTURE_NOT_SUPPORTED');
verdict=struct('status',status,'rows',height(T), ...
    'calibrationSeedsOnly',true,'freshConfirmation',false, ...
    'normalCompletionRate',mean(T.allReactivated(normal)), ...
    'maximumTransactionFailureUpperBound', ...
    max(T.transactionFailureUpperBound(normal)), ...
    'maximumProtectedRadialRatio', ...
    max(T.criticalRadialMaximumRatio(protected)), ...
    'minimumProtectedSeparation',min(T.MINSEP(protected)), ...
    'submissionClaimPermitted',false, ...
    'next','preregister_exp23ah_on_untouched_seeds');
writeJson(fullfile(expRun.dir,'phase_reserved_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','verdict','R');
disp(S); fprintf('EXP23AH DIAGNOSIS: %s\n',status);
finishExperiment(expRun);
if ~supported, error('exp23ah phase-reserved fixture unsupported.'); end

end


function writeJson(path,value)
fid=fopen(path,'w'); if fid<0, error('exp23ah diagnostic: write.'); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
