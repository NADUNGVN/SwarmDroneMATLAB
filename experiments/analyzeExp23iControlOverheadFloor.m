function analyzeExp23iControlOverheadFloor(runDir)
%ANALYZEEXP23ICONTROLOVERHEADFLOOR Exact posthoc control-byte decomposition.

if nargin<1 || isempty(runDir)
    error('analyzeExp23iControlOverheadFloor: run directory is required.');
end
startup;
R=exp23iCumulativeClosedLoopRegistry();
path=fullfile(runDir,'trajectory_tidy.csv');
if ~isfile(path), error('EXP23I tidy table not found.'); end
T=readtable(path,'TextType','string');
if height(T)~=R.expectedRuns
    error('EXP23I matrix is incomplete.');
end

rows=repmat(emptyRow(),numel(R.seeds),1);
for k=1:numel(R.seeds)
    seedValue=R.seeds(k);
    candidate=selectOne(T,seedValue,R.cumulativeArm);
    periodic=selectOne(T,seedValue,R.periodicArm);
    [Q,C]=rebuildCumulativeSchedule(seedValue,R);
    claim=Q.controlKind=="claim";
    response=Q.controlKind=="response";
    if sum(Q.controlAttemptBytes)~=candidate.ELCSW_PHYSICAL_CONTROL_BYTES
        error('Rebuilt physical control bytes do not match EXP23I.');
    end
    firstFrame=Q.kernel.firstAllCertifiedFrame;
    bootstrap=Q.controlFrame<=firstFrame;
    dataAckUtil=(candidate.DATA_AIRTIME+candidate.ACK_AIRTIME)/12;
    claimBytes=sum(Q.controlAttemptBytes(claim));
    responseBytes=sum(Q.controlAttemptBytes(response));
    responseHeaders=nnz(response)*C.certificateHeaderBytes;
    responseEntries=responseBytes-responseHeaders;
    bootstrapBytes=sum(Q.controlAttemptBytes(bootstrap));
    renewalBytes=sum(Q.controlAttemptBytes(~bootstrap));
    retryClaimBytes=Q.physicalRetryClaimAttempts*C.claimBytes;
    nominalClaimBytes=claimBytes-retryClaimBytes;
    targetBytes=max(0,(periodic.TOTAL_OFFERED_UTIL-dataAckUtil)*12* ...
        C.phyRateBps/8);
    removal=max(0,sum(Q.controlAttemptBytes)-targetBytes);
    denominator=targetBytes-bootstrapBytes;
    if denominator>0
        renewalScale=renewalBytes/denominator;
    else
        renewalScale=inf;
    end
    rows(k)=struct('seed',seedValue,'physicalFrames',Q.physicalFrameCount, ...
        'firstAllCertifiedFrame',firstFrame, ...
        'controlAttempts',numel(Q.controlAttemptBytes), ...
        'controlBytes',sum(Q.controlAttemptBytes), ...
        'claimAttempts',nnz(claim),'claimBytes',claimBytes, ...
        'responseAttempts',nnz(response),'responseBytes',responseBytes, ...
        'responseHeaderBytes',responseHeaders, ...
        'responseEntryBytes',responseEntries, ...
        'bootstrapBytes',bootstrapBytes,'renewalBytes',renewalBytes, ...
        'nominalClaimBytes',nominalClaimBytes, ...
        'retryClaimBytes',retryClaimBytes, ...
        'dataAckUtil',dataAckUtil, ...
        'candidateTotalUtil',candidate.TOTAL_OFFERED_UTIL, ...
        'periodicTotalUtil',periodic.TOTAL_OFFERED_UTIL, ...
        'targetControlBytesToTie',targetBytes, ...
        'requiredControlByteRemoval',removal, ...
        'requiredControlRemovalFraction', ...
        removal/sum(Q.controlAttemptBytes), ...
        'renewalControlFraction',renewalBytes/sum(Q.controlAttemptBytes), ...
        'noControlFloorUtil',dataAckUtil, ...
        'claimFreeFloorUtil',dataAckUtil+responseBytes*8/C.phyRateBps/12, ...
        'sharedHeaderFloorUtil', ...
        dataAckUtil+responseEntries*8/C.phyRateBps/12, ...
        'bootstrapOnlyFloorUtil', ...
        dataAckUtil+bootstrapBytes*8/C.phyRateBps/12, ...
        'renewalScaleFactorToTie',renewalScale);
end

D=struct2table(rows);
writetable(D,fullfile(runDir,'posthoc_control_overhead_decomposition.csv'));
S=summaryTable(D,R);
writetable(S,fullfile(runDir,'posthoc_control_overhead_floor.csv'));
verdict=struct( ...
    'status',char(S.status), ...
    'sourceRun','2026-09-04_162852', ...
    'rows',height(D), ...
    'reconstructionCloses',all(D.controlBytes>0), ...
    'bootstrapOnlyCheaperThanPeriodic', ...
    logical(S.bootstrapOnlyCheaperThanPeriodic), ...
    'sharedHeaderCheaperThanPeriodic', ...
    logical(S.sharedHeaderCheaperThanPeriodic), ...
    'renewalHasRequiredHeadroom',logical(S.renewalHasRequiredHeadroom), ...
    'kernelRedesignPermitted',logical(S.kernelRedesignPermitted), ...
    'newMethodPromotionAllowed',false, ...
    'submissionClaimPermitted',false);
writeJson(fullfile(runDir,'posthoc_control_overhead_verdict.json'),verdict);

fprintf('\nEXP23J control-overhead floor audit\n');
fprintf('  mean control bytes                  %.2f\n',S.meanControlBytes);
fprintf('  CLAIM / RESPONSE byte fractions     %.2f%% / %.2f%%\n', ...
    100*S.meanClaimFraction,100*S.meanResponseFraction);
fprintf('  bootstrap / renewal byte fractions %.2f%% / %.2f%%\n', ...
    100*S.meanBootstrapFraction,100*S.meanRenewalFraction);
fprintf('  required control removal            %.2f%%\n', ...
    100*S.meanRequiredRemovalFraction);
fprintf('  periodic cost                       %.8f\n',S.meanPeriodicUtil);
fprintf('  no-control floor                    %.8f\n',S.meanNoControlFloorUtil);
fprintf('  claim-free floor                    %.8f\n',S.meanClaimFreeFloorUtil);
fprintf('  shared-header floor                 %.8f\n',S.meanSharedHeaderFloorUtil);
fprintf('  bootstrap-only floor                %.8f\n',S.meanBootstrapOnlyFloorUtil);
fprintf('  renewal scale factor to tie         %.3f x\n', ...
    S.meanRenewalScaleFactorToTie);
fprintf('EXP23J DECISION: %s\n',char(S.status));

end


function [Q,C]=rebuildCumulativeSchedule(seedValue,R)

c=R.cells(1); condition=R.conditions(1);
base=applyExp21dClosedLoopCell(c.id,seedValue);
base.mac.backgroundLoad=condition.targetLoad;
base.mac=sharedMediumConfig(base);
trace=generateSharedMediumTrace(base);
C=elcsWitnessKernelConfig(base.swarm.N,R.elcsMaxFrames);
C.guardSec=R.missionSafeGuardSec;
C.dataBytes=base.mac.dataBytes;
C.phyRateBps=base.mac.phyRateBps;
C.neighborGraph=logical(base.swarm.A);
C.managementReach=C.neighborGraph;
C.interferenceMatrix=logical(base.mac.interferenceMatrix);
C.conflictGraph=buildSenderConflictGraph( ...
    C.neighborGraph,C.interferenceMatrix);
C.cumulativeReceiptRetry=true;
elcsTrace=generateElcsWitnessTrace(seedValue,C);
offset=(2*reshape(trace.exp21cClockOffsetU(1,:),[],1)-1)*R.maxOffsetSec;
drift=(2*reshape(trace.exp21cClockDriftU,[],1)-1)*R.maxDriftPpm;
clockSpec=struct('clockOffsetSec',offset,'clockDriftPpm',drift, ...
    'leadTimeSec',R.clockLeadTimeSec);
elcsTrace=applySharedBackgroundToElcsWitnessTrace( ...
    elcsTrace,C,trace,clockSpec,condition.targetLoad);
Q=buildElcsWitnessContinuousSchedule(C,elcsTrace,base.swarm.T);

end


function S=summaryTable(D,R)

meanControl=mean(D.controlBytes);
meanPeriodic=mean(D.periodicTotalUtil);
meanBootstrapFloor=mean(D.bootstrapOnlyFloorUtil);
meanHeaderFloor=mean(D.sharedHeaderFloorUtil);
renewalHeadroom=mean(D.renewalControlFraction)>= ...
    mean(D.requiredControlRemovalFraction);
bootstrapCheaper=meanBootstrapFloor<meanPeriodic;
headerCheaper=meanHeaderFloor<meanPeriodic;
permitted=bootstrapCheaper && renewalHeadroom;
if permitted
    status="RENEWAL_ARCHITECTURE_HAS_THEORETICAL_HEADROOM";
else
    status="CURRENT_DATA_SERVICE_REQUIRES_REDESIGN";
end
S=table(meanControl,mean(D.claimBytes)/meanControl, ...
    mean(D.responseBytes)/meanControl,mean(D.bootstrapBytes)/meanControl, ...
    mean(D.renewalBytes)/meanControl, ...
    mean(D.requiredControlRemovalFraction),meanPeriodic, ...
    mean(D.noControlFloorUtil),mean(D.claimFreeFloorUtil), ...
    meanHeaderFloor,meanBootstrapFloor, ...
    mean(D.renewalScaleFactorToTie(isfinite(D.renewalScaleFactorToTie))), ...
    double(bootstrapCheaper),double(headerCheaper), ...
    double(renewalHeadroom),double(permitted),status, ...
    R.policyOptimizationAllowed,R.newMethodPromotionAllowed, ...
    R.submissionClaimPermitted,'VariableNames',{ ...
    'meanControlBytes','meanClaimFraction','meanResponseFraction', ...
    'meanBootstrapFraction','meanRenewalFraction', ...
    'meanRequiredRemovalFraction','meanPeriodicUtil', ...
    'meanNoControlFloorUtil','meanClaimFreeFloorUtil', ...
    'meanSharedHeaderFloorUtil','meanBootstrapOnlyFloorUtil', ...
    'meanRenewalScaleFactorToTie','bootstrapOnlyCheaperThanPeriodic', ...
    'sharedHeaderCheaperThanPeriodic','renewalHasRequiredHeadroom', ...
    'kernelRedesignPermitted','status','policyOptimizationAllowed', ...
    'newMethodPromotionAllowed','submissionClaimPermitted'});

end


function row=selectOne(T,seedValue,arm)
index=T.seed==seedValue & string(T.arm)==string(arm);
if nnz(index)~=1, error('EXP23I seed/arm row is not unique.'); end
row=T(index,:);
end


function row=emptyRow()
names={'seed','physicalFrames','firstAllCertifiedFrame', ...
    'controlAttempts','controlBytes','claimAttempts','claimBytes', ...
    'responseAttempts','responseBytes','responseHeaderBytes', ...
    'responseEntryBytes','bootstrapBytes','renewalBytes', ...
    'nominalClaimBytes','retryClaimBytes','dataAckUtil', ...
    'candidateTotalUtil','periodicTotalUtil','targetControlBytesToTie', ...
    'requiredControlByteRemoval','requiredControlRemovalFraction', ...
    'renewalControlFraction','noControlFloorUtil','claimFreeFloorUtil', ...
    'sharedHeaderFloorUtil','bootstrapOnlyFloorUtil', ...
    'renewalScaleFactorToTie'};
row=cell2struct(num2cell(nan(size(names))),names,2);
end


function writeJson(path,value)
fid=fopen(path,'w');
if fid<0, error('Cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end
