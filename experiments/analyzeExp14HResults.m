function A=analyzeExp14HResults(runDir)
%ANALYZEEXP14HRESULTS Descriptive N20 causal support-closure analysis.

runDir=char(runDir); R=exp14hRegistry();
[registryHash,registryLeaves]=configHash(R);
if registryHash~=142973713 || registryLeaves~=25
    error('analyzeExp14HResults: frozen registry mismatch.');
end
G=readtable(fullfile(runDir,'gates.csv'),'TextType','string');
P=readtable(fullfile(runDir,'branch_pairs.csv'),'TextType','string');
if ~all(G.passed==1) || height(P)<R.minimumEventsPerCell
    error('analyzeExp14HResults: integrity-passing support closure required.');
end
metrics={'meanLeadSeconds','ackAirtimeCost','dataAirtimeSaved', ...
    'netAirtimeBenefit','dataAttemptsSaved','collisionsSaved', ...
    'trueAoIIntegralBenefit','estimatedAoIIntegralBenefit', ...
    'controlLossIntegralBenefit','minimumSeparationBenefit'};
effects=repmat(struct('metric','','nDecisions',NaN,'meanEffect',NaN, ...
    'ciLo',NaN,'ciHi',NaN,'crossesZero',false),numel(metrics),1);
for k=1:numel(metrics)
    x=P.(metrics{k}); ci=oneSampleCI(x);
    effects(k).metric=metrics{k}; effects(k).nDecisions=height(P);
    effects(k).meanEffect=ci.mean; effects(k).ciLo=ci.lo;
    effects(k).ciHi=ci.hi; effects(k).crossesZero=ci.lo<=0 && ci.hi>=0;
end
tol=1e-12;
good=P.netAirtimeBenefit>tol & P.trueAoIIntegralBenefit>=-tol & ...
    P.controlLossIntegralBenefit>=-tol;
bad=P.netAirtimeBenefit<-tol & P.trueAoIIntegralBenefit<=tol & ...
    P.controlLossIntegralBenefit<=tol;
summary=struct('scenario','n20-ring2','nDecisions',height(P), ...
    'nParentSeeds',numel(unique(P.seed)),'totalEntries',sum(P.nEntries), ...
    'positiveLeadEntryFraction',sum(P.positiveLeadEntries)/sum(P.nEntries), ...
    'actualConfirmationFraction',sum(P.actualConfirmedEntries)/sum(P.nEntries), ...
    'shadowConfirmationFraction',sum(P.shadowConfirmedEntries)/sum(P.nEntries), ...
    'meanLocalBusy',mean(P.localBusy),'meanPendingAge',mean(P.pendingAge), ...
    'meanEntries',mean(P.nEntries),'forcedFraction',mean(P.forced), ...
    'paretoBeneficialDecisions',sum(good), ...
    'paretoHarmfulDecisions',sum(bad), ...
    'mixedOrNullDecisions',height(P)-sum(good)-sum(bad));
A=struct('summary',struct2table(summary),'effects',struct2table(effects));
A.manifest=struct('analysisStatus','N20_DEVELOPMENT_SUPPORT_CLOSED', ...
    'exp14gVerdictChanged',false,'confirmatoryClaimPermitted',false, ...
    'thresholdTuningPermitted',false,'predictorFittingPermitted',false, ...
    'perDecisionCausalLeadIdentified',true, ...
    'predictiveCertificateReady',false, ...
    'nextRequiredStep', ...
    'freeze an interpretable rule and validate on a disjoint seed block', ...
    'registryHash',registryHash,'registryLeaves',registryLeaves, ...
    'createdAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')));
writetable(A.summary,fullfile(runDir,'causal_summary.csv'));
writetable(A.effects,fullfile(runDir,'causal_effects_long.csv'));
writeJson(fullfile(runDir,'analysis_manifest.json'),A.manifest);

end


function S=oneSampleCI(x)

n=numel(x); S.mean=mean(x); half=tinv(0.975,n-1)*std(x)/sqrt(n);
S.lo=S.mean-half; S.hi=S.mean+half;

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('analyzeExp14HResults: cannot write %s.',path); end
cleaner=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));

end
