function exp23ai_integer_phy_accounting()
%EXP23AI_INTEGER_PHY_ACCOUNTING Fresh exact-accounting confirmation.

startup; close all; runRequiredTests();
R=exp23aiIntegerAccountingRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23ai_integer_phy_accounting', ...
    'Fresh integer management-byte and derived-airtime confirmation.');
writeJson(fullfile(expRun.dir,'integer_accounting_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23afOnlineClosureEmptyRow(),R.expectedRuns,1); q=0;
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
for seedIndex=1:numel(R.seeds)
    block=runExp23afOnlineClosureSeed(R.seeds(seedIndex),R);
    rows(q+(1:numel(block)))=block; q=q+numel(block);
    if mod(seedIndex,5)==0
        writetable(struct2table(rows(1:q)),checkpoint);
        fprintf('  seed %2d / %2d; rows %3d / %3d\n', ...
            seedIndex,numel(R.seeds),q,R.expectedRuns);
    end
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
P=pairedTable(T,R); writetable(P,fullfile(expRun.dir,'paired_contrasts.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
valid=all(gates.passed==1);
status=ternary(valid,'INTEGER_ACCOUNTED_RADIAL_CLOSURE_FRESH_VALID', ...
    'INTEGER_ACCOUNTED_RADIAL_CLOSURE_FRESH_INVALID');
next=ternary(valid,'routed_multihop_management_then_online_renewal', ...
    'repair_exact_accounting_or_scientific_gate_without_relaxation');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'onlinePlantCouplingValidated',valid, ...
    'radialContractionContractValidated',valid, ...
    'finiteRetryReliabilityValidated',valid, ...
    'integerPhyAccountingValidated',valid, ...
    'freshPhaseReservedEvidence',valid, ...
    'managementRelayingValidated',false, ...
    'repeatedOnlineRenewalValidated',false, ...
    'freshSeedEvidence',false,'robustnessClaimPermitted',false, ...
    'submissionClaimPermitted',false,'next',next);
writeJson(fullfile(expRun.dir,'integer_accounting_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','P','gates','verdict','R');

fprintf('\nEXP23AI integer-PHY accounting gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-45s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S); disp(P);
fprintf('EXP23AI DECISION: %s\n',status);
finishExperiment(expRun);
if ~valid, error('exp23ai: integer-accounted closure invalid.'); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
closure=string(T.kind)=="closure";
normal=string(T.arm)=="closure-iid20-emergency";
response=string(T.arm)=="closure-response-blackout-emergency";
noEmergency=string(T.arm)=="closure-response-blackout-no-emergency";
prepare=string(T.arm)=="closure-prepare-blackout-emergency";
commit=string(T.arm)=="closure-commit-blackout-emergency";
protected=closure&~noEmergency;

used=[R.smokeSeed;R.calibrationSeeds;R.radialValidationSeeds; ...
    R.phaseValidationSeeds];
add('registry_frozen_fresh',isfinite(registryHash)&& ...
    registryLeaves>0&&isempty(intersect(R.seeds,used))&& ...
    R.expectedRuns==300,sprintf( ...
    'hash %.0f over %d leaves; 50 seeds disjoint', ...
    registryHash,registryLeaves));
parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ah_phase_reserved_radial_closure',R.parentPhaseRun, ...
    'phase_reserved_verdict.json')));
add('invalid_parent_retained',strcmp(parent.status,R.parentPhaseStatus)&& ...
    parent.gatesPassed==R.parentPhaseGatesPassed&& ...
    parent.gatesTotal==R.parentPhaseGatesTotal&& ...
    ~parent.freshPhaseReservedEvidence, ...
    'EXP23AH remains invalid at 26/27; accounting is not relabeled');
diagnosis=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ah_phase_reserved_diagnostic',R.parentPhaseDiagnosticRun, ...
    'phase_reserved_verdict.json')));
add('calibration_nonfresh',strcmp(diagnosis.status, ...
    R.parentPhaseDiagnosticStatus)&&diagnosis.calibrationSeedsOnly&& ...
    ~diagnosis.freshConfirmation, ...
    'phase and leader radius remain calibration-only');

key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
add('exact_matrix_coverage',isequal(unique(T.seed),R.seeds)&& ...
    isequal(sort(unique(string(T.arm))), ...
    sort(reshape(string({R.arms.id}),[],1))), ...
    '50 untouched seeds and six frozen arms exact');
add('seed_trace_pairing',perSeedUnique(T,R,'traceHash'), ...
    'one exogenous PHY trace is paired across arms per seed');
add('online_prefix_exact',all(T.prefixStateExact(closure)==1)&& ...
    perSeedUnique(T(closure,:),R,'decisionStateHash')&& ...
    perSeedUnique(T(closure,:),R,'prefixScheduleHash')&&all( ...
    T.prefixScheduleHash(closure)==T.probePrefixScheduleHash(closure)), ...
    'decision state and pre-PREPARE schedule are prefix-identical');
add('causal_geometry_pairing',perSeedUnique( ...
    T(closure,:),R,'geometryHash')&&perSeedUnique( ...
    T(closure,:),R,'selectorHash')&&perSeedUnique( ...
    T(closure,:),R,'reliabilityCertificateHash'), ...
    'geometry, selector, and reliability certificate pair per seed');
add('receiver_lifted_stimulus',all(T.graphAdmissible(closure)==1)&& ...
    all(T.changedSenderEdges(closure)>=1)&&all( ...
    T.nonincidentSenderEdges(closure)>=1)&&all( ...
    T.changedSlotCount(closure)>=1),sprintf( ...
    'minimum nonincident edges %d; affected range %d--%d', ...
    min(T.nonincidentSenderEdges(closure)), ...
    min(T.affectedCount(closure)),max(T.affectedCount(closure))));
add('union_packet_and_protected_slots',all( ...
    T.candidateProper(closure)==1)&&all(T.prepareBytes(closure)<= ...
    R.maxControlPacketBytes)&&all(T.maxResponseBytes(closure)<= ...
    R.maxControlPacketBytes)&&all(T.protectedSlotFree(closure)==1), ...
    'union coloring, MTU, and protected slots remain admissible');

add('persistent_quiet_kernel_bounds',all( ...
    T.kernelVersionHash(closure)== ...
    realizationHash(R.closureKernelVersion))&&all( ...
    T.kernelActualSubsetOld(closure)==1)&&all( ...
    T.kernelActualSubsetUnion(closure)==1)&&all( ...
    T.kernelFinalColoringProper(closure)==1)&&all( ...
    T.prematureActivationFrames(closure)==0)&&all( ...
    T.controlAttemptBoundRatio(closure)<=1+1e-12)&&all( ...
    T.controlByteBoundRatio(closure)<=1+1e-12), ...
    'v2 persistent QUIET and analytical kernel bounds hold');
add('motion_gate_exact',all(T.motionGateExact(closure)==1), ...
    'command begins at graph activation only');
add('prepare_blackout_blocks_motion',all(T.barrierClosed(prepare)==0)&& ...
    all(T.motionAuthorized(prepare)==0)&&all( ...
    T.prepareBudgetExhausted(prepare)==1), ...
    'PREPARE blackout safely exhausts without motion');

add('analytical_transaction_reliability',all( ...
    T.transactionHorizonFeasible(normal)==1)&&all( ...
    T.transactionFailureUpperBound(normal)< ...
    R.maxTransactionFailureProbability)&&all( ...
    T.completionProbabilityLowerBound(normal)> ...
    1-R.maxTransactionFailureProbability),sprintf( ...
    'maximum union failure bound %.9g', ...
    max(T.transactionFailureUpperBound(normal))));
normalRate=mean(T.allReactivated(normal));
normalTerminal=T.allReactivated(normal)==1| ...
    (T.finalSuppressedCount(normal)>0& ...
    T.kernelFinalColoringProper(normal)==1& ...
    T.kernelCollisionFrames(normal)==0);
add('normal_completion_or_safe_abort',normalRate>= ...
    R.minimumEmpiricalNormalCompletionRate&&all(normalTerminal),sprintf( ...
    'completion %d/%d = %.4f; any failure remains suppressed', ...
    nnz(T.allReactivated(normal)),nnz(normal),normalRate));
responseState=(T.motionAuthorized(response)==0& ...
    T.barrierClosed(response)==0)| ...
    (T.motionAuthorized(response)==1&T.barrierClosed(response)==1& ...
    T.commitReady(response)==0& ...
    T.finalSuppressedCount(response)==T.affectedCount(response));
add('response_blackout_conditional_silence',all(responseState), ...
    'pre-barrier abort or full post-barrier suppression only');
commitState=(T.motionAuthorized(commit)==0&T.barrierClosed(commit)==0)| ...
    (T.motionAuthorized(commit)==1&T.commitReady(commit)==0& ...
    T.finalSuppressedCount(commit)==T.affectedCount(commit))| ...
    (T.motionAuthorized(commit)==1&T.commitReady(commit)==1& ...
    T.reactivatedCount(commit)==1& ...
    T.finalSuppressedCount(commit)==T.affectedCount(commit)-1);
add('commit_blackout_conditional_safety',all(commitState)&&all( ...
    T.kernelCollisionFrames(commit)==0), ...
    'abort, evidence failure, or initiator-only COMMIT are safe');

add('parallel_emergency_mapping',all( ...
    T.emergencyParallelMode(protected)==1)&&all( ...
    T.emergencyMappingExact(protected)==1)&&all( ...
    T.emergencySuppressedDemand(protected)== ...
    T.emergencyOpportunities(protected))&&all( ...
    T.emergencyRecipientCollision(protected)==0), ...
    'each suppressed sender gets a distinct protected slot per frame');
add('radial_construction_premise',all( ...
    T.radialConstructionPremise(closure)==1)&&all( ...
    T.criticalCapsulePairChecks(closure)>0), ...
    'every omitted pair is nominally beyond R_I+b_ij');
add('protected_radial_theorem',all( ...
    T.criticalRadialBoundSatisfied(protected)==1)&&all( ...
    T.radialTheoremCertified(protected)==1),sprintf( ...
    'maximum inward-contraction ratio %.6f', ...
    max(T.criticalRadialMaximumRatio(protected))));
add('protected_actual_graph_subset',all( ...
    T.actualPhysicalSubset(protected)==1)&&all( ...
    T.actualSenderSubset(protected)==1)&&all( ...
    T.actualSubsetCheckSamples(protected)>0),sprintf( ...
    'minimum omitted-edge margin %.6f m', ...
    min(T.minimumOmittedEdgeMargin(protected))));

protectedRmse=armValues(T,R, ...
    'closure-response-blackout-emergency','MISSION_RMSE');
unprotectedRmse=armValues(T,R, ...
    'closure-response-blackout-no-emergency','MISSION_RMSE');
add('no_emergency_negative_visible',all( ...
    T.emergencyOpportunities(noEmergency)==0)&&all( ...
    T.radialTheoremCertified(noEmergency)==0)&&all( ...
    T.criticalRadialMaximumRatio(noEmergency)>1)&&all( ...
    unprotectedRmse-protectedRmse>0),sprintf( ...
    'minimum radial violation %.3f; mean paired RMSE penalty %.6f m', ...
    min(T.criticalRadialMaximumRatio(noEmergency)), ...
    mean(unprotectedRmse-protectedRmse)));
add('supported_collision_safety',all( ...
    T.kernelCollisionFrames(protected)==0)&&all( ...
    T.expectedCollisionRecipients(protected)==0)&&all( ...
    T.observedCollisionFrames(protected)==0)&&all( ...
    T.emergencyRecipientCollision(protected)==0), ...
    'all protected fresh rows are collision-free');
add('receiver_outcome_replay_exact',all( ...
    T.dataOutcomeMismatches(closure)==0)&&all( ...
    T.dataSkippedNoQueue(closure)==0)&&all( ...
    T.crossPlaneOverlaps(closure)==0)&&all( ...
    T.expectedDataSuccess(closure)==T.observedDataSuccess(closure))&&all( ...
    T.expectedDataErasure(closure)==T.observedDataErasure(closure)), ...
    'receiver success/erasure outcomes replay exactly');

integerExact=all(T.controlAttempts(closure)== ...
    T.expectedControlAttempts(closure))&&all( ...
    T.observedControlBytes(closure)==T.expectedControlBytes(closure))&& ...
    all(T.expectedControlBytes(closure)==T.controlBytes(closure))&&all( ...
    T.controlAttemptBoundRatio(closure)<=1+1e-12)&&all( ...
    T.controlByteBoundRatio(closure)<=1+1e-12);
add('integer_management_accounting',integerExact,sprintf( ...
    'maximum observed bytes %.0f; integer attempts/bytes exact', ...
    max(T.observedControlBytes(closure))));
airtimeExact=all(T.controlAirtime(closure)== ...
    8*T.observedControlBytes(closure)/R.phyRateBps)&&all( ...
    T.expectedControlAirtime(closure)== ...
    8*T.expectedControlBytes(closure)/R.phyRateBps)&&all( ...
    T.controlAirtime(closure)==T.expectedControlAirtime(closure));
add('derived_airtime_exact',airtimeExact, ...
    'runtime and schedule airtime equal 8*integer bytes/rate exactly');
add('affine_timing_and_causal_reads',all( ...
    T.clockConflictFree(closure)==1)&&all(T.clockResidual(closure)<1e-12)&& ...
    all(T.futureRandomReads(closure)==0)&&all( ...
    T.receiverTruthReads(closure)==0)&& ...
    R.missionSec<=R.clockResetHorizonSec,sprintf( ...
    'maximum equation residual %.3g s; forbidden reads zero', ...
    max(T.clockResidual(closure))));
scope=R.freshRadialContractEvidence&& ...
    ~R.integerPhyAccountingValidated&& ...
    ~R.freshPhaseReservedEvidence&& ...
    ~R.repeatedOnlineRenewalValidated&&~R.managementRelayingValidated&& ...
    ~R.freshSeedEvidence&&~R.robustnessClaimPermitted&& ...
    ~R.submissionClaimPermitted;
add('protected_safety_and_scope',all(T.SAFEFAIL(protected)==0)&& ...
    all(T.DIVERGED(protected)==0)&& ...
    all(isfinite(T.MISSION_RMSE(protected)))&& ...
    all(isfinite(T.MINSEP(protected)))&&scope,sprintf( ...
    'minimum protected separation %.6f m; downstream claims false', ...
    min(T.MINSEP(protected))));

gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23ai: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function exact=perSeedUnique(T,R,field)
exact=true;
for seed=R.seeds'
    value=T.(field)(T.seed==seed);
    exact=exact&&~isempty(value)&&isscalar(unique(value));
end
end


function value=armValues(T,R,arm,field)
value=nan(numel(R.seeds),1);
for k=1:numel(R.seeds)
    index=T.seed==R.seeds(k)&string(T.arm)==string(arm);
    if nnz(index)~=1, error('exp23ai: missing paired arm row.'); end
    value(k)=T.(field)(index);
end
end


function S=summaryTable(T)
[group,S]=findgroups(T(:,{'arm','kind','fault','emergencyEnabled'}));
S.nRuns=splitapply(@numel,T.MISSION_RMSE,group);
S.motionAuthorizationRate=splitapply(@omitMean,T.motionAuthorized,group);
S.reactivationRate=splitapply(@omitMean,T.allReactivated,group);
S.meanMissionRmse=splitapply(@omitMean,T.MISSION_RMSE,group);
S.minimumSeparation=splitapply(@min,T.MINSEP,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);
S.radialContractPassRate=splitapply( ...
    @omitMean,T.radialTheoremCertified,group);
S.maximumRadialRatio=splitapply( ...
    @omitMax,T.criticalRadialMaximumRatio,group);
S.maximumTransactionFailureBound=splitapply( ...
    @omitMax,T.transactionFailureUpperBound,group);
S.maximumObservedControlBytes=splitapply( ...
    @omitMax,T.observedControlBytes,group);
S.meanManagementAirtime=splitapply(@omitMean,T.MANAGEMENT_AIRTIME,group);
S.meanTotalCost=splitapply(@omitMean,T.TOTAL_COST,group);
end


function P=pairedTable(T,R)
pairs={ ...
    'response_no_emergency_minus_protected', ...
    'closure-response-blackout-no-emergency', ...
    'closure-response-blackout-emergency'; ...
    'normal_closure_minus_periodic', ...
    'closure-iid20-emergency','periodic-iid20'};
P=table();
for k=1:size(pairs,1)
    a=armValues(T,R,pairs{k,2},'MISSION_RMSE');
    b=armValues(T,R,pairs{k,3},'MISSION_RMSE');
    c=armValues(T,R,pairs{k,2},'TOTAL_COST');
    d=armValues(T,R,pairs{k,3},'TOTAL_COST');
    block=table(string(pairs{k,1}),numel(a),mean(a-b),min(a-b), ...
        max(a-b),mean(c-d),'VariableNames',{'contrast','nPairs', ...
        'meanDeltaMissionRmse','minimumDeltaMissionRmse', ...
        'maximumDeltaMissionRmse','meanDeltaTotalCost'});
    P=[P;block]; %#ok<AGROW>
end
end


function value=omitMean(x)
value=mean(x,'omitnan');
end


function value=omitMax(x)
if all(isnan(x)), value=NaN; else, value=max(x,[],'omitnan'); end
end


