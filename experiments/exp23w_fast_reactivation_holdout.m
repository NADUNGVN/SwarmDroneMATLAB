end


function [sourceHash,sourceLeaves]=snapshotSource(target)

root=projectRoot();
files={'docs/EXP23W_FAST_REACTIVATION_HOLDOUT_PLAN.md', ...
    'docs/EXP23V_FAST_REACTIVATION_DEVELOPMENT_RESULTS_2026-09-04.md', ...
    'docs/EXP23V_WITNESS_CONFIRMED_REACTIVATION_DESIGN.md', ...
    'network/simulateElcsWitnessScheduling.m', ...
    'network/buildElcsWitnessContinuousSchedule.m', ...
    'network/applySharedBackgroundToElcsWitnessTrace.m', ...
    'utils/exp23wFastReactivationHoldoutRegistry.m', ...
    'utils/analyzeExp23wFastReactivation.m', ...
    'utils/runExp23uDynamicClosedLoopSeed.m', ...
    'utils/runExp23cWitnessClosedLoopCell.m', ...
    'utils/exp23uDynamicClosedLoopEnvelopeEmptyRow.m', ...
    'utils/pairedBootstrapCI.m','utils/holmAdjustP.m', ...
    'utils/writeTableAtomic.m', ...
    'tests/test_exp23w_fast_reactivation_holdout_contracts.m', ...
    'tests/test_exp23w_fast_reactivation_analysis_contracts.m', ...
    'tests/test_elcs_dynamic_revocation_contracts.m', ...
    'tests/test_elcs_dynamic_continuous_integration_contracts.m', ...
    'experiments/exp23w_fast_reactivation_holdout.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    fileName=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,fileName));
end
[sourceHash,sourceLeaves,names]=hashFreezeDir(freeze);
manifest=struct('algorithm','configHash over sorted path/content records', ...
    'sourceHash',sourceHash,'sourceLeaves',sourceLeaves, ...
    'fileCount',numel(names),'files',{names});
writeJson(fullfile(target,'source_manifest.json'),manifest);

end


function [sourceHash,sourceLeaves,names]=hashFreezeDir(freeze)

listing=dir(freeze); listing=listing(~[listing.isdir]);
names=sort({listing.name});
records=repmat(struct('name','','content',''),numel(names),1);
for k=1:numel(names)
    records(k).name=names{k};
    records(k).content=fileread(fullfile(freeze,names{k}));
end
[sourceHash,sourceLeaves]=configHash(records);

end


function expRun=resumeRun(runDir,registryHash,registryLeaves,name)

if ~isfolder(runDir), error('exp23w: resume directory not found.'); end
opened=jsondecode(fileread(fullfile(runDir,'holdout_opened.json')));
if opened.registryHash~=registryHash || opened.registryLeaves~=registryLeaves
    error('exp23w: registry differs from opened holdout.');
end
[~,runId]=fileparts(runDir);
meta=struct('experiment',name,'runId',runId,'startedAt',opened.openedAt, ...
    'matlabVersion',version,'matlabRelease',version('-release'), ...
    'computer',computer,'projectRoot',projectRoot(),'gitCommit','', ...
    'notes','resumed frozen EXP23W checkpoint');
expRun=struct('name',name,'runId',runId,'dir',runDir, ...
    'figDir',fullfile(runDir,'figures'),'expRoot',fileparts(runDir), ...
    'meta',meta,'t0',tic);

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('exp23w: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));

end


function value=ternary(condition,a,b)

if condition, value=a; else, value=b; end

end
