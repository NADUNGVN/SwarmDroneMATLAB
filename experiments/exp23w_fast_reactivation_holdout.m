function exp23w_fast_reactivation_holdout(resumeDir)
%EXP23W_FAST_REACTIVATION_HOLDOUT Preregistered fixed-graph confirmation.

if nargin<1, resumeDir=''; end
startup; close all;
R=exp23wFastReactivationHoldoutRegistry();
[registryHash,registryLeaves]=configHash(R);
expectedRegistryHash=174479477;
expectedRegistryLeaves=159;
if registryHash~=expectedRegistryHash || registryLeaves~=expectedRegistryLeaves
    error(['exp23w: frozen registry hash mismatch (got %.0f/%d; ' ...
        'expected %.0f/%d).'],registryHash,registryLeaves, ...
        expectedRegistryHash,expectedRegistryLeaves);
end
name='exp23w_fast_reactivation_holdout';

if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(name, ...
        'Frozen 100-seed fixed-graph fast-reactivation confirmation.');
    writeJson(fullfile(expRun.dir,'frozen_registry.json'),R);
    [sourceHash,sourceLeaves]=snapshotSource(expRun.dir);
    opened=struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'sourceHash',sourceHash,'sourceLeaves',sourceLeaves, ...
        'firstSeed',R.seeds(1),'lastSeed',R.seeds(end), ...
        'freshSeedEvidence',true,'confirmatory',true, ...
        'performanceInspectedBeforeOpen',false, ...
        'policyMayChange',false,'matrixMayChange',false, ...
        'analysisMayChange',false,'primaryFamilySize',R.primaryFamilySize, ...
        'submissionClaimPermitted',false);
    writeJson(fullfile(expRun.dir,'holdout_opened.json'),opened);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,name);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
pending=find(~completed); checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=2;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending)); index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runExp23uDynamicClosedLoopSeed(R.seeds(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  seeds %3d--%3d / %3d; rows %4d / %4d\n', ...
        index(1),index(end),numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=integrityGates(T,R,registryHash,registryLeaves,expRun.dir, ...
    expectedRegistryHash,expectedRegistryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
structuralPass=all(gates.passed==1);
if structuralPass
    analysis=analyzeExp23wFastReactivation(T,R);
    P=analysis.primary;
    F=analysis.frontier;
    E=analysis.effects;
    writetable(P,fullfile(expRun.dir,'primary_tests.csv'));
    writetable(F,fullfile(expRun.dir,'frontier_audit.csv'));
    writetable(E,fullfile(expRun.dir,'effects.csv'));
    primaryPass=analysis.primaryPass;
    frontierPass=analysis.frontierPass;
    primaryRejected=sum(P.rejectAfterHolm);
    primaryTotal=height(P);
else
    P=table(); F=table(); E=table();
    primaryPass=false; frontierPass=false;
    primaryRejected=0; primaryTotal=0;
end

if ~structuralPass
    status='FAST_REACTIVATION_HOLDOUT_INVALID';
    next='repair_confirmation_infrastructure_without_replacing_seeds';
elseif ~(primaryPass && frontierPass)
    status='FAST_REACTIVATION_FIXED_GRAPH_NOT_CONFIRMED';
    next='retain_negative_confirmation_and_return_to_design';
else
    status='FAST_REACTIVATION_FIXED_GRAPH_CONFIRMED';
    next='online_union_graph_migration_validation';
end
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'primaryTestsRejected',primaryRejected, ...
    'primaryTestsTotal',primaryTotal,'frontierGuardPassed',frontierPass, ...
    'freshSeedEvidence',true,'fixedGraphOnly',true, ...
    'graphMigrationValidated',false, ...
    'submissionClaimPermitted',false,'next',next);
writeJson(fullfile(expRun.dir,'holdout_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','gates','P','F','E', ...
    'verdict','R','-v7.3');

fprintf('\nEXP23W integrity gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
if structuralPass
    fprintf('\nEXP23W six-test Holm family\n');
    disp(P(:,{'id','meanDelta','bootstrapLo','bootstrapHi', ...
        'oneSidedPRaw','holmAdjustedP','rejectAfterHolm'}));
    fprintf('EXP23W frontier audit\n');
    disp(F);
end
fprintf('EXP23W DECISION: %s\n',status);
finishExperiment(expRun);
if ~structuralPass
    error('exp23w: holdout infrastructure invalid; resume same run only.');
end

end


function gates=integrityGates(T,R,registryHash,registryLeaves,runDir, ...
    expectedHash,expectedLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_contract',registryHash==expectedHash && ...
    registryLeaves==expectedLeaves,sprintf('hash %.0f over %d leaves', ...
    registryHash,registryLeaves));
artifacts=isfile(fullfile(runDir,'holdout_opened.json')) && ...
    isfile(fullfile(runDir,'frozen_registry.json')) && ...
    isfile(fullfile(runDir,'source_manifest.json')) && ...
    isfolder(fullfile(runDir,'frozen_source'));
add('pre_run_freeze_artifacts',artifacts, ...
    'opening record, frozen registry, source manifest and snapshot exist');
sourceOk=false; sourceDetail='source manifest unavailable';
if artifacts
    manifest=jsondecode(fileread(fullfile(runDir,'source_manifest.json')));
    [sourceHash,sourceLeaves]=hashFreezeDir(fullfile(runDir,'frozen_source'));
    sourceOk=sourceHash==manifest.sourceHash && ...
        sourceLeaves==manifest.sourceLeaves;
    sourceDetail=sprintf('source hash %.0f over %d leaves', ...
        sourceHash,sourceLeaves);
end
add('frozen_source_hash',sourceOk,sourceDetail);
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
add('exact_holdout_seeds',isequal(unique(T.seed),R.seeds) && ...
    min(T.seed)>R.priorSeedUpperBound, ...
    'all and only 100 registered seeds are disjoint from prior blocks');
declared=sort(reshape(string({R.arms.id}),[],1)); coverage=true;
for seed=R.seeds'
    index=T.seed==seed;
    coverage=coverage && nnz(index)==numel(R.arms) && ...
        isequal(sort(string(T.arm(index))),declared);
end
add('exact_arm_coverage',coverage,'all eight arms occur once per seed');
paired=true;
for seed=R.seeds'
    index=T.seed==seed;
    paired=paired && isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
        isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
        max(T.BACKGROUND_BUSY_TIME(index))-min( ...
        T.BACKGROUND_BUSY_TIME(index))<=1e-9;
end
add('paired_realizations',paired, ...
    'channel, estimator, clocks and shared occupancy pair by seed');
fast=ismember(string(T.arm),string(R.fastArms));
scheduled=string(T.arm)~=string(R.periodicArm);
add('mode_assignment_exact',all( ...
    T.ELCSW_WITNESS_CONFIRMED_REACTIVATION(fast)==1) && all( ...
    T.ELCSW_WITNESS_CONFIRMED_REACTIVATION(scheduled & ~fast)==0) && ...
    all(isnan(T.ELCSW_WITNESS_CONFIRMED_REACTIVATION(~scheduled))), ...
    'four fast arms enabled; static/conservative/periodic modes exact');
dynamic=T.DYNAMIC_ENABLED==1;
add('dynamic_event_stimulus',all(T.PHYSICAL_EVENT_INCLUDED(dynamic)==1) && ...
    all(T.PHYSICAL_PRE_EVENT_ACTIVE(dynamic)==1) && all( ...
    T.PHYSICAL_EVENT_SUPPRESSED(dynamic)==1), ...
    'all 600 dynamic events follow positive state and suppress locally');
add('exact_revoke_mapping',all(T.PHYSICAL_REVOKE_ATTEMPTS(dynamic)==1) && ...
    all(T.PHYSICAL_REVOKE_BYTES(dynamic)==24) && all(abs( ...
    T.PHYSICAL_REVOKE_AIRTIME(dynamic)-24*8/250e3)<=1e-15), ...
    'one exact 24-byte common-PHY REVOKE per dynamic trajectory');
normalFast=ismember(string(T.arm),string({R.fastEarlyArm, ...
    R.fastRevokeBlackoutArm,R.fastLateArm}));
add('fresh_response_reactivation',all( ...
    T.PHYSICAL_REACQUIRED(normalFast)==1) && all( ...
    T.FIRST_PHYSICAL_REACQUIRED_FRAME(normalFast)>= ...
    T.REACQUIRE_ELIGIBLE_FRAME(normalFast)) && all( ...
    T.PHYSICAL_FINAL_SUPPRESSED(normalFast)==0),sprintf( ...
    '%d/%d normal fast rows reactivate after eligibility', ...
    sum(T.PHYSICAL_REACQUIRED(normalFast)),nnz(normalFast)));
add('old_fence_bypass',all( ...
    T.FIRST_PHYSICAL_REACQUIRED_FRAME(normalFast)< ...
    T.CAPTURED_FENCE_FRAME(normalFast)), ...
    'fresh incident-witness closure reuses before old fence');
delivered=sortrows(T(string(T.arm)==string(R.fastEarlyArm),:),'seed');
lost=sortrows(T(string(T.arm)==string(R.fastRevokeBlackoutArm),:),'seed');
revokeEquivalent=isequal(delivered.seed,lost.seed) && all( ...
    delivered.PHYSICAL_SUPPRESSION_HASH_EXACT== ...
    lost.PHYSICAL_SUPPRESSION_HASH_EXACT) && all( ...
    delivered.PHYSICAL_REACQUIRED_HASH_EXACT== ...
    lost.PHYSICAL_REACQUIRED_HASH_EXACT) && all(abs( ...
    delivered.RMSE-lost.RMSE)<=1e-12) && all(abs( ...
    delivered.TOTAL_OFFERED_UTIL-lost.TOTAL_OFFERED_UTIL)<=1e-12);
add('revoke_blackout_equivalence',revokeEquivalent, ...
    'REVOKE delivery cannot alter local suppression, reuse or endpoint metrics');
blocked=string(T.arm)==string(R.fastResponseBlackoutArm);
add('response_blackout_fail_silent',all( ...
    T.REACQUIRE_BLOCKED_WITNESSES(blocked)>0) && all( ...
    T.PHYSICAL_REACQUIRED(blocked)==0) && all( ...
    T.PHYSICAL_FINAL_SUPPRESSED(blocked)==1), ...
    'missing required witness RESPONSE leaves sender suppressed');
candidate=scheduled;
add('candidate_safety',all(T.ELCSW_FALSE_VALID_EDGE_FRAMES(candidate)==0) && ...
    all(T.ELCSW_SCHEDULED_COLLISION_FRAMES(candidate)==0) && all( ...
    T.SAFEFAIL(candidate)==0) && all(T.DIVERGED(candidate)==0), ...
    'zero certificate, collision, safety or divergence failures');
add('exact_continuous_replay',all( ...
    T.ELCSW_DATA_SKIPPED_NO_QUEUE(candidate)==0) && all( ...
    T.ELCSW_DATA_OUTCOME_MISMATCHES(candidate)==0) && all( ...
    T.ELCSW_DATA_COLLISION_WITNESS_MATCH(candidate)==1) && all( ...
    T.ELCSW_CROSS_PLANE_OVERLAPS(candidate)==0) && all( ...
    T.ELCSW_CLOCK_TIMING_CONFLICT_FREE(candidate)==1), ...
    'DATA/control outcomes and affine-clock timeline replay exactly');
add('management_airtime_accounting',all( ...
    T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE(candidate)==1) && all( ...
    T.ELCSW_MANAGEMENT_ATTEMPTS(candidate)== ...
    T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS(candidate)) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME(candidate))<=1e-12) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_CONTROL_BYTES_AIRTIME(candidate))<=1e-12), ...
    'management attempts, bytes, recipients and airtime close');
add('shared_background_certificate',all( ...
    T.ELCSW_BACKGROUND_OVERLAY_APPLIED(candidate)==1) && all( ...
    T.ELCSW_BACKGROUND_TRACE_HASH_EXACT(candidate)== ...
    T.TRACE_HASH_EXACT(candidate)) && all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS(candidate)>0), ...
    'every certified schedule composes its paired IID-15 trace');
add('absolute_control_bounds',all( ...
    T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)<=1+1e-12) && all( ...
    T.ELCSW_BYTE_BOUND_RATIO(candidate)<=1+1e-12), ...
    'absolute management attempt and byte bounds hold');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
add('causal_recipient_airtime',all(abs( ...
    T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && all( ...
    T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && all( ...
    T.FUTURE_RANDOM_READS==0) && all(T.RECEIVER_TRUTH_READS==0) && ...
    all(T.INVARIANT_VIOLATIONS==0), ...
    'recipient/airtime accounting closes with zero forbidden reads');
add('confirmatory_scope',R.confirmatory && R.freshSeedEvidence && ...
    ~R.policyOptimizationAllowed && ~R.broadRobustnessClaimPermitted && ...
    R.confirmedFixedGraphPromotionPermitted && ...
    ~R.submissionClaimPermitted, ...
    'fresh holdout may promote only the fixed-graph mechanism');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23w: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'arm','methodLabel'}));
S.nRuns=splitapply(@numel,T.RMSE,group);
S.meanRMSE=splitapply(@mean,T.RMSE,group);
S.meanOfferedUtil=splitapply(@mean,T.TOTAL_OFFERED_UTIL,group);
S.meanManagementAirtime=splitapply(@mean,T.TOTAL_MANAGEMENT_AIRTIME,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);

end


function [rows,completed]=loadCheckpoint(runDir,R)

completed=false(size(R.seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23uDynamicClosedLoopEnvelopeEmptyRow(),0,1); return;
end
T=readtable(path,'TextType','string'); rows=table2struct(T);
for q=1:numel(R.seeds)
    index=T.seed==R.seeds(q);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23w: partial checkpoint seed.'); end
end

end


