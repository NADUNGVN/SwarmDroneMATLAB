    variantFiles={'docs/EXP23R_COHERENCE_PACKET_GRAPH_REPAIR_PLAN.md', ...
        'docs/EXP23Q_BROADCAST_GRAPH_REPAIR_RESULTS_2026-09-04.md', ...
        'docs/EXP23P_INVALID_COHERENCE_PACKET_RESULTS_2026-09-04.md', ...
        'utils/exp23rCoherencePacketRepairRegistry.m', ...
        'tests/test_exp23r_coherence_packet_repair_contracts.m', ...
        'tests/test_exp23q_broadcast_graph_repair_contracts.m', ...
        'experiments/exp23r_coherence_packet_graph_repair.m'};
else
    variantFiles={'docs/EXP23P_COHERENCE_PACKET_KERNEL_PLAN.md', ...
        'docs/EXP23O_BROADCAST_COHERENCE_RESULTS_2026-09-04.md', ...
        'utils/exp23pCoherencePacketRegistry.m', ...
        'tests/test_exp23p_coherence_packet_contracts.m'};
end
files=[variantFiles, { ...
    'docs/EXP23L_COHERENCE_CERTIFIED_LEASE_DESIGN.md', ...
    'network/buildSenderConflictGraph.m', ...
    'network/buildReachableConflictSupergraph.m', ...
    'network/buildReachableBroadcastConflictSupergraph.m', ...
    'network/selectCoherenceLeaseHorizon.m', ...
    'network/coherenceSelfRevocationDecision.m', ...
    'network/applyCoherenceLeaseConfig.m', ...
    'network/simulateElcsWitnessScheduling.m', ...
    'utils/exp23pCoherencePacketEmptyRow.m', ...
    'utils/runExp23pCoherencePacketCell.m', ...
    'tests/test_elcs_coherence_integration_contracts.m', ...
    'experiments/exp23p_coherence_packet_kernel.m'}];
