function exp23p_coherence_packet_kernel(resumeDir,variant)
%EXP23P_COHERENCE_PACKET_KERNEL Fresh geometry-to-packet falsification.

if nargin<1, resumeDir=''; end
if nargin<2, variant='p'; end
startup;
close all;
switch lower(variant)
    case 'p'
        R=exp23pCoherencePacketRegistry();
        experimentName='exp23p_coherence_packet_kernel';
        label='EXP23P';
        validStatus='COHERENCE_ELCS_W_PACKET_KERNEL_VALID';
        invalidStatus='COHERENCE_ELCS_W_PACKET_KERNEL_INVALID';
        description=['Fresh coherence-aware ELCS-W packet-kernel ' ...
            'validation under control loss, occupancy, no-lease and blackout.'];
    case 'r'
        R=exp23rCoherencePacketRepairRegistry();
        experimentName='exp23r_coherence_packet_graph_repair';
        label='EXP23R';
        validStatus='COHERENCE_ELCS_W_GRAPH_REPAIR_PACKET_KERNEL_VALID';
        invalidStatus='COHERENCE_ELCS_W_GRAPH_REPAIR_PACKET_KERNEL_INVALID';
        description=['Fresh packet-kernel validation after receiver ' ...
            'detectability graph repair.'];
    otherwise
        error('exp23p: unknown study variant %s.',variant);
end
[registryHash,registryLeaves]=configHash(R);
if isempty(resumeDir)
    runRequiredTests(variant);
    expRun=startExperiment(experimentName,description);
    writeJson(fullfile(expRun.dir,'packet_registry.json'),R);
    writeJson(fullfile(expRun.dir,'packet_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir,variant);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
[seedIndex,nodeIndex,geometryIndex]=groups(R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'packet_checkpoint.csv');
batchSize=5;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        seed=R.seeds(seedIndex(index(q)));
        N=R.nodeCounts(nodeIndex(index(q)));
        base=generateExp23mCoherenceBase(seed,N,R);
        geometry=R.conditions(geometryIndex(index(q)));
        local=repmat(exp23pCoherencePacketEmptyRow(), ...
            numel(R.conditionsNetwork),1);
        for n=1:numel(R.conditionsNetwork)
            local(n)=runExp23pCoherencePacketCell(base,geometry, ...
                geometryIndex(index(q)),R.conditionsNetwork(n),n,R);
        end
        batch{q}=local;
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  groups %3d--%3d / %3d; rows %4d / %4d\n', ...
        index(1),index(end),numel(completed),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'packet_tidy.csv'));
S=summaryTable(T);
writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,validStatus,invalidStatus);
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'staticCommonPhyIntegrationPermitted',pass, ...
    'dynamicRevocationIntegrationPermitted',pass, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'packet_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','gates','verdict','R');

fprintf('\n%s coherence packet-kernel gates\n',label);
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\n%s DECISION: %s\n',label,status);
finishExperiment(expRun);
if ~pass, error('%s: coherence packet kernel invalid.',lower(label)); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.N)+'|'+ ...
    string(T.geometryCondition)+'|'+string(T.networkCondition);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(unique(T.N)',R.nodeCounts) && isequal( ...
    sort(unique(string(T.geometryCondition))), ...
    sort(reshape(string({R.conditions.id}),[],1))) && isequal( ...
    sort(unique(string(T.networkCondition))), ...
    sort(reshape(string({R.conditionsNetwork.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '50 seeds, N5/N10, three geometry and six channel cells exact');
paired=true;
for seed=R.seeds'
    for N=R.nodeCounts
        for geometry=R.conditions
            index=T.seed==seed & T.N==N & ...
                string(T.geometryCondition)==string(geometry.id);
            paired=paired && nnz(index)==numel(R.conditionsNetwork) && ...
                isscalar(unique(T.BASE_GEOMETRY_HASH(index))) && ...
                isscalar(unique(T.DATA_NEIGHBOR_GRAPH_HASH(index))) && ...
                isscalar(unique(T.MANAGEMENT_GRAPH_HASH(index))) && ...
                isscalar(unique(T.SELECTOR_HASH_EXACT(index))) && ...
                isscalar(unique(T.BASE_TRACE_HASH_EXACT(index))) && ...
                isscalar(unique(T.BACKGROUND_TRACE_HASH_EXACT(index)));
        end
    end
end
add('paired_absolute_realizations',paired, ...
    'geometry, receiver graph, selector, packet draws and occupancy pair');
add('coherence_mode_exact',all(T.COHERENCE_ENABLED==1) && ...
    all(T.CUMULATIVE_RECEIPT_RETRY==1), ...
    'every row uses coherence binding and cumulative receipts');
format=all(T.CLAIM_PACKET_BYTES==28) && all( ...
    T.CERTIFICATE_HEADER_BYTES==16) && all( ...
    T.CERTIFICATE_ENTRY_BYTES==10) && all( ...
    T.REVOKE_PACKET_BYTES==24);
add('packet_format_exact',format, ...
    '28-byte CLAIM, 16+10e RESPONSE and 24-byte REVOKE exact');
add('packet_mtu_closure',all(T.PACKET_MTU_VIOLATIONS==0) && ...
    all(T.MAX_RESPONSE_PACKET_BYTES<=96),sprintf( ...
    'maximum observed response packet %.0f bytes', ...
    max(T.MAX_RESPONSE_PACKET_BYTES)));
admitted=T.COHERENCE_ADMISSIBLE==1;
inadmissible=~admitted;
add('admitted_binding_exact',all(T.COHERENCE_HORIZON_FRAMES(admitted)== ...
    T.LEASE_FRAMES(admitted)) && all(T.RENEWAL_PERIOD_FRAMES(admitted)== ...
    T.LEASE_FRAMES(admitted)-6-1) && all( ...
    T.SELECTED_CONFLICT_EDGES(admitted)==T.CONFLICT_EDGES(admitted)), ...
    'lease horizon, renewal slack and certified sender graph bind exactly');
add('inadmissible_fail_silent',all(T.CONTROL_ATTEMPTS(inadmissible)==0) && ...
    all(T.SCHEDULED_ATTEMPTS(inadmissible)==0) && all( ...
    T.FINAL_ALL_CERTIFIED(inadmissible)==0) && all( ...
    T.FALSE_VALID_EDGE_FRAMES(inadmissible)==0), ...
    'no/too-short horizon produces no control or scheduled validity');
nonblackout=string(T.networkCondition)~=string(R.blackoutCondition);
add('admitted_nonblackout_liveness',all( ...
    T.FINAL_ALL_CERTIFIED(admitted & nonblackout)==1) && all(isfinite( ...
    T.FIRST_ALL_CERTIFIED_FRAME(admitted & nonblackout))),sprintf( ...
    '%d/%d admitted nonblackout rows terminally certify', ...
    sum(T.FINAL_ALL_CERTIFIED(admitted & nonblackout)), ...
    nnz(admitted & nonblackout)));
add('global_certificate_safety',all(T.FALSE_VALID_EDGE_FRAMES==0) && ...
    all(T.SCHEDULED_COLLISION_FRAMES==0) && all( ...
    T.CERTIFICATE_WITHOUT_FRESH_CLAIMS==0), ...
    'zero false-valid, scheduled-collision and unsupported certificates');
blackout=string(T.networkCondition)==string(R.blackoutCondition) & admitted;
stimulated=blackout & T.BLACKOUT_APPLIED==1;
add('blackout_stimulus',any(stimulated),sprintf( ...
    '%d admitted rows lose one required witness response permanently', ...
    nnz(stimulated)));
add('blackout_fail_silent',all(T.FINAL_ALL_CERTIFIED(stimulated)==0) && ...
    all(T.FALSE_VALID_EDGE_FRAMES(stimulated)==0) && all( ...
    T.SCHEDULED_COLLISION_FRAMES(stimulated)==0), ...
    'missing required response never creates complete validity');
account=all(T.ACCOUNTING_CLOSES==1) && all( ...
    T.CLAIM_BYTES==T.CLAIM_ATTEMPTS.*T.CLAIM_PACKET_BYTES) && all( ...
    T.CONTROL_BYTES==T.CLAIM_BYTES+T.CERTIFICATE_BYTES) && all( ...
    T.MAX_FALLBACK_ATTEMPTS_PER_NODE_FRAME<=1);
add('attempt_byte_recipient_accounting',account, ...
    'control bytes and management/DATA recipient partitions close');
add('absolute_control_bounds',all(T.CONTROL_ATTEMPT_BOUND_RATIO<=1+1e-12) && ...
    all(T.CONTROL_BYTE_BOUND_RATIO<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.CONTROL_ATTEMPT_BOUND_RATIO),max(T.CONTROL_BYTE_BOUND_RATIO)));
loss=ismember(string(T.networkCondition), ...
    ["claim-iid5" "response-iid5" "joint-control-iid5" ...
    "iid-occupancy15"]) & admitted;
add('loss_retry_stimulus',any(T.RETRY_CLAIM_ATTEMPTS(loss)>0) && ...
    any(T.BACKGROUND_POTENTIAL_HITS(string(T.networkCondition)== ...
    string(R.backgroundCondition) & admitted)>0), ...
    'loss and fragmented occupancy activate same-sequence retry');
selectorNo=T.SELECTED_HORIZON_INDEX==0;
bindingRejected=T.SELECTED_HORIZON_INDEX>0 & inadmissible;
target=T.SELECTED_HORIZON_SEC==R.horizonsSec(end);
contracted=T.SELECTED_HORIZON_INDEX>0 & ~target;
add('selector_binding_branch_stimulus',any(target) && any(contracted) && ...
    any(selectorNo) && any(bindingRejected) && any(admitted),sprintf( ...
    'target/contract/no-selector/binding-reject/admit %d/%d/%d/%d/%d', ...
    nnz(target),nnz(contracted),nnz(selectorNo),nnz(bindingRejected), ...
    nnz(admitted)));
add('hidden_sender_witness_stimulus',any( ...
    T.SELECTED_HIDDEN_EDGES(admitted)>0) && all( ...
    T.MAX_WITNESS_LOAD(admitted)<=8),sprintf( ...
    'maximum witness load %.0f with receiver-lifted hidden edges', ...
    max(T.MAX_WITNESS_LOAD(admitted))));
add('revocation_not_yet_claimed',all(T.SELF_REVOCATIONS==0) && ...
    all(T.REVOKE_ATTEMPTS==0) && all(T.REVOKE_BYTES==0), ...
    'static per-run packet kernel does not claim dynamic revocation');
add('causal_kernel_scope_only',all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && ~R.policyOptimizationAllowed && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted, ...
    'causal kernel only; no closed-loop, promotion or submission claim');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23p: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function S=summaryTable(T)
[group,S]=findgroups(T(:,{'N','geometryCondition','networkCondition', ...
    'bindingReason'}));
S.nRuns=splitapply(@numel,T.CONTROL_ATTEMPTS,group);
S.admissionRate=splitapply(@mean,T.COHERENCE_ADMISSIBLE,group);
S.meanSelectedHorizonSec=splitapply(@mean,T.SELECTED_HORIZON_SEC,group);
S.terminalCertificationRate=splitapply(@mean,T.FINAL_ALL_CERTIFIED,group);
S.meanControlAttempts=splitapply(@mean,T.CONTROL_ATTEMPTS,group);
S.meanControlBytes=splitapply(@mean,T.CONTROL_BYTES,group);
S.meanRetryClaims=splitapply(@mean,T.RETRY_CLAIM_ATTEMPTS,group);
S.falseValidEdgeFrames=splitapply(@sum,T.FALSE_VALID_EDGE_FRAMES,group);
S.scheduledCollisionFrames=splitapply(@sum,T.SCHEDULED_COLLISION_FRAMES,group);
end


function [seedIndex,nodeIndex,geometryIndex]=groups(R)
nNode=numel(R.nodeCounts); nGeometry=numel(R.conditions);
seedIndex=repelem((1:numel(R.seeds))',nNode*nGeometry);
nodeIndex=repmat(repelem((1:nNode)',nGeometry),numel(R.seeds),1);
geometryIndex=repmat((1:nGeometry)',numel(R.seeds)*nNode,1);
end


function [rows,completed]=loadCheckpoint(runDir,R)
[seedIndex,nodeIndex,geometryIndex]=groups(R);
completed=false(size(seedIndex));
path=fullfile(runDir,'packet_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23pCoherencePacketEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string'); rows=table2struct(T);
for q=1:numel(completed)
    seed=R.seeds(seedIndex(q)); N=R.nodeCounts(nodeIndex(q));
    geometry=R.conditions(geometryIndex(q));
    index=T.seed==seed & T.N==N & ...
        string(T.geometryCondition)==string(geometry.id);
    if nnz(index)==numel(R.conditionsNetwork), completed(q)=true;
    elseif any(index), error('exp23p: partial checkpoint group.'); end
end
end


function runRequiredTests(variant)
if strcmpi(variant,'r')
    leading={'test_exp23r_coherence_packet_repair_contracts', ...
        'test_exp23q_broadcast_graph_repair_contracts'};
else
    leading={'test_exp23p_coherence_packet_contracts', ...
        'test_exp23o_broadcast_coherence_contracts'};
end
names=[leading, { ...
    'test_coherence_certified_lease_contracts', ...
    'test_elcs_coherence_integration_contracts', ...
    'test_elcs_cumulative_receipt_contracts', ...
    'test_elcs_kernel_contracts'}];
for k=1:numel(names), runScriptIsolated(names{k}); end
end


