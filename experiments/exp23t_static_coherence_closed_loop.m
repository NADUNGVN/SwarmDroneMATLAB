function exp23t_static_coherence_closed_loop(resumeDir)
%EXP23T_STATIC_COHERENCE_CLOSED_LOOP Fresh common-PHY confirmation.

if nargin<1, resumeDir=''; end
startup; close all;
R=exp23tStaticCoherenceClosedLoopRegistry();
[registryHash,registryLeaves]=configHash(R);
name='exp23t_static_coherence_closed_loop';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(name, ...
        'Fresh static-coherence common-PHY closed-loop confirmation.');
    writeJson(fullfile(expRun.dir,'static_registry.json'),R);
    writeJson(fullfile(expRun.dir,'static_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,name);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
pending=find(~completed); checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=4;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending)); index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runExp23tStaticCoherenceSeed(R.seeds(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  seeds %3d--%3d / %3d; rows %3d / %3d\n', ...
        index(1),index(end),numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
D=mechanismContrast(T,R); writetable(D,fullfile(expRun.dir,'contrast.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
safetyNames=["candidate_safety" "candidate_terminal_liveness"];
safetyGate=ismember(string(gates.gate),safetyNames);
structuralPass=all(gates.passed(~safetyGate)==1);
safetyPass=all(gates.passed(safetyGate)==1);
mechanismPass=logical(D.mechanismPassed);
if ~structuralPass
    status='STATIC_COHERENCE_CLOSED_LOOP_INVALID';
    next='repair_common_phy_infrastructure';
elseif ~safetyPass
    status='STATIC_COHERENCE_CLOSED_LOOP_SAFETY_FAIL';
    next='reject_static_integration';
elseif ~mechanismPass
    status='STATIC_COHERENCE_MECHANISM_INSUFFICIENT';
    next='retain_negative_and_revisit_cost_horizon';
else
    status='STATIC_COHERENCE_COMMON_PHY_SURVIVES';
    next='design_dynamic_closed_loop_operating_envelope';
end
verdict=struct('status',status,'validationGatesPassed',sum(gates.passed), ...
    'validationGatesTotal',height(gates),'rows',height(T), ...
    'structuralIntegrityPassed',structuralPass, ...
    'candidateSafetyAndLivenessPassed',safetyPass, ...
    'mechanismPassed',mechanismPass, ...
    'periodicEpsilonDominanceFound',logical(D.periodicEpsilonDominates), ...
    'next',next,'freshSeedEvidence',true, ...
    'dynamicClosedLoopValidated',false, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'static_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','D','gates','verdict','R');

fprintf('\nEXP23T static coherence closed-loop gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf(['\nEXP23T EFFECT: management vs short %.2f%%; cost vs periodic ' ...
    '%.2f%%; RMSE vs short %.2f%%\n'], ...
    100*D.relativeManagementVsShort,100*D.relativeCostVsPeriodic, ...
    100*D.relativeRmseVsShort);
fprintf('EXP23T DECISION: %s\n',status);
finishExperiment(expRun);
if ~structuralPass
    error('exp23t: static closed-loop study structurally invalid.');
end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
parent=fullfile(projectRoot(),'results','exp23s_dynamic_revocation_kernel', ...
    R.parentDynamicRun,'dynamic_verdict.json');
parentVerdict=jsondecode(fileread(parent));
add('parent_dynamic_kernel_valid',strcmp(parentVerdict.status, ...
    R.parentDynamicStatus),'EXP23S fixed-supergraph lifecycle is valid');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && isequal( ...
    sort(unique(string(T.arm))),sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '100 fresh seeds and three paired common-PHY arms exact');
paired=true;
for seed=R.seeds'
    index=T.seed==seed;
    paired=paired && nnz(index)==numel(R.arms) && ...
        isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
        isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
        isscalar(unique(T.BACKGROUND_RANDOM_FIELD_HASH_EXACT(index))) && ...
        max(T.BACKGROUND_BUSY_TIME(index))-min(T.BACKGROUND_BUSY_TIME(index))<=1e-9;
end
add('paired_absolute_realizations',paired, ...
    'channel, estimator, clock and occupied busy time pair by seed');
candidate=string(T.arm)~=string(R.periodicArm);
short=string(T.arm)==string(R.shortArm);
target=string(T.arm)==string(R.targetArm);
periodic=string(T.arm)==string(R.periodicArm);
configuration=all(abs(T.STATIC_SELECTED_HORIZON_SEC(short)-1)<=1e-12) && ...
    all(abs(T.STATIC_SELECTED_HORIZON_SEC(target)-6.8)<=1e-12) && ...
    all(T.STATIC_CLAIM_PACKET_BYTES(candidate)==R.claimBytes) && ...
    all(T.STATIC_CERTIFICATE_HEADER_BYTES(candidate)== ...
    R.certificateHeaderBytes) && all( ...
    T.STATIC_CERTIFICATE_ENTRY_BYTES(candidate)==R.certificateEntryBytes) && ...
    all(T.STATIC_REVOKE_PACKET_BYTES(candidate)==R.revokeBytes);
add('coherence_configuration_exact',configuration, ...
    '1/6.8 s arms use exact 28/16+10e/24-byte metadata');
binding=all(T.STATIC_BINDING_ADMISSIBLE(candidate)==1) && ...
    all(T.STATIC_SELECTED_HORIZON_FRAMES(target)> ...
    T.STATIC_SELECTED_HORIZON_FRAMES(short)) && all( ...
    T.STATIC_CONFLICT_EDGES(candidate)==T.ELCSW_CONFLICT_EDGES(candidate));
add('static_certificate_binding',binding, ...
    'fixed graph binds admissibly and target horizon is longer');
certificate=all(T.ELCSW_BACKGROUND_OVERLAY_APPLIED(candidate)==1) && ...
    all(T.ELCSW_BACKGROUND_TRACE_HASH_EXACT(candidate)== ...
    T.TRACE_HASH_EXACT(candidate)) && all(abs( ...
    T.ELCSW_BACKGROUND_LOAD(candidate)-0.15)<=1e-12);
add('shared_background_certificate',certificate, ...
    'both coherence arms compose the same IID-15 occupancy trace');
add('background_stimulus_activation',all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS(candidate)>0) && ...
    all(T.BACKGROUND_BUSY_TIME>0), ...
    'occupancy intersects potential coherence transmissions');
add('periodic_boundary_and_timing',all(abs( ...
    T.PERIODIC_RATE_HZ(periodic)-R.cells.lowerCostRateHz)<1e-12) && ...
    all(T.ENDOGENOUS_COLLISION_FRAMES(periodic)==0) && all( ...
    T.CONTINUOUS_MAX_CLOCK_RESIDUAL(periodic)<=2e-12), ...
    'EXP23D lower-cost boundary remains continuously guarded');
add('witness_payload_mtu_closure',all( ...
    T.ELCSW_ALL_EDGES_COVERED(candidate)==1) && all( ...
    T.STATIC_MAX_RESPONSE_PACKET_BYTES(candidate)<=R.maxControlPacketBytes) && ...
    all(T.STATIC_MAX_WITNESS_LOAD(candidate)<=8),sprintf( ...
    'maximum observed response %.0f bytes', ...
    max(T.STATIC_MAX_RESPONSE_PACKET_BYTES(candidate))));
add('absolute_control_bounds',all( ...
    T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)<=1+1e-12) && all( ...
    T.ELCSW_BYTE_BOUND_RATIO(candidate)<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)), ...
    max(T.ELCSW_BYTE_BOUND_RATIO(candidate))));
replay=all(T.ELCSW_DATA_SKIPPED_NO_QUEUE(candidate)==0) && ...
    all(T.ELCSW_DATA_OUTCOME_MISMATCHES(candidate)==0) && ...
    all(T.ELCSW_DATA_COLLISION_WITNESS_MATCH(candidate)==1) && ...
    all(T.ELCSW_CROSS_PLANE_OVERLAPS(candidate)==0) && ...
    all(T.ELCSW_CLOCK_TIMING_CONFLICT_FREE(candidate)==1);
add('exact_continuous_replay',replay, ...
    'queue, outcome, clock and control/DATA contracts close');
management=all(T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE(candidate)==1) && ...
    all(T.ELCSW_MANAGEMENT_ATTEMPTS(candidate)== ...
    T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS(candidate)) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME(candidate))<=1e-12) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_CONTROL_BYTES_AIRTIME(candidate))<=1e-12);
add('variable_payload_management_accounting',management, ...
    'attempt, recipient, byte and airtime accounting close');
add('candidate_safety',all(T.ELCSW_FALSE_VALID_EDGE_FRAMES(candidate)==0) && ...
    all(T.ELCSW_SCHEDULED_COLLISION_FRAMES(candidate)==0) && all( ...
    T.ELCSW_CERTIFICATE_WITHOUT_FRESH_CLAIMS(candidate)==0) && ...
    all(T.SAFEFAIL(candidate)==0) && all(T.DIVERGED(candidate)==0), ...
    'zero certificate, collision, safety and divergence failures');
add('candidate_terminal_liveness',all( ...
    T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED(candidate)==1) && all( ...
    T.ELCSW_FINAL_OPEN_CLAIM_TRANSACTIONS(candidate)==0), ...
    'both coherence arms certify and close cumulative transactions');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
account=all(abs(T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && all( ...
    T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && all( ...
    T.CHANNEL_UTIL<=T.TOTAL_OFFERED_UTIL+ ...
    T.REALIZED_BACKGROUND_FRACTION+1e-9) && all( ...
    T.FUTURE_RANDOM_READS==0) && all(T.RECEIVER_TRUTH_READS==0) && ...
    all(T.INVARIANT_VIOLATIONS==0);
add('causal_recipient_airtime_scope',account && ...
    ~R.policyOptimizationAllowed && ~R.broadRobustnessClaimPermitted && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted, ...
    'causal accounting closes; static confirmation cannot promote');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23t: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function D=mechanismContrast(T,R)

P=sortrows(T(string(T.arm)==string(R.periodicArm),:),'seed');
S=sortrows(T(string(T.arm)==string(R.shortArm),:),'seed');
L=sortrows(T(string(T.arm)==string(R.targetArm),:),'seed');
mgmt=pairedBootstrapCI(L.ELCSW_MANAGEMENT_AIRTIME, ...
    S.ELCSW_MANAGEMENT_AIRTIME,R.bootstrapReplicates,R.bootstrapSeedBase+1, ...
    numel(R.seeds));
cost=pairedBootstrapCI(L.TOTAL_OFFERED_UTIL,P.TOTAL_OFFERED_UTIL, ...
    R.bootstrapReplicates,R.bootstrapSeedBase+2,numel(R.seeds));
rmse=pairedBootstrapCI(L.RMSE,S.RMSE,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+3,numel(R.seeds));
relativeMgmt=mean(L.ELCSW_MANAGEMENT_AIRTIME)/ ...
    mean(S.ELCSW_MANAGEMENT_AIRTIME)-1;
relativeCost=mean(L.TOTAL_OFFERED_UTIL)/mean(P.TOTAL_OFFERED_UTIL)-1;
relativeRmse=mean(L.RMSE)/mean(S.RMSE)-1;
periodicDominates=mean(P.RMSE)<=(1+R.epsilonRmse)*mean(L.RMSE) && ...
    mean(P.TOTAL_OFFERED_UTIL)<= ...
    (1-R.requiredCostImprovement)*mean(L.TOTAL_OFFERED_UTIL);
confidence=mgmt.hi<0 && cost.hi<0 && ...
    rmse.hi<=R.allowedRmseInflationVsShort*mean(S.RMSE);
mechanism=relativeMgmt<=-R.requiredManagementReduction && ...
    relativeCost<=-R.requiredPeriodicCostAdvantage && ...
    relativeRmse<=R.allowedRmseInflationVsShort && confidence && ...
    ~periodicDominates;
D=table(numel(R.seeds),mean(S.ELCSW_MANAGEMENT_AIRTIME), ...
    mean(L.ELCSW_MANAGEMENT_AIRTIME),relativeMgmt,mgmt.meanD,mgmt.lo,mgmt.hi, ...
    mean(P.TOTAL_OFFERED_UTIL),mean(L.TOTAL_OFFERED_UTIL),relativeCost, ...
    cost.meanD,cost.lo,cost.hi,mean(S.RMSE),mean(L.RMSE),relativeRmse, ...
    rmse.meanD,rmse.lo,rmse.hi,double(confidence), ...
    double(periodicDominates),double(mechanism), ...
    'VariableNames',{'nPairs','shortMeanManagementAirtime', ...
    'targetMeanManagementAirtime','relativeManagementVsShort', ...
    'managementDelta','managementCiLo','managementCiHi', ...
    'periodicMeanCost','targetMeanCost','relativeCostVsPeriodic', ...
    'costDelta','costCiLo','costCiHi','shortMeanRMSE','targetMeanRMSE', ...
    'relativeRmseVsShort','rmseDelta','rmseCiLo','rmseCiHi', ...
    'confidenceSupported','periodicEpsilonDominates','mechanismPassed'});
end


function S=summaryTable(T)
[group,S]=findgroups(T(:,{'arm','methodLabel'}));
S.nRuns=splitapply(@numel,T.RMSE,group);
S.meanRMSE=splitapply(@mean,T.RMSE,group);
S.meanOfferedUtil=splitapply(@mean,T.TOTAL_OFFERED_UTIL,group);
S.meanManagementAirtime=splitapply(@mean,T.TOTAL_MANAGEMENT_AIRTIME,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);
end


function [rows,completed]=loadCheckpoint(runDir,R)
completed=false(size(R.seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23tStaticCoherenceClosedLoopEmptyRow(),0,1); return;
end
T=readtable(path,'TextType','string'); rows=table2struct(T);
for q=1:numel(R.seeds)
    index=T.seed==R.seeds(q);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23t: partial checkpoint seed.'); end
end
end


