%% TCNS R2.5 ADVERSARIAL VALIDATION OF THE FROZEN R2 CLAIMS

startup;
close all;
R = startExperiment('tcns_r2_5_adversarial_validation', ...
    ['Adversarial audit of the already frozen R2 registry, numerical-rank ' ...
     'bookkeeping, persisted actual-action witnesses, normalization, and ' ...
     'coalitions. No registry expansion, scheduler, or held-out experiment.']);

repositoryRoot = fileparts(fileparts(mfilename('fullpath')));
r2Root = fullfile(repositoryRoot,'results', ...
    'tcns_r2_generalization_validation');
r2Id = strtrim(fileread(fullfile(r2Root,'LATEST.txt')));
r2Directory = fullfile(r2Root,r2Id);
audit = tcnsR25AdversarialAudit(r2Directory);

writetable(audit.registryTable, ...
    fullfile(R.dir,'registry_adversarial_audit.csv'));
writetable(audit.numericRankTable, ...
    fullfile(R.dir,'numerical_rank_diagnostic.csv'));
writetable(audit.fragileVpaTable, ...
    fullfile(R.dir,'fragile_vpa_diagnostic.csv'));
writetable(audit.witnessReplayTable, ...
    fullfile(R.dir,'actual_witness_independent_replay.csv'));
writetable(audit.normalizationTable, ...
    fullfile(R.dir,'practical_normalization_sensitivity.csv'));
writetable(audit.coalitionTable, ...
    fullfile(R.dir,'coalition_independent_audit.csv'));
writetable(audit.coalitionDistribution, ...
    fullfile(R.dir,'coalition_size_distribution.csv'));

summary.schemaVersion = 1;
summary.studyClass = audit.studyClass;
summary.gitCommit = R.meta.gitCommit;
summary.r2PushedHead = audit.r2PushedHead;
summary.r2Directory = audit.r2Directory;
summary.registryRowCount = height(audit.registryTable);
summary.modelInfeasibleCount = nnz(audit.registryTable.modelInfeasible);
summary.scientificResultExcludedCount = nnz( ...
    audit.registryTable.scientificResultExcluded);
summary.silentExclusionFailureCount = nnz( ...
    ~audit.registryTable.noSilentExclusion);
summary.numericDiagnosticRowCount = height(audit.numericRankTable);
summary.structurallyNonidentifiableCount = nnz( ...
    ~audit.numericRankTable.identifiable);
summary.storedRankMismatchCount = nnz( ...
    ~audit.numericRankTable.storedRankMatch);
summary.storedIdentifiabilityMismatchCount = nnz( ...
    ~audit.numericRankTable.storedIdentifiabilityMatch);
summary.maximumStoredResidualDifference = max( ...
    audit.numericRankTable.storedResidualDifference);
reference = audit.numericRankTable( ...
    audit.numericRankTable.tolerance==audit.options.referenceTolerance,:);
summary.maximumStoredResidualDifferenceAtReference = max( ...
    reference.storedResidualDifference);
summary.actionFunctionalCount = height(reference);
summary.rawRankStableActionCount = nnz(reference.storedActionRankStable);
summary.minimumNormalizedProjectionResidual = min( ...
    audit.numericRankTable.normalizedProjectionResidual);
summary.minimumSeparationMultipleAtLoosestTolerance = min( ...
    audit.numericRankTable.valueSeparationMultiple( ...
    audit.numericRankTable.tolerance==max(audit.options.toleranceGrid)));
summary.toleranceGrid = audit.options.toleranceGrid;
summary.rawAugmentedRankIncreaseCounts = arrayfun(@(tol) nnz( ...
    audit.numericRankTable.tolerance==tol & ...
    audit.numericRankTable.rawAugmentedRankIncrease==1), ...
    audit.options.toleranceGrid);
summary.normalizedBasisRankIncreaseCounts = arrayfun(@(tol) nnz( ...
    audit.numericRankTable.tolerance==tol & ...
    audit.numericRankTable.normalizedBasisRankIncrease==1), ...
    audit.options.toleranceGrid);
summary.vpaCaseCount = height(audit.fragileVpaTable);
summary.vpaFailureCount = nnz( ...
    audit.fragileVpaTable.failureReason~="NONE");
summary.witnessCount = height(audit.witnessReplayTable);
summary.witnessReplayPassCount = nnz(audit.witnessReplayTable.replayPass);
summary.fixedResponsePassCount = nnz( ...
    audit.witnessReplayTable.fixedResponseConsistent);
summary.minimumWitnessSignMarginOverTolerance = min( ...
    audit.witnessReplayTable.signMarginOverAcceptanceTolerance);
summary.minimumWitnessSaturationMargin = min( ...
    audit.witnessReplayTable.minimumSaturationMargin);
summary.maximumWitnessAffineOracleMismatch = max( ...
    audit.witnessReplayTable.affineOracleMismatch);
summary.normalizationFailureCount = nnz( ...
    audit.normalizationTable.failureReason~="NONE");
summary.maximumPersistedNormalizationDifference = max( ...
    audit.normalizationTable.persistedNormalizationDifference);
summary.maximumNormalizedMedianAbs = max( ...
    audit.normalizationTable.normalizedByMedianAbs);
summary.maximumNormalizedRms = max( ...
    audit.normalizationTable.normalizedByRms);
summary.maximumNormalizedIqrScale = max( ...
    audit.normalizationTable.normalizedByIqrScale);
summary.coalitionRowCount = height(audit.coalitionTable);
summary.coalitionMinimumSizeMismatchCount = nnz( ...
    ~audit.coalitionTable.storedMinimumSizeMatch);
summary.coalitionMultiplicityMismatchCount = nnz( ...
    ~audit.coalitionTable.storedMultiplicityMatch);
summary.noNewRegistryCell = audit.noNewRegistryCell;
summary.noSchedulerImplemented = audit.noSchedulerImplemented;
summary.noHeldOutSeedUsed = audit.noHeldOutSeedUsed;

fid = fopen(fullfile(R.dir,'summary.json'),'w');
assert(fid>0,'TCNSR25: cannot create summary.json.');
fprintf(fid,'%s\n',jsonencode(summary,'PrettyPrint',true));
fclose(fid);
fid = fopen(fullfile(R.dir,'actual_witness_independent_replay.json'),'w');
assert(fid>0,'TCNSR25: cannot create witness JSON.');
fprintf(fid,'%s\n',jsonencode(table2struct( ...
    audit.witnessReplayTable),'PrettyPrint',true));
fclose(fid);

save(fullfile(R.dir,'workspace.mat'),'audit','summary','r2Directory','-v7.3');

fprintf('R2.5 registry rows                 : %d\n',summary.registryRowCount);
fprintf('R2.5 silent-exclusion failures     : %d\n', ...
    summary.silentExclusionFailureCount);
fprintf('R2.5 numeric rows/non-ID           : %d / %d\n', ...
    summary.structurallyNonidentifiableCount, ...
    summary.numericDiagnosticRowCount);
fprintf('R2.5 raw-rank stable actions       : %d / %d\n', ...
    summary.rawRankStableActionCount,summary.actionFunctionalCount);
fprintf('R2.5 independent witness replay    : %d / %d\n', ...
    summary.witnessReplayPassCount,summary.witnessCount);
fprintf('R2.5 fixed-response consistency    : %d / %d\n', ...
    summary.fixedResponsePassCount,summary.witnessCount);
fprintf('R2.5 coalition-size mismatches     : %d\n', ...
    summary.coalitionMinimumSizeMismatchCount);
disp(audit.witnessReplayTable(:,{'actionId','qMinus','qPlus', ...
    'informationHistoryResidual','responseResidual', ...
    'minimumSaturationMargin','replayPass'}));
finishExperiment(R);
