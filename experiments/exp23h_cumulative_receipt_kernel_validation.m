function exp23h_cumulative_receipt_kernel_validation(resumeDir)
%EXP23H_CUMULATIVE_RECEIPT_KERNEL_VALIDATION Frozen paired kernel study.

if nargin<1, resumeDir=''; end
startup;
close all;
R=exp23hCumulativeReceiptRegistry();
[registryHash,registryLeaves]=configHash(R);
experimentName='exp23h_cumulative_receipt_kernel_validation';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(experimentName, ...
        ['Paired kernel falsification of same-sequence cumulative witness ' ...
        'receipts after EXP23G retry amplification.']);
    writeJson(fullfile(expRun.dir,'cumulative_registry.json'),R);
    writeJson(fullfile(expRun.dir,'cumulative_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'policyOptimizationAllowed',false, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
[seeds,cells,conditions]=groups(R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'kernel_checkpoint.csv');
batchSize=10;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runGroup(seeds(index(q)),cells(index(q)), ...
            conditions(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  groups %4d--%4d / %4d; rows %4d / %4d\n', ...
        index(1),index(end),numel(seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'kernel_tidy.csv'));
S=summaryTable(T);
writetable(S,fullfile(expRun.dir,'summary.csv'));
P=pairedEfficiency(T,R);
writetable(P,fullfile(expRun.dir,'paired_efficiency.csv'));
gates=validationGates(T,R,registryHash,registryLeaves,P);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'ELCS_W_CUMULATIVE_KERNEL_VALID', ...
    'ELCS_W_CUMULATIVE_KERNEL_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'closedLoopBackgroundRerunPermitted',pass, ...
    'newMethodPromotionAllowed',false, ...
    'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'cumulative_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','P','gates','verdict','R');

fprintf('\nEXP23H cumulative-receipt kernel gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23H DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23h: cumulative-receipt kernel invalid.'); end

end


function rows=runGroup(seedValue,cellIndex,conditionIndex,R)

cellInfo=R.cells(cellIndex);
condition=R.conditions(conditionIndex);
rows=repmat(exp23hCumulativeReceiptEmptyRow(),numel(R.modes),1);
for k=1:numel(R.modes)
    rows(k)=runExp23hCumulativeReceiptCell( ...
        seedValue,cellInfo,condition,R.modes(k),R);
end

end


function gates=validationGates(T,R,registryHash,registryLeaves,P)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.scenario)+'|'+ ...
    string(T.condition)+'|'+string(T.retryMode);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(sort(unique(string(T.scenario))), ...
        sort(reshape(string({R.cells.id}),[],1))) && ...
    isequal(sort(unique(string(T.condition))), ...
        sort(reshape(string({R.conditions.id}),[],1))) && ...
    isequal(sort(unique(string(T.retryMode))), ...
        sort(reshape(string({R.modes.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '100 seeds, two graphs, six conditions and two retry modes exact');
paired=true;
for seed=R.seeds'
    for c=R.cells
        for condition=R.conditions
            index=T.seed==seed & string(T.scenario)==string(c.id) & ...
                string(T.condition)==string(condition.id);
            paired=paired && nnz(index)==2 && ...
                isscalar(unique(T.BASE_TRACE_HASH_EXACT(index))) && ...
                isscalar(unique(T.CONDITION_TRACE_HASH_EXACT(index))) && ...
                isscalar(unique(T.WITNESS_HASH_EXACT(index))) && ...
                isscalar(unique(T.BACKGROUND_TRACE_HASH_EXACT(index))) && ...
                scalarOrAllNaN(T.BACKGROUND_OVERLAY_HASH_EXACT(index));
        end
    end
end
add('paired_absolute_realizations',paired, ...
    'loss, occupancy and witness assignments pair exactly by retry mode');
legacy=string(T.retryMode)==string(R.legacyMode);
cumulative=string(T.retryMode)==string(R.cumulativeMode);
add('mode_declaration_exact',all(T.CUMULATIVE_RECEIPT_RETRY(legacy)==0) && ...
    all(T.CUMULATIVE_RECEIPT_RETRY(cumulative)==1), ...
    'only the candidate mode enables cumulative receipt state');
add('one_hop_witness_cover',all(T.HIDDEN_CONFLICT_EDGES>0) && ...
    all(T.MAX_WITNESS_LOAD<=floor((96-16)/8)), ...
    'hidden conflicts covered within the 96-byte response MTU');

zero=string(T.condition)==string(R.zeroCondition);
equivalent=true;
for seed=R.seeds'
    for c=R.cells
        A=selectRows(T,seed,c.id,R.zeroCondition,R.legacyMode);
        B=selectRows(T,seed,c.id,R.zeroCondition,R.cumulativeMode);
        equivalent=equivalent && height(A)==1 && height(B)==1 && ...
            A.CONTROL_ATTEMPTS==B.CONTROL_ATTEMPTS && ...
            A.CONTROL_BYTES==B.CONTROL_BYTES && ...
            A.SCHEDULED_ATTEMPTS==B.SCHEDULED_ATTEMPTS && ...
            A.FALLBACK_ATTEMPTS==B.FALLBACK_ATTEMPTS && ...
            A.CERTIFIED_NODE_FRAME_FRACTION== ...
                B.CERTIFIED_NODE_FRAME_FRACTION;
    end
end
add('zero_loss_effort_equivalence',equivalent, ...
    'attempts, bytes, DATA regions and certification match legacy exactly');
add('zero_loss_nominal_bound_exact',all( ...
    T.CONTROL_ATTEMPTS(zero)==T.NOMINAL_CONTROL_ATTEMPT_BOUND(zero)) && ...
    all(T.CONTROL_BYTES(zero)==T.NOMINAL_CONTROL_BYTE_BOUND(zero)) && ...
    all(T.RETRY_CLAIM_ATTEMPTS(zero)==0), ...
    'both modes equal the scheduled renewal bound with zero retry');
add('cumulative_safety',all(T.FALSE_VALID_EDGE_FRAMES(cumulative)==0) && ...
    all(T.SCHEDULED_COLLISION_FRAMES(cumulative)==0) && ...
    all(T.CERTIFICATE_WITHOUT_FRESH_CLAIMS(cumulative)==0), ...
    'zero false-valid, scheduled-collision and unsupported certificates');
blackout=string(T.condition)==string(R.blackoutCondition);
nonblackout=cumulative & ~blackout;
add('nonblackout_terminal_liveness',all( ...
    T.FINAL_ALL_CERTIFIED(nonblackout)==1) && all(isfinite( ...
    T.FIRST_ALL_CERTIFIED_FRAME(nonblackout))),sprintf( ...
    '%d/%d cumulative rows terminally certified', ...
    sum(T.FINAL_ALL_CERTIFIED(nonblackout)),nnz(nonblackout)));
add('blackout_fail_silent',all(T.FINAL_ALL_CERTIFIED( ...
    cumulative & blackout)==0) && all(T.FINAL_OPEN_CLAIM_TRANSACTIONS( ...
    cumulative & blackout)>0) && all(T.FALSE_VALID_EDGE_FRAMES( ...
    cumulative & blackout)==0), ...
    'permanent missing witness response never creates validity');
add('recipient_accounting_closes',all(T.ACCOUNTING_CLOSES==1) && all( ...
    T.MAX_FALLBACK_ATTEMPTS_PER_NODE_FRAME<=1), ...
    'management/DATA recipient partitions and fallback bound close');
add('causal_information_contract',all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0), ...
    'zero future-random and receiver-truth reads');
add('absolute_attempt_byte_bounds',all( ...
    T.CONTROL_ATTEMPT_BOUND_RATIO<=1+1e-12) && all( ...
    T.CONTROL_BYTE_BOUND_RATIO<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.CONTROL_ATTEMPT_BOUND_RATIO),max(T.CONTROL_BYTE_BOUND_RATIO)));
loss=cumulative & ~zero & ~blackout;
accumulates=all(T.CLAIM_TRANSACTION_STARTS(loss)<= ...
    T.CLAIM_ATTEMPTS(loss));
for c=R.cells
    for condition=R.conditions(2:5)
        index=loss & string(T.scenario)==string(c.id) & ...
            string(T.condition)==string(condition.id);
        accumulates=accumulates && sum(T.CLAIM_ATTEMPTS(index)- ...
            T.CLAIM_TRANSACTION_STARTS(index))>0;
    end
end
add('cumulative_receipt_stimulus',accumulates, ...
    'every stochastic cell has same-sequence retries after transaction start');
background=P(string(P.condition)==string(R.backgroundCondition),:);
efficient=height(background)==numel(R.cells) && ...
    all(background.meanAttemptDelta<0) && all(background.meanByteDelta<0);
add('fragmented_load_efficiency',efficient,sprintf( ...
    'attempt reduction range %.2f%% to %.2f%%', ...
    100*min(background.relativeAttemptDelta), ...
    100*max(background.relativeAttemptDelta)));
add('kernel_scope_only',~R.policyOptimizationAllowed && ...
    ~R.closedLoopClaimPermitted && ~R.newMethodPromotionAllowed && ...
    ~R.submissionClaimPermitted, ...
    'no tuning, closed-loop, promotion or submission decision');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredGates
    error('exp23h: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function P=pairedEfficiency(T,R)

rows=cell(0,11);
for c=R.cells
    for condition=R.conditions
        A=selectGroup(T,c.id,condition.id,R.cumulativeMode);
        B=selectGroup(T,c.id,condition.id,R.legacyMode);
        rows(end+1,:)={string(c.id),string(condition.id),height(A), ...
            mean(A.CONTROL_ATTEMPTS),mean(B.CONTROL_ATTEMPTS), ...
            mean(A.CONTROL_ATTEMPTS-B.CONTROL_ATTEMPTS), ...
            mean(A.CONTROL_ATTEMPTS)/mean(B.CONTROL_ATTEMPTS)-1, ...
            mean(A.CONTROL_BYTES),mean(B.CONTROL_BYTES), ...
            mean(A.CONTROL_BYTES-B.CONTROL_BYTES), ...
            mean(A.CONTROL_BYTES)/mean(B.CONTROL_BYTES)-1}; %#ok<AGROW>
    end
end
P=cell2table(rows,'VariableNames',{'scenario','condition','nPairs', ...
    'cumulativeMeanAttempts','legacyMeanAttempts','meanAttemptDelta', ...
    'relativeAttemptDelta','cumulativeMeanBytes','legacyMeanBytes', ...
    'meanByteDelta','relativeByteDelta'});

end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'scenario','scenarioLabel','condition', ...
    'conditionLabel','retryMode'}));
S.nRuns=splitapply(@numel,T.FINAL_ALL_CERTIFIED,group);
S.terminalCertificationRate=splitapply(@mean,T.FINAL_ALL_CERTIFIED,group);
S.meanFirstCertificationFrame=splitapply( ...
    @finiteMean,T.FIRST_ALL_CERTIFIED_FRAME,group);
S.meanCertifiedNodeFrameFraction=splitapply( ...
    @mean,T.CERTIFIED_NODE_FRAME_FRACTION,group);
S.meanControlAttempts=splitapply(@mean,T.CONTROL_ATTEMPTS,group);
S.meanControlBytes=splitapply(@mean,T.CONTROL_BYTES,group);
S.meanRetryClaims=splitapply(@mean,T.RETRY_CLAIM_ATTEMPTS,group);
S.falseValidEdgeFrames=splitapply(@sum,T.FALSE_VALID_EDGE_FRAMES,group);
S.scheduledCollisionFrames=splitapply( ...
    @sum,T.SCHEDULED_COLLISION_FRAMES,group);

end


function T=selectRows(T,seed,scenario,condition,mode)
T=T(T.seed==seed & string(T.scenario)==string(scenario) & ...
    string(T.condition)==string(condition) & ...
    string(T.retryMode)==string(mode),:);
end


function T=selectGroup(T,scenario,condition,mode)
T=T(string(T.scenario)==string(scenario) & ...
    string(T.condition)==string(condition) & ...
    string(T.retryMode)==string(mode),:);
T=sortrows(T,'seed');
end


function yes=scalarOrAllNaN(x)
yes=all(isnan(x)) || isscalar(unique(x));
end


function y=finiteMean(x)
x=x(isfinite(x));
if isempty(x), y=NaN; else, y=mean(x); end
end


function [seeds,cells,conditions]=groups(R)
nCells=numel(R.cells); nConditions=numel(R.conditions);
seeds=repelem(R.seeds,nCells*nConditions);
cells=repmat(repelem((1:nCells)',nConditions),numel(R.seeds),1);
conditions=repmat((1:nConditions)',numel(R.seeds)*nCells,1);
end


function [rows,completed]=loadCheckpoint(runDir,R)

[seeds,cells,conditions]=groups(R);
completed=false(size(seeds));
path=fullfile(runDir,'kernel_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23hCumulativeReceiptEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string');
rows=table2struct(T);
for q=1:numel(seeds)
    c=R.cells(cells(q)); condition=R.conditions(conditions(q));
    index=T.seed==seeds(q) & string(T.scenario)==string(c.id) & ...
        string(T.condition)==string(condition.id);
    if nnz(index)==numel(R.modes), completed(q)=true;
    elseif any(index), error('exp23h: partial checkpoint group.'); end
end

end


function runRequiredTests()
names={'test_elcs_cumulative_receipt_contracts', ...
    'test_elcs_kernel_contracts','test_elcs_background_load_contracts'};
for k=1:numel(names), runScriptIsolated(names{k}); end
end


function snapshotSource(target)

root=projectRoot();
files={'docs/EXP23H_CUMULATIVE_RECEIPT_KERNEL_PLAN.md', ...
    'docs/EXP23G_BACKGROUND_GATE_REPAIR_RESULTS_2026-09-04.md', ...
    'network/simulateElcsWitnessScheduling.m', ...
    'network/elcsWitnessPriorityColor.m', ...
    'network/applySharedBackgroundToElcsWitnessTrace.m', ...
    'utils/elcsWitnessKernelConfig.m', ...
    'utils/exp23hCumulativeReceiptRegistry.m', ...
    'utils/exp23hCumulativeReceiptEmptyRow.m', ...
    'utils/runExp23hCumulativeReceiptCell.m', ...
    'tests/test_elcs_cumulative_receipt_contracts.m', ...
    'experiments/exp23h_cumulative_receipt_kernel_validation.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    name=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,name));
end

end


function expRun=resumeRun(runDir,registryHash,registryLeaves,experimentName)

if ~isfolder(runDir), error('exp23h: resume directory not found.'); end
opened=jsondecode(fileread(fullfile(runDir,'cumulative_opened.json')));
if opened.registryHash~=registryHash || opened.registryLeaves~=registryLeaves
    error('exp23h: registry differs from opened run.');
end
[~,runId]=fileparts(runDir);
meta=struct('experiment',experimentName, ...
    'runId',runId,'startedAt',opened.openedAt, ...
    'matlabVersion',version,'matlabRelease',version('-release'), ...
    'computer',computer,'projectRoot',projectRoot(),'gitCommit','', ...
    'notes','resumed frozen cumulative-receipt kernel checkpoint');
expRun=struct('name',experimentName, ...
    'runId',runId,'dir',runDir,'figDir',fullfile(runDir,'figures'), ...
    'expRoot',fileparts(runDir),'meta',meta,'t0',tic);

end


function writeJson(path,value)
fid=fopen(path,'w');
if fid<0, error('exp23h: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
