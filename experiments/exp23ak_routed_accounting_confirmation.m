function exp23ak_routed_accounting_confirmation(R)
%EXP23AK_ROUTED_ACCOUNTING_CONFIRMATION Exact routed-PHY accounting repair.

if nargin<1, R=exp23akRoutedAccountingRegistry(); end
startup; close all; runRequiredTests(R);
[registryHash,registryLeaves]=configHash(R);
parentDir=fullfile(projectRoot(),'results', ...
    'exp23aj_routed_management_diagnostic',R.parentRun);
W=load(fullfile(parentDir,'workspace.mat'));

expRun=startExperiment(R.experimentName, ...
    ['Fresh-trace exact integer byte and derived-airtime confirmation for ' ...
    'the retained routed-management diagnostic.']);
writeJson(fullfile(expRun.dir,'routed_accounting_registry.json'),R);
snapshotSource(expRun.dir,R);

S=confirmStructural(W.S,R);
writetable(S,fullfile(expRun.dir,'structural_accounting.csv'));
Q=confirmRandom(W.S,R);
writetable(Q,fullfile(expRun.dir,'conditional_trace_accounting.csv'));
E=confirmSemantic(W.E,R);
writetable(E,fullfile(expRun.dir,'semantic_accounting.csv'));
parentGates=readtable(fullfile(parentDir,'validation_gates.csv'), ...
    'TextType','string');
gates=validationGates(S,Q,E,parentGates,R, ...
    registryHash,registryLeaves,parentDir);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));

valid=all(gates.passed==1);
status=ternary(valid, ...
    'INTEGER_ACCOUNTED_ROUTING_PRIMITIVE_DIAGNOSTIC_VALID', ...
    'INTEGER_ACCOUNTED_ROUTING_PRIMITIVE_DIAGNOSTIC_INVALID');
next=ternary(valid,'multi_origin_common_phy_routing_integration', ...
    'repair_routed_accounting_without_relaxing_registered_gates');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'parentInvalidRetained',true, ...
    'parentPassedScientificGates',sum(parentGates.passed), ...
    'structuralRows',height(S),'conditionalTraceRows',height(Q), ...
    'semanticRows',height(E),'routingPrimitiveValidated',valid, ...
    'integerRoutedAccountingValidated',valid, ...
    'closedLoopManagementRelayingValidated',false, ...
    'managementRelayingValidated',false, ...
    'repeatedOnlineRenewalValidated',false, ...
    'freshSeedEvidence',false,'robustnessClaimPermitted',false, ...
    'submissionClaimPermitted',false,'next',next);
writeJson(fullfile(expRun.dir,'routed_accounting_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'S','Q','E','parentGates', ...
    'gates','verdict','R');

fprintf('\nEXP23AK routed integer-accounting gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-44s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nConditional replay summary\n');
disp(groupsummary(Q,{'N','interferenceMode','linkErasureProbability'}, ...
    {'min','max','mean'},{'attempts','physicalBytes'}));
fprintf('EXP23AK DECISION: %s\n',status);
finishExperiment(expRun);
if ~valid
    error('exp23ak: routed integer-accounting confirmation invalid.');
end

end


function T=confirmStructural(parent,R)

rows=repmat(structuralEmptyRow(),height(parent),1);
for k=1:height(parent)
    old=parent(k,:); N=old.N;
    reach=topologyFixture(N);
    interference=interferenceFixture(N,old.interferenceMode);
    P=buildSlottedManagementFloodPlan(reach,interference,old.source, ...
        setdiff(1:N,old.source),N-1);
    D=dimensionRepeatedHopManagementFlood(P, ...
        old.linkErasureProbability,R.maximumLogicalPacketFailure, ...
        R.maxRepetitionsPerHop);
    repetitions=D.selectedRepetitions;
    O=simulateRepeatedHopManagementFlood(P,ones(N,N,repetitions), ...
        old.linkErasureProbability,repetitions,R.maximumPacketBytes, ...
        R.phyRateBps,R.safeGuardSec);
    row=structuralEmptyRow();
    row.N=N; row.interferenceMode=old.interferenceMode;
    row.source=old.source;
    row.linkErasureProbability=old.linkErasureProbability;
    row.parentPlanHash=old.planHash; row.currentPlanHash=P.hashExact;
    row.planHashExact=double(P.hashExact==old.planHash);
    row.repetitionExact=double(repetitions==old.selectedRepetitions);
    row.reliabilityExact=double(D.certificate.multicastFailureExact== ...
        old.multicastFailureExact&& ...
        D.certificate.multicastFailureUnionUpperBound== ...
        old.multicastFailureUnionUpperBound);
    row.boundExact=double(D.certificate.maximumPhysicalAttemptBound== ...
        old.maximumPhysicalAttempts&& ...
        D.certificate.reservedSlotCount==old.reservedSlotCount&& ...
        old.maximumPhysicalBytes== ...
        D.certificate.maximumPhysicalAttemptBound*R.maximumPacketBytes);
    row.durationExact=double(O.reservedDurationSec== ...
        old.reservedDurationSec);
    row.simulatorVersionHash=realizationHash(O.version);
    row.attempts=O.attempts; row.physicalBytes=O.bytes;
    row.offeredAirtimeSec=O.offeredAirtimeSec;
    row.reservedDurationSec=O.reservedDurationSec;
    row.attemptExact=double(O.attempts== ...
        D.certificate.maximumPhysicalAttemptBound);
    row.byteExact=double(O.bytes==O.attempts*R.maximumPacketBytes);
    row.airtimeExact=double(O.offeredAirtimeSec== ...
        8*O.bytes/R.phyRateBps);
    row.deliveryExact=O.allRecipientsDelivered;
    row.collisionRecipients=O.collisionRecipients;
    row.duplicateForwards=O.duplicateForwardCount;
    row.forbiddenReads=O.futureRandomReads+O.receiverTruthDecisionReads;
    rows(k)=row;
end
T=struct2table(rows);

end


function T=confirmRandom(parent,R)

rows=repmat(randomEmptyRow(),R.expectedRandomRows,1);
q=0; cellIndex=0;
for N=R.swarmSizes
    reach=topologyFixture(N);
    for modeIndex=1:numel(R.interferenceModes)
        mode=string(R.interferenceModes{modeIndex});
        interference=interferenceFixture(N,mode);
        for p=R.linkErasureProbability
            cellIndex=cellIndex+1;
            source=worstSource(parent,N,mode,p);
            P=buildSlottedManagementFloodPlan(reach,interference,source, ...
                setdiff(1:N,source),N-1);
            B=repeatedHopManagementFloodReliabilityCertificate(P,p, ...
                R.randomReplayRepetitionsPerHop);
            stream=RandStream('mt19937ar', ...
                'Seed',R.randomReplaySeeds(cellIndex));
            for trial=1:R.randomReplayTrialsPerCell
                q=q+1;
                packetBytes=R.packetBytes(mod(trial-1, ...
                    numel(R.packetBytes))+1);
                U=rand(stream,N,N,R.randomReplayRepetitionsPerHop);
                O=simulateRepeatedHopManagementFlood(P,U,p, ...
                    R.randomReplayRepetitionsPerHop,packetBytes, ...
                    R.phyRateBps,R.safeGuardSec);
                row=randomEmptyRow();
                row.N=N; row.interferenceMode=mode;
                row.linkErasureProbability=p; row.source=source;
                row.seed=R.randomReplaySeeds(cellIndex); row.trial=trial;
                row.packetBytes=packetBytes; row.planHash=P.hashExact;
                row.simulatorVersionHash=realizationHash(O.version);
                row.delivered=O.allRecipientsDelivered;
                row.attempts=O.attempts; row.physicalBytes=O.bytes;
                row.offeredAirtimeSec=O.offeredAirtimeSec;
                row.reservedDurationSec=O.reservedDurationSec;
                row.analyticalAttemptBound=B.maximumPhysicalAttemptBound;
                row.attemptBoundExact=double(O.attempts<= ...
                    B.maximumPhysicalAttemptBound);
                row.byteExact=double(O.bytes==O.attempts*packetBytes);
                row.airtimeExact=double(O.offeredAirtimeSec== ...
                    8*O.bytes/R.phyRateBps);
                row.durationExact=double(O.reservedDurationSec== ...
                    P.reservedSlotCount*(8*packetBytes/R.phyRateBps+ ...
                    R.safeGuardSec));
                row.collisionRecipients=O.collisionRecipients;
                row.duplicateForwards=O.duplicateForwardCount;
                row.forbiddenReads=O.futureRandomReads+ ...
                    O.receiverTruthDecisionReads;
                rows(q)=row;
            end
            fprintf(['  conditional accounting N=%d, %-35s p=%.2f ' ...
                'complete\n'],N,mode,p);
        end
    end
end
if q~=R.expectedRandomRows||cellIndex~=R.expectedRandomCells
    error('exp23ak: random replay matrix mismatch.');
end
T=struct2table(rows);

end


function T=confirmSemantic(parent,R)

PARENT=exp23aiIntegerAccountingRegistry();
[~,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,PARENT);
migration=context.geometry.migration;
reach=logical(context.neighborGraph);
interference=context.geometry.oldPhysicalGraph| ...
    context.geometry.proposedPhysicalGraph;
rows=repmat(semanticEmptyRow(),height(parent),1);
for k=1:height(parent)
    old=parent(k,:); kind=char(old.kind); sender=old.sender;
    recipients=receiverLiftedClosureControlRecipients( ...
        migration,kind,sender);
    row=semanticEmptyRow();
    row.kind=old.kind; row.sender=sender; row.packetBytes=old.packetBytes;
    row.recipientHashExact=double( ...
        realizationHash(double(recipients))==old.recipientHash);
    row.selfOnly=double(~any(recipients));
    if ~any(recipients)
        row.planExact=double(old.selfOnly==1&&isnan(old.planHash));
        row.reliabilityExact=double(old.multicastFailureExact==0);
        row.accountingExact=double(old.observedAttempts==0&& ...
            old.observedBytes==0&&old.observedAirtimeSec==0);
        row.deliveryExact=1;
        rows(k)=row; continue;
    end
    plan=buildSlottedManagementFloodPlan(reach,interference,sender, ...
        recipients,migration.N-1);
    D=dimensionRepeatedHopManagementFlood(plan, ...
        R.semanticLinkErasureProbability,R.maximumLogicalPacketFailure, ...
        R.maxRepetitionsPerHop);
    O=simulateRepeatedHopManagementFlood(plan, ...
        ones(migration.N,migration.N,D.selectedRepetitions), ...
        R.semanticLinkErasureProbability,D.selectedRepetitions, ...
        old.packetBytes,R.phyRateBps,R.safeGuardSec);
    row.planHash=plan.hashExact;
    row.planExact=double(plan.hashExact==old.planHash&& ...
        D.selectedRepetitions==old.selectedRepetitions&& ...
        D.certificate.maximumPhysicalAttemptBound== ...
        old.maximumPhysicalAttempts&& ...
        D.certificate.reservedSlotCount==old.reservedSlotCount);
    row.reliabilityExact=double(D.certificate.multicastFailureExact== ...
        old.multicastFailureExact);
    row.simulatorVersionHash=realizationHash(O.version);
    row.attempts=O.attempts; row.physicalBytes=O.bytes;
    row.offeredAirtimeSec=O.offeredAirtimeSec;
    row.accountingExact=double(O.attempts== ...
        D.certificate.maximumPhysicalAttemptBound&& ...
        O.bytes==O.attempts*old.packetBytes&& ...
        O.offeredAirtimeSec==8*O.bytes/R.phyRateBps);
    row.deliveryExact=O.allRecipientsDelivered;
    row.collisionRecipients=O.collisionRecipients;
    row.duplicateForwards=O.duplicateForwardCount;
    row.forbiddenReads=O.futureRandomReads+O.receiverTruthDecisionReads;
    rows(k)=row;
end
T=struct2table(rows);

end


function gates=validationGates(S,Q,E,parentGates,R, ...
    registryHash,registryLeaves,parentDir)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
parent=jsondecode(fileread(fullfile(parentDir, ...
    'routed_management_verdict.json')));
failed=sort(string(parentGates.gate(parentGates.passed==0)));
expectedFailed=sort(string(R.parentFailedGates(:)));
abortExact=true;
if isfield(R,'abortedPredecessorRecord')
    aborted=jsondecode(fileread(fullfile(projectRoot(), ...
        R.abortedPredecessorRecord)));
    abortExact=strcmp(aborted.status,R.abortedPredecessorStatus)&& ...
        ~aborted.scientificOutcomeObserved&& ...
        ~aborted.registeredRandomDrawAccepted;
end
add('registry_and_invalid_parent_retained',isfinite(registryHash)&& ...
    registryLeaves>0&&strcmp(parent.status,R.parentStatus)&& ...
    parent.gatesPassed==R.parentGatesPassed&& ...
    parent.gatesTotal==R.parentGatesTotal&&isequal(failed,expectedFailed)&& ...
    abortExact, ...
    sprintf('registry %.0f/%d leaves; parent retained at %d/%d', ...
    registryHash,registryLeaves,parent.gatesPassed,parent.gatesTotal));
add('replay_v2_narrow_repair',all(S.simulatorVersionHash== ...
    realizationHash(R.repairedSimulatorVersion))&&all( ...
    Q.simulatorVersionHash==realizationHash(R.repairedSimulatorVersion))&& ...
    all(E.simulatorVersionHash(E.selfOnly==0)== ...
    realizationHash(R.repairedSimulatorVersion)), ...
    'all radio replays use integer-derived-airtime version v2');
add('parent_scientific_gates_retained',height(parentGates)==17&& ...
    sum(parentGates.passed)==15&&numel(failed)==2, ...
    'all 15 routing/reliability/causality parent gates remain passed');

key=string(S.N)+'|'+string(S.interferenceMode)+'|'+ ...
    string(S.source)+'|'+string(S.linkErasureProbability);
add('structural_matrix_and_mechanism_identity',height(S)== ...
    R.expectedStructuralRows&&numel(unique(key))==height(S)&&all( ...
    S.planHashExact==1)&&all(S.repetitionExact==1)&&all( ...
    S.reliabilityExact==1)&&all(S.boundExact==1)&&all( ...
    S.durationExact==1),sprintf( ...
    '%d/%d route plans and certificates reproduce exactly', ...
    nnz(S.planHashExact),height(S)));
add('structural_integer_attempts_and_bytes',all(S.attemptExact==1)&& ...
    all(S.byteExact==1)&&all(S.deliveryExact==1)&&all( ...
    S.collisionRecipients==0)&&all(S.duplicateForwards==0)&&all( ...
    S.forbiddenReads==0),sprintf('maximum confirmed bytes %.0f', ...
    max(S.physicalBytes)));
add('structural_derived_airtime_exact',all(S.airtimeExact==1), ...
    '210/210 offered airtimes equal 8*integer bytes/rate exactly');

diverse=randomPathDiversity(Q,R);
add('conditional_random_matrix_and_path_diversity',height(Q)== ...
    R.expectedRandomRows&&numel(unique(Q.seed))==R.expectedRandomCells&& ...
    diverse,sprintf('%d new traces across %d cells; attempt paths vary', ...
    height(Q),R.expectedRandomCells));
add('conditional_random_accounting_exact',all(Q.attemptBoundExact==1)&& ...
    all(Q.byteExact==1)&&all(Q.airtimeExact==1)&&all( ...
    Q.durationExact==1)&&all(Q.collisionRecipients==0)&&all( ...
    Q.duplicateForwards==0)&&all(Q.forbiddenReads==0),sprintf( ...
    'attempt range %.0f--%.0f; every trace byte/airtime exact', ...
    min(Q.attempts),max(Q.attempts)));

add('semantic_routes_reproduced_and_accounted',height(E)== ...
    R.expectedSemanticRows&&all(E.recipientHashExact==1)&&all( ...
    E.planExact==1)&&all(E.reliabilityExact==1)&&all( ...
    E.accountingExact==1)&&all(E.deliveryExact==1)&&all( ...
    E.collisionRecipients==0)&&all(E.duplicateForwards==0)&&all( ...
    E.forbiddenReads==0),sprintf( ...
    '%d/%d semantic routes exact, including %d local-only packet', ...
    nnz(E.accountingExact),height(E),nnz(E.selfOnly)));

scope=R.developmentOnly&&~R.confirmatoryEvidence&& ...
    ~R.managementRelayingValidated&&~R.repeatedOnlineRenewalValidated&& ...
    ~R.freshSeedEvidence&&~R.robustnessClaimPermitted&& ...
    ~R.submissionClaimPermitted;
add('primitive_scope_only',scope, ...
    'routed primitive repaired; closed-loop and renewal flags remain false');

gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23ak: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function diverse=randomPathDiversity(T,R)

diverse=true;
for N=R.swarmSizes
    for mode=string(R.interferenceModes)
        for p=R.linkErasureProbability
            block=T(T.N==N&T.interferenceMode==mode& ...
                abs(T.linkErasureProbability-p)<1e-15,:);
            diverse=diverse&&height(block)==R.randomReplayTrialsPerCell&& ...
                numel(unique(block.attempts))>1&& ...
                numel(unique(block.physicalBytes))>1;
        end
    end
end

end


function source=worstSource(parent,N,mode,p)

block=parent(parent.N==N&string(parent.interferenceMode)==mode& ...
    abs(parent.linkErasureProbability-p)<1e-15,:);
score=[block.reservedSlotCount,block.maximumPhysicalAttempts, ...
    block.maximumRecipientDepth,block.source];
[~,order]=sortrows(score,[-1 -2 -3 4]);
source=block.source(order(1));

end


function reach=topologyFixture(N)

cfg=applyTopologyConfig(defaultConfig(),N,'ring2');
reach=logical(cfg.swarm.A);
reach(logical(cfg.swarm.pin(:)),1)=true;
reach=reach|reach'; reach(1:N+1:end)=false;

end


function interference=interferenceFixture(N,mode)

switch char(mode)
    case 'spatial-reuse-lower-bound'
        interference=false(N);
    case 'complete-interference-upper-bound'
        interference=~eye(N);
    otherwise
        error('exp23ak: unknown interference mode.');
end

end


