function runRequiredTests(R)

names={R.testScript, ...
    'test_exp23aj_routed_management_contracts', ...
    'test_slotted_management_flood_contracts', ...
    'test_receiver_lifted_control_routing_contracts'};
for k=1:numel(names), runScriptIsolated(names{k}); end

end


function snapshotSource(target,R)

root=projectRoot(); files={ ...
    R.planFile, ...
    'docs/EXP23AJ_ROUTED_MANAGEMENT_DIAGNOSTIC_PLAN.md', ...
    'results/exp23aj_routed_management_diagnostic/2026-09-06_070738/routed_management_verdict.json', ...
    'results/exp23aj_routed_management_diagnostic/2026-09-06_070738/validation_gates.csv', ...
    'network/buildSlottedManagementFloodPlan.m', ...
    'network/repeatedHopManagementFloodReliabilityCertificate.m', ...
    'network/dimensionRepeatedHopManagementFlood.m', ...
    'network/simulateRepeatedHopManagementFlood.m', ...
    'network/receiverLiftedClosureControlRecipients.m', ...
    R.registryFile, ...
    'utils/exp23ajRoutedManagementRegistry.m', ...
    R.testFile, ...
    'tests/test_exp23aj_routed_management_contracts.m', ...
    'tests/test_slotted_management_flood_contracts.m', ...
    'tests/test_receiver_lifted_control_routing_contracts.m', ...
    'experiments/exp23ak_routed_accounting_confirmation.m', ...
    R.entryFile};
if isfield(R,'abortedPredecessorRecord')
    files{end+1}=R.abortedPredecessorRecord;
end
files=unique(files,'stable');
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    source=fullfile(root,files{k});
    if ~isfile(source)
        error('exp23ak: missing snapshot source %s.',source);
    end
    name=replace(files{k},{'/' '\'},'__');
    copyfile(source,fullfile(freeze,name));
end

end


function writeJson(path,value)

fid=fopen(path,'w'); if fid<0, error('exp23ak: cannot write.'); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));

end


function value=ternary(condition,a,b)

if condition, value=a; else, value=b; end

end
