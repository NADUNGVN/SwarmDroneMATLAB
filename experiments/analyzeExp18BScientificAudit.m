function A=analyzeExp18BScientificAudit(runDir)
%ANALYZEEXP18BSCIENTIFICAUDIT Post-hoc research audit, never inference.

if nargin~=1 || ~(ischar(runDir) || (isstring(runDir) && isscalar(runDir)))
    error('analyzeExp18BScientificAudit: runDir must be scalar text.');
end
runDir=char(runDir);
R=exp18bRegistry();
T=readtable(fullfile(runDir,'tidy.csv'),'TextType','string');
G=readtable(fullfile(runDir,'gates.csv'),'TextType','string');
V=jsondecode(fileread(fullfile(runDir,'claim_verdict.json')));
if height(T)~=R.expectedRuns || ~all(G.passed==1) || ...
        ~strcmp(V.status,'SUPPORTED_WITHIN_REGISTERED_SCOPE')
    error('analyzeExp18BScientificAudit: frozen result is incomplete.');
end

A=struct();
A.routeValue=routeValueAudit(T,R);
A.serviceScreen=serviceScreenAudit(T,R);
A.accessIsolation=accessIsolationAudit(T,R);
A.verdict=researchVerdict(A.routeValue,A.serviceScreen, ...
    A.accessIsolation,R);

writetable(A.routeValue,fullfile(runDir,'posthoc_route_value_audit.csv'));
writetable(A.serviceScreen,fullfile(runDir, ...
    'posthoc_service_screen_audit.csv'));
writetable(A.accessIsolation,fullfile(runDir, ...
    'posthoc_access_isolation_audit.csv'));
writeJson(fullfile(runDir,'posthoc_research_gate_verdict.json'),A.verdict);

end


function Q=routeValueAudit(T,R)

Q=table();
for c=R.cells
    for m=1:numel(R.macTypes)
        mac=R.macTypes{m};
        P=armRows(T,R,c.id,mac,'frame-piggyback');
        A=armRows(T,R,c.id,mac,'frame-adaptive');
        C=armRows(T,R,c.id,mac,R.candidate);
        validatePair(P,A,c.id,mac);
        rmse=paired(P,A,'RMSE',R);
        load=paired(P,A,'OFFERED_UTIL',R);
        aoi=paired(P,A,'MEAN_TRUE_AOI',R);
        collision=paired(P,A,'COLLISION_FRAMES',R);
        label=classifyTwoMetricRoute(rmse.lo,rmse.hi,load.lo,load.hi);
        selected=char(C.routedReference(1));
        selectedShort=erase(selected,'frame-');
        aligned=NaN;
        if strcmp(label,'PIGGYBACK_DOMINATES')
            aligned=double(strcmp(selectedShort,'piggyback'));
        elseif strcmp(label,'ADAPTIVE_DOMINATES')
            aligned=double(strcmp(selectedShort,'adaptive'));
        end
        operational=double(sum(P.SAFEFAIL)==0 || sum(A.SAFEFAIL)==0);
        row=table(string(c.id),string(c.role),string(mac), ...
            C.serviceCertificateFeasible(1),C.serviceRatio(1), ...
            string(selectedShort),string(label),aligned,operational, ...
            mean(P.RMSE),mean(A.RMSE),rmse.meanD,rmse.lo,rmse.hi, ...
            mean(P.OFFERED_UTIL),mean(A.OFFERED_UTIL), ...
            load.meanD,load.lo,load.hi,aoi.meanD,aoi.lo,aoi.hi, ...
            collision.meanD,collision.lo,collision.hi, ...
            sum(P.SAFEFAIL),sum(A.SAFEFAIL), ...
            mean(P.ACK_STANDALONE),mean(A.ACK_STANDALONE), ...
            'VariableNames',{'cell','role','macType','screenFeasible', ...
            'serviceRatio','candidateRoute','routeClassification', ...
            'candidateAlignedWhenResolved','atLeastOneRouteZeroFailures', ...
            'piggyRMSE','adaptiveRMSE','piggyMinusAdaptiveRMSE', ...
            'rmseTLo','rmseTHi','piggyOffered','adaptiveOffered', ...
            'piggyMinusAdaptiveOffered','offeredTLo','offeredTHi', ...
            'piggyMinusAdaptiveAoI','aoiTLo','aoiTHi', ...
            'piggyMinusAdaptiveCollisions','collisionTLo','collisionTHi', ...
            'piggyFailures','adaptiveFailures','piggyStandaloneAck', ...
            'adaptiveStandaloneAck'});
        Q=[Q; row]; %#ok<AGROW>
    end
end

end


function S=serviceScreenAudit(T,R)

S=table();
for c=R.cells
    for m=1:numel(R.macTypes)
        mac=R.macTypes{m};
        C=armRows(T,R,c.id,mac,R.candidate);
        observed=C.DATA_GOODPUT_HZ./C.N;
        target=C.requiredUpdateRateHz;
        d=observed-target;
        ci=oneSampleCI(d);
        screen=logical(C.serviceCertificateFeasible(1));
        observedMean=mean(d)>0;
        if screen && observedMean
            classification='SCREEN_POSITIVE_MEAN_POSITIVE';
        elseif screen && ~observedMean
            classification='SCREEN_FALSE_POSITIVE';
        elseif ~screen && observedMean
            classification='CONSERVATIVE_FALSE_NEGATIVE';
        else
            classification='SCREEN_NEGATIVE_MEAN_NEGATIVE';
        end
        row=table(string(c.id),string(c.role),string(mac),double(screen), ...
            C.successfulUpdateRateHz(1),mean(observed),mean(target), ...
            mean(d),ci.lo,ci.hi,double(observedMean), ...
            string(classification),sum(C.SAFEFAIL), ...
            'VariableNames',{'cell','role','macType','screenFeasible', ...
            'predictedPerNodeHz','observedPerNodeHz','requiredPerNodeHz', ...
            'observedMarginHz','marginTLo','marginTHi', ...
            'observedMeanExceedsTarget','classification','candidateFailures'});
        S=[S; row]; %#ok<AGROW>
    end
end

end


function X=accessIsolationAudit(T,R)

% Under ALOHA, frame-adaptive and legacy-selector share adaptive feedback.
% Their difference therefore isolates access geometry descriptively. The
% registered H8--H9 candidate-versus-legacy contrast does not: the candidate
% is piggyback-only in all N10 ALOHA cells.
X=table();
for c=R.cells
    F=armRows(T,R,c.id,'aloha','frame-adaptive');
    L=armRows(T,R,c.id,'aloha','legacy-selector');
    validatePair(F,L,c.id,'aloha');
    rmse=paired(F,L,'RMSE',R);
    load=paired(F,L,'OFFERED_UTIL',R);
    collision=paired(F,L,'COLLISION_FRAMES',R);
    goodput=paired(F,L,'DATA_GOODPUT_HZ',R);
    row=table(string(c.id),string(c.role), ...
        mean(F.RMSE),mean(L.RMSE),rmse.meanD,rmse.lo,rmse.hi, ...
        mean(F.OFFERED_UTIL),mean(L.OFFERED_UTIL), ...
        load.meanD,load.lo,load.hi, ...
        mean(F.COLLISION_FRAMES),mean(L.COLLISION_FRAMES), ...
        collision.meanD,collision.lo,collision.hi, ...
        mean(F.DATA_GOODPUT_HZ),mean(L.DATA_GOODPUT_HZ), ...
        goodput.meanD,goodput.lo,goodput.hi, ...
        sum(F.SAFEFAIL),sum(L.SAFEFAIL), ...
        'VariableNames',{'cell','role','frameAdaptiveRMSE','legacyRMSE', ...
        'frameMinusLegacyRMSE','rmseTLo','rmseTHi', ...
        'frameAdaptiveOffered','legacyOffered','frameMinusLegacyOffered', ...
        'offeredTLo','offeredTHi','frameAdaptiveCollisions', ...
        'legacyCollisions','frameMinusLegacyCollisions','collisionTLo', ...
        'collisionTHi','frameAdaptiveGoodputHz','legacyGoodputHz', ...
        'frameMinusLegacyGoodputHz','goodputTLo','goodputTHi', ...
        'frameAdaptiveFailures','legacyFailures'});
    X=[X; row]; %#ok<AGROW>
end

end


function V=researchVerdict(Q,S,X,R)

feasibleAloha=Q(Q.screenFeasible==1 & Q.macType=="aloha",:);
safeResolved=Q(Q.atLeastOneRouteZeroFailures==1 & ...
    Q.routeClassification~="MIXED_OR_UNRESOLVED",:);
adaptiveSafe=sum(safeResolved.routeClassification=="ADAPTIVE_DOMINATES");
piggySafe=sum(safeResolved.routeClassification=="PIGGYBACK_DOMINATES");
falsePositive=sum(S.classification=="SCREEN_FALSE_POSITIVE");
falseNegative=sum(S.classification=="CONSERVATIVE_FALSE_NEGATIVE");
n10=ismember(X.cell,string(R.n10CollisionCells));
isolatedAccessCollision=all(X.collisionTHi(n10)<0);
isolatedAccessLoad=all(X.offeredTHi(n10)<0);
V=struct( ...
    'status','CURRENT_CANDIDATE_NOT_SUBMISSION_READY', ...
    'analysisType','post-hoc descriptive research audit', ...
    'confirmatoryClaimAdded',false, ...
    'feasibleAlohaCells',height(feasibleAloha), ...
    'feasibleAlohaPiggybackDominates', ...
    sum(feasibleAloha.routeClassification=="PIGGYBACK_DOMINATES"), ...
    'feasibleAlohaAdaptiveDominates', ...
    sum(feasibleAloha.routeClassification=="ADAPTIVE_DOMINATES"), ...
    'candidateMisroutesResolvedFeasibleAloha', ...
    sum(feasibleAloha.candidateAlignedWhenResolved==0), ...
    'safeResolvedPiggybackDominates',piggySafe, ...
    'safeResolvedAdaptiveDominates',adaptiveSafe, ...
    'screenFalsePositiveCellMeans',falsePositive, ...
    'screenConservativeFalseNegativeCellMeans',falseNegative, ...
    'registeredH8H9CleanAccessIsolation',false, ...
    'descriptiveMatchedAccessRepairN10Collision',isolatedAccessCollision, ...
    'descriptiveMatchedAccessRepairN10Load',isolatedAccessLoad, ...
    'standaloneAckAsPrimaryNoveltyPermitted',false, ...
    'capacityScreenAsSufficientGateRetained',falsePositive==0, ...
    'frameAwareAccessMechanismRetained', ...
    isolatedAccessCollision && isolatedAccessLoad, ...
    'hardwarePolicyValidationPermitted',false, ...
    'measurementInfrastructureWorkPermitted',true, ...
    'nextResearchQuestion', ...
    ['Can service-aware semantic admission/scheduling improve control ' ...
    'over frame-aware piggyback when service demand exceeds capacity?'], ...
    'nextStage','EXP19A_ORACLE_SERVICE_ACTION_SPACE_DIAGNOSTIC');

end


function A=armRows(T,R,cellId,macType,armId)

A=sortrows(T(T.scenario==string(cellId) & ...
    T.macType==string(macType) & T.arm==string(armId),:),'seed');
if height(A)~=numel(R.seeds) || ~isequal(A.seed,R.seeds)
    error('analyzeExp18BScientificAudit: incomplete arm.');
end

end


function validatePair(A,B,cellId,macType)

if ~isequal(A.seed,B.seed) || ...
        ~isequal(A.TRACE_HASH_EXACT,B.TRACE_HASH_EXACT) || ...
        ~isequal(A.CHANNEL_STATE_HASH,B.CHANNEL_STATE_HASH) || ...
        ~isequal(A.ESTIMATOR_HASH_EXACT,B.ESTIMATOR_HASH_EXACT)
    error('analyzeExp18BScientificAudit: non-CRN pair %s/%s.', ...
        cellId,macType);
end

end


function s=paired(A,B,metric,R)

a=A.(metric); b=B.(metric);
invalid=logical(A.DIVERGED) | logical(B.DIVERGED);
a(invalid)=NaN; b(invalid)=NaN;
s=pairedCI(a,b,numel(R.seeds));

end


function s=oneSampleCI(d)

d=d(isfinite(d)); n=numel(d); s.meanD=mean(d);
if n<2
    s.lo=NaN; s.hi=NaN; return;
end
half=tinv(0.975,n-1)*std(d)/sqrt(n);
s.lo=s.meanD-half; s.hi=s.meanD+half;

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('analyzeExp18BScientificAudit: cannot write file.'); end
cleaner=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));

end
