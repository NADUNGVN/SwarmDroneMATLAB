function exp23ae_receiver_lifted_closure_common_phy()
%EXP23AE_RECEIVER_LIFTED_CLOSURE_COMMON_PHY Registered PHY integration.

startup; close all; runRequiredTests();
R=exp23aeClosureCommonPhyRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23ae_receiver_lifted_closure_common_phy', ...
    'Receiver-lifted closure common-PHY and affine-clock validation.');
writeJson(fullfile(expRun.dir,'common_phy_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23aeClosureCommonPhyEmptyRow(),R.expectedRuns,1); q=0;
checkpoint=fullfile(expRun.dir,'common_phy_checkpoint.csv');
for n=R.swarmSizes
    for s=1:numel(R.seeds)
        for c=1:numel(R.conditions)
            for a=1:numel(R.clockArms)
                q=q+1;
                rows(q)=runExp23aeClosureCommonPhyCell(R.seeds(s),n, ...
                    R.conditions{c},R.clockArms(a).id,R);
            end
        end
        if mod(s,10)==0
            writetable(struct2table(rows(1:q)),checkpoint);
            fprintf('  N=%2d seed %2d / %2d; rows %4d / %4d\n', ...
                n,s,numel(R.seeds),q,R.expectedRuns);
        end
    end
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'common_phy_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
valid=all(gates.passed==1);
status=ternary(valid,'RECEIVER_LIFTED_CLOSURE_COMMON_PHY_VALID', ...
    'RECEIVER_LIFTED_CLOSURE_COMMON_PHY_INVALID');
next=ternary(valid,'online_plant_coupled_tube_integration', ...
    'repair_common_phy_mapping_without_relaxing_gates');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'freshSeedEvidence',false,'closedLoopClaimPermitted',false, ...
    'onlinePlantCouplingPermitted',false, ...
    'submissionClaimPermitted',false,'next',next);
writeJson(fullfile(expRun.dir,'common_phy_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','gates','verdict','R');

fprintf('\nEXP23AE receiver-lifted closure common-PHY gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-42s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S);
fprintf('EXP23AE DECISION: %s\n',status);
finishExperiment(expRun);
if ~valid, error('exp23ae: common-PHY closure invalid.'); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash)&&registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ad_receiver_lifted_closure_kernel',R.parentKernelRun, ...
    'closure_kernel_verdict.json')));
add('kernel_parent_locked',strcmp(parent.status,R.parentKernelStatus)&& ...
    parent.gatesPassed==parent.gatesTotal&&~parent.closedLoopClaimPermitted, ...
    'canonical EXP23AD 24/24 kernel result retained');
key=string(T.seed)+'|'+string(T.N)+'|'+string(T.condition)+'|'+ ...
    string(T.clockArm);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds)&& ...
    isequal(unique(T.N)',R.swarmSizes)&& ...
    isequal(sort(unique(string(T.condition))), ...
        sort(reshape(string(R.conditions),[],1)))&& ...
    isequal(sort(unique(string(T.clockArm))), ...
        sort(reshape(string({R.clockArms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '50 seeds, three sizes, seven faults and two clocks exact');
add('clock_arm_pairing',clockPairsExact(T,R), ...
    'trace, kernel, native schedule and logical hashes pair exactly');
add('receiver_lift_stimulus',all(T.selectorAdmissible==1)&& ...
    all(T.physicalChangeCount>=1)&&all(T.senderChangeCount>=1)&& ...
    all(T.nonincidentSenderChangeCount>=1)&&all(T.affectedCount>=3), ...
    'all cells contain nonincident sender edges induced at a receiver');
add('joint_union_coloring',all(T.candidateProper==1)&& ...
    all(T.changedSlotCount>=1), ...
    'every candidate is proper on old/new union and changes a slot');
add('piggyback_revocation_mapping',all(T.piggybackRevoke==1)&& ...
    all(T.revokeMapped==0)&&all(T.kernelRevokeAttempts==0), ...
    'PREPARE/QUIESCENT carry revoke semantics; no standalone packet');
kinds=T.prepareMapped==T.kernelPrepareAttempts & ...
    T.quietMapped==T.kernelQuietAttempts & ...
    T.claimMapped==T.kernelClaimAttempts & ...
    T.proofMapped==T.kernelProofAttempts & ...
    T.responseMapped==T.kernelResponseAttempts & ...
    T.commitMapped==T.kernelCommitAttempts;
add('control_kind_mapping',all(kinds)&& ...
    all(T.maxControlPacketBytes<=R.maxControlPacketBytes), ...
    'six transmitted management kinds and MTU map exactly');
add('control_attempt_byte_airtime_accounting',all( ...
    T.physicalControlAttempts==T.kernelControlAttempts)&&all( ...
    T.physicalControlBytes==T.kernelControlBytes)&&all(abs( ...
    T.physicalControlAirtime-T.kernelControlAirtime)<=1e-12), ...
    'kernel and common-PHY attempt, byte and airtime totals match');
add('control_recipient_accounting',all(T.physicalRecipientAttempts== ...
    T.kernelRecipientAttempts)&&all(T.physicalRecipientSuccess== ...
    T.kernelRecipientSuccess)&&all(T.physicalRecipientErasure== ...
    T.kernelRecipientErasure), ...
    'management recipient attempts, successes and erasures replay');
add('data_state_slot_mapping',all(T.dataStateSlotExact==1), ...
    'every active kernel node has one exact DATA slot; silence is exact');
add('data_receiver_outcome_partition',all( ...
    T.dataRecipientPartitionExact==1)&&all(T.dataRecipientAttempts== ...
    T.dataRecipientSuccess+T.dataRecipientCollision), ...
    'receiver-level DATA successes/collisions form an exact partition');
incomplete=string(T.condition)=="incomplete-union";
supported=~incomplete;
add('supported_collision_safety',all(T.actualSubsetUnion(supported)==1)&& ...
    all(T.kernelCollisionFrames(supported)==0)&& ...
    all(T.physicalCollisionFrames(supported)==0)&& ...
    all(T.dataRecipientCollision(supported)==0), ...
    'all supported fault and clock cells are receiver-collision free');
add('incomplete_union_oracle_visible',all( ...
    T.actualSubsetUnion(incomplete)==0)&&all( ...
    T.kernelCollisionFrames(incomplete)>0)&&all( ...
    T.physicalCollisionFrames(incomplete)== ...
    T.kernelCollisionFrames(incomplete))&&all( ...
    T.dataRecipientCollision(incomplete)>0), ...
    'omitted physical interferer is visible at kernel and receiver PHY');
add('affine_clock_safety',all(T.clockTimingConflictFree==1)&& ...
    all(T.clockEquationResidual<2e-12)&& ...
    all(T.clockMinIntergroupGap>=-1e-12)&& ...
    all(T.horizonSec<=R.clockResetHorizonSec), ...
    'analytical guard prevents inter-group overlap within reset horizon');
add('logical_opportunities_preserved',all(T.nativeDataAttempts== ...
    T.physicalDataAttempts)&&all(T.nativeControlAttempts== ...
    T.physicalControlAttempts), ...
    'affine mapping trims no registered management or DATA event');
prepare=string(T.condition)=="prepare-blackout";
quiet=string(T.condition)=="quiescent-blackout";
add('quiescence_blackouts_block_motion',all( ...
    T.barrierClosed(prepare|quiet)==0)&&all( ...
    T.motionAuthorized(prepare|quiet)==0)&&all( ...
    T.prepareBudgetExhausted(prepare|quiet)==1), ...
    'missing PREPARE or positive QUIESCENT receipt prevents motion');
response=string(T.condition)=="response-blackout";
add('response_blackout_fail_silent',all(T.motionAuthorized(response)==1)&& ...
    all(T.commitReady(response)==0)&&all( ...
    T.finalSuppressedCount(response)==T.affectedCount(response)), ...
    'post-barrier graph activation retains full closure silence');
commit=string(T.condition)=="commit-blackout";
add('commit_blackout_partial_safe',all(T.commitReady(commit)==1)&& ...
    all(T.allReactivated(commit)==0)&&all(T.reactivatedCount(commit)==1)&& ...
    all(T.commitBudgetExhausted(commit)==1)&&all( ...
    T.physicalCollisionFrames(commit)==0), ...
    'initiator-only commit remains collision free under both clocks');
iid=string(T.condition)=="iid20"&string(T.clockArm)=="zero-clock";
ci=wilsonCI(nnz(T.allReactivated(iid)==0),nnz(iid),.05);
add('iid20_completion_reliability',1-ci.hi>= ...
    R.minAggregateIidCompletionWilsonLower,sprintf( ...
    'completion %.4f, Wilson lower %.4f', ...
    mean(T.allReactivated(iid)),1-ci.hi));
scope=~R.freshSeedEvidence&&~R.closedLoopClaimPermitted&& ...
    ~R.onlinePlantCouplingPermitted&&~R.submissionClaimPermitted;
add('bounds_causality_and_scope',all(T.attemptBoundRatio<=1+1e-12)&& ...
    all(T.byteBoundRatio<=1+1e-12)&&all(T.futureRandomReads==0)&& ...
    all(T.receiverTruthReads==0)&&scope, ...
    'bounds and forbidden-read checks pass; no downstream claim promoted');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23ae: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function exact=clockPairsExact(T,R)

exact=true;
for seed=R.seeds'
    for n=R.swarmSizes
        for condition=string(R.conditions)
            index=T.seed==seed&T.N==n&string(T.condition)==condition;
            exact=exact&&nnz(index)==2&& ...
                isscalar(unique(T.traceHash(index)))&& ...
                isscalar(unique(T.kernelStateHash(index)))&& ...
                isscalar(unique(T.nativeScheduleHash(index)))&& ...
                isscalar(unique(T.logicalHash(index)));
        end
    end
end

end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'N','condition','clockArm'}));
S.nRuns=splitapply(@numel,T.allReactivated,group);
S.completionRate=splitapply(@mean,T.allReactivated,group);
S.motionAuthorizationRate=splitapply(@mean,T.motionAuthorized,group);
S.meanAffectedCount=splitapply(@mean,T.affectedCount,group);
S.meanControlAttempts=splitapply(@mean,T.physicalControlAttempts,group);
S.meanControlBytes=splitapply(@mean,T.physicalControlBytes,group);
S.meanControlAirtime=splitapply(@mean,T.physicalControlAirtime,group);
S.collisionFrames=splitapply(@sum,T.physicalCollisionFrames,group);

end


function runRequiredTests()

names={'test_exp23ae_closure_common_phy_contracts', ...
    'test_receiver_lifted_closure_continuous_contracts', ...
    'test_receiver_lifted_closure_kernel_contracts', ...
    'test_receiver_lifted_dependency_migration_contracts'};
for k=1:numel(names), runScriptIsolated(names{k}); end

end


function snapshotSource(target)

root=projectRoot(); files={ ...
    'docs/EXP23AE_RECEIVER_LIFTED_CLOSURE_COMMON_PHY_PLAN.md', ...
    'docs/EXP23AD_RECEIVER_LIFTED_CLOSURE_RESULTS_2026-09-05.md', ...
    'network/buildReceiverLiftedDependencyMigration.m', ...
    'network/receiverLiftedClosureTraceHash.m', ...
    'network/generateReceiverLiftedClosureTrace.m', ...
    'network/simulateReceiverLiftedClosureMigration.m', ...
    'network/buildReceiverLiftedClosureContinuousSchedule.m', ...
    'network/buildSenderConflictGraph.m', ...
    'network/bindReplayDataOutcomes.m', ...
    'network/applyDstrAffineClockSchedule.m', ...
    'network/continuousTdmaGuardBound.m', ...
    'utils/exp23aeClosureCommonPhyRegistry.m', ...
    'utils/exp23aeClosureCommonPhyEmptyRow.m', ...
    'utils/runExp23aeClosureCommonPhyCell.m', ...
    'tests/test_exp23ae_closure_common_phy_contracts.m', ...
    'tests/test_receiver_lifted_closure_continuous_contracts.m', ...
    'experiments/exp23ae_receiver_lifted_closure_common_phy.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    name=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,name));
end

end


function writeJson(path,value)

fid=fopen(path,'w'); if fid<0, error('exp23ae: cannot write.'); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));

end


function value=ternary(condition,a,b)

if condition, value=a; else, value=b; end

end
