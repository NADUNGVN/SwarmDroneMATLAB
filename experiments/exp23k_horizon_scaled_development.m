function exp23k_horizon_scaled_development(resumeDir)
%EXP23K_HORIZON_SCALED_DEVELOPMENT Same-seed renewal feasibility probe.

if nargin<1, resumeDir=''; end
startup;
close all;
R=exp23kHorizonScaledRegistry();
[registryHash,registryLeaves]=configHash(R);
experimentName='exp23k_horizon_scaled_development';
sourceDir=fullfile(projectRoot(),'results', ...
    'exp23i_cumulative_closed_loop_target',R.sourceRun);
source=loadSource(sourceDir,R);
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(experimentName, ...
        ['Development-only feasibility test of the analytically selected ' ...
        '9x ELCS-W renewal horizon.']);
    writeJson(fullfile(expRun.dir,'horizon_registry.json'),R);
    writeJson(fullfile(expRun.dir,'horizon_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'sourceRun',R.sourceRun,'freshSeedEvidence',false, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=4;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=repmat(exp23kHorizonScaledEmptyRow(),numel(index),1);
    for q=1:numel(index)
        batch(q)=runSeed(R.seeds(index(q)),R);
    end
    rows=[rows;batch(:)]; %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  seeds %2d--%2d / %2d; rows %2d / %2d\n', ...
        index(1),index(end),numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
D=developmentContrast(T,source,R);
writetable(D,fullfile(expRun.dir,'development_contrast.csv'));
gates=validationGates(T,source,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
safetyNames=["candidate_safety" "candidate_terminal_liveness"];
safetyGate=ismember(string(gates.gate),safetyNames);
structuralPass=all(gates.passed(~safetyGate)==1);
safetyPass=all(gates.passed(safetyGate)==1);
mechanismPass=logical(D.mechanismPassed);
if ~structuralPass
    status='ELCS_W_HORIZON_DEVELOPMENT_INVALID';
    next='repair_probe_infrastructure';
elseif ~safetyPass
    status='ELCS_W_HORIZON_DEVELOPMENT_SAFETY_FAIL';
    next='reject_long_horizon';
elseif ~mechanismPass
    status='ELCS_W_HORIZON_DEVELOPMENT_INSUFFICIENT';
    next='return_to_renewal_design';
else
    status='ELCS_W_HORIZON_DEVELOPMENT_FEASIBLE';
    next='design_topology_coherence_and_revocation_semantics';
end
verdict=struct('status',status,'validationGatesPassed',sum(gates.passed), ...
    'validationGatesTotal',height(gates),'rows',height(T), ...
    'structuralIntegrityPassed',structuralPass, ...
    'candidateSafetyAndLivenessPassed',safetyPass, ...
    'mechanismPassed',mechanismPass,'next',next, ...
    'freshSeedEvidence',false,'newMethodPromotionAllowed',false, ...
    'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'horizon_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','D','gates','verdict','R');

fprintf('\nEXP23K horizon-scaled development gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf(['\nEXP23K EFFECT: management %.2f%%; cost vs periodic %.2f%%; ' ...
    'RMSE vs short %.2f%%\n'],100*D.relativeManagementDelta, ...
    100*D.relativeCostVsPeriodic,100*D.relativeRmseVsShort);
fprintf('EXP23K DECISION: %s\n',status);
finishExperiment(expRun);
if ~structuralPass
    error('exp23k: horizon development study structurally invalid.');
end

end


function row=runSeed(seedValue,R)

c=R.cells(1); condition=R.conditions(1);
base=applyExp21dClosedLoopCell(c.id,seedValue);
base.mac.backgroundLoad=condition.targetLoad;
base.mac=sharedMediumConfig(base);
trace=generateSharedMediumTrace(base);
C=elcsWitnessKernelConfig(base.swarm.N,R.elcsMaxFrames);
C.guardSec=R.missionSafeGuardSec;
C.dataBytes=base.mac.dataBytes;
C.phyRateBps=base.mac.phyRateBps;
C.neighborGraph=logical(base.swarm.A);
C.managementReach=C.neighborGraph;
C.interferenceMatrix=logical(base.mac.interferenceMatrix);
C.conflictGraph=buildSenderConflictGraph( ...
    C.neighborGraph,C.interferenceMatrix);
C.cumulativeReceiptRetry=true;
C.renewalPeriodFrames=R.renewalPeriodFrames;
C.leaseFrames=R.leaseFrames;
elcsTrace=generateElcsWitnessTrace(seedValue,C);
offset=(2*reshape(trace.exp21cClockOffsetU(1,:),[],1)-1)*R.maxOffsetSec;
drift=(2*reshape(trace.exp21cClockDriftU,[],1)-1)*R.maxDriftPpm;
clockSpec=struct('clockOffsetSec',offset,'clockDriftPpm',drift, ...
    'leadTimeSec',R.clockLeadTimeSec);
[elcsTrace,backgroundCertificate]=applySharedBackgroundToElcsWitnessTrace( ...
    elcsTrace,C,trace,clockSpec,condition.targetLoad);
nativeQ=buildElcsWitnessContinuousSchedule(C,elcsTrace,base.swarm.T);
nativeQ.backgroundOverlay=backgroundCertificate;
nativeQ.hashExact=realizationHash([ ...
    nativeQ.hashExact;backgroundCertificate.hashExact]);
CR=exp23cWitnessClosedLoopRegistry();
clockArm=CR.arms(strcmp({CR.arms.id},CR.clockArm));
[cfg,method,~,details]=applyExp23cWitnessClockArm( ...
    base,clockArm,nativeQ,trace,CR);
details.kind='candidate-elcs-w';
details.retryMode='cumulative-same-sequence-horizon9';
meta=struct('stage',R.stage,'scenario',c.id, ...
    'scenarioLabel',c.label,'family','EXP23K horizon development', ...
    'arm',R.arm.id,'pointIndex',1, ...
    'parameterValue',R.renewalScaleFactor);
[src,~]=runExp23fWitnessBackgroundCell(cfg,method,R.arm.label,meta, ...
    trace,details,R.arm.family,condition);
row=exp23kHorizonScaledEmptyRow();
names=fieldnames(src);
for k=1:numel(names), row.(names{k})=src.(names{k}); end
row.RENEWAL_SCALE_FACTOR=R.renewalScaleFactor;
row.RENEWAL_PERIOD_FRAMES=C.renewalPeriodFrames;
row.LEASE_FRAMES=C.leaseFrames;
row.REFRESH_LEAD_FRAMES=C.refreshLeadFrames;
row.LEASE_FENCE_FRAMES=C.leaseFenceFrames;

end


function D=developmentContrast(T,source,R)

L=sortrows(T,'seed');
I=exp23iCumulativeClosedLoopRegistry();
S=selectSource(source,I.cumulativeArm);
P=selectSource(source,I.periodicArm);
mgmt=pairedBootstrapCI(L.ELCSW_MANAGEMENT_AIRTIME, ...
    S.ELCSW_MANAGEMENT_AIRTIME,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+1,numel(R.seeds));
cost=pairedBootstrapCI(L.TOTAL_OFFERED_UTIL, ...
    P.TOTAL_OFFERED_UTIL,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+2,numel(R.seeds));
rmse=pairedBootstrapCI(L.RMSE,S.RMSE,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+3,numel(R.seeds));
relativeMgmt=mean(L.ELCSW_MANAGEMENT_AIRTIME)/ ...
    mean(S.ELCSW_MANAGEMENT_AIRTIME)-1;
relativeCost=mean(L.TOTAL_OFFERED_UTIL)/ ...
    mean(P.TOTAL_OFFERED_UTIL)-1;
relativeRmse=mean(L.RMSE)/mean(S.RMSE)-1;
mechanism=relativeMgmt<=-R.requiredManagementReduction && ...
    relativeCost<=-R.requiredPeriodicCostAdvantage && ...
    relativeRmse<=R.allowedRmseInflation;
D=table(numel(R.seeds),mean(S.ELCSW_MANAGEMENT_AIRTIME), ...
    mean(L.ELCSW_MANAGEMENT_AIRTIME),relativeMgmt, ...
    mgmt.meanD,mgmt.lo,mgmt.hi,mean(P.TOTAL_OFFERED_UTIL), ...
    mean(L.TOTAL_OFFERED_UTIL),relativeCost, ...
    cost.meanD,cost.lo,cost.hi,mean(S.RMSE),mean(L.RMSE), ...
    relativeRmse,rmse.meanD,rmse.lo,rmse.hi, ...
    mean(L.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS), ...
    mean(L.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED), ...
    double(mechanism),'VariableNames',{'nPairs', ...
    'shortMeanManagementAirtime','longMeanManagementAirtime', ...
    'relativeManagementDelta','managementDelta','managementCiLo', ...
    'managementCiHi','periodicMeanCost','longMeanCost', ...
    'relativeCostVsPeriodic','costDelta','costCiLo','costCiHi', ...
    'shortMeanRMSE','longMeanRMSE','relativeRmseVsShort', ...
    'rmseDelta','rmseCiLo','rmseCiHi','longMeanRetryClaims', ...
    'terminalCertificationRate','mechanismPassed'});

end


function gates=validationGates(T,source,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
sourceVerdict=jsondecode(fileread(fullfile(source.dir,'target_verdict.json')));
add('source_run_valid',strcmp(sourceVerdict.status,R.sourceDecision) && ...
    sourceVerdict.rows==180, ...
    'valid 180-row EXP23I source is fixed');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
add('exact_matrix_coverage',isequal(unique(T.seed),R.seeds) && ...
    isscalar(unique(string(T.scenario))) && all( ...
    string(T.arm)==string(R.arm.id)), ...
    'all 60 reused development seeds and one arm exact');
paired=true;
I=exp23iCumulativeClosedLoopRegistry();
for seed=R.seeds'
    a=T(T.seed==seed,:);
    b=source.T(source.T.seed==seed & ...
        string(source.T.arm)==string(I.cumulativeArm),:);
    paired=paired && height(a)==1 && height(b)==1 && ...
        a.TRACE_HASH_EXACT==b.TRACE_HASH_EXACT && ...
        a.ESTIMATOR_HASH_EXACT==b.ESTIMATOR_HASH_EXACT && ...
        a.BACKGROUND_RANDOM_FIELD_HASH_EXACT== ...
        b.BACKGROUND_RANDOM_FIELD_HASH_EXACT && abs( ...
        a.REALIZED_BACKGROUND_FRACTION-b.REALIZED_BACKGROUND_FRACTION)<= ...
        R.realizedFractionPairTolerance && abs( ...
        a.BACKGROUND_BUSY_TIME-b.BACKGROUND_BUSY_TIME)<=1e-9;
end
add('source_realization_pairing',paired, ...
    'trace, estimator, occupancy field and busy time match EXP23I');
declared=all(T.RENEWAL_SCALE_FACTOR==9) && all( ...
    T.RENEWAL_PERIOD_FRAMES==117) && all(T.LEASE_FRAMES==124) && ...
    all(T.REFRESH_LEAD_FRAMES==6) && all(T.LEASE_FENCE_FRAMES==1) && ...
    all(T.ELCSW_CUMULATIVE_RECEIPT_RETRY==1);
add('horizon_configuration_exact',declared, ...
    '9x period, exact lease slack and cumulative receipts observed');
certificate=all(T.ELCSW_BACKGROUND_OVERLAY_APPLIED==1) && all( ...
    T.ELCSW_BACKGROUND_TRACE_HASH_EXACT==T.TRACE_HASH_EXACT) && ...
    all(abs(T.ELCSW_BACKGROUND_LOAD-0.15)<=1e-12);
add('background_certificate',certificate, ...
    'candidate composes the shared IID-15 occupancy trace');
add('background_stimulus_activation',all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS>0) && all(T.BACKGROUND_BUSY_TIME>0), ...
    'occupancy intersects potential ELCS-W transmissions');
add('one_hop_witness_cover',all(T.ELCSW_ALL_EDGES_COVERED==1) && ...
    all(T.ELCSW_HIDDEN_CONFLICT_EDGES>0) && all( ...
    T.ELCSW_MAX_WITNESS_LOAD<=10), ...
    'hidden conflicts retain bounded one-hop witnesses');
add('absolute_control_bounds',all( ...
    T.ELCSW_ATTEMPT_BOUND_RATIO<=1+1e-12) && all( ...
    T.ELCSW_BYTE_BOUND_RATIO<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.ELCSW_ATTEMPT_BOUND_RATIO),max(T.ELCSW_BYTE_BOUND_RATIO)));
replay=all(T.ELCSW_DATA_SKIPPED_NO_QUEUE==0) && ...
    all(T.ELCSW_DATA_OUTCOME_MISMATCHES==0) && ...
    all(T.ELCSW_DATA_COLLISION_WITNESS_MATCH==1) && ...
    all(T.ELCSW_CROSS_PLANE_OVERLAPS==0) && ...
    all(T.ELCSW_CLOCK_TIMING_CONFLICT_FREE==1);
add('exact_elcs_w_replay',replay, ...
    'queue, outcome, clock and control/DATA contracts close');
management=all(T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE==1) && all( ...
    T.ELCSW_MANAGEMENT_ATTEMPTS==T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME- ...
    T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME)<=1e-12) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME-T.ELCSW_CONTROL_BYTES_AIRTIME)<=1e-12);
add('variable_payload_management_accounting',management, ...
    'attempt, byte, recipient and airtime accounting close');
add('candidate_safety',all(T.ELCSW_FALSE_VALID_EDGE_FRAMES==0) && ...
    all(T.ELCSW_SCHEDULED_COLLISION_FRAMES==0) && all( ...
    T.ELCSW_CERTIFICATE_WITHOUT_FRESH_CLAIMS==0) && ...
    all(T.SAFEFAIL==0) && all(T.DIVERGED==0), ...
    'zero certificate, collision, safety and divergence failures');
add('candidate_terminal_liveness',all( ...
    T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED==1) && all( ...
    T.ELCSW_FINAL_OPEN_CLAIM_TRANSACTIONS==0), ...
    'all rows certify and cumulative transactions close');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
account=all(abs(T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && all( ...
    T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && all( ...
    T.CHANNEL_UTIL<=T.TOTAL_OFFERED_UTIL+ ...
    T.REALIZED_BACKGROUND_FRACTION+1e-9);
add('causal_recipient_accounting',account && all( ...
    T.FUTURE_RANDOM_READS==0) && all(T.RECEIVER_TRUTH_READS==0) && ...
    all(T.INVARIANT_VIOLATIONS==0), ...
    'offered/recipient accounting and causal contracts close');
add('development_scope_only',~R.policyOptimizationAllowed && ...
    ~R.broadRobustnessClaimPermitted && ~R.newMethodPromotionAllowed && ...
    ~R.submissionClaimPermitted, ...
    'same-seed probe cannot support robustness or promotion');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23k: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function source=loadSource(sourceDir,R)

if ~isfolder(sourceDir), error('EXP23I source run not found.'); end
path=fullfile(sourceDir,'trajectory_tidy.csv');
if ~isfile(path), error('EXP23I source tidy table not found.'); end
source=struct('dir',sourceDir,'T',readtable(path,'TextType','string'));
I=exp23iCumulativeClosedLoopRegistry();
if height(source.T)~=I.expectedRuns || ~isequal(unique(source.T.seed),R.seeds)
    error('EXP23I source matrix does not match the probe registry.');
end

end


function T=selectSource(source,arm)
T=source.T(string(source.T.arm)==string(arm),:);
T=sortrows(T,'seed');
end


function [rows,completed]=loadCheckpoint(runDir,R)

completed=false(size(R.seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23kHorizonScaledEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string');
rows=table2struct(T);
for q=1:numel(R.seeds)
    index=T.seed==R.seeds(q);
    if nnz(index)==1, completed(q)=true;
    elseif any(index), error('exp23k: duplicate checkpoint seed.'); end
end

end


function runRequiredTests()
names={'test_exp23k_horizon_scaled_contracts', ...
    'test_elcs_cumulative_receipt_contracts', ...
    'test_elcs_background_load_contracts', ...
    'test_elcs_continuous_integration_contracts'};
for k=1:numel(names), runScriptIsolated(names{k}); end
end


function snapshotSource(target)

root=projectRoot();
files={'docs/EXP23K_HORIZON_SCALED_RENEWAL_DEVELOPMENT_PLAN.md', ...
    'docs/EXP23J_CONTROL_OVERHEAD_FLOOR_AUDIT_RESULTS_2026-09-04.md', ...
    'network/simulateElcsWitnessScheduling.m', ...
    'network/applySharedBackgroundToElcsWitnessTrace.m', ...
    'network/buildElcsWitnessContinuousSchedule.m', ...
    'utils/exp23kHorizonScaledRegistry.m', ...
    'utils/exp23kHorizonScaledEmptyRow.m', ...
    'utils/runExp23fWitnessBackgroundCell.m', ...
    'utils/runExp23cWitnessClosedLoopCell.m', ...
    'tests/test_exp23k_horizon_scaled_contracts.m', ...
    'experiments/exp23k_horizon_scaled_development.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    name=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,name));
end

end


function expRun=resumeRun(runDir,registryHash,registryLeaves,experimentName)
if ~isfolder(runDir), error('exp23k: resume directory not found.'); end
opened=jsondecode(fileread(fullfile(runDir,'horizon_opened.json')));
if opened.registryHash~=registryHash || opened.registryLeaves~=registryLeaves
    error('exp23k: registry differs from opened run.');
end
[~,runId]=fileparts(runDir);
meta=struct('experiment',experimentName,'runId',runId, ...
    'startedAt',opened.openedAt,'matlabVersion',version, ...
    'matlabRelease',version('-release'),'computer',computer, ...
    'projectRoot',projectRoot(),'gitCommit','', ...
    'notes','resumed frozen EXP23K checkpoint');
expRun=struct('name',experimentName,'runId',runId,'dir',runDir, ...
    'figDir',fullfile(runDir,'figures'),'expRoot',fileparts(runDir), ...
    'meta',meta,'t0',tic);
end


function writeJson(path,value)
fid=fopen(path,'w');
if fid<0, error('exp23k: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
