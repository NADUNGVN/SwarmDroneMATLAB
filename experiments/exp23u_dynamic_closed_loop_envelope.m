function exp23u_dynamic_closed_loop_envelope(resumeDir)
%EXP23U_DYNAMIC_CLOSED_LOOP_ENVELOPE Fresh dynamic common-PHY study.

if nargin<1, resumeDir=''; end
startup; close all;
R=exp23uDynamicClosedLoopEnvelopeRegistry();
[registryHash,registryLeaves]=configHash(R);
name='exp23u_dynamic_closed_loop_envelope';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(name, ...
        'Fresh dynamic common-PHY closed-loop operating envelope.');
    writeJson(fullfile(expRun.dir,'envelope_registry.json'),R);
    writeJson(fullfile(expRun.dir,'envelope_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,name);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
pending=find(~completed); checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=2;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending)); index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runExp23uDynamicClosedLoopSeed(R.seeds(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  seeds %2d--%2d / %2d; rows %3d / %3d\n', ...
        index(1),index(end),numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
D=operatingEnvelope(T,R); writetable(D,fullfile(expRun.dir,'operating_envelope.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'DYNAMIC_CLOSED_LOOP_OPERATING_ENVELOPE_VALID', ...
    'DYNAMIC_CLOSED_LOOP_OPERATING_ENVELOPE_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'performanceIsOperatingEnvelopeNotPassGate',true, ...
    'onlineGraphMigrationValidated',false, ...
    'next','implement_online_graph_reselection_and_color_migration', ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'envelope_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','D','gates','verdict','R');

fprintf('\nEXP23U dynamic closed-loop envelope gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23U operating envelope\n');
disp(D(:,{'arm','relativeRmseVsStatic','relativeCostVsStatic', ...
    'physicalReacquisitionRate','periodicEpsilonDominates'}));
fprintf('EXP23U DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23u: dynamic closed-loop envelope invalid.'); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
staticPath=fullfile(projectRoot(),'results','exp23t_static_coherence_closed_loop', ...
    R.parentStaticRun,'static_verdict.json');
dynamicPath=fullfile(projectRoot(),'results','exp23s_dynamic_revocation_kernel', ...
    R.parentDynamicKernelRun,'dynamic_verdict.json');
static=jsondecode(fileread(staticPath)); dynamic=jsondecode(fileread(dynamicPath));
add('parent_evidence_valid',strcmp(static.status,R.parentStaticStatus) && ...
    strcmp(dynamic.status,R.parentDynamicKernelStatus), ...
    'EXP23T static and EXP23S dynamic-kernel parents are valid');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && isequal( ...
    sort(unique(string(T.arm))),sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '60 fresh seeds and six paired operating-envelope arms exact');
paired=true;
for seed=R.seeds'
    index=T.seed==seed;
    paired=paired && nnz(index)==numel(R.arms) && ...
        isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
        isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
        isscalar(unique(T.BACKGROUND_RANDOM_FIELD_HASH_EXACT(index))) && ...
        max(T.BACKGROUND_BUSY_TIME(index))-min(T.BACKGROUND_BUSY_TIME(index))<=1e-9;
end
add('paired_closed_loop_realizations',paired, ...
    'channel, estimator, clocks and occupied busy time pair by seed');
candidate=string(T.arm)~=string(R.periodicArm);
dynamicRows=T.DYNAMIC_ENABLED==1;
basePair=true;
for seed=R.seeds'
    index=T.seed==seed & candidate;
    basePair=basePair && isscalar(unique(T.BASE_KERNEL_TRACE_HASH_EXACT(index))) && ...
        isscalar(unique(T.STATIC_SELECTOR_HASH_EXACT(index))) && ...
        isscalar(unique(T.STATIC_GRAPH_HASH_EXACT(index)));
end
add('paired_kernel_and_certificate',basePair, ...
    'all coherence arms share base kernel draws and fixed certificate');
add('coherence_configuration_exact',all( ...
    T.STATIC_SELECTED_HORIZON_SEC(candidate)==6.8) && all( ...
    T.STATIC_BINDING_ADMISSIBLE(candidate)==1) && all( ...
    T.STATIC_CLAIM_PACKET_BYTES(candidate)==28) && all( ...
    T.STATIC_CERTIFICATE_ENTRY_BYTES(candidate)==10) && all( ...
    T.STATIC_REVOKE_PACKET_BYTES(candidate)==24), ...
    'all coherence arms bind the 6.8 s exact packet certificate');
certificate=all(T.ELCSW_BACKGROUND_OVERLAY_APPLIED(candidate)==1) && ...
    all(T.ELCSW_BACKGROUND_TRACE_HASH_EXACT(candidate)== ...
    T.TRACE_HASH_EXACT(candidate)) && all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS(candidate)>0);
add('shared_background_certificate',certificate, ...
    'IID-15 occupancy overlays every coherence schedule');
periodic=string(T.arm)==string(R.periodicArm);
add('periodic_boundary_and_timing',all(abs( ...
    T.PERIODIC_RATE_HZ(periodic)-R.cells.lowerCostRateHz)<1e-12) && ...
    all(T.ENDOGENOUS_COLLISION_FRAMES(periodic)==0) && all( ...
    T.CONTINUOUS_MAX_CLOCK_RESIDUAL(periodic)<=2e-12), ...
    'periodic reference remains at the frozen guarded boundary');
add('dynamic_event_stimulus',all(T.PHYSICAL_EVENT_INCLUDED(dynamicRows)==1) && ...
    all(T.PHYSICAL_PRE_EVENT_ACTIVE(dynamicRows)==1),sprintf( ...
    '%d/%d events occur after positive scheduled state', ...
    sum(T.PHYSICAL_PRE_EVENT_ACTIVE(dynamicRows)),nnz(dynamicRows)));
add('exact_revoke_common_phy_mapping',all( ...
    T.PHYSICAL_REVOKE_ATTEMPTS(dynamicRows)==1) && all( ...
    T.PHYSICAL_REVOKE_BYTES(dynamicRows)==24) && all(abs( ...
    T.PHYSICAL_REVOKE_AIRTIME(dynamicRows)-24*8/250e3)<=1e-15), ...
    'one exact 24-byte REVOKE is mapped in each dynamic mission');
add('event_frame_fail_silent',all( ...
    T.PHYSICAL_EVENT_SUPPRESSED(dynamicRows)==1), ...
    'revoker stops scheduled DATA in the event frame');
reacquired=dynamicRows & T.PHYSICAL_REACQUIRED==1;
add('old_fence_respected',all(T.FIRST_PHYSICAL_REACQUIRED_FRAME(reacquired)> ...
    T.CAPTURED_FENCE_FRAME(reacquired)), ...
    'every physical scheduled reuse occurs after the old fence');
early=ismember(string(T.arm),[string(R.earlyArm) ...
    string(R.revokeBlackoutArm)]);
add('early_event_reacquisition_liveness',all( ...
    T.PHYSICAL_REACQUIRED(early)==1) && all( ...
    T.PHYSICAL_FINAL_SUPPRESSED(early)==0) && all( ...
    T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED(early)==1),sprintf( ...
    '%d/%d early non-RESPONSE-blackout rows reacquire', ...
    sum(T.PHYSICAL_REACQUIRED(early)),nnz(early)));
late=string(T.arm)==string(R.lateArm);
add('late_event_fence_boundary',all(T.PHYSICAL_REACQUIRED(late)==0) && ...
    all(T.PHYSICAL_FINAL_SUPPRESSED(late)==1) && all( ...
    T.CAPTURED_FENCE_FRAME(late)>=T.PHYSICAL_FRAME_COUNT_DYNAMIC(late)), ...
    'late event remains suppressed because old fence exceeds mission');
blocked=string(T.arm)==string(R.responseBlackoutArm);
add('response_blackout_fail_silent',all( ...
    T.REACQUIRE_BLOCKED_WITNESSES(blocked)>0) && all( ...
    T.PHYSICAL_REACQUIRED(blocked)==0) && all( ...
    T.PHYSICAL_FINAL_SUPPRESSED(blocked)==1), ...
    'permanent required RESPONSE loss prevents scheduled reuse');
independent=true;
for seed=R.seeds'
    a=T.seed==seed & string(T.arm)==string(R.earlyArm);
    b=T.seed==seed & string(T.arm)==string(R.revokeBlackoutArm);
    independent=independent && T.PHYSICAL_SUPPRESSION_HASH_EXACT(a)== ...
        T.PHYSICAL_SUPPRESSION_HASH_EXACT(b) && ...
        T.PHYSICAL_REACQUIRED_HASH_EXACT(a)== ...
        T.PHYSICAL_REACQUIRED_HASH_EXACT(b);
end
add('revoke_loss_safety_independence',independent && all( ...
    T.REVOKE_FORCED_BLACKOUT(string(T.arm)== ...
    string(R.revokeBlackoutArm))==1), ...
    'REVOKE blackout cannot change local silence or reuse time');
safe=all(T.ELCSW_FALSE_VALID_EDGE_FRAMES(candidate)==0) && ...
    all(T.ELCSW_SCHEDULED_COLLISION_FRAMES(candidate)==0) && ...
    all(T.SAFEFAIL(candidate)==0) && all(T.DIVERGED(candidate)==0);
add('candidate_safety',safe, ...
    'zero false-valid, scheduled-collision, safety or divergence failures');
replay=all(T.ELCSW_DATA_SKIPPED_NO_QUEUE(candidate)==0) && ...
    all(T.ELCSW_DATA_OUTCOME_MISMATCHES(candidate)==0) && ...
    all(T.ELCSW_DATA_COLLISION_WITNESS_MATCH(candidate)==1) && ...
    all(T.ELCSW_CROSS_PLANE_OVERLAPS(candidate)==0) && ...
    all(T.ELCSW_CLOCK_TIMING_CONFLICT_FREE(candidate)==1);
add('exact_continuous_replay',replay, ...
    'dynamic DATA/control outcomes and clock timeline replay exactly');
management=all(T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE(candidate)==1) && ...
    all(T.ELCSW_MANAGEMENT_ATTEMPTS(candidate)== ...
    T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS(candidate)) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME(candidate))<=1e-12) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_CONTROL_BYTES_AIRTIME(candidate))<=1e-12);
add('management_revoke_airtime_accounting',management, ...
    'CLAIM/RESPONSE/REVOKE recipient, byte and airtime totals close');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
account=all(abs(T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && all( ...
    T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && all( ...
    T.CHANNEL_UTIL<=T.TOTAL_OFFERED_UTIL+ ...
    T.REALIZED_BACKGROUND_FRACTION+1e-9);
add('causal_recipient_airtime_scope',account && all( ...
    T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && all(T.INVARIANT_VIOLATIONS==0) && ...
    ~R.policyOptimizationAllowed && ~R.broadRobustnessClaimPermitted && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted, ...
    ['offered airtime, recipients and busy union close; zero forbidden ' ...
    'reads; operating envelope cannot promote']);
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23u: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function D=operatingEnvelope(T,R)

P=sortrows(T(string(T.arm)==string(R.periodicArm),:),'seed');
S=sortrows(T(string(T.arm)==string(R.staticArm),:),'seed');
arms=R.arms(2:end); rows=cell(numel(arms),18);
for k=1:numel(arms)
    C=sortrows(T(string(T.arm)==string(arms(k).id),:),'seed');
    rmse=pairedBootstrapCI(C.RMSE,S.RMSE,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+4*k,numel(R.seeds));
    cost=pairedBootstrapCI(C.TOTAL_OFFERED_UTIL,S.TOTAL_OFFERED_UTIL, ...
        R.bootstrapReplicates,R.bootstrapSeedBase+4*k+1,numel(R.seeds));
    cr=mean(C.RMSE); cc=mean(C.TOTAL_OFFERED_UTIL);
    periodicDominates=mean(P.RMSE)<=(1+R.epsilonRmse)*cr && ...
        mean(P.TOTAL_OFFERED_UTIL)<= ...
        (1-R.requiredCostImprovement)*cc;
    rows(k,:)={string(arms(k).id),height(C),cr,cc, ...
        cr/mean(S.RMSE)-1,cc/mean(S.TOTAL_OFFERED_UTIL)-1, ...
        cr/mean(P.RMSE)-1,cc/mean(P.TOTAL_OFFERED_UTIL)-1, ...
        rmse.meanD,rmse.lo,rmse.hi,cost.meanD,cost.lo,cost.hi, ...
        mean(C.PHYSICAL_REACQUIRED,'omitnan'), ...
        mean(C.PHYSICAL_FINAL_SUPPRESSED,'omitnan'), ...
        mean(C.TOTAL_MANAGEMENT_AIRTIME),double(periodicDominates)};
end
D=cell2table(rows,'VariableNames',{'arm','nPairs','meanRMSE','meanCost', ...
    'relativeRmseVsStatic','relativeCostVsStatic', ...
    'relativeRmseVsPeriodic','relativeCostVsPeriodic', ...
    'rmseDeltaVsStatic','rmseCiLo','rmseCiHi','costDeltaVsStatic', ...
    'costCiLo','costCiHi','physicalReacquisitionRate', ...
    'physicalFinalSuppressionRate','meanManagementAirtime', ...
    'periodicEpsilonDominates'});
end


function S=summaryTable(T)
[group,S]=findgroups(T(:,{'arm','methodLabel'}));
S.nRuns=splitapply(@numel,T.RMSE,group);
S.meanRMSE=splitapply(@mean,T.RMSE,group);
S.meanOfferedUtil=splitapply(@mean,T.TOTAL_OFFERED_UTIL,group);
S.meanManagementAirtime=splitapply(@mean,T.TOTAL_MANAGEMENT_AIRTIME,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);
end


function [rows,completed]=loadCheckpoint(runDir,R)
completed=false(size(R.seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23uDynamicClosedLoopEnvelopeEmptyRow(),0,1); return;
end
T=readtable(path,'TextType','string'); rows=table2struct(T);
for q=1:numel(R.seeds)
    index=T.seed==R.seeds(q);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23u: partial checkpoint seed.'); end
end
end


