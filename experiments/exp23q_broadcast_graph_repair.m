function exp23q_broadcast_graph_repair()
%EXP23Q_BROADCAST_GRAPH_REPAIR Fresh independent-oracle graph validation.

startup; close all;
runScriptIsolated('test_exp23q_broadcast_graph_repair_contracts');
runScriptIsolated('test_coherence_certified_lease_contracts');
runScriptIsolated('test_elcs_coherence_integration_contracts');
R=exp23qBroadcastGraphRepairRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23q_broadcast_graph_repair', ...
    'Fresh independent-oracle validation of repaired broadcast graph.');
writeJson(fullfile(expRun.dir,'graph_registry.json'),R);
writeJson(fullfile(expRun.dir,'graph_opened.json'),struct( ...
    'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
    'registryHash',registryHash,'registryLeaves',registryLeaves, ...
    'submissionClaimPermitted',false));
snapshotSource(expRun.dir);

rows=repmat(exp23qBroadcastGraphRepairEmptyRow(),R.expectedRuns,1); q=0;
for seed=R.seeds'
    for N=R.nodeCounts
        base=generateExp23mCoherenceBase(seed,N,R);
        for conditionIndex=1:numel(R.conditions)
            q=q+1;
            rows(q)=runExp23qBroadcastGraphRepairCell( ...
                base,R.conditions(conditionIndex),conditionIndex,R);
        end
    end
    seedIndex=find(R.seeds==seed);
    if mod(seedIndex,10)==0
        fprintf('  seeds %3d / %3d; rows %3d / %3d\n', ...
            seedIndex,numel(R.seeds),q,R.expectedRuns);
    end
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'graph_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'BROADCAST_DETECTABILITY_GRAPH_REPAIR_VALID', ...
    'BROADCAST_DETECTABILITY_GRAPH_REPAIR_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'freshPacketKernelRepairPermitted',pass, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'graph_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','gates','verdict','R');

fprintf('\nEXP23Q broadcast graph-repair gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-45s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23Q DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23q: broadcast graph repair invalid.'); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.N)+'|'+string(T.condition);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(unique(T.N)',R.nodeCounts) && isequal( ...
    sort(unique(string(T.condition))), ...
    sort(reshape(string({R.conditions.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '100 fresh seeds, N5/N10 and three geometry cells exact');
paired=true;
for seed=R.seeds'
    for N=R.nodeCounts
        index=T.seed==seed & T.N==N;
        paired=paired && nnz(index)==numel(R.conditions) && ...
            isscalar(unique(T.BASE_REALIZATION_HASH(index))) && ...
            isscalar(unique(T.DATA_NEIGHBOR_GRAPH_HASH(index)));
    end
end
add('paired_base_and_receiver_graph',paired, ...
    'geometry cells share base realization and intended receiver graph');
base=generateExp23mCoherenceBase(R.seeds(1),R.nodeCounts(1),R);
a=runExp23qBroadcastGraphRepairCell(base,R.conditions(1),1,R);
b=runExp23qBroadcastGraphRepairCell(base,R.conditions(1),1,R);
add('deterministic_reproduction',isequaln(a,b), ...
    'repeated seed/cell is bit-identical');
add('independent_actual_graph_subset',all(T.actualSubsetViolations==0), ...
    'independently enumerated actual sender graph is a subset');
add('independent_proper_color_safety',all( ...
    T.sameColorConflictViolations==0), ...
    'independent conflicting sender pairs never share a color');
add('direct_receiver_delivery_safety',all( ...
    T.directDeliveryCollisionViolations==0), ...
    'direct receiver oracle observes zero same-color DATA collisions');
add('reach_beyond_interference_stimulus',sum( ...
    T.reachOnlyActualConflictEdges)>0,sprintf( ...
    'aggregate intended-reach-only conflict instances %.0f', ...
    sum(T.reachOnlyActualConflictEdges)));
add('sender_graph_horizon_monotonicity',all( ...
    T.horizonMonotonicViolations==0), ...
    'receiver-lifted sender edges never disappear with horizon');
static=string(T.condition)==string(R.staticCondition);
add('static_target_activation',all(T.targetHorizonSelected(static)==1) && ...
    all(T.noLeaseIssued(static)==0),sprintf( ...
    '%d/%d static/wide rows select 6.8 s', ...
    nnz(T.targetHorizonSelected(static)),nnz(static)));
contraction=true;
for seed=R.seeds'
    for N=R.nodeCounts
        low=T.selectedHorizonSec(T.seed==seed & T.N==N & ...
            string(T.condition)==string(R.mobileLowCondition));
        high=T.selectedHorizonSec(T.seed==seed & T.N==N & ...
            string(T.condition)==string(R.mobileHighCondition));
        contraction=contraction && isscalar(low) && isscalar(high) && ...
            high<=low+1e-12;
    end
end
add('uncertainty_horizon_contraction',contraction, ...
    'mobile high uncertainty never lengthens paired horizon');
issued=T.selectedIndex>0;
add('issued_witness_payload_slot_feasibility',all( ...
    T.selectedWitnessCovered(issued)==1) && all( ...
    T.selectedPayloadFits(issued)==1) && all( ...
    T.selectedColorCount(issued)<=T.N(issued)), ...
    'issued sender graph has witness, MTU and color feasibility');
add('uncovered_fail_silent',all(T.noLeaseIssued==double( ...
    T.selectedIndex==0)), ...
    'no feasible repaired horizon yields no lease');
add('self_revocation_contract',all(T.normalSelfRevocations==0) && ...
    all(T.injectedViolationMisses==0), ...
    'bounded motion stays active; injected bound violation self-revokes');
add('causal_information_contract',all(T.futureRandomReads==0) && ...
    all(T.receiverTruthDecisionReads==0), ...
    'zero future-random and receiver-truth decision reads');
add('hidden_sender_conflict_stimulus',sum( ...
    T.hiddenSenderConflictEdges)>0,sprintf( ...
    'aggregate receiver-lifted hidden-edge instances %.0f', ...
    sum(T.hiddenSenderConflictEdges)));
stimulus=any(T.dataNeighborEdges>0) && any( ...
    T.targetHorizonSelected==1) && any(T.selectedHorizonSec>0 & ...
    T.targetHorizonSelected==0) && any(T.noLeaseIssued==1);
add('selector_boundary_stimulus',stimulus,sprintf( ...
    'target/contracted/no-lease rows %d/%d/%d', ...
    nnz(T.targetHorizonSelected),nnz(T.selectedHorizonSec>0 & ...
    T.targetHorizonSelected==0),nnz(T.noLeaseIssued)));
add('kernel_scope_only',~R.policyOptimizationAllowed && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted, ...
    'graph repair only; no packet, closed-loop or submission decision');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23q: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'N','condition','positionError', ...
    'velocityError','speedScale','accelerationScale','managementRadius'}));
S.nRuns=splitapply(@numel,T.selectedHorizonSec,group);
S.meanSelectedHorizonSec=splitapply(@mean,T.selectedHorizonSec,group);
S.targetHorizonRate=splitapply(@mean,T.targetHorizonSelected,group);
S.noLeaseRate=splitapply(@mean,T.noLeaseIssued,group);
S.meanSelectedSenderEdges=splitapply(@mean,T.selectedEdgeCount,group);
S.reachOnlyConflictInstances=splitapply(@sum, ...
    T.reachOnlyActualConflictEdges,group);
S.directDeliveryCollisionViolations=splitapply(@sum, ...
    T.directDeliveryCollisionViolations,group);
end


function snapshotSource(target)

root=projectRoot();
files={'docs/EXP23Q_BROADCAST_GRAPH_REPAIR_PLAN.md', ...
    'docs/EXP23P_INVALID_COHERENCE_PACKET_RESULTS_2026-09-04.md', ...
    'docs/EXP23L_COHERENCE_CERTIFIED_LEASE_DESIGN.md', ...
    'network/buildSenderConflictGraph.m', ...
    'network/buildReachableConflictSupergraph.m', ...
    'network/buildReachableBroadcastConflictSupergraph.m', ...
    'network/selectCoherenceLeaseHorizon.m', ...
    'network/coherenceSelfRevocationDecision.m', ...
    'utils/exp23qBroadcastGraphRepairRegistry.m', ...
    'utils/exp23qBroadcastGraphRepairEmptyRow.m', ...
    'utils/runExp23qBroadcastGraphRepairCell.m', ...
    'tests/test_exp23q_broadcast_graph_repair_contracts.m', ...
    'tests/test_coherence_certified_lease_contracts.m', ...
    'tests/test_elcs_coherence_integration_contracts.m', ...
    'experiments/exp23q_broadcast_graph_repair.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    name=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,name));
end
end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('exp23q: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
