function exp23v_fast_reactivation_development(resumeDir)
%EXP23V_FAST_REACTIVATION_DEVELOPMENT Same-seed mechanism probe.

if nargin<1, resumeDir=''; end
startup; close all;
R=exp23vFastReactivationDevelopmentRegistry();
[registryHash,registryLeaves]=configHash(R);
source=loadSource(R);
name='exp23v_fast_reactivation_development';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(name, ...
        'Same-seed witness-confirmed early-reactivation mechanism probe.');
    writeJson(fullfile(expRun.dir,'fast_registry.json'),R);
    writeJson(fullfile(expRun.dir,'fast_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'freshSeedEvidence',false,'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,name);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
pending=find(~completed); checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=3;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending)); index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runExp23uDynamicClosedLoopSeed(R.seeds(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  seeds %2d--%2d / %2d; rows %3d / %3d\n', ...
        index(1),index(end),numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
D=repairEffects(T,source.T,R);
writetable(D,fullfile(expRun.dir,'repair_effects.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=validationGates(T,source,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
structuralPass=all(gates.passed==1);
mechanismPass=all(D.mechanismRelief(D.arm~=string( ...
    R.fastResponseBlackoutArm))==1);
if ~structuralPass
    status='FAST_REACTIVATION_DEVELOPMENT_INVALID';
    next='repair_fast_reactivation_infrastructure';
elseif ~mechanismPass
    status='FAST_REACTIVATION_MECHANISM_INSUFFICIENT';
    next='retain_negative_and_design_transition_ack';
else
    status='FAST_REACTIVATION_DEVELOPMENT_FEASIBLE';
    next='fresh_seed_fast_reactivation_confirmation';
end
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'mechanismReliefPassed',mechanismPass, ...
    'freshSeedEvidence',false,'next',next, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'fast_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','D','S','gates','verdict','R');

fprintf('\nEXP23V fast-reactivation development gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23V repair effects\n');
disp(D(:,{'arm','relativeRmseVsOld','relativeCostVsOld', ...
    'physicalReacquisitionRate','periodicEpsilonDominates','mechanismRelief'}));
fprintf('EXP23V DECISION: %s\n',status);
finishExperiment(expRun);
if ~structuralPass, error('exp23v: development probe invalid.'); end

end


function gates=validationGates(T,source,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
add('source_envelope_valid',strcmp(source.verdict.status, ...
    R.parentEnvelopeStatus) && height(source.T)==360, ...
    'valid 360-row EXP23U operating envelope is fixed');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && isequal( ...
    sort(unique(string(T.arm))),sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '60 reused paired seeds and three fast arms exact');
paired=true;
for seed=R.seeds'
    fast=T.seed==seed;
    old=source.T.seed==seed;
    paired=paired && nnz(fast)==3 && nnz(old)==6 && ...
        isscalar(unique(T.TRACE_HASH_EXACT(fast))) && ...
        unique(T.TRACE_HASH_EXACT(fast))==unique(source.T.TRACE_HASH_EXACT(old)) && ...
        isscalar(unique(T.ESTIMATOR_HASH_EXACT(fast))) && ...
        unique(T.ESTIMATOR_HASH_EXACT(fast))== ...
        unique(source.T.ESTIMATOR_HASH_EXACT(old)) && ...
        max(T.BACKGROUND_BUSY_TIME(fast))-min(T.BACKGROUND_BUSY_TIME(fast))<=1e-9;
end
add('source_realization_pairing',paired, ...
    'channel, estimator, clocks and occupancy match EXP23U by seed');
add('fast_mode_exact',all( ...
    T.ELCSW_WITNESS_CONFIRMED_REACTIVATION==1) && all( ...
    T.DYNAMIC_ENABLED==1),'every row activates union-graph fast mode');
add('dynamic_event_stimulus',all(T.PHYSICAL_EVENT_INCLUDED==1) && ...
    all(T.PHYSICAL_PRE_EVENT_ACTIVE==1) && all( ...
    T.PHYSICAL_EVENT_SUPPRESSED==1), ...
    'every event follows positive state and suppresses immediately');
add('exact_revoke_mapping',all(T.PHYSICAL_REVOKE_ATTEMPTS==1) && ...
    all(T.PHYSICAL_REVOKE_BYTES==24) && all(abs( ...
    T.PHYSICAL_REVOKE_AIRTIME-24*8/250e3)<=1e-15), ...
    'one exact 24-byte common-PHY REVOKE per trajectory');
normal=string(T.arm)~=string(R.fastResponseBlackoutArm);
add('fresh_response_reactivation',all(T.PHYSICAL_REACQUIRED(normal)==1) && ...
    all(T.FIRST_PHYSICAL_REACQUIRED_FRAME(normal)>= ...
    T.REACQUIRE_ELIGIBLE_FRAME(normal)) && all( ...
    T.PHYSICAL_FINAL_SUPPRESSED(normal)==0),sprintf( ...
    '%d/%d early/late rows reactivate after eligibility', ...
    sum(T.PHYSICAL_REACQUIRED(normal)),nnz(normal)));
early=string(T.arm)==string(R.fastEarlyArm);
late=string(T.arm)==string(R.fastLateArm);
add('old_fence_bypass_stimulus',all( ...
    T.FIRST_PHYSICAL_REACQUIRED_FRAME(early)<T.CAPTURED_FENCE_FRAME(early)) && ...
    all(T.FIRST_PHYSICAL_REACQUIRED_FRAME(late)<T.CAPTURED_FENCE_FRAME(late)), ...
    'fresh union-witness closure reuses before conservative old fence');
blocked=string(T.arm)==string(R.fastResponseBlackoutArm);
add('response_blackout_fail_silent',all( ...
    T.REACQUIRE_BLOCKED_WITNESSES(blocked)>0) && all( ...
    T.PHYSICAL_REACQUIRED(blocked)==0) && all( ...
    T.PHYSICAL_FINAL_SUPPRESSED(blocked)==1), ...
    'missing required witness RESPONSE prevents fast reactivation');
add('candidate_safety',all(T.ELCSW_FALSE_VALID_EDGE_FRAMES==0) && ...
    all(T.ELCSW_SCHEDULED_COLLISION_FRAMES==0) && all(T.SAFEFAIL==0) && ...
    all(T.DIVERGED==0),'zero certificate, collision, safety or divergence failures');
add('exact_continuous_replay',all(T.ELCSW_DATA_SKIPPED_NO_QUEUE==0) && ...
    all(T.ELCSW_DATA_OUTCOME_MISMATCHES==0) && all( ...
    T.ELCSW_DATA_COLLISION_WITNESS_MATCH==1) && all( ...
    T.ELCSW_CROSS_PLANE_OVERLAPS==0) && all( ...
    T.ELCSW_CLOCK_TIMING_CONFLICT_FREE==1), ...
    'DATA/control outcomes and affine-clock timeline replay exactly');
add('management_airtime_accounting',all( ...
    T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE==1) && all( ...
    T.ELCSW_MANAGEMENT_ATTEMPTS==T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME- ...
    T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME)<=1e-12) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME-T.ELCSW_CONTROL_BYTES_AIRTIME)<=1e-12), ...
    'REVOKE/CLAIM/RESPONSE recipient, byte and airtime totals close');
add('shared_background_certificate',all( ...
    T.ELCSW_BACKGROUND_OVERLAY_APPLIED==1) && all( ...
    T.ELCSW_BACKGROUND_TRACE_HASH_EXACT==T.TRACE_HASH_EXACT) && all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS>0), ...
    'every fast schedule composes the paired IID-15 trace');
add('absolute_control_bounds',all(T.ELCSW_ATTEMPT_BOUND_RATIO<=1+1e-12) && ...
    all(T.ELCSW_BYTE_BOUND_RATIO<=1+1e-12), ...
    'absolute attempt and byte bounds hold');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
add('causal_recipient_airtime',all(abs(T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && ...
    all(T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && all( ...
    T.FUTURE_RANDOM_READS==0) && all(T.RECEIVER_TRUTH_READS==0) && ...
    all(T.INVARIANT_VIOLATIONS==0), ...
    'recipient/airtime accounting closes with zero forbidden reads');
add('development_scope_only',~R.freshSeedEvidence && ...
    ~R.policyOptimizationAllowed && ~R.broadRobustnessClaimPermitted && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted, ...
    'same-seed mechanism probe cannot promote');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23v: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function D=repairEffects(T,U,R)

static=sortrows(U(string(U.arm)==string(R.staticSourceArm),:),'seed');
periodic=sortrows(U(string(U.arm)==string(R.periodicSourceArm),:),'seed');
fastIds=[string(R.fastEarlyArm) string(R.fastLateArm) ...
    string(R.fastResponseBlackoutArm)];
oldIds=[string(R.oldEarlyArm) string(R.oldLateArm) ...
    string(R.oldResponseBlackoutArm)];
rows=cell(3,19);
for k=1:3
    F=sortrows(T(string(T.arm)==fastIds(k),:),'seed');
    O=sortrows(U(string(U.arm)==oldIds(k),:),'seed');
    rmse=pairedBootstrapCI(F.RMSE,O.RMSE,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+4*k,numel(R.seeds));
    cost=pairedBootstrapCI(F.TOTAL_OFFERED_UTIL,O.TOTAL_OFFERED_UTIL, ...
        R.bootstrapReplicates,R.bootstrapSeedBase+4*k+1,numel(R.seeds));
    periodicDominates=mean(periodic.RMSE)<= ...
        (1+R.epsilonRmse)*mean(F.RMSE) && ...
        mean(periodic.TOTAL_OFFERED_UTIL)<= ...
        (1-R.requiredCostImprovement)*mean(F.TOTAL_OFFERED_UTIL);
    relief=rmse.hi<0 && mean(F.RMSE)<mean(O.RMSE) && ...
        all(F.ELCSW_SCHEDULED_COLLISION_FRAMES==0);
    if k==3, relief=true; end
    rows(k,:)={fastIds(k),oldIds(k),numel(R.seeds),mean(F.RMSE), ...
        mean(O.RMSE),mean(F.RMSE)/mean(O.RMSE)-1,rmse.meanD,rmse.lo,rmse.hi, ...
        mean(F.TOTAL_OFFERED_UTIL),mean(O.TOTAL_OFFERED_UTIL), ...
        mean(F.TOTAL_OFFERED_UTIL)/mean(O.TOTAL_OFFERED_UTIL)-1, ...
        cost.meanD,cost.lo,cost.hi,mean(F.RMSE)/mean(static.RMSE)-1, ...
        mean(F.PHYSICAL_REACQUIRED),double(periodicDominates),double(relief)};
end
D=cell2table(rows,'VariableNames',{'arm','oldArm','nPairs','fastMeanRMSE', ...
    'oldMeanRMSE','relativeRmseVsOld','rmseDelta','rmseCiLo','rmseCiHi', ...
    'fastMeanCost','oldMeanCost','relativeCostVsOld','costDelta', ...
    'costCiLo','costCiHi','relativeRmseVsStatic', ...
    'physicalReacquisitionRate','periodicEpsilonDominates','mechanismRelief'});
end


function S=summaryTable(T)
[group,S]=findgroups(T(:,{'arm','methodLabel'}));
S.nRuns=splitapply(@numel,T.RMSE,group);
S.meanRMSE=splitapply(@mean,T.RMSE,group);
S.meanOfferedUtil=splitapply(@mean,T.TOTAL_OFFERED_UTIL,group);
S.meanManagementAirtime=splitapply(@mean,T.TOTAL_MANAGEMENT_AIRTIME,group);
end


function source=loadSource(R)
dirPath=fullfile(projectRoot(),'results','exp23u_dynamic_closed_loop_envelope', ...
    R.parentEnvelopeRun);
source=struct('dir',dirPath, ...
    'T',readtable(fullfile(dirPath,'trajectory_tidy.csv'),'TextType','string'), ...
    'verdict',jsondecode(fileread(fullfile(dirPath,'envelope_verdict.json'))));
end


function [rows,completed]=loadCheckpoint(runDir,R)
completed=false(size(R.seeds)); path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23uDynamicClosedLoopEnvelopeEmptyRow(),0,1); return;
end
T=readtable(path,'TextType','string'); rows=table2struct(T);
for q=1:numel(R.seeds)
    index=T.seed==R.seeds(q);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23v: partial checkpoint seed.'); end
end
end


function runRequiredTests()
names={'test_exp23v_fast_reactivation_development_contracts', ...
    'test_elcs_dynamic_revocation_contracts', ...
    'test_elcs_dynamic_continuous_integration_contracts'};
for k=1:numel(names), runScriptIsolated(names{k}); end
end


function snapshotSource(target)
root=projectRoot();
files={'docs/EXP23V_FAST_REACTIVATION_DEVELOPMENT_PLAN.md', ...
    'docs/EXP23V_WITNESS_CONFIRMED_REACTIVATION_DESIGN.md', ...
    'docs/EXP23U_DYNAMIC_CLOSED_LOOP_ENVELOPE_RESULTS_2026-09-04.md', ...
    'network/simulateElcsWitnessScheduling.m', ...
    'network/buildElcsWitnessContinuousSchedule.m', ...
    'utils/exp23vFastReactivationDevelopmentRegistry.m', ...
    'utils/runExp23uDynamicClosedLoopSeed.m', ...
    'utils/runExp23cWitnessClosedLoopCell.m', ...
    'tests/test_exp23v_fast_reactivation_development_contracts.m', ...
    'tests/test_elcs_dynamic_revocation_contracts.m', ...
    'experiments/exp23v_fast_reactivation_development.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    fileName=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,fileName));
end
end


function expRun=resumeRun(runDir,registryHash,registryLeaves,name)
if ~isfolder(runDir), error('exp23v: resume directory not found.'); end
opened=jsondecode(fileread(fullfile(runDir,'fast_opened.json')));
if opened.registryHash~=registryHash || opened.registryLeaves~=registryLeaves
    error('exp23v: registry differs from opened run.');
end
[~,runId]=fileparts(runDir);
meta=struct('experiment',name,'runId',runId,'startedAt',opened.openedAt, ...
    'matlabVersion',version,'matlabRelease',version('-release'), ...
    'computer',computer,'projectRoot',projectRoot(),'gitCommit','', ...
    'notes','resumed frozen EXP23V checkpoint');
expRun=struct('name',name,'runId',runId,'dir',runDir, ...
    'figDir',fullfile(runDir,'figures'),'expRoot',fileparts(runDir), ...
    'meta',meta,'t0',tic);
end


function writeJson(path,value)
fid=fopen(path,'w');
if fid<0, error('exp23v: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end
