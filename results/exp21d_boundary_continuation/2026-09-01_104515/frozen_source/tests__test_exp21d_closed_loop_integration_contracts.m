%% TEST_EXP21D_CLOSED_LOOP_INTEGRATION_CONTRACTS D-STR timeline contracts.

startup;
fprintf('\n============================================================\n');
fprintf('test_exp21d_closed_loop_integration_contracts\n');
fprintf('============================================================\n\n');
checks=cell(0,2);

C=kernelCfg(4,90);
R=struct('maxFrames',C.maxFrames,'traceSeedOffset',21092026);
T=generateExp21dDstrTrace(16035991,C.N,R);
probe=simulateDstrScheduling(C,T);
Q=buildDstrContinuousSchedule(C,T,probe.elapsedSec);

checks(end+1,:)={numel(Q.dataStartTime)==probe.dataAttempts && ...
    numel(Q.controlStartTime)==probe.managementAttempts, ...
    'every complete-horizon kernel DATA/control attempt maps once'};
checks(end+1,:)={sum(Q.controlGroupAttempts)==probe.managementAttempts && ...
    sum(Q.controlGroupRecipientAttempts)== ...
        probe.managementRecipientAttempts && ...
    sum(Q.controlGroupRecipientSuccess)== ...
        probe.managementRecipientSuccess && ...
    sum(Q.controlGroupRecipientErasure)== ...
        probe.managementRecipientErasure && ...
    sum(Q.controlGroupRecipientCollision)== ...
        probe.managementRecipientCollision, ...
    'management group recipient accounting equals the kernel'};
checks(end+1,:)={crossPlaneClear(Q), ...
    'management and DATA transmission intervals never overlap'};
checks(end+1,:)={all(diff(Q.dataStartTime)>=-1e-12) && ...
    all(diff(Q.controlStartTime)>=-1e-12) && ...
    Q.futureRandomReads==0 && Q.receiverTruthDecisionReads==0, ...
    'translated schedule is monotone and information-causal'};

Q2=buildDstrContinuousSchedule(C,T,probe.elapsedSec);
checks(end+1,:)={Q.hashExact==Q2.hashExact && ...
    Q.kernel.realizationHash==Q2.kernel.realizationHash, ...
    'identical configuration and absolute trace replay bit-identically'};

unresolved=Q;
unresolved.kernel.finalAllResolved=false;
unresolved.kernel.finalCollisionFree=false;
unresolved.kernel.assignedSlot(:)=0;
warm=buildDstrWarmContinuousSchedule(unresolved,Q.horizonSec);
checks(end+1,:)={all(warm.warmAssignedSlot>0) && ...
    warm.expectedDataCollisionFrames==0 && ...
    isempty(warm.controlGroupStartTime) && ...
    warm.firstConvergenceTimeSec==0, ...
    'oracle-warm coloring is independent of native terminal resolution'};

shortHorizon=0.45*probe.elapsedSec;
short=buildDstrContinuousSchedule(C,T,shortHorizon);
dataPrefix=Q.dataStartTime<shortHorizon-1e-12;
controlPrefix=Q.controlStartTime<shortHorizon-1e-12;
checks(end+1,:)={isequal(short.dataStartTime,Q.dataStartTime(dataPrefix)) && ...
    isequal(short.dataNode,Q.dataNode(dataPrefix)) && ...
    isequal(short.controlStartTime,Q.controlStartTime(controlPrefix)) && ...
    isequal(short.controlNode,Q.controlNode(controlPrefix)), ...
    'a shorter mission exposes an exact prefix of the longer replay'};

cfg=eventCfg(C,Q);
trace=generateSharedMediumTrace(cfg);
net=initSharedMediumState(cfg,cfg.swarm.A);
net=fillQueues(net,Q,cfg);
[net,events]=advanceSharedMedium(net,0,cfg.swarm.T,cfg,trace);
S=net.serviceScheduler;
checks(end+1,:)={S.dstrDataOpportunities==numel(Q.dataStartTime) && ...
    S.dstrDataAttempts==numel(Q.dataStartTime) && ...
    S.dstrDataSkippedNoQueue==0 && ...
    S.dstrDataCursor==numel(Q.dataStartTime)+1, ...
    'event engine consumes each due DATA opportunity exactly once'};
checks(end+1,:)={S.dstrManagementAttempts==probe.managementAttempts && ...
    S.dstrManagementBusySlots==numel(Q.controlGroupStartTime) && ...
    abs(S.dstrManagementAirtime- ...
        probe.managementAttempts*Q.airtimeSec)<1e-12 && ...
    S.dstrControlCursor==numel(Q.controlGroupStartTime)+1, ...
    'management attempts, busy slots, airtime and cursor close'};
checks(end+1,:)={net.stats.dataFramesAttempted==probe.dataAttempts && ...
    net.stats.collisionFrames==probe.dataCollisionFrames && ...
    net.stats.collisionFrames==Q.expectedCompletedDataCollisionFrames && ...
    S.dstrManagementCollisionSlots==probe.managementCollisionSlots && ...
    S.dstrCrossPlaneOverlapCount==0, ...
    'event-engine DATA and management collision witnesses match kernel'};
checks(end+1,:)={net.stats.dataRecipientSuccess+ ...
    net.stats.dataRecipientLoss==net.stats.dataRecipientAttempts && ...
    S.dstrManagementRecipientSuccess+ ...
    S.dstrManagementRecipientErasure+ ...
    S.dstrManagementRecipientCollision== ...
    S.dstrManagementRecipientAttempts && ~isempty(events), ...
    'DATA and management recipient accounting closes'};

lossC=C;
lossC.dataErasureProbability=1;
lossProbe=simulateDstrScheduling(lossC,T);
lossQ=buildDstrContinuousSchedule(lossC,T,lossProbe.elapsedSec);
lossCfg=eventCfg(lossC,lossQ);
lossTrace=generateSharedMediumTrace(lossCfg);
lossNet=initSharedMediumState(lossCfg,lossCfg.swarm.A);
lossNet=fillQueues(lossNet,lossQ,lossCfg);
[lossNet,~]=advanceSharedMedium( ...
    lossNet,0,lossCfg.swarm.T,lossCfg,lossTrace);
checks(end+1,:)={lossNet.serviceScheduler.dstrDataOutcomeMismatchCount==0 && ...
    lossNet.serviceScheduler.dstrDataRecipientErasureObserved== ...
        lossQ.expectedCompletedDataRecipientErasure && ...
    lossNet.serviceScheduler.dstrDataRecipientCollisionObserved== ...
        lossQ.expectedCompletedDataRecipientCollision && ...
    lossNet.stats.dataRecipientLoss== ...
        lossQ.expectedCompletedDataRecipientErasure+ ...
        lossQ.expectedCompletedDataRecipientCollision, ...
    'scheduled DATA erasure masks reach the physical controller timeline'};

split=0.37*cfg.swarm.T;
net2=initSharedMediumState(cfg,cfg.swarm.A);
net2=fillQueues(net2,Q,cfg);
[net2,e1]=advanceSharedMedium(net2,0,split,cfg,trace);
dataAfterFirst=net2.serviceScheduler.dstrDataCursor;
controlAfterFirst=net2.serviceScheduler.dstrControlCursor;
[net2,e2]=advanceSharedMedium(net2,split,cfg.swarm.T,cfg,trace);
checks(end+1,:)={dataAfterFirst>1 && controlAfterFirst>1 && ...
    net2.serviceScheduler.dstrDataCursor==S.dstrDataCursor && ...
    net2.serviceScheduler.dstrControlCursor==S.dstrControlCursor && ...
    configHash(net2.stats)==configHash(net.stats) && ...
    configHash([e1(:);e2(:)])==configHash(events), ...
    'split calls consume only due entries and equal one-shot replay'};

RR=exp21dClosedLoopRegistry();
base=applyExp21dClosedLoopCell(RR.cells(1).id,16035998);
base.swarm.T=0.30;
base.shared.evalStart=0;
base.sixdof.enable=false;
arm=RR.arms(strcmp({RR.arms.id},RR.nativeArm));
[closedCfg,method]=applyExp21dClosedLoopArm(base,arm);
closedTrace=generateSharedMediumTrace(closedCfg);
closed=simSwarmSharedMedium(closedCfg,method,closedTrace);
closedMetrics=computeSharedMediumMetrics(closed,closedCfg);
checks(end+1,:)={closed.serviceScheduler.dstrInitialized && ...
    closed.netStats.dataFramesAttempted>0 && ...
    closed.serviceScheduler.dstrManagementAttempts>0 && ...
    closed.serviceScheduler.dstrCrossPlaneOverlapCount==0 && ...
    closed.invariantViolations==0 && ...
    abs(closedMetrics.managementAirtime- ...
        closed.serviceScheduler.dstrManagementAirtime)<1e-12, ...
    'closed-loop controller consumes D-STR deliveries with exact charge'};

base10=applyExp21dClosedLoopCell(RR.cells(2).id,16035997);
base10.swarm.T=0.30;
base10.shared.evalStart=0;
base10.sixdof.enable=false;
warmArm=RR.arms(strcmp({RR.arms.id},RR.warmArm));
[warmCfg,warmMethod]=applyExp21dClosedLoopArm(base10,warmArm);
warmTrace=generateSharedMediumTrace(warmCfg);
warmOut=simSwarmSharedMedium(warmCfg,warmMethod,warmTrace);
warmSchedule=warmOut.serviceScheduler.config.dstrSchedule;
checks(end+1,:)={warmOut.netStats.collisionFrames== ...
    warmSchedule.expectedCompletedDataCollisionFrames && ...
    warmOut.netStats.collisionFrames==0 && ...
    warmOut.serviceScheduler.dstrCrossPlaneOverlapCount==0 && ...
    warmOut.invariantViolations==0, ...
    'pin-augmented N10 graph has exact zero-collision warm witness'};

flags=cellfun(@logical,checks(:,1));
for k=1:size(checks,1)
    if flags(k), tag='ok'; else, tag='FAIL'; end
    fprintf('    %-4s %s\n',tag,checks{k,2});
end
if ~all(flags)
    error(['test_exp21d_closed_loop_integration_contracts: ' ...
        '%d of %d failed.'],nnz(~flags),numel(flags));
end
fprintf(['\ntest_exp21d_closed_loop_integration_contracts: ' ...
    'PASS (%d checks)\n'],numel(flags));


function clear=crossPlaneClear(Q)

clear=true;
for k=1:numel(Q.dataStartTime)
    overlap=Q.dataStartTime(k)<Q.controlGroupStartTime+Q.airtimeSec-1e-12 & ...
        Q.controlGroupStartTime<Q.dataStartTime(k)+Q.airtimeSec-1e-12;
    if any(overlap), clear=false; return; end
end

end


function C=kernelCfg(N,F)

C=struct('N',N,'maxFrames',F,'initialDataSlots',N+2, ...
    'maxDataSlots',24,'collisionThreshold',3,'growthMargin',3, ...
    'shrinkThreshold',5,'failedShrinkTimeout',30, ...
    'shrinkBackoffExponentCap',6,'shrinkInitialOrder',(1:N)', ...
    'retentionProbability',0.75,'frameBytes',10, ...
    'phyRateBps',80e3,'guardSec',0.2e-3,'enableShrink',true, ...
    'churnEnabled',false,'churnFrame',min(40,F), ...
    'churnNode',min(2,N),'dataErasureProbability',0, ...
    'managementErasureProbability',0,'neighborGraph',false(N), ...
    'managementReach',true(N)-eye(N)>0, ...
    'interferenceMatrix',false(N));
C.neighborGraph=true(N)-eye(N)>0;
C.interferenceMatrix=C.neighborGraph;

end


function cfg=eventCfg(C,Q)

N=C.N;
cfg=struct();
cfg.swarm=struct('N',N,'T',Q.horizonSec,'A',C.neighborGraph);
cfg.net=struct('seed',16035991);
cfg.mac=struct('type','tdma','slotTime',0.1e-3,'queueCapacity',512, ...
    'dataBytes',C.frameBytes,'ackBaseBytes',4,'ackEntryBytes',2, ...
    'phyRateBps',C.phyRateBps,'ackDeadline',0.01,'pAccess',1, ...
    'historySize',512,'residualLoss',0,'dataResidualLoss',0, ...
    'ackResidualLoss',0,'lossModel','iid','separateAckTrace',false, ...
    'maxRetries',0,'backgroundLoad',0, ...
    'interferenceMatrix',C.interferenceMatrix, ...
    'carrierSenseMatrix',true(N),'applyDeliveriesInline',false);
cfg.aoiEvent=struct('posThreshold',0.05,'velThreshold',0.10, ...
    'aoiThreshold',0.12,'maxSilence',0.50);
cfg.shared=struct('feedbackMode','none');
cfg.shared.serviceScheduler=struct('mode','continuous-dstr-replay', ...
    'logDecisions',true,'continuousExactAirtime',true, ...
    'dstrSchedule',Q);
cfg.mac=sharedMediumConfig(cfg);
cfg.shared.serviceScheduler=serviceSchedulerConfig(cfg);

end


function net=fillQueues(net,Q,cfg)

N=net.N;
for node=1:N
    count=nnz(Q.dataNode==node);
    q=repmat(net.frameTemplate,count,1);
    for k=1:count
        f=net.frameTemplate;
        f.id=net.nextFrameId;
        net.nextFrameId=net.nextFrameId+1;
        f.type='data';
        f.dataMode='broadcast';
        f.sender=node;
        f.seq=k;
        f.genTime=0;
        f.pos=[node 0 0];
        f.vel=[0 0 0];
        f.dataReceiverMask=reshape(logical(cfg.swarm.A(:,node)),1,[]);
        f.receiverMask=f.dataReceiverMask;
        f.bytes=cfg.mac.dataBytes;
        f.enqueueTime=0;
        q(k)=f;
    end
    net.queues{node}=q;
end

end
