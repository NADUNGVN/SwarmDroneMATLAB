function C=elcsWitnessKernelConfig(N,maxFrames)
%ELCSWITNESSKERNELCONFIG Conservative local-witness kernel defaults.

if nargin<2, maxFrames=160; end
graph=true(N)-eye(N)>0;
C=struct('version','ELCS-W-KERNEL-CONFIG-v0','N',N, ...
    'maxFrames',maxFrames,'frameLength',N,'controlSlots',N, ...
    'fallbackSlots',2,'leaseFrames',20,'refreshLeadFrames',6, ...
    'leaseFenceFrames',1,'renewalPeriodFrames',13, ...
    'fallbackAccessProbability',1/N,'deterministicControlSlots',true, ...
    'dataBytes',96,'claimBytes',24,'certificateHeaderBytes',16, ...
    'certificateEntryBytes',8,'maxControlPacketBytes',96, ...
    'phyRateBps',250e3,'guardSec',0, ...
    'claimErasureProbability',0,'certificateErasureProbability',0, ...
    'dataErasureProbability',0,'neighborGraph',graph, ...
    'managementReach',graph,'interferenceMatrix',graph, ...
    'conflictGraph',graph);

end
