function B=conflictWitnessPayloadBound(W,claimBytes,headerBytes, ...
    entryBytes,maxPacketBytes)
%CONFLICTWITNESSPAYLOADBOUND Exact per-epoch witness control byte bound.

values=[claimBytes headerBytes entryBytes maxPacketBytes];
if ~isstruct(W) || ~isfield(W,'allCovered') || ~W.allCovered
    error('conflictWitnessPayloadBound: witness cover must be complete.');
end
if any(~isfinite(values)) || any(values<=0) || any(values~=round(values))
    error('conflictWitnessPayloadBound: byte counts must be positive integers.');
end
entriesPerPacket=floor((maxPacketBytes-headerBytes)/entryBytes);
if entriesPerPacket<1
    error('conflictWitnessPayloadBound: packet cannot hold one CERT entry.');
end
load=reshape(W.witnessEdgeLoad,[],1);
responseLoad=load;
if isfield(W,'responseEntryLoad')
    responseLoad=reshape(W.responseEntryLoad,[],1);
end
fragments=ceil(responseLoad/entriesPerPacket);
fragments(responseLoad==0)=0;
responseBytes=zeros(size(responseLoad));
for w=1:numel(responseLoad)
    remaining=responseLoad(w);
    while remaining>0
        entries=min(entriesPerPacket,remaining);
        responseBytes(w)=responseBytes(w)+headerBytes+entries*entryBytes;
        remaining=remaining-entries;
    end
end
B=struct('version','CONFLICT-WITNESS-PAYLOAD-BOUND-v1', ...
    'claimBytes',claimBytes,'certificateHeaderBytes',headerBytes, ...
    'certificateEntryBytes',entryBytes,'maxPacketBytes',maxPacketBytes, ...
    'entriesPerPacket',entriesPerPacket, ...
    'claimAttemptsPerEpoch',W.N, ...
    'claimBytesPerEpoch',W.N*claimBytes, ...
    'responseFragmentsByWitness',fragments, ...
    'responseAttemptsPerEpoch',sum(fragments), ...
    'responseBytesByWitness',responseBytes, ...
    'responseBytesPerEpoch',sum(responseBytes), ...
    'totalAttemptsPerEpoch',W.N+sum(fragments), ...
    'totalBytesPerEpoch',W.N*claimBytes+sum(responseBytes), ...
    'maxEntriesAtWitness',max(load), ...
    'maxTransmittedEntriesAtWitness',max(responseLoad), ...
    'localCertificateEntriesPerEpoch',sum(load-responseLoad), ...
    'transmittedCertificateEntriesPerEpoch',sum(responseLoad), ...
    'hashExact',realizationHash([W.hashExact;values(:);fragments; ...
    responseBytes]));

end
