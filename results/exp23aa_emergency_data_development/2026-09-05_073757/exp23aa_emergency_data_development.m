function exp23aa_emergency_data_development()
%EXP23AA_EMERGENCY_DATA_DEVELOPMENT Protected fallback development study.

startup; close all;
run('tests/test_local_migration_emergency_data_contracts.m');
run('tests/test_exp23aa_emergency_data_contracts.m');
R=exp23aaEmergencyDataRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23aa_emergency_data_development', ...
    'Protected emergency DATA development after EXP23Z boundary.');
writeJson(fullfile(expRun.dir,'emergency_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23zLocalMigrationClosedLoopEmptyRow(),0,1);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
for s=1:numel(R.seeds)
    batch=runExp23zLocalMigrationClosedLoopSeed(R.seeds(s),R);
    rows=[rows;batch(:)]; %#ok<AGROW>
    writetable(struct2table(rows),checkpoint);
    fprintf('  seed %2d / %2d; rows %3d / %3d\n', ...
        s,numel(R.seeds),numel(rows),R.expectedRuns);
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T,R); writetable(S,fullfile(expRun.dir,'summary.csv'));
C=pairedContrasts(T,R);
writetable(C,fullfile(expRun.dir,'paired_contrasts.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'PROTECTED_EMERGENCY_DATA_DEVELOPMENT_FEASIBLE', ...
    'PROTECTED_EMERGENCY_DATA_DEVELOPMENT_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'developmentOnly',true,'geometryCoupledToPlant',false, ...
    'freshSeedEvidence',false,'submissionClaimPermitted',false, ...
    'next','bounded_retry_then_online_state_tube_coupling');
writeJson(fullfile(expRun.dir,'emergency_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','C','gates','verdict','R');

fprintf('\nEXP23AA protected emergency DATA gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-42s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S(:,{'arm','meanRMSE','meanCost','safeFailureRate', ...
    'meanEmergencyOpportunities'}));
disp(C);
fprintf('EXP23AA DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23aa: emergency DATA development invalid.'); end

end


function S=summaryTable(T,R)

rows=cell(numel(R.arms),9);
for k=1:numel(R.arms)
    index=string(T.arm)==string(R.arms(k).id);
    rows(k,:)={string(R.arms(k).id),nnz(index),mean(T.RMSE(index)), ...
        mean(T.TOTAL_COST(index)),mean(T.MINSEP(index)), ...
        mean(T.SAFEFAIL(index)),mean(T.reacquired(index),'omitnan'), ...
        mean(T.MANAGEMENT_AIRTIME(index)), ...
        mean(T.emergencyOpportunities(index),'omitnan')};
end
S=cell2table(rows,'VariableNames',{'arm','nRuns','meanRMSE', ...
    'meanCost','meanMinSep','safeFailureRate','reacquisitionRate', ...
    'meanManagementAirtime','meanEmergencyOpportunities'});

end


function C=pairedContrasts(T,R)

pairs={ ...
    'migration-iid20-no-emergency','periodic-iid20'; ...
    'migration-iid20-emergency','migration-iid20-no-emergency'; ...
    'migration-iid20-emergency-response-blackout', ...
        'migration-iid20-no-emergency-response-blackout'; ...
    'migration-iid20-emergency-response-blackout','periodic-iid20'; ...
    'migration-iid20-emergency-revoke-blackout', ...
        'migration-iid20-emergency'};
rows=cell(size(pairs,1),11);
for k=1:size(pairs,1)
    A=sortrows(T(string(T.arm)==string(pairs{k,1}),:),'seed');
    B=sortrows(T(string(T.arm)==string(pairs{k,2}),:),'seed');
    if ~isequal(A.seed,B.seed), error('exp23aa: paired seeds differ.'); end
    rmse=pairedBootstrapCI(A.RMSE,B.RMSE,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+2*k,numel(R.seeds));
    cost=pairedBootstrapCI(A.TOTAL_COST,B.TOTAL_COST, ...
        R.bootstrapReplicates,R.bootstrapSeedBase+2*k+1,numel(R.seeds));
    rows(k,:)={string(pairs{k,1}),string(pairs{k,2}),height(A), ...
        mean(A.RMSE)/mean(B.RMSE)-1,rmse.meanD,rmse.lo,rmse.hi, ...
        mean(A.TOTAL_COST)/mean(B.TOTAL_COST)-1, ...
        cost.meanD,cost.lo,cost.hi};
end
C=cell2table(rows,'VariableNames',{'candidate','reference','nPairs', ...
    'relativeRmse','rmseDelta','rmseCiLo','rmseCiHi', ...
    'relativeCost','costDelta','costCiLo','costCiHi'});

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash)&&registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23z_local_migration_closed_loop',R.parentRun, ...
    'closed_loop_verdict.json')));
add('negative_parent_retained',strcmp(parent.status,R.parentStatus)&& ...
    parent.gatesPassed==R.parentPassedGates&& ...
    parent.gatesTotal==R.parentTotalGates, ...
    'EXP23Z remains negative at 15/16 gates');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
add('exact_matrix_coverage',isequal(unique(T.seed),R.seeds)&& ...
    isequal(sort(unique(string(T.arm))), ...
    sort(reshape(string({R.arms.id}),[],1))), ...
    '20 new seeds and six paired arms exact');
paired=true;
for seed=R.seeds'
    index=T.seed==seed;
    paired=paired&&isscalar(unique(T.traceHash(index)))&& ...
        isscalar(unique(T.geometryHash(index)))&& ...
        isscalar(unique(T.interferenceEventHash(index)));
end
add('paired_realizations',paired, ...
    'DATA random field, clock, geometry and event pair by seed');
candidate=string(T.kind)=="migration";
add('geometry_selector_stimulus',all(T.graphAdmissible(candidate)==1)&& ...
    all(T.graphLocalOnly(candidate)==1)&& ...
    all(T.graphAddedEdges(candidate)==1)&& ...
    all(T.oldSlot(candidate)==7)&&all(T.newSlot(candidate)==9), ...
    'one local edge forces UAV 10 from shared slot 7 to slot 9');
protected=T.emergencyEnabled==1;
add('protected_slot_mapping',all(T.emergencySlot(protected)==10)&& ...
    all(T.emergencyOpportunities(protected)>0)&& ...
    all(T.emergencyExpectedSuccess(protected)>0)&& ...
    all(T.emergencyExpectedCollision(protected)==0), ...
    'protected arms map suppressed DATA only to collision-free slot 10');
unprotected=candidate & ~protected;
add('unprotected_control_arms',all(T.emergencyEnabled(unprotected)==0), ...
    'silent comparator contains no emergency DATA opportunity');
add('causal_instrumentation',all(T.futureRandomReads==0)&& ...
    all(T.receiverTruthReads==0)&&all(T.geometryCoupledToPlant==0), ...
    'zero forbidden reads; plant-tube coupling remains explicitly absent');
add('clock_timing_valid',all(T.clockConflictFree(candidate)==1)&& ...
    all(T.clockResidual(candidate)<2e-12), ...
    'all migration arms retain affine-clock safety');
add('exact_closed_loop_replay',all(T.dataOutcomeMismatches(candidate)==0)&& ...
    all(T.dataSkippedNoQueue(candidate)==0)&& ...
    all(T.crossPlaneOverlaps(candidate)==0)&& ...
    all(T.expectedDataSuccess(candidate)==T.observedDataSuccess(candidate))&& ...
    all(T.expectedDataErasure(candidate)==T.observedDataErasure(candidate))&& ...
    all(T.expectedDataCollision(candidate)==T.observedDataCollision(candidate)), ...
    'receiver success, erasure and collision outcomes replay exactly');
add('control_airtime_accounting',all(T.controlAttempts(candidate)== ...
    T.expectedControlAttempts(candidate))&&all(abs( ...
    T.controlAirtime(candidate)-T.expectedControlAirtime(candidate))<1e-12)&& ...
    all(abs(T.controlAirtime(candidate)- ...
    T.controlBytes(candidate)*8/250e3)<1e-12), ...
    'management attempts, bytes and airtime close');
add('collision_safety',all(T.COLLISION_FRAMES==0)&& ...
    all(T.expectedDataCollision(candidate)==0), ...
    'all arms remain collision-free');
normal=ismember(string(T.arm),["migration-iid20-no-emergency" ...
    "migration-iid20-emergency" ...
    "migration-iid20-emergency-revoke-blackout"]);
add('normal_reacquisition',all(T.reacquired(normal)==1)&& ...
    all(T.finalSuppressed(normal)==0),sprintf( ...
    '%d/%d ordinary rows reacquire',sum(T.reacquired(normal)),nnz(normal)));
response=T.responseBlackout==1;
add('response_blackout_lease_silence',all(T.reacquired(response)==0)&& ...
    all(T.finalSuppressed(response)==1), ...
    'both RESPONSE-blackout arms refuse uncertified shared-slot reuse');
silent=string(T.arm)=="migration-iid20-no-emergency-response-blackout";
add('silent_negative_replicated',all(T.SAFEFAIL(silent)==1)&& ...
    all(T.emergencyEnabled(silent)==0), ...
    'the EXP23Z unsafe silent boundary remains visible');
rescued=string(T.arm)=="migration-iid20-emergency-response-blackout";
add('protected_blackout_safety_recovered',all(T.SAFEFAIL(rescued)==0)&& ...
    all(T.DIVERGED(rescued)==0)&&all(T.emergencyOpportunities(rescued)>0), ...
    'protected DATA restores closed-loop safety under permanent RESPONSE loss');
supported=~silent;
add('supported_closed_loop_safety',all(T.SAFEFAIL(supported)==0)&& ...
    all(T.DIVERGED(supported)==0), ...
    'all intended protected and ordinary operating arms remain safe');
equivalent=true;
for seed=R.seeds'
    a=T.seed==seed & string(T.arm)=="migration-iid20-emergency";
    b=T.seed==seed & string(T.arm)== ...
        "migration-iid20-emergency-revoke-blackout";
    equivalent=equivalent&&T.suppressionHash(a)==T.suppressionHash(b)&& ...
        T.reacquisitionHash(a)==T.reacquisitionHash(b)&& ...
        abs(T.RMSE(a)-T.RMSE(b))<1e-15&& ...
        abs(T.TOTAL_COST(a)-T.TOTAL_COST(b))<1e-15;
end
add('revoke_loss_independence',equivalent, ...
    'protected local state, performance and cost ignore REVOKE delivery');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23aa: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


