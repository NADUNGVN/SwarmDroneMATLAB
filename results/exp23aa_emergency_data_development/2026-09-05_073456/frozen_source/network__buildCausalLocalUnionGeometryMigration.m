function G=buildCausalLocalUnionGeometryMigration(oldState,newState, ...
    horizonSec,interferenceRadius,dataNeighborGraph,managementReach,node,config)
%BUILDCAUSALLOCALUNIONGEOMETRYMIGRATION Bind two causal tubes to migration.
%
% oldState and newState are the bounded state snapshots available before and
% at the local topology event.  No sampled future trajectory or receiver
% delivery outcome is consumed by this construction.

N=size(oldState.p,1);
if size(newState.p,1)~=N || ~isequal(size(dataNeighborGraph),[N N]) || ...
        ~isequal(size(managementReach),[N N])
    error('buildCausalLocalUnionGeometryMigration: dimension mismatch.');
end
B0=buildReachableBroadcastConflictSupergraph(oldState,horizonSec, ...
    interferenceRadius,dataNeighborGraph,false(N));
B1=buildReachableBroadcastConflictSupergraph(newState,horizonSec, ...
    interferenceRadius,dataNeighborGraph,false(N));
oldSlot=elcsWitnessPriorityColor(B0.senderConflictGraph);
M=buildLocalUnionGraphMigration(B0.senderConflictGraph, ...
    B1.senderConflictGraph,oldSlot,node,managementReach,config);

G=struct('version','CAUSAL-LOCAL-UNION-GEOMETRY-MIGRATION-v1', ...
    'N',N,'node',node,'horizonSec',horizonSec, ...
    'interferenceRadius',interferenceRadius, ...
    'dataNeighborGraph',logical(dataNeighborGraph), ...
    'managementReach',logical(managementReach), ...
    'oldState',oldState,'newState',newState, ...
    'oldBroadcastGraph',B0,'newBroadcastGraph',B1, ...
    'oldPhysicalGraph',B0.potentialInterferenceGraph, ...
    'newPhysicalGraph',B1.potentialInterferenceGraph, ...
    'unionPhysicalGraph',B0.potentialInterferenceGraph | ...
        B1.potentialInterferenceGraph, ...
    'migration',M,'causalStateOnly',true,'futureRandomReads',0, ...
    'receiverTruthDecisionReads',0);
G.hashExact=realizationHash([B0.hashExact;B1.hashExact;M.hashExact; ...
    horizonSec;interferenceRadius;double(dataNeighborGraph(:)); ...
    double(managementReach(:));node]);

end
