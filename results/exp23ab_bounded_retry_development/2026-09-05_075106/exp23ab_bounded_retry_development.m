function exp23ab_bounded_retry_development()
%EXP23AB_BOUNDED_RETRY_DEVELOPMENT Finite retry/backoff development study.

startup; close all;
run('tests/test_local_union_migration_retry_backoff_contracts.m');
run('tests/test_exp23ab_bounded_retry_contracts.m');
R=exp23abBoundedRetryRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23ab_bounded_retry_development', ...
    'Finite CLAIM retry/backoff with protected emergency DATA.');
writeJson(fullfile(expRun.dir,'bounded_retry_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23zLocalMigrationClosedLoopEmptyRow(),0,1);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
for s=1:numel(R.seeds)
    batch=runExp23zLocalMigrationClosedLoopSeed(R.seeds(s),R);
    rows=[rows;batch(:)]; %#ok<AGROW>
    writetable(struct2table(rows),checkpoint);
    fprintf('  seed %2d / %2d; rows %3d / %3d\n', ...
        s,numel(R.seeds),numel(rows),R.expectedRuns);
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T,R); writetable(S,fullfile(expRun.dir,'summary.csv'));
C=pairedContrasts(T,R);
writetable(C,fullfile(expRun.dir,'paired_contrasts.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'BOUNDED_RETRY_DEVELOPMENT_FEASIBLE', ...
    'BOUNDED_RETRY_DEVELOPMENT_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'developmentOnly',true,'geometryCoupledToPlant',false, ...
    'freshSeedEvidence',false,'submissionClaimPermitted',false, ...
    'next','online_state_tube_coupling');
writeJson(fullfile(expRun.dir,'bounded_retry_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','C','gates','verdict','R');

fprintf('\nEXP23AB bounded retry gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-42s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S(:,{'arm','meanRMSE','meanCost','safeFailureRate', ...
    'meanControlAttempts','meanClaimAttempts','meanManagementAirtime'}));
disp(C);
fprintf('EXP23AB DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23ab: bounded retry development invalid.'); end

end


function S=summaryTable(T,R)

rows=cell(numel(R.arms),12);
for k=1:numel(R.arms)
    index=string(T.arm)==string(R.arms(k).id);
    rows(k,:)={string(R.arms(k).id),nnz(index),mean(T.RMSE(index)), ...
        mean(T.TOTAL_COST(index)),mean(T.MINSEP(index)), ...
        mean(T.SAFEFAIL(index)),mean(T.reacquired(index),'omitnan'), ...
        mean(T.controlAttempts(index)),mean(T.claimAttempts(index),'omitnan'), ...
        mean(T.responseAttempts(index),'omitnan'), ...
        mean(T.MANAGEMENT_AIRTIME(index)), ...
        mean(T.retryUnionFailureBound(index),'omitnan')};
end
S=cell2table(rows,'VariableNames',{'arm','nRuns','meanRMSE', ...
    'meanCost','meanMinSep','safeFailureRate','reacquisitionRate', ...
    'meanControlAttempts','meanClaimAttempts','meanResponseAttempts', ...
    'meanManagementAirtime','meanRetryUnionFailureBound'});

end


function C=pairedContrasts(T,R)

pairs={ ...
    'migration-backoff-iid20-emergency', ...
        'migration-dense-iid20-emergency'; ...
    'migration-backoff-iid20-emergency-response-blackout', ...
        'migration-dense-iid20-emergency-response-blackout'; ...
    'migration-backoff-iid20-emergency-revoke-blackout', ...
        'migration-backoff-iid20-emergency'; ...
    'migration-backoff-iid20-emergency-response-blackout', ...
        'periodic-iid20'};
rows=cell(size(pairs,1),17);
for k=1:size(pairs,1)
    A=sortrows(T(string(T.arm)==string(pairs{k,1}),:),'seed');
    B=sortrows(T(string(T.arm)==string(pairs{k,2}),:),'seed');
    if ~isequal(A.seed,B.seed), error('exp23ab: paired seeds differ.'); end
    rmse=pairedBootstrapCI(A.RMSE,B.RMSE,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+3*k,numel(R.seeds));
    cost=pairedBootstrapCI(A.TOTAL_COST,B.TOTAL_COST, ...
        R.bootstrapReplicates,R.bootstrapSeedBase+3*k+1,numel(R.seeds));
    air=pairedBootstrapCI(A.MANAGEMENT_AIRTIME,B.MANAGEMENT_AIRTIME, ...
        R.bootstrapReplicates,R.bootstrapSeedBase+3*k+2,numel(R.seeds));
    rows(k,:)={string(pairs{k,1}),string(pairs{k,2}),height(A), ...
        mean(A.RMSE)/mean(B.RMSE)-1,rmse.meanD,rmse.lo,rmse.hi, ...
        mean(A.TOTAL_COST)/mean(B.TOTAL_COST)-1, ...
        cost.meanD,cost.lo,cost.hi, ...
        mean(A.MANAGEMENT_AIRTIME)-mean(B.MANAGEMENT_AIRTIME), ...
        air.lo,air.hi,mean(A.controlAttempts)-mean(B.controlAttempts), ...
        mean(A.claimAttempts,'omitnan')-mean(B.claimAttempts,'omitnan'), ...
        mean(A.responseAttempts,'omitnan')-mean(B.responseAttempts,'omitnan')};
end
C=cell2table(rows,'VariableNames',{'candidate','reference','nPairs', ...
    'relativeRmse','rmseDelta','rmseCiLo','rmseCiHi', ...
    'relativeCost','costDelta','costCiLo','costCiHi', ...
    'managementAirtimeDelta','managementAirtimeCiLo', ...
    'managementAirtimeCiHi','controlAttemptDelta','claimAttemptDelta', ...
    'responseAttemptDelta'});

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash)&&registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23aa_emergency_data_development',R.parentRun, ...
    'emergency_verdict.json')));
add('positive_parent_locked',strcmp(parent.status,R.parentStatus)&& ...
    parent.gatesPassed==R.parentPassedGates&& ...
    parent.gatesTotal==R.parentTotalGates, ...
    'EXP23AA remains feasible at 19/19 gates');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
add('exact_matrix_coverage',isequal(unique(T.seed),R.seeds)&& ...
    isequal(sort(unique(string(T.arm))), ...
    sort(reshape(string({R.arms.id}),[],1))), ...
    '20 new seeds and six paired arms exact');
paired=true;
for seed=R.seeds'
    index=T.seed==seed;
    paired=paired&&isscalar(unique(T.traceHash(index)))&& ...
        isscalar(unique(T.geometryHash(index)))&& ...
        isscalar(unique(T.interferenceEventHash(index)));
end
add('paired_realizations',paired, ...
    'DATA field, clocks, geometry and event pair by seed');
migration=string(T.kind)=="migration";
add('geometry_selector_stimulus',all(T.graphAdmissible(migration)==1)&& ...
    all(T.graphLocalOnly(migration)==1)&& ...
    all(T.graphAddedEdges(migration)==1)&&all(T.oldSlot(migration)==7)&& ...
    all(T.newSlot(migration)==9), ...
    'same one-edge local migration fixture retained');
add('all_migration_arms_protected',all(T.emergencyEnabled(migration)==1)&& ...
    all(T.emergencySlot(migration)==R.emergencySlot)&& ...
    all(T.emergencyOpportunities(migration)>0), ...
    'every migration arm carries protected emergency DATA');
backoff=T.claimBackoffEnabled==1;
add('backoff_policy_exact',all(T.claimDenseRetryFrames(backoff)== ...
    R.claimDenseRetryFrames)&&all(T.claimMaxBackoffFrames(backoff)== ...
    R.claimMaxBackoffFrames)&&all(T.claimRetryAttemptLimit(backoff)== ...
    R.claimRetryAttemptLimit), ...
    'dense 6, capped 8-frame backoff, ten-attempt budget');
add('local_schedule_deterministic', ...
    all(T.claimOpportunityCount(backoff)==R.claimRetryAttemptLimit)&& ...
    numel(unique(T.claimScheduleHash(backoff)))==1, ...
    'ten public opportunities; schedule independent of seed and outcomes');
add('analytical_retry_certificate', ...
    all(T.retryUnionFailureBound(backoff)< ...
    R.maxRetryUnionFailureProbability),sprintf( ...
    'max union failure bound %.3g < %.3g', ...
    max(T.retryUnionFailureBound(backoff)), ...
    R.maxRetryUnionFailureProbability));
denseBlack=string(T.arm)== ...
    "migration-dense-iid20-emergency-response-blackout";
backBlack=string(T.arm)== ...
    "migration-backoff-iid20-emergency-response-blackout";
add('finite_retry_exhaustion',all(T.retryBudgetExhausted(backBlack)==1)&& ...
    all(T.claimAttempts(backBlack)==R.claimRetryAttemptLimit), ...
    'all blackout rows stop after exactly ten CLAIM attempts');
add('persistent_comparator_visible', ...
    all(T.retryBudgetExhausted(denseBlack)==0)&& ...
    all(T.claimAttempts(denseBlack)>R.claimRetryAttemptLimit), ...
    'legacy dense retry remains active through the blackout');
[claimLess,responseLess,controlLess,airLess,costLess,physicalSame,proofSame]= ...
    blackoutPairs(T,R,denseBlack,backBlack);
add('claim_response_attempt_reduction',claimLess&&responseLess, ...
    'every pair uses fewer CLAIM and RESPONSE attempts');
add('total_control_overhead_reduction',controlLess&&airLess&&costLess, ...
    'every pair reduces control attempts, airtime and total cost');
add('blackout_closed_loop_equivalence',physicalSame, ...
    'paired DATA service, RMSE, separation and safety are exact');
add('fixed_proof_window_invariant',proofSame, ...
    'CLAIM backoff does not alter LOCK-PROOF attempts');
add('emergency_mapping_safe',all(T.emergencyExpectedSuccess(migration)>0)&& ...
    all(T.emergencyExpectedCollision(migration)==0), ...
    'protected DATA has delivered recipients and zero collision recipients');
add('collision_safety',all(T.COLLISION_FRAMES==0)&& ...
    all(T.expectedDataCollision(migration)==0), ...
    'all six arms remain collision-free');
add('exact_closed_loop_replay',all(T.dataOutcomeMismatches(migration)==0)&& ...
    all(T.dataSkippedNoQueue(migration)==0)&& ...
    all(T.crossPlaneOverlaps(migration)==0)&& ...
    all(T.expectedDataSuccess(migration)==T.observedDataSuccess(migration))&& ...
    all(T.expectedDataErasure(migration)==T.observedDataErasure(migration)), ...
    'recipient outcomes replay exactly');
add('control_airtime_accounting',all(T.controlAttempts(migration)== ...
    T.expectedControlAttempts(migration))&&all(abs( ...
    T.controlAirtime(migration)-T.expectedControlAirtime(migration))<1e-12)&& ...
    all(abs(T.controlAirtime(migration)- ...
    T.controlBytes(migration)*8/250e3)<1e-12), ...
    'attempts, bytes and PHY airtime close');
add('timing_and_causality',all(T.clockConflictFree(migration)==1)&& ...
    all(T.clockResidual(migration)<2e-12)&& ...
    all(T.futureRandomReads==0)&&all(T.receiverTruthReads==0)&& ...
    all(T.geometryCoupledToPlant==0), ...
    'affine timing closes and forbidden reads remain zero');
normal=ismember(string(T.arm),[ ...
    "migration-dense-iid20-emergency" ...
    "migration-backoff-iid20-emergency" ...
    "migration-backoff-iid20-emergency-revoke-blackout"]);
add('ordinary_reacquisition_and_safety',all(T.reacquired(normal)==1)&& ...
    all(T.finalSuppressed(normal)==0)&&all(T.SAFEFAIL(normal)==0)&& ...
    all(T.DIVERGED(normal)==0),sprintf('%d/%d rows reacquire safely', ...
    sum(T.reacquired(normal)),nnz(normal)));
response=denseBlack|backBlack;
add('blackout_lease_silence_and_safety',all(T.reacquired(response)==0)&& ...
    all(T.finalSuppressed(response)==1)&&all(T.SAFEFAIL(response)==0)&& ...
    all(T.DIVERGED(response)==0), ...
    'both retry policies stay silent on shared slots and remain safe');
add('revoke_loss_independence',revokePairs(T,R), ...
    'backoff local state, performance and cost ignore REVOKE delivery');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23ab: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function [claimLess,responseLess,controlLess,airLess,costLess,physicalSame,proofSame]= ...
        blackoutPairs(T,R,denseMask,backoffMask)

claimLess=true; responseLess=true; controlLess=true; airLess=true;
costLess=true; physicalSame=true; proofSame=true;
for seed=R.seeds'
    a=find(denseMask&T.seed==seed); b=find(backoffMask&T.seed==seed);
    claimLess=claimLess&&T.claimAttempts(b)<T.claimAttempts(a);
    responseLess=responseLess&&T.responseAttempts(b)<T.responseAttempts(a);
    controlLess=controlLess&&T.controlAttempts(b)<T.controlAttempts(a);
    airLess=airLess&&T.MANAGEMENT_AIRTIME(b)<T.MANAGEMENT_AIRTIME(a);
    costLess=costLess&&T.TOTAL_COST(b)<T.TOTAL_COST(a);
    physicalSame=physicalSame&&abs(T.RMSE(b)-T.RMSE(a))<1e-15&& ...
        abs(T.MINSEP(b)-T.MINSEP(a))<1e-15&& ...
        T.SAFEFAIL(b)==T.SAFEFAIL(a)&& ...
        T.DATA_ATTEMPTS(b)==T.DATA_ATTEMPTS(a)&& ...
        T.DATA_RECIPIENT_SUCCESS(b)==T.DATA_RECIPIENT_SUCCESS(a)&& ...
        T.DATA_RECIPIENT_LOSS(b)==T.DATA_RECIPIENT_LOSS(a);
    proofSame=proofSame&&T.lockProofAttempts(b)==T.lockProofAttempts(a);
end

end


function equal=revokePairs(T,R)

equal=true;
for seed=R.seeds'
    a=T.seed==seed & string(T.arm)== ...
        "migration-backoff-iid20-emergency";
    b=T.seed==seed & string(T.arm)== ...
        "migration-backoff-iid20-emergency-revoke-blackout";
    equal=equal&&T.suppressionHash(a)==T.suppressionHash(b)&& ...
        T.reacquisitionHash(a)==T.reacquisitionHash(b)&& ...
        abs(T.RMSE(a)-T.RMSE(b))<1e-15&& ...
        abs(T.TOTAL_COST(a)-T.TOTAL_COST(b))<1e-15;
end

end


