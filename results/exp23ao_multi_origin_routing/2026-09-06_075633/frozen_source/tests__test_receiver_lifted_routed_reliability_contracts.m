%% TEST_RECEIVER_LIFTED_ROUTED_RELIABILITY_CONTRACTS Cross-layer bound.
startup;

R=exp23afOnlineClosureRegistry(); N=5;
reach=false(N);
for node=1:N
    reach(mod(node,N)+1,node)=true;
    reach(mod(node-2,N)+1,node)=true;
end
I0=false(N); I1=I0; I1(5,[2 3])=true; I1([2 3],5)=true;
neighbor=false(N); neighbor(5,1)=true;
F0=buildSenderConflictGraph(neighbor,I0);
F1=buildSenderConflictGraph(neighbor,I1);
slot=elcsWitnessPriorityColor(F0); management=true(N);
management(1:N+1:end)=false;
packet=struct('maxDataSlots',2*N,'maxAffectedNodes',N, ...
    'prepareHeaderBytes',R.prepareHeaderBytes, ...
    'affectedEntryBytes',R.affectedEntryBytes,'claimBytes',R.claimBytes, ...
    'quietBytes',R.quietBytes,'lockProofBytes',R.lockProofBytes, ...
    'certificateHeaderBytes',R.certificateHeaderBytes, ...
    'certificateEntryBytes',R.certificateEntryBytes, ...
    'commitBytes',R.commitBytes,'revokeBytes',R.revokeBytes, ...
    'maxControlPacketBytes',R.maxControlPacketBytes);
M=buildReceiverLiftedDependencyMigration( ...
    F0,F1,slot,5,management,packet);
C=struct('maxFrames',48,'prepareFrame',20, ...
    'prepareDenseRetryFrames',7,'prepareMaxBackoffFrames',4, ...
    'prepareRetryAttemptLimit',7,'claimEligibilityDelayFrames',2, ...
    'lockProofRepeatFrames',15,'claimBackoffEnabled',true, ...
    'claimDenseRetryFrames',15,'claimMaxBackoffFrames',8, ...
    'claimRetryAttemptLimit',15,'commitRetryAttemptLimit',6);
spec=struct('directReach',reach,'physicalInterference',I1, ...
    'linkErasureProbability',.2,'repetitionsPerHop',2);
B=receiverLiftedRoutedClosureReliabilityCertificate(M,C,8,spec);
assert(B.horizonFeasible&&B.unionFailureUpperBound<1e-3&& ...
    B.maximumEndpointErasureProbability<=.2&& ...
    B.minimumEndpointDeliveryProbability>=.8&& ...
    B.completionProbabilityLowerBound==1-B.unionFailureUpperBound);
spec.endpointModel=receiverLiftedRoutedEndpointModel(B);
BC=receiverLiftedRoutedClosureReliabilityCertificate(M,C,8,spec);
assert(BC.hashExact==B.hashExact&& ...
    BC.unionFailureUpperBound==B.unionFailureUpperBound);
spec=rmfield(spec,'endpointModel');
spec.repetitionsPerHop=1;
B1=receiverLiftedRoutedClosureReliabilityCertificate(M,C,8,spec);
assert(B1.maximumEndpointErasureProbability> ...
    B.maximumEndpointErasureProbability&& ...
    B1.unionFailureUpperBound>B.unionFailureUpperBound);
kindRepetition=struct('prepare',2,'quiescent',2,'claim',2, ...
    'lockproof',2,'response',2,'commit',2);
spec.repetitionsPerHop=kindRepetition;
BK=receiverLiftedRoutedClosureReliabilityCertificate(M,C,8,spec);
assert(BK.hashExact==B.hashExact);

fprintf('test_receiver_lifted_routed_reliability_contracts: PASS\n');
