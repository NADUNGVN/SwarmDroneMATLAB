function B=multiOriginRoutedReliabilityCertificate( ...
    schedule,linkErasureProbability)
%MULTIORIGINROUTEDRELIABILITYCERTIFICATE Joint collision-free route bound.

if ~isstruct(schedule)||~isscalar(schedule)||~isfield(schedule,'admissible')|| ...
        ~schedule.admissible||~isfield(schedule,'routePlans')|| ...
        ~isfield(schedule,'repetitionsPerPacket')
    error('multiOriginRoutedReliabilityCertificate: invalid schedule.');
end
K=schedule.packetCount; p=reshape(double(linkErasureProbability),[],1);
if isscalar(p), p=repmat(p,K,1); end
if numel(p)~=K||any(~isfinite(p))||any(p<0|p>1)
    error('multiOriginRoutedReliabilityCertificate: invalid probability.');
end
packetFailure=zeros(K,1); packetSuccess=zeros(K,1);
packetAttemptBound=zeros(K,1); certificateHash=zeros(K,1);
for k=1:K
    C=repeatedHopManagementFloodReliabilityCertificate( ...
        schedule.routePlans{k},p(k),schedule.repetitionsPerPacket(k));
    packetFailure(k)=C.multicastFailureExact;
    packetSuccess(k)=C.multicastSuccessExact;
    packetAttemptBound(k)=C.maximumPhysicalAttemptBound;
    certificateHash(k)=C.hashExact;
end
jointSuccess=prod(packetSuccess); jointFailure=1-jointSuccess;
unionFailure=min(1,sum(packetFailure));
B=struct('version','MULTI-ORIGIN-ROUTED-RELIABILITY-v1', ...
    'assumption',["independent per-link erasures across packets, links, " ...
    "and repetitions; collision-free frozen schedule"], ...
    'scheduleHash',schedule.hashExact,'linkErasureProbability',p, ...
    'packetFailureExact',packetFailure,'packetSuccessExact',packetSuccess, ...
    'jointFailureExact',jointFailure,'jointSuccessExact',jointSuccess, ...
    'jointFailureUnionUpperBound',unionFailure, ...
    'packetPhysicalAttemptBound',packetAttemptBound, ...
    'maximumPhysicalAttemptBound',sum(packetAttemptBound), ...
    'packetCertificateHash',certificateHash, ...
    'hashExact',realizationHash([schedule.hashExact;p;packetFailure; ...
    packetSuccess;jointFailure;unionFailure;packetAttemptBound; ...
    certificateHash]));

end
