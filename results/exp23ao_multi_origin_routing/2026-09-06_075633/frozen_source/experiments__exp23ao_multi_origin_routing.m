function exp23ao_multi_origin_routing()
%EXP23AO_MULTI_ORIGIN_ROUTING Common-PHY multi-packet route diagnostic.

% This is a development experiment.  It validates the joint routed-control
% primitive and a conservative cross-layer retry allocation on the retained
% N=10 online fixture; it does not execute the closed-loop plant.

startup; close all; R=exp23aoMultiOriginRoutingRegistry();
runRequiredTests();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment(R.experimentName, ...
    ['Frozen multi-origin common-PHY routing, packet isolation, and ' ...
    'cross-layer retry diagnostic.']);
writeJson(fullfile(expRun.dir,'multi_origin_registry.json'),R);
[sourceHash,sourceLeaves]=snapshotSource(expRun.dir,R);

PARENT=exp23aiIntegerAccountingRegistry();
[~,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,PARENT);
migration=context.geometry.migration;
directReach=logical(context.neighborGraph);
physicalInterference=context.geometry.oldPhysicalGraph| ...
    context.geometry.proposedPhysicalGraph;
packets=semanticPackets(migration);

[bundleTable,bundleDetails]=buildBundleSet(migration,directReach, ...
    physicalInterference,packets,R.selectedUniformRepetitions,R);
writetable(bundleTable,fullfile(expRun.dir,'bundle_schedules.csv'));

[frontier,selected]=retryFrontier(migration,directReach, ...
    physicalInterference,packets,R);
writetable(frontier,fullfile(expRun.dir,'uniform_retry_frontier.csv'));
writeJson(fullfile(expRun.dir,'selected_transaction_certificate.json'), ...
    selected);

monteCarlo=monteCarloBundles(bundleDetails,R);
writetable(monteCarlo,fullfile(expRun.dir, ...
    'multi_origin_monte_carlo.csv'));

gates=validationGates(bundleTable,frontier,monteCarlo,selected,R, ...
    registryHash,registryLeaves,sourceHash,sourceLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
valid=all(gates.passed==1);
status=ternary(valid,R.validStatus,R.invalidStatus);
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'bundleRows',height(bundleTable), ...
    'frontierRows',height(frontier),'monteCarloRows',height(monteCarlo), ...
    'selectedUniformRepetitions',selected.repetitionsPerHop, ...
    'selectedTransactionFailureUpperBound', ...
    selected.certificate.unionFailureUpperBound, ...
    'selectedConservativeTransactionTimeSec', ...
    selected.conservativeTransactionTimeSec, ...
    'multiOriginRoutingDiagnosticValidated',valid, ...
    'managementRelayingValidated',false, ...
    'closedLoopManagementRelayingValidated',false, ...
    'repeatedOnlineRenewalValidated',false, ...
    'freshSeedEvidence',false,'robustnessClaimPermitted',false, ...
    'submissionClaimPermitted',false, ...
    'next',ternary(valid,'routed_common_phy_closed_loop_integration', ...
    'repair_multi_origin_primitive_without_relaxing_registered_gates'));
writeJson(fullfile(expRun.dir,'multi_origin_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'bundleTable','bundleDetails', ...
    'frontier','selected','monteCarlo','gates','verdict','R','context', ...
    'migration','directReach','physicalInterference','packets');

fprintf('\n%s validation gates\n',R.version);
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nBundle schedules at r=%d\n',R.selectedUniformRepetitions);
disp(bundleTable(:,{'bundle','routedPacketCount','taskCount', ...
    'serialSlotCount','compactSlotCount','compactDurationSec', ...
    'jointAttemptFailureExact'}));
disp(frontier(:,{'repetitionsPerHop','feasible','bestTimeSec', ...
    'prepareAttempts','claimAttempts','evidencePrefixAttempts', ...
    'commitAttempts','transactionFailureUpperBound'}));
fprintf('%s DECISION: %s\n',R.version,status);
finishExperiment(expRun);
if ~valid
    error('exp23ao: multi-origin routing diagnostic invalid.');
end

end


function [T,details]=buildBundleSet(M,direct,physical,packets,r,R)

rows=repmat(bundleEmptyRow(),numel(R.bundles),1);
details=cell(numel(R.bundles),1);
for b=1:numel(R.bundles)
    definition=R.bundles(b); wanted=string(definition.kinds);
    selected=packets(ismember(string({packets.kind}),wanted));
    plans=cell(0,1); bytes=zeros(0,1); ids=strings(0,1);
    localOnly=0;
    for k=1:numel(selected)
        recipients=receiverLiftedClosureControlRecipients( ...
            M,selected(k).kind,selected(k).sender);
        if ~any(recipients)
            localOnly=localOnly+1; continue;
        end
        plans{end+1,1}=buildSlottedManagementFloodPlan( ...
            direct,physical,selected(k).sender,recipients,M.N-1); %#ok<AGROW>
        bytes(end+1,1)=selected(k).bytes; %#ok<AGROW>
        ids(end+1,1)=string(selected(k).kind)+'-'+ ...
            string(selected(k).sender); %#ok<AGROW>
    end
    schedule=buildMultiOriginRoutedControlSchedule( ...
        plans,repmat(r,numel(plans),1),ids);
    certificate=multiOriginRoutedReliabilityCertificate( ...
        schedule,R.linkErasureProbability);
    U=cellfun(@(~) ones(M.N,M.N,r),plans,'UniformOutput',false);
    maximumBytes=max(bytes);
    noLoss=simulateMultiOriginRoutedControl(schedule,U, ...
        R.linkErasureProbability,bytes,R.phyRateBps,R.safeGuardSec, ...
        maximumBytes);
    blackout=U; blackout{1}=zeros(M.N,M.N,r);
    isolated=simulateMultiOriginRoutedControl(schedule,blackout, ...
        R.linkErasureProbability,bytes,R.phyRateBps,R.safeGuardSec, ...
        maximumBytes);
    expectedBytes=sum(certificate.packetPhysicalAttemptBound.*bytes);
    expectedDuration=schedule.reservedSlotCount*( ...
        8*maximumBytes/R.phyRateBps+R.safeGuardSec);
    [membershipHash,membershipLeaves]=configHash(struct( ...
        'id',cellstr(ids),'bytes',num2cell(bytes)));

    row=bundleEmptyRow(); row.bundle=string(definition.id);
    row.logicalPacketCount=numel(selected);
    row.routedPacketCount=numel(plans); row.localOnlyPacketCount=localOnly;
    row.membershipHash=membershipHash;
    row.membershipLeaves=membershipLeaves; row.taskCount=schedule.taskCount;
    row.serialSlotCount=schedule.serialSlotCount;
    row.compactSlotCount=schedule.reservedSlotCount;
    row.compactionSlotSavings=schedule.compactionSlotSavings;
    row.maximumConcurrentTasks=schedule.maximumConcurrentTasks;
    row.maximumPacketBytes=maximumBytes;
    row.serialDurationSec=schedule.serialSlotCount*( ...
        8*maximumBytes/R.phyRateBps+R.safeGuardSec);
    row.compactDurationSec=expectedDuration;
    row.scheduleHash=schedule.hashExact;
    row.scheduleAdmissible=schedule.admissible;
    row.conflictFree=schedule.conflictFree;
    row.precedenceExact=schedule.precedenceExact;
    row.noLossAllPacketsDelivered=noLoss.allPacketsDelivered;
    row.noLossCollisionRecipients=noLoss.collisionRecipients;
    row.noLossPhysicalAttempts=noLoss.attempts;
    row.maximumPhysicalAttemptBound= ...
        certificate.maximumPhysicalAttemptBound;
    row.noLossPhysicalBytes=noLoss.physicalBytes;
    row.expectedMaximumPhysicalBytes=expectedBytes;
    row.noLossOfferedAirtimeSec=noLoss.offeredAirtimeSec;
    row.integerAccountingExact=double(noLoss.attempts== ...
        certificate.maximumPhysicalAttemptBound&& ...
        noLoss.physicalBytes==expectedBytes&& ...
        noLoss.offeredAirtimeSec==8*noLoss.physicalBytes/R.phyRateBps&& ...
        noLoss.reservedDurationSec==expectedDuration);
    row.blackoutTargetFailed=double(~isolated.packetDelivered(1));
    row.blackoutOtherPacketsDelivered=double( ...
        all(isolated.packetDelivered(2:end)));
    row.packetIsolationExact=double(row.blackoutTargetFailed&& ...
        row.blackoutOtherPacketsDelivered&& ...
        isolated.crossPacketStateWrites==0);
    row.jointAttemptFailureExact=certificate.jointFailureExact;
    row.jointAttemptFailureUnionUpperBound= ...
        certificate.jointFailureUnionUpperBound;
    row.scheduleVersionHash=realizationHash(schedule.version);
    row.replayVersionHash=realizationHash(noLoss.version);
    row.reliabilityVersionHash=realizationHash(certificate.version);
    rows(b)=row;
    details{b}=struct('definition',definition,'schedule',schedule, ...
        'packetBytes',bytes,'certificate',certificate, ...
        'membershipHash',membershipHash,'noLoss',noLoss, ...
        'blackout',isolated);
end
T=struct2table(rows);

end


function [T,selected]=retryFrontier(M,direct,physical,packets,R)

rows=repmat(frontierEmptyRow(),numel(R.uniformRepetitionGrid),1);
selected=struct(); selectedTime=inf;
dataDuration=R.maxDataSlots*(8*R.dataBytes/R.phyRateBps+ ...
    R.safeGuardSec);
for index=1:numel(R.uniformRepetitionGrid)
    r=R.uniformRepetitionGrid(index);
    [bundles,~]=buildBundleSet(M,direct,physical,packets,r,R);
    duration=containers.Map(cellstr(bundles.bundle), ...
        num2cell(bundles.compactDurationSec));
    routeSpec=struct('directReach',direct, ...
        'physicalInterference',physical, ...
        'linkErasureProbability',R.linkErasureProbability, ...
        'repetitionsPerHop',r);
    seedC=transactionConfig(R,max(R.prepareAttemptRange), ...
        max(R.claimAttemptRange),8,max(R.commitAttemptRange));
    seedCertificate=receiverLiftedRoutedClosureReliabilityCertificate( ...
        M,seedC,8,routeSpec);
    endpointModel=receiverLiftedRoutedEndpointModel(seedCertificate);
    routeSpec.endpointModel=endpointModel;
    cached=receiverLiftedRoutedClosureReliabilityCertificate( ...
        M,seedC,8,routeSpec);
    cacheExact=double(seedCertificate.hashExact==cached.hashExact&& ...
        seedCertificate.unionFailureUpperBound== ...
        cached.unionFailureUpperBound);

    bestTime=inf; bestCertificate=[]; bestC=[]; bestPrefix=NaN;
    for prepareAttempts=reshape(R.prepareAttemptRange,1,[])
        for claimAttempts=reshape(R.claimAttemptRange,1,[])
            for prefix=1:claimAttempts-1
                for commitAttempts=reshape(R.commitAttemptRange,1,[])
                    C=transactionConfig(R,prepareAttempts, ...
                        claimAttempts,prefix,commitAttempts);
                    certificate= ...
                        receiverLiftedRoutedClosureReliabilityCertificate( ...
                        M,C,prefix,routeSpec);
                    time=prepareAttempts*(duration('prepare')+ ...
                        duration('quiescent')+dataDuration)+ ...
                        claimAttempts*(duration('evidence')+ ...
                        duration('response')+dataDuration)+ ...
                        commitAttempts*(duration('commit')+dataDuration)+ ...
                        R.claimEligibilityDelayFrames*dataDuration;
                    feasible=certificate.horizonFeasible&& ...
                        certificate.unionFailureUpperBound<= ...
                        R.maximumTransactionFailure;
                    if feasible&&time<bestTime-1e-15
                        bestTime=time; bestCertificate=certificate;
                        bestC=C; bestPrefix=prefix;
                    end
                end
            end
        end
    end
    row=frontierEmptyRow(); row.repetitionsPerHop=r;
    row.maximumEndpointErasureProbability= ...
        seedCertificate.maximumEndpointErasureProbability;
    row.endpointEntryCount=endpointModel.entryCount;
    row.endpointModelHash=endpointModel.hashExact;
    row.endpointCacheReplayExact=cacheExact;
    row.prepareBundleDurationSec=duration('prepare');
    row.quiescentBundleDurationSec=duration('quiescent');
    row.evidenceBundleDurationSec=duration('evidence');
    row.responseBundleDurationSec=duration('response');
    row.commitBundleDurationSec=duration('commit');
    row.dataRoundDurationSec=dataDuration;
    if isfinite(bestTime)
        row.feasible=1; row.bestTimeSec=bestTime;
        row.prepareAttempts=bestC.prepareRetryAttemptLimit;
        row.claimAttempts=bestC.claimRetryAttemptLimit;
        row.evidencePrefixAttempts=bestPrefix;
        row.responseSuffixAttempts=bestCertificate.responseSuffixAttempts;
        row.commitAttempts=bestC.commitRetryAttemptLimit;
        row.maxFrames=bestC.maxFrames;
        row.transactionFailureUpperBound= ...
            bestCertificate.unionFailureUpperBound;
        row.transactionCertificateHash=bestCertificate.hashExact;
        if r==R.selectedUniformRepetitions
            selected=struct('version','EXP23AO-SELECTED-TRANSACTION-v1', ...
                'repetitionsPerHop',r, ...
                'prepareAttempts',row.prepareAttempts, ...
                'claimAttempts',row.claimAttempts, ...
                'evidencePrefixAttempts',row.evidencePrefixAttempts, ...
                'responseSuffixAttempts',row.responseSuffixAttempts, ...
                'commitAttempts',row.commitAttempts, ...
                'maxFrames',row.maxFrames, ...
                'conservativeTransactionTimeSec',bestTime, ...
                'postRequestTimeBudgetSec',R.postRequestTimeBudgetSec, ...
                'maximumTransactionFailure', ...
                R.maximumTransactionFailure, ...
                'endpointModel',endpointModel, ...
                'kernelConfig',bestC,'certificate',bestCertificate);
            selectedTime=bestTime;
        end
    end
    rows(index)=row;
end
T=struct2table(rows);
if isempty(fieldnames(selected))||~isfinite(selectedTime)
    error('exp23ao: registered repetition has no feasible allocation.');
end

end


function C=transactionConfig(R,prepareAttempts,claimAttempts,prefix, ...
    commitAttempts)

C=struct('maxFrames',prepareAttempts+1+ ...
    R.claimEligibilityDelayFrames+claimAttempts+commitAttempts-1, ...
    'prepareFrame',1,'prepareDenseRetryFrames',prepareAttempts, ...
    'prepareMaxBackoffFrames',1, ...
    'prepareRetryAttemptLimit',prepareAttempts, ...
    'claimEligibilityDelayFrames',R.claimEligibilityDelayFrames, ...
    'lockProofRepeatFrames',prefix,'claimBackoffEnabled',true, ...
    'claimDenseRetryFrames',claimAttempts,'claimMaxBackoffFrames',1, ...
    'claimRetryAttemptLimit',claimAttempts, ...
    'commitRetryAttemptLimit',commitAttempts);

end


function T=monteCarloBundles(details,R)

rows=repmat(monteCarloEmptyRow(),numel(details),1);
for b=1:numel(details)
    D=details{b}; S=D.schedule; K=S.packetCount;
    stream=RandStream('mt19937ar','Seed',R.monteCarloSeeds(b));
    failures=0; accountingViolations=0; attemptBoundViolations=0;
    collisions=0; forbidden=0; crossWrites=0; maximumAttempts=0;
    totalAttempts=0;
    for trial=1:R.monteCarloTrials
        U=cell(K,1);
        for k=1:K
            U{k}=rand(stream,S.N,S.N,S.repetitionsPerPacket(k));
        end
        O=simulateMultiOriginRoutedControl(S,U, ...
            R.linkErasureProbability,D.packetBytes,R.phyRateBps, ...
            R.safeGuardSec,max(D.packetBytes));
        failures=failures+~O.allPacketsDelivered;
        exactBytes=sum(O.packetAttempts.*D.packetBytes);
        accountingViolations=accountingViolations+double( ...
            O.physicalBytes~=exactBytes||O.offeredAirtimeSec~= ...
            8*O.physicalBytes/R.phyRateBps);
        attemptBoundViolations=attemptBoundViolations+double( ...
            ~O.attemptBoundSatisfied||O.attempts> ...
            D.certificate.maximumPhysicalAttemptBound);
        collisions=collisions+O.collisionRecipients;
        forbidden=forbidden+O.futureRandomReads+ ...
            O.receiverTruthDecisionReads+O.duplicateForwards;
        crossWrites=crossWrites+O.crossPacketStateWrites;
        maximumAttempts=max(maximumAttempts,O.attempts);
        totalAttempts=totalAttempts+O.attempts;
    end
    empirical=failures/R.monteCarloTrials;
    exact=D.certificate.jointFailureExact;
    tolerance=R.monteCarloStandardErrorMultiplier*sqrt( ...
        exact*(1-exact)/R.monteCarloTrials)+1/R.monteCarloTrials;
    row=monteCarloEmptyRow(); row.bundle=string(D.definition.id);
    row.seed=R.monteCarloSeeds(b); row.trials=R.monteCarloTrials;
    row.failures=failures; row.failureProbabilityExact=exact;
    row.failureProbabilityEmpirical=empirical;
    row.absoluteError=abs(empirical-exact);
    row.registeredTolerance=tolerance;
    row.probabilityAgreement=double(row.absoluteError<=tolerance);
    row.meanPhysicalAttempts=totalAttempts/R.monteCarloTrials;
    row.maximumObservedAttempts=maximumAttempts;
    row.analyticalAttemptBound= ...
        D.certificate.maximumPhysicalAttemptBound;
    row.accountingViolations=accountingViolations;
    row.attemptBoundViolations=attemptBoundViolations;
    row.collisionRecipients=collisions; row.forbiddenReads=forbidden;
    row.crossPacketStateWrites=crossWrites;
    row.scheduleHash=S.hashExact;
    rows(b)=row;
    fprintf('  Monte Carlo %-10s: %d/%d failures (exact %.6g)\n', ...
        D.definition.id,failures,R.monteCarloTrials,exact);
end
T=struct2table(rows);

end


