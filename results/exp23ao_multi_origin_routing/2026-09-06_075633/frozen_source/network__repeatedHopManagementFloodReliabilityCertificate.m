function B=repeatedHopManagementFloodReliabilityCertificate( ...
    plan,linkErasureProbability,repetitionsPerHop)
%REPEATEDHOPMANAGEMENTFLOODRELIABILITYCERTIFICATE Tree-flood certificate.
%
% Every scheduled tree transmitter repeats the same broadcast R times
% before the next tree depth is allowed to forward.  Under independent
% per-link erasures, a tree edge fails with probability p^R.  Multicast to
% every requested recipient succeeds exactly when every edge in the active
% multicast tree succeeds, hence
%
%       Pr{multicast failure} = 1 - (1-p^R)^E,
%
% where E is the active tree-edge count.  This is stronger and cheaper than
% repeating a complete end-to-end flood because successful upstream hops
% are not discarded between repetitions.

required={'N','admissible','recipientMask','depth','transmitterMask', ...
    'plannedTransmitterCount','treeEdgeCount','reservedSlotCount','hashExact'};
if ~isstruct(plan)||~isscalar(plan)||~all(isfield(plan,required))|| ...
        ~plan.admissible
    error(['repeatedHopManagementFloodReliabilityCertificate: ' ...
        'admissible plan required.']);
end
if ~isscalar(linkErasureProbability)|| ...
        ~isfinite(linkErasureProbability)||linkErasureProbability<0|| ...
        linkErasureProbability>1||~isscalar(repetitionsPerHop)|| ...
        ~isfinite(repetitionsPerHop)||repetitionsPerHop<1|| ...
        repetitionsPerHop~=floor(repetitionsPerHop)
    error(['repeatedHopManagementFloodReliabilityCertificate: ' ...
        'invalid input.']);
end

recipients=find(plan.recipientMask);
depth=plan.depth(recipients);
edgeFailure=linkErasureProbability^repetitionsPerHop;
edgeSuccess=1-edgeFailure;
recipientDelivery=edgeSuccess.^depth;
multicastSuccess=edgeSuccess^plan.treeEdgeCount;
multicastFailure=1-multicastSuccess;
unionFailure=min(1,plan.treeEdgeCount*edgeFailure);
expectedTransmitters=0;
for sender=find(plan.transmitterMask)'
    expectedTransmitters=expectedTransmitters+ ...
        edgeSuccess^plan.depth(sender);
end

B=struct('version','REPEATED-HOP-MANAGEMENT-FLOOD-RELIABILITY-v1', ...
    'assumption',["independent per-link erasures across links and " ...
    "reserved repetitions"], ...
    'planHash',plan.hashExact,'linkErasureProbability', ...
    linkErasureProbability,'repetitionsPerHop',repetitionsPerHop, ...
    'edgeFailureProbability',edgeFailure, ...
    'edgeSuccessProbability',edgeSuccess, ...
    'recipientNode',recipients,'recipientDepth',depth, ...
    'recipientDeliveryProbability',recipientDelivery, ...
    'multicastFailureExact',multicastFailure, ...
    'multicastFailureUnionUpperBound',unionFailure, ...
    'multicastSuccessExact',multicastSuccess, ...
    'maximumPhysicalAttemptBound',repetitionsPerHop* ...
    plan.plannedTransmitterCount, ...
    'expectedPhysicalAttempts',repetitionsPerHop*expectedTransmitters, ...
    'treeEdgeCount',plan.treeEdgeCount, ...
    'reservedSlotCount',repetitionsPerHop*plan.reservedSlotCount, ...
    'hashExact',realizationHash([plan.hashExact;linkErasureProbability; ...
    repetitionsPerHop;edgeFailure;edgeSuccess;recipients;depth; ...
    recipientDelivery;multicastFailure;unionFailure; ...
    expectedTransmitters]));

end
