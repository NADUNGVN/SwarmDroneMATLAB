function S=buildStaticBroadcastCoherenceSelector( ...
    neighbor,physicalInterference,managementReach,horizonSec,C)
%BUILDSTATICBROADCASTCOHERENCESELECTOR Certify a declared fixed topology.

N=size(neighbor,1);
required={'maxDataSlots','claimBytes','certificateHeaderBytes', ...
    'certificateEntryBytes','maxControlPacketBytes'};
if ~isequal(size(neighbor),[N N]) || ...
        ~isequal(size(physicalInterference),[N N]) || ...
        ~isequal(size(managementReach),[N N]) || ...
        ~isstruct(C) || ~all(isfield(C,required)) || ...
        ~isscalar(horizonSec) || ~isfinite(horizonSec) || horizonSec<=0
    error('buildStaticBroadcastCoherenceSelector: invalid input.');
end
neighbor=logical(neighbor); physical=logical(physicalInterference);
neighbor(1:N+1:end)=false; physical(1:N+1:end)=false;
if ~isequal(physical,physical')
    error(['buildStaticBroadcastCoherenceSelector: physical graph ' ...
        'must be symmetric.']);
end
sender=buildSenderConflictGraph(neighbor,physical);
W=buildConflictWitnessMap(sender,managementReach);
color=elcsWitnessPriorityColor(sender);
payloadFits=false;
if W.allCovered
    B=conflictWitnessPayloadBound(W,C.claimBytes, ...
        C.certificateHeaderBytes,C.certificateEntryBytes, ...
        C.maxControlPacketBytes);
    payloadFits=B.maxTransmittedEntriesAtWitness<=B.entriesPerPacket;
end
feasible=W.allCovered && payloadFits && max(color)<=C.maxDataSlots;
G=struct('version','STATIC-BROADCAST-COHERENCE-GRAPH-v1', ...
    'N',N,'horizonSec',horizonSec,'dataNeighborGraph',neighbor, ...
    'potentialInterferenceGraph',physical, ...
    'senderConflictGraph',sender,'potentialGraph',sender, ...
    'physicalEdgeCount',nnz(triu(physical,1)), ...
    'edgeCount',nnz(triu(sender,1)));
G.hashExact=realizationHash([horizonSec;double(neighbor(:)); ...
    double(physical(:));double(sender(:))]);
selectedIndex=double(feasible);
selectedHorizonSec=horizonSec*double(feasible);
S=struct('version','STATIC-BROADCAST-COHERENCE-SELECTOR-v1', ...
    'selectedIndex',selectedIndex, ...
    'selectedHorizonSec',selectedHorizonSec, ...
    'selectedGraph',G,'selectedWitnessMap',W,'selectedColor',color, ...
    'feasible',feasible,'futureRandomReads',0, ...
    'receiverTruthDecisionReads',0);
S.hashExact=realizationHash([G.hashExact;W.hashExact;color; ...
    selectedIndex;selectedHorizonSec;double(feasible)]);

end
