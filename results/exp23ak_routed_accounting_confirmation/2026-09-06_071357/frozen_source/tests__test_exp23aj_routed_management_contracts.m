%% TEST_EXP23AJ_ROUTED_MANAGEMENT_CONTRACTS Frozen diagnostic registry.
startup;

R=exp23ajRoutedManagementRegistry();
assert(strcmp(R.version,'EXP23AJ-ROUTED-MANAGEMENT-DIAGNOSTIC-v1'));
assert(isequal(R.swarmSizes,[5 10 20])&& ...
    isequal(R.linkErasureProbability,[.05 .2 .3]));
assert(R.maximumLogicalPacketFailure==1e-3&& ...
    R.maxRepetitionsPerHop==20&&R.expectedStructuralRows==210&& ...
    R.expectedMonteCarloRows==6&&R.expectedSemanticRows==25&& ...
    R.requiredValidationContracts==17);
assert(R.developmentOnly&&~R.confirmatoryEvidence&& ...
    ~R.managementRelayingValidated&&~R.repeatedOnlineRenewalValidated&& ...
    ~R.freshSeedEvidence&&~R.robustnessClaimPermitted&& ...
    ~R.submissionClaimPermitted);

for N=R.swarmSizes
    cfg=applyTopologyConfig(defaultConfig(),N,'ring2');
    reach=logical(cfg.swarm.A);
    reach(logical(cfg.swarm.pin(:)),1)=true;
    reach=reach|reach'; reach(1:N+1:end)=false;
    assert(all(conncomp(graph(reach))==1));
    for source=1:N
        P=buildSlottedManagementFloodPlan( ...
            reach,~eye(N),source,setdiff(1:N,source),N-1);
        assert(P.admissible&&P.treeEdgeCount==N-1&& ...
            P.maximumRecipientDepth<=N-1&&P.slotColoringProper);
        D=dimensionRepeatedHopManagementFlood(P,.2, ...
            R.maximumLogicalPacketFailure,R.maxRepetitionsPerHop);
        assert(D.admissible&& ...
            D.certificate.multicastFailureExact< ...
            R.maximumLogicalPacketFailure);
    end
end

fprintf('test_exp23aj_routed_management_contracts: PASS\n');
