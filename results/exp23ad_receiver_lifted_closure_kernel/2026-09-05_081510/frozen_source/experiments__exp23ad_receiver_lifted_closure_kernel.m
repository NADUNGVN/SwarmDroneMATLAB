function exp23ad_receiver_lifted_closure_kernel()
%EXP23AD_RECEIVER_LIFTED_CLOSURE_KERNEL Registered kernel falsification.

startup; close all;
run('tests/test_receiver_lifted_dependency_migration_contracts.m');
run('tests/test_receiver_lifted_closure_kernel_contracts.m');
run('tests/test_exp23ad_closure_kernel_contracts.m');
R=exp23adClosureKernelRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23ad_receiver_lifted_closure_kernel', ...
    'Receiver-lifted dependency closure kernel falsification.');
writeJson(fullfile(expRun.dir,'closure_kernel_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23adClosureKernelEmptyRow(),R.expectedRuns,1); q=0;
checkpoint=fullfile(expRun.dir,'kernel_checkpoint.csv');
for n=R.nodeCounts
    for s=1:numel(R.seeds)
        for c=1:numel(R.conditions)
            q=q+1;
            rows(q)=runExp23adClosureKernelCell( ...
                R.seeds(s),n,R.conditions{c},R);
        end
        if mod(s,10)==0
            writetable(struct2table(rows(1:q)),checkpoint);
            fprintf('  N=%2d seed %3d / %3d; rows %4d / %4d\n', ...
                n,s,numel(R.seeds),q,R.expectedRuns);
        end
    end
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'kernel_tidy.csv'));
S=summaryTable(T,R); writetable(S,fullfile(expRun.dir,'summary.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'RECEIVER_LIFTED_CLOSURE_KERNEL_VALID', ...
    'RECEIVER_LIFTED_CLOSURE_KERNEL_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'developmentOnly',true,'closedLoopClaimPermitted',false, ...
    'submissionClaimPermitted',false, ...
    'next','common_phy_then_online_plant_coupling');
writeJson(fullfile(expRun.dir,'closure_kernel_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','gates','verdict','R');

fprintf('\nEXP23AD receiver-lifted closure gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-42s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S);
fprintf('EXP23AD DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23ad: receiver-lifted closure kernel invalid.'); end

end


function S=summaryTable(T,R)

rows=cell(numel(R.nodeCounts)*numel(R.conditions),12); q=0;
for n=R.nodeCounts
    for c=1:numel(R.conditions)
        q=q+1; index=T.N==n & string(T.condition)==R.conditions{c};
        rows(q,:)={n,string(R.conditions{c}),nnz(index), ...
            mean(T.affectedCount(index)),mean(T.changedSlotCount(index)), ...
            mean(T.barrierClosed(index)),mean(T.motionAuthorized(index)), ...
            mean(T.allReactivated(index)),mean(T.collisionFrames(index)), ...
            mean(T.controlAttempts(index)),mean(T.controlBytes(index)), ...
            mean(T.actualSubsetUnion(index))};
    end
end
S=cell2table(rows,'VariableNames',{'N','condition','nRuns', ...
    'meanAffectedCount','meanChangedSlots','barrierRate', ...
    'motionAuthorizationRate','reactivationRate','meanCollisionFrames', ...
    'meanControlAttempts','meanControlBytes','actualSubsetRate'});

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash)&&registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ac_receiver_lift_diagnostic',R.parentRun, ...
    'receiver_lift_verdict.json')));
add('negative_parent_locked',strcmp(parent.status,R.parentStatus)&& ...
    ~parent.onlinePlantCouplingPermitted, ...
    'EXP23AC one-sender locality rejection retained');
key=string(T.seed)+'|'+string(T.N)+'|'+string(T.condition);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
add('exact_coverage',isequal(unique(T.seed),R.seeds)&& ...
    isequal(unique(T.N)',R.nodeCounts)&& ...
    isequal(sort(unique(string(T.condition))),sort(string(R.conditions)')), ...
    'all seeds, sizes and fault conditions exact');
add('receiver_lift_nonincident_change', ...
    all(T.nonincidentSenderChangeCount>0)&& ...
    all(T.initiatorIsChangedEndpoint==0), ...
    'every moving receiver induces nonincident sender edges');
add('closure_membership_exact',all(T.affectedCount== ...
    T.senderChangeCount+2), ...
    'closure is initiator plus star centre and changed endpoints');
add('closure_size_varied',numel(unique(T.affectedCount))>=4&& ...
    min(T.affectedCount)==3&&max(T.affectedCount)>=6, ...
    'affected-set sizes span three through at least six nodes');
add('joint_union_coloring',all(T.candidateProper==1)&& ...
    all(T.changedSlotCount>=1), ...
    'every fixture has a proper union coloring and forced change');
add('outside_state_preserved',all(T.outsideUnchanged==1), ...
    'outside subgraph and fixed slots remain unchanged');
add('payloads_within_mtu',all(T.prepareBytes<=R.maxControlPacketBytes)&& ...
    all(T.maxResponseBytes<=R.maxControlPacketBytes), ...
    'PREPARE and aggregate witness responses fit MTU');
nominal=string(T.condition)=="nominal-zero";
add('nominal_barrier_and_activation',all(T.barrierClosed(nominal)==1)&& ...
    all(T.motionAuthorized(nominal)==1)&& ...
    all(T.activationFrame(nominal)==R.prepareFrame+1), ...
    'all 300 nominal barriers authorize next-frame activation');
add('nominal_full_reactivation',all(T.commitReady(nominal)==1)&& ...
    all(T.allReactivated(nominal)==1)&& ...
    all(T.finalSuppressedCount(nominal)==0), ...
    'all 300 nominal closures commit and reactivate');
iid=string(T.condition)=="iid20";
ci=wilsonCI(nnz(T.allReactivated(iid)==0),nnz(iid),.05);
add('iid20_completion_reliability',1-ci.hi>= ...
    R.minAggregateIidCompletionWilsonLower,sprintf( ...
    'completion %.4f, Wilson lower %.4f',mean(T.allReactivated(iid)),1-ci.hi));
prepare=string(T.condition)=="prepare-blackout";
add('prepare_blackout_blocks_motion',all(T.barrierClosed(prepare)==0)&& ...
    all(T.motionAuthorized(prepare)==0)&& ...
    all(T.prepareBudgetExhausted(prepare)==1), ...
    'missing PREPARE member prevents every motion authorization');
quiet=string(T.condition)=="quiescent-blackout";
add('quiescent_blackout_blocks_motion',all(T.barrierClosed(quiet)==0)&& ...
    all(T.motionAuthorized(quiet)==0)&& ...
    all(T.prepareBudgetExhausted(quiet)==1), ...
    'missing positive QUIESCENT receipt prevents activation');
response=string(T.condition)=="response-blackout";
add('response_blackout_fail_silent',all(T.motionAuthorized(response)==1)&& ...
    all(T.commitReady(response)==0)&& ...
    all(T.finalSuppressedCount(response)==T.affectedCount(response)), ...
    'activated graph retains full closure silence without witness receipts');
commit=string(T.condition)=="commit-blackout";
add('commit_blackout_partial_safe',all(T.commitReady(commit)==1)&& ...
    all(T.allReactivated(commit)==0)&& ...
    all(T.reactivatedCount(commit)==1)&& ...
    all(T.commitBudgetExhausted(commit)==1), ...
    'only initiator reactivates; remote closure stays suppressed');
add('revoke_loss_independence',revokeEquivalent(T,R), ...
    'nominal and REVOKE-blackout state hashes are exact');
incomplete=string(T.condition)=="incomplete-union";
add('incomplete_union_detected',all(T.actualSubsetUnion(incomplete)==0), ...
    'independent post-activation oracle rejects omitted edge');
supported=~incomplete;
add('scheduled_collision_safety',all(T.collisionFrames(supported)==0)&& ...
    all(T.collisionEdges(supported)==0), ...
    'all supported nominal, lossy and blackout rows are collision-free');
fault=ismember(string(T.condition),["prepare-blackout" ...
    "quiescent-blackout" "response-blackout" "commit-blackout"]);
add('faults_never_unsafe_activate',all(T.collisionFrames(fault)==0), ...
    'partial suppression/commit fault states remain safe');
add('control_accounting_and_bounds',all(T.controlAttempts<=T.attemptBound)&& ...
    all(T.controlBytes<=T.byteBound)&&all(T.attemptBoundRatio<=1)&& ...
    all(T.byteBoundRatio<=1)&&all(abs(T.controlAirtime- ...
    T.controlBytes*8/R.phyRateBps)<1e-12)&& ...
    all(T.recipientSuccess+T.recipientErasure==T.recipientAttempts), ...
    'attempt, byte, airtime, recipient and upper bounds close');
add('causal_instrumentation',all(T.futureRandomReads==0)&& ...
    all(T.receiverTruthReads==0), ...
    'no future random or receiver-private truth reads');
add('finite_retry_behavior',all(T.prepareAttempts<= ...
    R.prepareRetryAttemptLimit)&&all(T.commitAttempts<= ...
    R.commitRetryAttemptLimit)&&all(T.claimAttempts<= ...
    R.claimRetryAttemptLimit.*T.affectedCount), ...
    'PREPARE, CLAIM and COMMIT transmissions respect hard budgets');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23ad: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function equal=revokeEquivalent(T,R)

equal=true;
for n=R.nodeCounts
    for seed=R.seeds'
        a=T.N==n&T.seed==seed&string(T.condition)=="nominal-zero";
        b=T.N==n&T.seed==seed&string(T.condition)=="revoke-blackout";
        equal=equal&&T.stateHash(a)==T.stateHash(b)&& ...
            T.controlAttempts(a)==T.controlAttempts(b)&& ...
            T.controlBytes(a)==T.controlBytes(b);
    end
end

end


function snapshotSource(target)

