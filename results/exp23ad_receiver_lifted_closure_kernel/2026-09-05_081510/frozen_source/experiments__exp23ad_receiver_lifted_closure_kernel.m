    'docs/EXP23AD_RECEIVER_LIFTED_CLOSURE_DESIGN.md', ...
    'docs/EXP23AD_RECEIVER_LIFTED_CLOSURE_KERNEL_PLAN.md', ...
    'docs/EXP23AC_RECEIVER_LIFT_DIAGNOSTIC_RESULTS_2026-09-05.md', ...
    'network/buildReceiverLiftedDependencyMigration.m', ...
    'network/buildCausalReceiverLiftedDependencyMigration.m', ...
    'network/receiverLiftedClosureTraceHash.m', ...
    'network/generateReceiverLiftedClosureTrace.m', ...
    'network/simulateReceiverLiftedClosureMigration.m', ...
    'utils/exp23adClosureKernelRegistry.m', ...
    'utils/exp23adClosureKernelEmptyRow.m', ...
    'utils/runExp23adClosureKernelCell.m', ...
    'tests/test_receiver_lifted_dependency_migration_contracts.m', ...
    'tests/test_receiver_lifted_closure_kernel_contracts.m', ...
