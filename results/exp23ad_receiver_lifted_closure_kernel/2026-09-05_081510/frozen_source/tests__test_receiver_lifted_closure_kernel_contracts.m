%% TEST_RECEIVER_LIFTED_CLOSURE_KERNEL_CONTRACTS

startup;
[M,C,T]=fixture();
O=simulateReceiverLiftedClosureMigration(M,C,T);
assert(O.barrierClosed && O.motionAuthorized && ...
    O.graphActivationFrame==C.prepareFrame+1 && ...
    O.allAffectedReactivated && O.finalSuppressedCount==0);
assert(O.edgeReceipts==O.requiredEdgeReceipts && ...
    O.scheduledCollisionFrames==0 && O.actualSubsetUnion && ...
    O.prematureActivationFrames==0 && O.finalActiveColoringProper);

lostPrepare=T; target=M.affectedNodes(find(M.affectedNodes~=M.initiator,1));
lostPrepare.prepareDeliveryU(:,target,M.initiator)=0;
lostPrepare.hashExact=receiverLiftedClosureTraceHash(lostPrepare);
P=simulateReceiverLiftedClosureMigration(M,C,lostPrepare);
assert(~P.barrierClosed && ~P.motionAuthorized && ...
    isnan(P.graphActivationFrame) && P.prepareBudgetExhausted && ...
    P.scheduledCollisionFrames==0);

lostQuiet=T; lostQuiet.quietDeliveryU(:,M.initiator,target)=0;
lostQuiet.hashExact=receiverLiftedClosureTraceHash(lostQuiet);
Q=simulateReceiverLiftedClosureMigration(M,C,lostQuiet);
assert(~Q.barrierClosed && ~Q.motionAuthorized && ...
    Q.prepareBudgetExhausted && Q.scheduledCollisionFrames==0);

stale=T; stale.responseDigest(:)=0;
stale.hashExact=receiverLiftedClosureTraceHash(stale);
S=simulateReceiverLiftedClosureMigration(M,C,stale);
assert(S.barrierClosed && S.motionAuthorized && ~S.commitReady && ...
    ~S.allAffectedReactivated && S.finalSuppressedCount==M.affectedCount && ...
    S.scheduledCollisionFrames==0);

lostCommit=T;
for node=reshape(M.affectedNodes(M.affectedNodes~=M.initiator),1,[])
    lostCommit.commitDeliveryU(:,node,M.initiator)=0;
end
lostCommit.hashExact=receiverLiftedClosureTraceHash(lostCommit);
K=simulateReceiverLiftedClosureMigration(M,C,lostCommit);
assert(K.commitReady && ~K.allAffectedReactivated && ...
    K.reactivatedCount==1 && K.commitBudgetExhausted && ...
    K.scheduledCollisionFrames==0);

assert(O.controlAttempts==sum(struct2array(O.attempts)) && ...
    O.controlBytes==sum(struct2array(O.bytes)) && ...
    O.controlAttemptBoundRatio<=1 && O.controlByteBoundRatio<=1 && ...
    O.recipientSuccess+O.recipientErasure==O.recipientAttempts && ...
    abs(O.controlAirtimeSec-O.controlBytes*8/C.phyRateBps)<1e-15 && ...
    O.futureRandomReads==0 && O.receiverTruthDecisionReads==0);

fprintf('test_receiver_lifted_closure_kernel_contracts: PASS\n');


function [M,C,T]=fixture()

N=5; neighbor=false(N); neighbor(5,1)=true;
I0=false(N); I1=I0; I1(5,3)=true; I1(3,5)=true;
F0=buildSenderConflictGraph(neighbor,I0);
F1=buildSenderConflictGraph(neighbor,I1);
oldSlot=elcsWitnessPriorityColor(F0);
reach=true(N); reach(1:N+1:end)=false;
packet=struct('maxDataSlots',N,'maxAffectedNodes',N, ...
    'prepareHeaderBytes',32,'affectedEntryBytes',4, ...
    'claimBytes',72,'quietBytes',24,'lockProofBytes',28, ...
    'certificateHeaderBytes',16,'certificateEntryBytes',10, ...
    'commitBytes',28,'maxControlPacketBytes',96,'revokeBytes',24);
M=buildReceiverLiftedDependencyMigration(F0,F1,oldSlot,5,reach,packet);
C=struct('maxFrames',60,'prepareFrame',5,'transactionVersion',2, ...
    'prepareDenseRetryFrames',4,'prepareMaxBackoffFrames',4, ...
    'prepareRetryAttemptLimit',8,'claimEligibilityDelayFrames',2, ...
    'lockProofRepeatFrames',12,'claimBackoffEnabled',true, ...
    'claimDenseRetryFrames',6,'claimMaxBackoffFrames',8, ...
    'claimRetryAttemptLimit',10,'commitRetryAttemptLimit',6, ...
    'phyRateBps',250e3,'prepareErasureProbability',.2, ...
    'quietErasureProbability',.2,'claimErasureProbability',.2, ...
    'lockProofErasureProbability',.2,'responseErasureProbability',.2, ...
    'commitErasureProbability',.2,'revokeErasureProbability',.2);
T=generateReceiverLiftedClosureTrace(16090000,M,C);
fields={'prepareDeliveryU','quietDeliveryU','claimDeliveryU', ...
    'lockProofDeliveryU','responseDeliveryU','commitDeliveryU', ...
    'revokeDeliveryU'};
for k=1:numel(fields), T.(fields{k})(:)=1; end
T.hashExact=receiverLiftedClosureTraceHash(T);

end
