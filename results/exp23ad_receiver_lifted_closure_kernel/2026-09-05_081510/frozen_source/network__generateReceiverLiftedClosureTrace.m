function T=generateReceiverLiftedClosureTrace(seedValue,M,C)
%GENERATERECEIVERLIFTEDCLOSURETRACE Pre-draw closure protocol randomness.

if ~isscalar(seedValue) || ~isfinite(seedValue) || ...
        seedValue~=floor(seedValue)
    error('generateReceiverLiftedClosureTrace: integer seed required.');
end
F=C.maxFrames; N=M.N;
stream=RandStream('mt19937ar','Seed',seedValue);
T=struct('version','RECEIVER-LIFTED-CLOSURE-TRACE-v1', ...
    'seed',seedValue, ...
    'prepareDeliveryU',rand(stream,F,N,N), ...
    'quietDeliveryU',rand(stream,F,N,N), ...
    'claimDeliveryU',rand(stream,F,N,N), ...
    'lockProofDeliveryU',rand(stream,F,N,N), ...
    'responseDeliveryU',rand(stream,F,N,N), ...
    'commitDeliveryU',rand(stream,F,N,N), ...
    'revokeDeliveryU',rand(stream,F,N,N), ...
    'actualGraphAfter',repmat(reshape(M.newGraph,1,N,N),F,1,1), ...
    'prepareVersion',C.transactionVersion*ones(F,1), ...
    'prepareDigest',M.hashExact*ones(F,1), ...
    'quietVersion',C.transactionVersion*ones(F,N), ...
    'quietDigest',M.hashExact*ones(F,N), ...
    'claimVersion',C.transactionVersion*ones(F,N), ...
    'claimDigest',M.hashExact*ones(F,N), ...
    'responseVersion',C.transactionVersion*ones(F,N), ...
    'responseDigest',M.hashExact*ones(F,N), ...
    'commitVersion',C.transactionVersion*ones(F,1), ...
    'commitDigest',M.hashExact*ones(F,1));
T.hashExact=receiverLiftedClosureTraceHash(T);

end
