%% TEST_EXP21D_CLOCK_COMPOSITION_CONTRACTS D-STR affine-clock replay.

startup;
fprintf('\n============================================================\n');
fprintf('test_exp21d_clock_composition_contracts\n');
fprintf('============================================================\n\n');
checks=cell(0,2);

N=4;
H=2.0;
theta=0.10e-3;
ppm=20;
B=continuousTdmaGuardBound(theta,ppm,H);
C=kernelCfg(N,300,B.safeGuardSec);
R=struct('maxFrames',C.maxFrames,'traceSeedOffset',21092026);
T=generateExp21dDstrTrace(16037991,N,R);
native=buildDstrContinuousSchedule(C,T,H);

zero=clockSpec(N,theta,ppm,B,zeros(N,1),zeros(N,1));
offset=linspace(-theta,theta,N)';
drift=linspace(-ppm,ppm,N)';
impaired=clockSpec(N,theta,ppm,B,offset,drift);
Q0=applyDstrAffineClockSchedule(native,zero);
Q=applyDstrAffineClockSchedule(native,impaired);

checks(end+1,:)={Q.clockTimingConflictFree==1 && ...
    Q.clockMinimumIntergroupGapSec>=-1e-12 && ...
    Q.clockMaximumIntragroupSkewSec<Q.airtimeSec && ...
    Q.clockEquationMaxResidualSec<1e-12, ...
    'affine clock equation and sufficient-guard certificate close'};
checks(end+1,:)={numel(Q.dataStartTime)==numel(Q0.dataStartTime) && ...
    numel(Q.controlStartTime)==numel(Q0.controlStartTime) && ...
    isequal(sortrows([Q.dataFrame Q.dataSlot Q.dataNode]), ...
        sortrows([Q0.dataFrame Q0.dataSlot Q0.dataNode])) && ...
    all(Q.dataCompletesByHorizon), ...
    'common nominal cutoff preserves identical logical opportunities'};
checks(end+1,:)={all(Q.dataStartTime>=0) && ...
    all(Q.dataStartTime+Q.airtimeSec<=H+1e-12) && ...
    all(Q.controlGroupStartTime>=0) && ...
    all(Q.controlGroupEndTime<=H+1e-12), ...
    'lead time and cutoff keep every retained interval inside the horizon'};

cfg=eventCfg(C,Q,theta,ppm);
trace=generateSharedMediumTrace(cfg);
net=initSharedMediumState(cfg,cfg.swarm.A);
net=fillQueues(net,Q,cfg);
[net,events]=advanceSharedMedium(net,0,H,cfg,trace);
S=net.serviceScheduler;
checks(end+1,:)={S.dstrDataOpportunities==numel(Q.dataStartTime) && ...
    S.dstrDataAttempts==numel(Q.dataStartTime) && ...
    S.dstrDataSkippedNoQueue==0 && ...
    S.dstrManagementAttempts==sum(Q.controlGroupAttempts), ...
    'event engine consumes every retained clocked DATA/control attempt'};
checks(end+1,:)={S.dstrDataOutcomeMismatchCount==0 && ...
    net.stats.collisionFrames==Q.expectedCompletedDataCollisionFrames && ...
    S.dstrDataRecipientSuccessObserved== ...
        Q.expectedCompletedDataRecipientSuccess && ...
    S.dstrDataRecipientErasureObserved== ...
        Q.expectedCompletedDataRecipientErasure && ...
    S.dstrDataRecipientCollisionObserved== ...
        Q.expectedCompletedDataRecipientCollision, ...
    'staggered co-slot attempts preserve scheduled physical outcomes'};
checks(end+1,:)={S.dstrCrossPlaneOverlapCount==0 && ...
    abs(S.continuousMaxClockEquationResidual- ...
        Q.clockEquationMaxResidualSec)<1e-15 && ...
    max(abs(S.continuousClockDriftPpm-drift))<1e-12 && ...
    ~isempty(events), ...
    'closed event timeline exposes clock state without cross-plane overlap'};

flags=cellfun(@logical,checks(:,1));
for k=1:size(checks,1)
    if flags(k), tag='ok'; else, tag='FAIL'; end
    fprintf('    %-4s %s\n',tag,checks{k,2});
end
if ~all(flags)
    error(['test_exp21d_clock_composition_contracts: ' ...
        '%d of %d failed.'],nnz(~flags),numel(flags));
end
fprintf(['\ntest_exp21d_clock_composition_contracts: ' ...
    'PASS (%d checks)\n'],numel(flags));


function S=clockSpec(N,theta,ppm,B,offset,drift)

S=struct('clockOffsetSec',reshape(offset,N,1), ...
    'clockDriftPpm',reshape(drift,N,1), ...
    'maxOffsetSec',theta,'maxDriftPpm',ppm, ...
    'leadTimeSec',B.maxBoundaryErrorSec, ...
    'safeGuardSec',B.safeGuardSec);

end


function C=kernelCfg(N,F,guard)

C=struct('N',N,'maxFrames',F,'initialDataSlots',N+2, ...
    'maxDataSlots',24,'collisionThreshold',3,'growthMargin',3, ...
    'shrinkThreshold',5,'failedShrinkTimeout',30, ...
    'shrinkBackoffExponentCap',6,'shrinkInitialOrder',(1:N)', ...
    'retentionProbability',0.75,'frameBytes',10, ...
    'phyRateBps',80e3,'guardSec',guard,'enableShrink',true, ...
    'churnEnabled',false,'churnFrame',min(40,F), ...
    'churnNode',min(2,N),'dataErasureProbability',0, ...
    'managementErasureProbability',0,'neighborGraph',false(N), ...
    'managementReach',true(N)-eye(N)>0, ...
    'interferenceMatrix',false(N));
C.neighborGraph=true(N)-eye(N)>0;
C.interferenceMatrix=C.neighborGraph;

end


function cfg=eventCfg(C,Q,theta,ppm)

N=C.N;
cfg=struct();
cfg.swarm=struct('N',N,'T',Q.horizonSec,'A',C.neighborGraph);
cfg.net=struct('seed',16037991);
cfg.mac=struct('type','tdma','slotTime',0.1e-3,'queueCapacity',4096, ...
    'dataBytes',C.frameBytes,'ackBaseBytes',4,'ackEntryBytes',2, ...
    'phyRateBps',C.phyRateBps,'ackDeadline',0.01,'pAccess',1, ...
    'historySize',4096,'residualLoss',0,'dataResidualLoss',0, ...
    'ackResidualLoss',0,'lossModel','iid','separateAckTrace',false, ...
    'maxRetries',0,'backgroundLoad',0, ...
    'interferenceMatrix',C.interferenceMatrix, ...
    'carrierSenseMatrix',true(N),'applyDeliveriesInline',false);
cfg.aoiEvent=struct('posThreshold',0.05,'velThreshold',0.10, ...
    'aoiThreshold',0.12,'maxSilence',0.50);
cfg.shared=struct('feedbackMode','none');
cfg.shared.serviceScheduler=struct('mode','continuous-dstr-replay', ...
    'logDecisions',true,'clockOffsetMaxSec',theta, ...
    'clockDriftMaxPpm',ppm,'continuousGuardTime',Q.guardSec, ...
    'continuousSyncPeriod',inf,'continuousExactAirtime',true, ...
    'dstrSchedule',Q);
cfg.exp21c=struct('version','EXP21D-CLOCK-CONTRACT-v1');
cfg.mac=sharedMediumConfig(cfg);
cfg.shared.serviceScheduler=serviceSchedulerConfig(cfg);

end


function net=fillQueues(net,Q,cfg)

for node=1:net.N
    count=nnz(Q.dataNode==node);
    q=repmat(net.frameTemplate,count,1);
    for k=1:count
        f=net.frameTemplate;
        f.id=net.nextFrameId;
        net.nextFrameId=net.nextFrameId+1;
        f.type='data';
        f.dataMode='broadcast';
        f.sender=node;
        f.seq=k;
        f.genTime=0;
        f.pos=[node 0 0];
        f.vel=[0 0 0];
        f.dataReceiverMask=reshape(logical(cfg.swarm.A(:,node)),1,[]);
        f.receiverMask=f.dataReceiverMask;
        f.bytes=cfg.mac.dataBytes;
        f.enqueueTime=0;
        q(k)=f;
    end
    net.queues{node}=q;
end

end
