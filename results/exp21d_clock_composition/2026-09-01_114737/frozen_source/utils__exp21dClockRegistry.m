    R.maxOffsetSec,R.maxDriftPpm,R.clockResetHorizonSec);
R.clockLeadTimeSec=B.maxBoundaryErrorSec;
R.missionSafeGuardSec=B.safeGuardSec;
R.shortGuardSec=base.safeGuardSec;
