function exp22d_elcs_closed_loop_integration(resumeDir,variant)
%EXP22D_ELCS_CLOSED_LOOP_INTEGRATION Frozen ELCS-F composition study.

if nargin<1, resumeDir=''; end
if nargin<2, variant='v1'; end
startup;
close all;
switch lower(char(variant))
    case 'v1'
        R=exp22dElcsClosedLoopRegistry();
        experimentName='exp22d_elcs_closed_loop_integration';
    case 'v2'
        R=exp22eElcsClosedLoopRegistry();
        experimentName='exp22e_elcs_closed_loop_repair_validation';
    otherwise
        error('exp22d: unknown integration variant %s.',char(variant));
end
[registryHash,registryLeaves]=configHash(R);
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(experimentName, ...
        ['ELCS-F common-PHY closed-loop composition with paired zero and ' ...
        'bounded affine clocks.']);
    writeJson(fullfile(expRun.dir,'elcs_registry.json'),R);
    writeJson(fullfile(expRun.dir,'elcs_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'policyOptimizationAllowed',false, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir,R);
else
    expRun=resumeRun( ...
        resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
[seeds,cells]=groups(R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=4;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runGroup(seeds(index(q)),cells(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  groups %2d--%2d / %2d; rows %3d / %3d\n', ...
        index(1),index(end),numel(seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T);
writetable(S,fullfile(expRun.dir,'summary.csv'));
P=pairedComparison(T,R);
writetable(P,fullfile(expRun.dir,'paired_clock_comparison.csv'));
gates=integrationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'integration_gates.csv'));
pass=all(gates.passed==1);
if startsWith(R.version,'EXP22E')
    status=ternary(pass,'ELCS_F_FALLBACK_REPAIR_CLOSED_LOOP_VALID', ...
        'ELCS_F_FALLBACK_REPAIR_CLOSED_LOOP_INVALID');
else
    status=ternary(pass,'ELCS_F_CONTINUOUS_INTEGRATION_VALID', ...
        'ELCS_F_CONTINUOUS_INTEGRATION_INVALID');
end
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'robustnessContinuationPermitted',pass, ...
    'newMethodPromotionAllowed',false, ...
    'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'integration_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','P','gates','verdict','R');

fprintf('\nEXP22D ELCS-F closed-loop integration gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP22D VERDICT: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp22d: ELCS-F continuous integration invalid.'); end

end


function rows=runGroup(seedValue,cellIndex,R)

c=R.cells(cellIndex);
base=applyExp21dClosedLoopCell(c.id,seedValue);
if abs(base.swarm.T-R.clockResetHorizonSec)>1e-12
    error('exp22d: cell horizon differs from the frozen clock horizon.');
end
if base.mac.dataBytes~=96 || base.mac.phyRateBps~=250e3
    error('exp22d: cell differs from the frozen common PHY.');
end
trace=generateSharedMediumTrace(base);
N=base.swarm.N;
C=elcsKernelConfig(N,R.maxFrames);
C.guardSec=R.missionSafeGuardSec;
C.dataBytes=base.mac.dataBytes;
C.phyRateBps=base.mac.phyRateBps;
C.neighborGraph=logical(base.swarm.A);
C.interferenceMatrix=logical(base.mac.interferenceMatrix);
C.conflictGraph=buildSenderConflictGraph( ...
    C.neighborGraph,C.interferenceMatrix);
C.managementReach=true(N)-eye(N)>0;
elcsTrace=generateElcsTrace(seedValue,C);
nativeQ=buildElcsContinuousSchedule(C,elcsTrace,base.swarm.T);

rows=repmat(exp22dElcsClosedLoopEmptyRow(),numel(R.arms),1);
for k=1:numel(R.arms)
    arm=R.arms(k);
    [cfg,method,label,details]=applyExp22dElcsClockArm( ...
        base,arm,nativeQ,trace,R);
    meta=struct('stage',R.stage,'scenario',c.id, ...
        'scenarioLabel',c.label,'family', ...
        'EXP22D ELCS-F continuous integration', ...
        'arm',arm.id,'pointIndex',k, ...
        'parameterValue',nativeQ.guardSec);
    rows(k)=runExp22dElcsClosedLoopCell( ...
        cfg,method,label,meta,trace,details);
end

end


function gates=integrationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.scenario)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(sort(unique(string(T.scenario))), ...
        sort(reshape(string({R.cells.id}),[],1))) && ...
    isequal(sort(unique(string(T.arm))), ...
        sort(reshape(string({R.arms.id}),[],1)));
add('exact_seed_cell_arm_coverage',coverage, ...
    '30 fresh seeds, two cells and two arms exact');

paired=true;
for seed=R.seeds'
    for c=R.cells
        index=T.seed==seed & string(T.scenario)==string(c.id);
        paired=paired && nnz(index)==2 && ...
            isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.EXP21C_TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCS_KERNEL_TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCS_KERNEL_CONFIG_HASH(index))) && ...
            isscalar(unique(T.ELCS_KERNEL_REALIZATION_HASH(index))) && ...
            isscalar(unique(T.ELCS_CLOCK_BASE_SCHEDULE_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCS_LOGICAL_OPPORTUNITY_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCS_DATA_OPPORTUNITIES(index))) && ...
            isscalar(unique(T.ELCS_MANAGEMENT_ATTEMPTS(index)));
    end
end
add('paired_absolute_realizations',paired, ...
    'channel, estimator, ELCS kernel and logical opportunities paired');

clock=string(T.arm)==string(R.clockArm);
zero=string(T.arm)==string(R.zeroArm);
declared=all(T.ELCS_CLOCK_APPLIED(clock)==1) && ...
    all(T.ELCS_CLOCK_APPLIED(zero)==0) && ...
    all(T.ELCS_CLOCK_REALIZED_MAX_OFFSET_SEC(clock)<= ...
        R.maxOffsetSec+1e-15) && ...
    all(T.ELCS_CLOCK_REALIZED_MAX_DRIFT_PPM(clock)<= ...
        R.maxDriftPpm+1e-12);
add('clock_impairment_declared',declared, ...
    'only affine arm consumes the paired bounded clock realization');
timing=all(T.ELCS_CLOCK_TIMING_CONFLICT_FREE==1) && ...
    all(T.ELCS_CLOCK_MIN_INTERGROUP_GAP_SEC>=-1e-12) && ...
    all(T.ELCS_CLOCK_MAX_INTRAGROUP_SKEW_SEC<8*96/250e3) && ...
    all(T.ELCS_CLOCK_EQUATION_MAX_RESIDUAL_SEC<=1e-12) && ...
    all(T.CONTINUOUS_MAX_CLOCK_RESIDUAL<=1e-12);
add('affine_clock_and_guard_certificate',timing,sprintf( ...
    'max residual %.3g s; min gap %.3g s', ...
    max(T.ELCS_CLOCK_EQUATION_MAX_RESIDUAL_SEC), ...
    min(T.ELCS_CLOCK_MIN_INTERGROUP_GAP_SEC)));

kernel=all(T.ELCS_FINAL_ALL_CERTIFIED==1) && ...
    all(T.ELCS_FALSE_VALID_EDGE_FRAMES==0) && ...
    all(T.ELCS_OWNER_LOCK_VIOLATIONS==0) && ...
    all(T.ELCS_SCHEDULED_COLLISION_FRAMES==0);
add('elcs_kernel_safety',kernel,sprintf( ...
    '%d false-valid, %d lock and %d scheduled-collision witnesses', ...
    sum(T.ELCS_FALSE_VALID_EDGE_FRAMES), ...
    sum(T.ELCS_OWNER_LOCK_VIOLATIONS), ...
    sum(T.ELCS_SCHEDULED_COLLISION_FRAMES)));
add('causal_information_contract',all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && all(T.LOCAL_SCHEDULE_ONLY==1), ...
    'zero future-random and receiver-truth decision reads');
add('all_elcs_opportunities_served',all( ...
    T.ELCS_DATA_SKIPPED_NO_QUEUE==0) && all( ...
    T.ELCS_DATA_ATTEMPTS==T.ELCS_DATA_OPPORTUNITIES) && all( ...
    T.ELCS_DATA_OPPORTUNITIES==T.ELCS_SCHEDULED_OPPORTUNITIES+ ...
        T.ELCS_FALLBACK_OPPORTUNITIES), ...
    sprintf('%d skipped opportunities',sum(T.ELCS_DATA_SKIPPED_NO_QUEUE)));
outcomes=all(T.ELCS_DATA_OUTCOME_MISMATCHES==0) && ...
    all(T.ELCS_OBSERVED_DATA_RECIPIENT_SUCCESS== ...
        T.ELCS_EXPECTED_DATA_RECIPIENT_SUCCESS) && ...
    all(T.ELCS_OBSERVED_DATA_RECIPIENT_ERASURE== ...
        T.ELCS_EXPECTED_DATA_RECIPIENT_ERASURE) && ...
    all(T.ELCS_OBSERVED_DATA_RECIPIENT_COLLISION== ...
        T.ELCS_EXPECTED_DATA_RECIPIENT_COLLISION);
add('exact_data_outcome_replay',outcomes, ...
    'scheduled/fallback success, erasure and collision masks match');
add('data_collision_witness_match',all( ...
    T.ELCS_DATA_COLLISION_WITNESS_MATCH==1), ...
    'event collision frames equal completed ELCS witnesses');

management=all(T.ELCS_MANAGEMENT_ACCOUNTING_CLOSE==1) && ...
    all(T.ELCS_MANAGEMENT_ATTEMPTS== ...
        T.ELCS_EXPECTED_MANAGEMENT_ATTEMPTS) && ...
    all(T.ELCS_MANAGEMENT_RECIPIENT_ATTEMPTS== ...
        T.ELCS_EXPECTED_MANAGEMENT_RECIPIENT_ATTEMPTS) && ...
    all(T.ELCS_MANAGEMENT_RECIPIENT_SUCCESS== ...
        T.ELCS_EXPECTED_MANAGEMENT_RECIPIENT_SUCCESS) && ...
    all(T.ELCS_MANAGEMENT_RECIPIENT_ERASURE== ...
        T.ELCS_EXPECTED_MANAGEMENT_RECIPIENT_ERASURE) && ...
    all(T.ELCS_MANAGEMENT_RECIPIENT_COLLISION== ...
        T.ELCS_EXPECTED_MANAGEMENT_RECIPIENT_COLLISION) && ...
    all(abs(T.ELCS_MANAGEMENT_AIRTIME-(8*32/250e3)* ...
        T.ELCS_MANAGEMENT_ATTEMPTS)<=1e-9);
add('management_accounting_closes',management, ...
    'STATUS/GRANT recipient partitions and 32-byte attempt-airtime close');
add('cross_plane_nonoverlap',all(T.ELCS_CROSS_PLANE_OVERLAPS==0), ...
    sprintf('%d overlap witnesses',sum(T.ELCS_CROSS_PLANE_OVERLAPS)));
recipient=all(T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS);
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.ELCS_MANAGEMENT_AIRTIME)/12;
add('recipient_and_airtime_accounting',recipient && ...
    all(abs(T.OFFERED_UTIL-charge)<=1e-9) && ...
    all(T.CHANNEL_UTIL<=T.OFFERED_UTIL+1e-9), ...
    'recipient partition and fully charged offered/busy utilization close');
add('protocol_invariants',all(T.INVARIANT_VIOLATIONS==0), ...
    sprintf('%d invariant violations',sum(T.INVARIANT_VIOLATIONS)));
retained=all(ismember(T.SAFEFAIL,[0 1])) && ...
    all(T.SAFEFAIL>=T.DIVERGED) && ...
    all(ismember(T.ELCS_FINAL_ALL_CERTIFIED,[0 1]));
add('all_failures_retained',retained,sprintf( ...
    '%d unsafe, %d divergent and %d uncertified retained', ...
    sum(T.SAFEFAIL),sum(T.DIVERGED),sum(T.ELCS_FINAL_ALL_CERTIFIED==0)));
add('integration_scope_only',~R.policyOptimizationAllowed && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted && ...
    ~R.robustnessContinuationPermitted, ...
    'no tuning, promotion, robustness claim or submission decision');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function S=summaryTable(T)

U=T;
U.RMSE(logical(U.DIVERGED))=NaN;
[group,S]=findgroups(U(:,{'scenario','scenarioLabel','arm', ...
    'methodLabel','armKind'}));
S.n=splitapply(@numel,U.RMSE,group);
S.meanRMSE=splitapply(@finiteMean,U.RMSE,group);
S.meanTrueAoI=splitapply(@finiteMean,U.MEAN_TRUE_AOI,group);
S.meanOfferedUtil=splitapply(@finiteMean,U.OFFERED_UTIL,group);
S.meanChannelUtil=splitapply(@finiteMean,U.CHANNEL_UTIL,group);
S.meanGoodputHz=splitapply(@finiteMean,U.DATA_GOODPUT_HZ,group);
S.meanManagementUtil=splitapply( ...
    @(x) finiteMean(x/12),U.ELCS_MANAGEMENT_AIRTIME,group);
S.meanFallbackOpportunities=splitapply( ...
    @finiteMean,U.ELCS_FALLBACK_OPPORTUNITIES,group);
S.safeFailures=splitapply(@sum,U.SAFEFAIL,group);

end


function P=pairedComparison(T,R)

metrics={'RMSE','MEAN_TRUE_AOI','OFFERED_UTIL','CHANNEL_UTIL', ...
    'DATA_GOODPUT_HZ'};
rows=cell(0,8);
q=0;
for c=R.cells
    A=selectRows(T,c.id,R.clockArm);
    B=selectRows(T,c.id,R.zeroArm);
    for m=1:numel(metrics)
        q=q+1;
        boot=pairedBootstrapCI(A.(metrics{m}),B.(metrics{m}), ...
            10000,16044900+q,30);
        relative=boot.meanD/max(abs(mean(B.(metrics{m}))),eps);
        rows(end+1,:)={string(c.id),string(metrics{m}),boot.nPairs, ...
            boot.meanD,boot.lo,boot.hi,relative, ...
            string(R.clockArm)+" minus "+string(R.zeroArm)}; %#ok<AGROW>
    end
end
P=cell2table(rows,'VariableNames',{'scenario','metric','nPairs', ...
    'meanDelta','ciLo','ciHi','relativeDelta','contrast'});

end


function T=selectRows(T,scenario,arm)

T=T(string(T.scenario)==string(scenario) & string(T.arm)==string(arm),:);
T=sortrows(T,'seed');

end


function y=finiteMean(x)

x=x(isfinite(x));
if isempty(x), y=NaN; else, y=mean(x); end

end


function [seeds,cells]=groups(R)

seeds=repelem(R.seeds,numel(R.cells));
cells=repmat((1:numel(R.cells))',numel(R.seeds),1);

end


function [rows,completed]=loadCheckpoint(runDir,R)

[seeds,cells]=groups(R);
completed=false(size(seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp22dElcsClosedLoopEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string');
rows=table2struct(T);
for q=1:numel(seeds)
    c=R.cells(cells(q));
    index=T.seed==seeds(q) & string(T.scenario)==string(c.id);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp22d: partial checkpoint group.'); end
end

end


function runRequiredTests()

names={'test_elcs_continuous_integration_contracts', ...
    'test_elcs_kernel_contracts', ...
    'test_exp21d_clock_composition_contracts', ...
    'test_exp21d_closed_loop_integration_contracts', ...
    'test_shared_medium_infrastructure'};
for k=1:numel(names), runScriptIsolated(names{k}); end

end


function snapshotSource(target,R)

root=projectRoot();
if startsWith(R.version,'EXP22E')
    plan='docs/EXP22E_ELCS_FALLBACK_REPAIR_PLAN.md';
    registry='utils/exp22eElcsClosedLoopRegistry.m';
else
    plan='docs/EXP22D_ELCS_CLOSED_LOOP_INTEGRATION_PLAN.md';
    registry='utils/exp22dElcsClosedLoopRegistry.m';
end
files={plan, ...
    'docs/EXP22_EDGE_LEASE_CANDIDATE_DESIGN.md', ...
    'network/simulateElcsScheduling.m', ...
    'network/buildElcsContinuousSchedule.m', ...
    'network/applyDstrAffineClockSchedule.m', ...
    'network/advanceSharedMedium.m','network/initSharedMediumState.m', ...
    'network/serviceSchedulerConfig.m', ...
    'utils/elcsKernelConfig.m','utils/generateElcsTrace.m', ...
    'utils/exp22dElcsClosedLoopRegistry.m',registry, ...
    'utils/applyExp22dElcsClockArm.m', ...
    'utils/exp22dElcsClosedLoopEmptyRow.m', ...
    'utils/runExp22dElcsClosedLoopCell.m', ...
    'tests/test_elcs_continuous_integration_contracts.m', ...
    'experiments/exp22d_elcs_closed_loop_integration.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    name=replace(files{k},{'/' '\'},'__');
    copyfile(fullfile(root,files{k}),fullfile(freeze,name));
end

end


function expRun=resumeRun( ...
    runDir,registryHash,registryLeaves,experimentName)

if ~isfolder(runDir), error('exp22d: resume directory not found.'); end
opened=jsondecode(fileread(fullfile(runDir,'elcs_opened.json')));
if opened.registryHash~=registryHash || opened.registryLeaves~=registryLeaves
    error('exp22d: registry differs from the opened run.');
end
[~,runId]=fileparts(runDir);
meta=struct('experiment',experimentName, ...
    'runId',runId,'startedAt',opened.openedAt, ...
    'matlabVersion',version,'matlabRelease',version('-release'), ...
    'computer',computer,'projectRoot',projectRoot(),'gitCommit','', ...
    'notes','resumed from frozen ELCS-F integration checkpoint');
expRun=struct('name',experimentName, ...
    'runId',runId,'dir',runDir,'figDir',fullfile(runDir,'figures'), ...
    'expRoot',fileparts(runDir),'meta',meta,'t0',tic);

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('exp22d: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));

end


function value=ternary(condition,a,b)

if condition, value=a; else, value=b; end

end
