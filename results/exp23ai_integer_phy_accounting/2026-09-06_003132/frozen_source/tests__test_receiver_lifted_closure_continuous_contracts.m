%% TEST_RECEIVER_LIFTED_CLOSURE_CONTINUOUS_CONTRACTS

startup;
R=exp23adClosureKernelRegistry();
row=runExp23adClosureKernelCell(R.seeds(1),5,'nominal-zero',R); %#ok<NASGU>
[M,C,T]=fixture(R);
P=struct('guardSec',0.0015,'dataBytes',96,'horizonSec',20);
Q=buildReceiverLiftedClosureContinuousSchedule(M,C,T,P);
K=Q.kernel;
assert(numel(Q.controlStartTime)==K.controlAttempts && ...
    sum(Q.controlAttemptBytes)==K.controlBytes && ...
    sum(Q.controlGroupBytes)==K.controlBytes && ...
    Q.expectedManagementBytes==K.controlBytes && ...
    Q.controlPhyRateBps==C.phyRateBps && ...
    abs(sum(Q.controlAttemptAirtimeSec)-K.controlAirtimeSec)<1e-12);
assert(nnz(Q.controlKind=="prepare")==K.attempts.prepare && ...
    nnz(Q.controlKind=="quiescent")==K.attempts.quiet && ...
    nnz(Q.controlKind=="claim")==K.attempts.claim && ...
    nnz(Q.controlKind=="lock-proof")==K.attempts.lockProof && ...
    nnz(Q.controlKind=="response")==K.attempts.response && ...
    nnz(Q.controlKind=="commit")==K.attempts.commit);
assert(~any(Q.controlKind=="revoke") && K.revokePiggybacked);
assert(Q.expectedDataCollisionFrames==0 && ...
    Q.expectedDataRecipientCollision==0);
assert(all(Q.controlStartTime+Q.controlAttemptAirtimeSec<= ...
    Q.frameEndTime(Q.controlFrame)+1e-12));

spec=struct('clockOffsetSec',zeros(5,1), ...
    'clockDriftPpm',zeros(5,1),'maxOffsetSec',0.25e-3, ...
    'maxDriftPpm',40,'leadTimeSec',0.00073003, ...
    'safeGuardSec',0.0015);
A=applyDstrAffineClockSchedule(Q,spec);
assert(A.clockTimingConflictFree && A.clockEquationMaxResidualSec<2e-12 && ...
    A.expectedManagementBytes==K.controlBytes && ...
    A.controlPhyRateBps==C.phyRateBps);

fprintf('test_receiver_lifted_closure_continuous_contracts: PASS\n');


function [M,C,T]=fixture(R)

N=5; initiator=N; neighbor=false(N); neighbor(initiator,1)=true;
I0=false(N); I1=I0; I1(initiator,[2 3])=true;
I1([2 3],initiator)=true;
F0=buildSenderConflictGraph(neighbor,I0); F1=buildSenderConflictGraph(neighbor,I1);
oldSlot=elcsWitnessPriorityColor(F0); reach=true(N); reach(1:N+1:end)=false;
packet=struct('maxDataSlots',N,'maxAffectedNodes',N, ...
    'prepareHeaderBytes',R.prepareHeaderBytes, ...
    'affectedEntryBytes',R.affectedEntryBytes,'claimBytes',R.claimBytes, ...
    'quietBytes',R.quietBytes,'lockProofBytes',R.lockProofBytes, ...
    'certificateHeaderBytes',R.certificateHeaderBytes, ...
    'certificateEntryBytes',R.certificateEntryBytes, ...
    'commitBytes',R.commitBytes, ...
    'maxControlPacketBytes',R.maxControlPacketBytes, ...
    'revokeBytes',R.revokeBytes);
M=buildReceiverLiftedDependencyMigration(F0,F1,oldSlot,initiator,reach,packet);
C=struct('maxFrames',60,'prepareFrame',5,'transactionVersion',2, ...
    'prepareDenseRetryFrames',4,'prepareMaxBackoffFrames',4, ...
    'prepareRetryAttemptLimit',8,'claimEligibilityDelayFrames',2, ...
    'lockProofRepeatFrames',12,'claimBackoffEnabled',true, ...
    'claimDenseRetryFrames',6,'claimMaxBackoffFrames',8, ...
    'claimRetryAttemptLimit',10,'commitRetryAttemptLimit',6, ...
    'phyRateBps',250e3,'prepareErasureProbability',.2, ...
    'quietErasureProbability',.2,'claimErasureProbability',.2, ...
    'lockProofErasureProbability',.2,'responseErasureProbability',.2, ...
    'commitErasureProbability',.2,'revokeErasureProbability',.2, ...
    'piggybackRevoke',true);
T=generateReceiverLiftedClosureTrace(16092000,M,C);
fields={'prepareDeliveryU','quietDeliveryU','claimDeliveryU', ...
    'lockProofDeliveryU','responseDeliveryU','commitDeliveryU', ...
    'revokeDeliveryU'};
for k=1:numel(fields), T.(fields{k})(:)=1; end
T.hashExact=receiverLiftedClosureTraceHash(T);

end
