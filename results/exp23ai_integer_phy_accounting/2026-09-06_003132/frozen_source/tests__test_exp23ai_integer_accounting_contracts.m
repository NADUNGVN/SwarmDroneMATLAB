%% TEST_EXP23AI_INTEGER_ACCOUNTING_CONTRACTS Registry and exact-byte smoke.
startup;
fprintf('\n============================================================\n');
fprintf('test_exp23ai_integer_accounting_contracts\n');
fprintf('============================================================\n\n');

R=exp23aiIntegerAccountingRegistry(); checks=0;
used=[R.smokeSeed;R.calibrationSeeds;R.radialValidationSeeds; ...
    R.phaseValidationSeeds];
assert(R.expectedRuns==300&&numel(R.seeds)==50&&numel(R.arms)==6&& ...
    R.requiredValidationContracts==28&&isempty(intersect(R.seeds,used)));
fprintf('    ok   300-row integer-accounting matrix is fresh\n');
checks=checks+1;

parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ah_phase_reserved_radial_closure',R.parentPhaseRun, ...
    'phase_reserved_verdict.json')));
assert(strcmp(parent.status,R.parentPhaseStatus)&& ...
    parent.gatesPassed==26&&parent.gatesTotal==27&& ...
    ~parent.freshPhaseReservedEvidence);
fprintf('    ok   EXP23AH remains invalid at its accounting gate\n');
checks=checks+1;

[rows,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,R);
T=struct2table(rows); closure=string(T.kind)=="closure";
normal=string(T.arm)=="closure-iid20-emergency";
noEmergency=string(T.arm)== ...
    "closure-response-blackout-no-emergency";
protected=closure&~noEmergency;
assert(all(T.observedControlBytes(closure)== ...
    T.expectedControlBytes(closure))&&all( ...
    T.expectedControlBytes(closure)==T.controlBytes(closure))&&all( ...
    T.controlAirtime(closure)== ...
    8*T.observedControlBytes(closure)/R.phyRateBps));
fprintf('    ok   observed integer bytes determine airtime exactly\n');
checks=checks+1;

B=context.reliabilityCertificate;
assert(B.horizonFeasible&& ...
    B.unionFailureUpperBound<R.maxTransactionFailureProbability&& ...
    T.allReactivated(normal)==1&& ...
    all(T.radialTheoremCertified(protected)==1)&& ...
    all(T.actualSenderSubset(protected)==1)&& ...
    all(T.observedCollisionFrames(protected)==0)&& ...
    T.radialTheoremCertified(noEmergency)==0);
fprintf('    ok   reliability, radial theorem and negative control persist\n');
checks=checks+1;

assert(all(T.prefixStateExact(closure)==1)&& ...
    all(T.dataOutcomeMismatches(closure)==0)&& ...
    all(T.futureRandomReads(closure)==0)&& ...
    all(T.receiverTruthReads(closure)==0)&& ...
    R.registeredIntegerAccountingSeeds&& ...
    ~R.integerPhyAccountingValidated&& ...
    ~R.freshPhaseReservedEvidence&& ...
    ~R.managementRelayingValidated&& ...
    ~R.repeatedOnlineRenewalValidated&&~R.submissionClaimPermitted);
fprintf('    ok   causality passes with no premature claim promotion\n');
checks=checks+1;

fprintf('\ntest_exp23ai_integer_accounting_contracts: PASS (%d checks)\n',checks);
