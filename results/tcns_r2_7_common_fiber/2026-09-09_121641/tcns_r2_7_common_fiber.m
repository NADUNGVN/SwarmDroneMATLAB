%% TCNS R2.7 COMMON MULTI-ACTION FIBER CLOSURE

startup;
R = startExperiment('tcns_r2_7_common_fiber', ...
    ['Deterministic replay/post-processing of ten frozen N=5 R2 centers ' ...
     'for senders 1, 3, and 4. No new trajectory, seed, random search, ' ...
     'scheduler, registry cell, or noise model.']);

sourceWorkspace = fullfile(projectRoot(),'results', ...
    'tcns_r2_generalization_validation','2026-09-08_161130', ...
    'workspace.mat');
audit = tcnsR27CommonFiberAudit(sourceWorkspace);

writetable(audit.candidateTable, ...
    fullfile(R.dir,'common_fiber_candidates.csv'));
writetable(audit.dimensionTable, ...
    fullfile(R.dir,'common_fiber_dimensions.csv'));
writetable(audit.argmaxTable, ...
    fullfile(R.dir,'common_fiber_argmax.csv'));
writetable(audit.replayTable, ...
    fullfile(R.dir,'common_fiber_replay.csv'));

outcome = audit.argmaxTable.outcome;
summary.schemaVersion = 1;
summary.studyClass = char(audit.studyClass);
summary.protocolCommit = '55340bff657d8881482810b9ca457d736951c0b5';
summary.sourceWorkspace = char(audit.sourceWorkspace);
summary.frozenN = 5;
summary.frozenH = 25;
summary.frozenD = 4;
summary.senders = [1 3 4];
summary.persistedCenterCount = 10;
summary.attemptCount = height(audit.candidateTable);
summary.eligibleCount = nnz(audit.candidateTable.sourceEligible);
summary.excludedCount = nnz(~audit.candidateTable.sourceEligible);
summary.outcomeA = nnz(outcome=="COMMON_FIBER_ARGMAX_AMBIGUOUS");
summary.outcomeB = nnz(outcome=="COMMON_FIBER_WINNER_CERTIFIED");
summary.outcomeC = nnz(outcome=="COMMON_FIBER_ZERO_DIMENSION");
summary.outcomeD = nnz(outcome=="COMMON_FIBER_NOT_CERTIFIABLE");
summary.allCandidateResponsesJointlyPreserved = ...
    max(audit.argmaxTable.maximumJointResponseResidual,[],'omitnan')<= ...
    audit.options.responseTolerance;
summary.maximumInformationResidual = max( ...
    audit.argmaxTable.maximumInformationResidual,[],'omitnan');
summary.maximumJointResponseResidual = max( ...
    audit.argmaxTable.maximumJointResponseResidual,[],'omitnan');
summary.maximumDynamicResidual = max( ...
    audit.argmaxTable.maximumDynamicResidual,[],'omitnan');
summary.maximumAffineOracleMismatch = max( ...
    audit.argmaxTable.maximumAffineOracleMismatch,[],'omitnan');
summary.minimumPositiveWinnerMargin = min([ ...
    audit.argmaxTable.leftWinnerMargin( ...
        audit.argmaxTable.leftWinnerMargin>0); ...
    audit.argmaxTable.rightWinnerMargin( ...
        audit.argmaxTable.rightWinnerMargin>0)],[],'omitnan');
summary.noNewTrajectoryGenerated = audit.noNewTrajectoryGenerated;
summary.noRandomSearch = audit.noRandomSearch;
summary.noNewSeed = audit.noNewSeed;
summary.manuscriptEdited = audit.manuscriptEdited;
summary.outcomeLabels = struct( ...
    'A','COMMON_FIBER_ARGMAX_AMBIGUOUS', ...
    'B','COMMON_FIBER_WINNER_CERTIFIED', ...
    'C','COMMON_FIBER_ZERO_DIMENSION', ...
    'D','COMMON_FIBER_NOT_CERTIFIABLE');

fid = fopen(fullfile(R.dir,'summary.json'),'w');
assert(fid>0,'R27: cannot create summary.json.');
fprintf(fid,'%s\n',jsonencode(summary,'PrettyPrint',true));
fclose(fid);
save(fullfile(R.dir,'workspace.mat'),'audit','summary');

fprintf('Persisted centers                      : %d\n', ...
    summary.persistedCenterCount);
fprintf('Sender/center attempts                 : %d\n', ...
    summary.attemptCount);
fprintf('Eligible / excluded                    : %d / %d\n', ...
    summary.eligibleCount,summary.excludedCount);
fprintf('Outcomes A / B / C / D                 : %d / %d / %d / %d\n', ...
    summary.outcomeA,summary.outcomeB,summary.outcomeC,summary.outcomeD);
fprintf('Maximum sender-information residual    : %.3e\n', ...
    summary.maximumInformationResidual);
fprintf('Maximum joint-response residual        : %.3e\n', ...
    summary.maximumJointResponseResidual);
fprintf('Maximum reachability residual          : %.3e\n', ...
    summary.maximumDynamicResidual);
fprintf('Maximum affine/oracle mismatch         : %.3e\n', ...
    summary.maximumAffineOracleMismatch);
fprintf('Minimum positive winner margin         : %.3e\n', ...
    summary.minimumPositiveWinnerMargin);

finishExperiment(R);
