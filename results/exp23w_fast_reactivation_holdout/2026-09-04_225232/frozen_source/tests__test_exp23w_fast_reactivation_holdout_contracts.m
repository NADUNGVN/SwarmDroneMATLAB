% TEST_EXP23W_FAST_REACTIVATION_HOLDOUT_CONTRACTS Holdout preflight.
startup;
fprintf('\n============================================================\n');
fprintf('test_exp23w_fast_reactivation_holdout_contracts\n');
fprintf('============================================================\n\n');

checks=0; R=exp23wFastReactivationHoldoutRegistry();
assert(R.expectedRuns==800 && numel(R.seeds)==100 && ...
    min(R.seeds)>R.priorSeedUpperBound && R.primaryFamilySize==6 && ...
    R.requiredValidationContracts==21);
fprintf('    ok   800-row disjoint 100-seed holdout is frozen\n'); checks=checks+1;

assert(nnz([R.arms.fastReactivation])==4 && ...
    nnz([R.arms.responseBlackout])==1 && ...
    nnz([R.arms.revokeBlackout])==1 && ...
    isequaln([R.arms.eventTimeSec],[NaN NaN 3 3 3 8 8 3]));
fprintf('    ok   comparator, fast and fault arms are exact\n'); checks=checks+1;

assert(R.staticRmseNoninferiorityMargin==0.01 && ...
    R.oldFenceCostPenaltyMargin==0.05 && ...
    R.familywiseAlpha==0.05 && R.bootstrapReplicates==10000);
fprintf('    ok   six-test Holm family and margins are frozen\n'); checks=checks+1;

assert(R.confirmatory && R.freshSeedEvidence && ...
    ~R.policyOptimizationAllowed && ~R.broadRobustnessClaimPermitted && ...
    R.confirmedFixedGraphPromotionPermitted && ...
    ~R.submissionClaimPermitted);
fprintf('    ok   confirmation can promote only fixed-graph mechanism\n');
checks=checks+1;

fprintf('\ntest_exp23w_fast_reactivation_holdout_contracts: PASS (%d checks)\n',checks);
