function exp23am_semantic_local_sentinel()
%EXP23AM_SEMANTIC_LOCAL_SENTINEL Confirm undefined local-route sentinel.

startup; close all; runRequiredTests();
R=exp23amSemanticSentinelRegistry();
[registryHash,registryLeaves]=configHash(R);
alDir=fullfile(projectRoot(),'results', ...
    'exp23al_routed_accounting_confirmation',R.parentRun);
ajDir=fullfile(projectRoot(),'results', ...
    'exp23aj_routed_management_diagnostic',R.scientificParentRun);
A=load(fullfile(alDir,'workspace.mat'));
J=load(fullfile(ajDir,'workspace.mat'));

expRun=startExperiment('exp23am_semantic_local_sentinel', ...
    ['Deterministic confirmation of NaN route-hash semantics for local-only ' ...
    'closure control delivery.']);
writeJson(fullfile(expRun.dir,'semantic_sentinel_registry.json'),R);
snapshotSource(expRun.dir,R);

T=rebuildSemantic(J.E,A.E,R);
writetable(T,fullfile(expRun.dir,'semantic_sentinel_confirmation.csv'));
parentGates=readtable(fullfile(alDir,'validation_gates.csv'), ...
    'TextType','string');
gates=validationGates(T,parentGates,R,registryHash,registryLeaves,alDir);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
valid=all(gates.passed==1);
status=ternary(valid, ...
    'INTEGER_ACCOUNTED_ROUTING_PRIMITIVE_DIAGNOSTIC_VALID', ...
    'INTEGER_ACCOUNTED_ROUTING_PRIMITIVE_DIAGNOSTIC_INVALID');
next=ternary(valid,'multi_origin_common_phy_routing_integration', ...
    'repair_semantic_sentinel_without_relaxing_registered_gates');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'exp23ajInvalidRetained',true, ...
    'exp23alInvalidRetained',true,'routingPrimitiveValidated',valid, ...
    'integerRoutedAccountingValidated',valid, ...
    'semanticRecipientRoutingValidated',valid, ...
    'closedLoopManagementRelayingValidated',false, ...
    'managementRelayingValidated',false, ...
    'repeatedOnlineRenewalValidated',false, ...
    'freshSeedEvidence',false,'robustnessClaimPermitted',false, ...
    'submissionClaimPermitted',false,'next',next);
writeJson(fullfile(expRun.dir,'semantic_sentinel_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','parentGates','gates', ...
    'verdict','R');

fprintf('\nEXP23AM semantic sentinel gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(T);
fprintf('EXP23AM DECISION: %s\n',status);
finishExperiment(expRun);
if ~valid, error('exp23am: semantic sentinel confirmation invalid.'); end

end


function T=rebuildSemantic(parent,al,R)

PARENT=exp23aiIntegerAccountingRegistry();
[~,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,PARENT);
M=context.geometry.migration; reach=logical(context.neighborGraph);
interference=context.geometry.oldPhysicalGraph| ...
    context.geometry.proposedPhysicalGraph;
rows=repmat(emptyRow(),height(parent),1);
for k=1:height(parent)
    old=parent(k,:); key=string(al.kind)==string(old.kind)& ...
        al.sender==old.sender;
    if nnz(key)~=1, error('exp23am: missing EXP23AL semantic row.'); end
    prior=al(key,:); kind=char(old.kind); sender=old.sender;
    recipients=receiverLiftedClosureControlRecipients(M,kind,sender);
    row=emptyRow(); row.kind=old.kind; row.sender=sender;
    row.packetBytes=old.packetBytes; row.recipientCount=nnz(recipients);
    row.currentRecipientHash=realizationHash(double(recipients));
    row.recipientHashExact=double(row.currentRecipientHash== ...
        old.recipientHash&&prior.recipientHashExact==1);
    row.localOnly=double(~any(recipients));
    if row.localOnly
        row.parentUndefinedRouteHash=double(isnan(old.planHash));
        row.noRouteInstantiated=1; row.planExact=1;
        row.reliabilityExact=double(old.multicastFailureExact==0&& ...
            prior.reliabilityExact==1);
        row.deliveryExact=double(old.allRecipientsDelivered==1&& ...
            prior.deliveryExact==1);
        row.attempts=0; row.physicalBytes=0; row.offeredAirtimeSec=0;
        row.accountingExact=double(old.observedAttempts==0&& ...
            old.observedBytes==0&&old.observedAirtimeSec==0&& ...
            prior.attempts==0&&prior.physicalBytes==0&& ...
            prior.offeredAirtimeSec==0&&prior.accountingExact==1);
        rows(k)=row; continue;
    end

    P=buildSlottedManagementFloodPlan(reach,interference,sender, ...
        recipients,M.N-1);
    D=dimensionRepeatedHopManagementFlood(P, ...
        R.semanticLinkErasureProbability,R.maximumLogicalPacketFailure, ...
        R.maxRepetitionsPerHop);
    O=simulateRepeatedHopManagementFlood(P, ...
        ones(M.N,M.N,D.selectedRepetitions), ...
        R.semanticLinkErasureProbability,D.selectedRepetitions, ...
        old.packetBytes,R.phyRateBps,R.safeGuardSec);
    row.currentPlanHash=P.hashExact;
    row.planExact=double(P.hashExact==old.planHash&& ...
        prior.planExact==1&&D.selectedRepetitions== ...
        old.selectedRepetitions&&O.attempts==old.maximumPhysicalAttempts);
    row.reliabilityExact=double(D.certificate.multicastFailureExact== ...
        old.multicastFailureExact&&prior.reliabilityExact==1);
    row.simulatorVersionHash=realizationHash(O.version);
    row.deliveryExact=double(O.allRecipientsDelivered&& ...
        prior.deliveryExact==1);
    row.attempts=O.attempts; row.physicalBytes=O.bytes;
    row.offeredAirtimeSec=O.offeredAirtimeSec;
    row.accountingExact=double(O.bytes==O.attempts*old.packetBytes&& ...
        O.offeredAirtimeSec==8*O.bytes/R.phyRateBps&& ...
        prior.accountingExact==1);
    row.collisionRecipients=O.collisionRecipients;
    row.duplicateForwards=O.duplicateForwardCount;
    row.forbiddenReads=O.futureRandomReads+O.receiverTruthDecisionReads;
    rows(k)=row;
end
T=struct2table(rows);

end


function gates=validationGates(T,parentGates,R,registryHash, ...
    registryLeaves,parentDir)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
parent=jsondecode(fileread(fullfile(parentDir, ...
    'routed_accounting_verdict.json')));
failed=string(parentGates.gate(parentGates.passed==0));
add('registry_and_invalid_parent_retained',isfinite(registryHash)&& ...
    registryLeaves>0&&strcmp(parent.status,R.parentStatus)&& ...
    parent.gatesPassed==R.parentGatesPassed&& ...
    parent.gatesTotal==R.parentGatesTotal&&isscalar(failed)&& ...
    failed==string(R.parentFailedGate),sprintf( ...
    'registry %.0f/%d leaves; EXP23AL retained at %d/%d', ...
    registryHash,registryLeaves,parent.gatesPassed,parent.gatesTotal));
add('other_parent_gates_retained',height(parentGates)==10&& ...
    sum(parentGates.passed)==9, ...
    'all nine non-sentinel EXP23AL gates remain passed');
local=T.localOnly==1;
add('local_only_nan_sentinel',nnz(local)==R.expectedLocalOnlyRows&& ...
    all(T.parentUndefinedRouteHash(local)==1)&&all( ...
    T.noRouteInstantiated(local)==1)&&all(T.attempts(local)==0)&&all( ...
    T.physicalBytes(local)==0)&&all(T.offeredAirtimeSec(local)==0), ...
    'one initiator-local RESPONSE has NaN route hash and zero radio cost');
add('semantic_recipient_identity',height(T)==R.expectedSemanticRows&& ...
    all(T.recipientHashExact==1),sprintf( ...
    '%d/%d semantic recipient hashes reproduce exactly', ...
    nnz(T.recipientHashExact),height(T)));
nonlocal=~local;
add('nonlocal_plan_and_reliability_identity',all(T.planExact==1)&& ...
    all(T.reliabilityExact==1)&&all( ...
    T.simulatorVersionHash(nonlocal)== ...
    realizationHash(R.repairedSimulatorVersion)),sprintf( ...
    '%d nonlocal routed plans/certificates exact; local route undefined', ...
    nnz(nonlocal)));
add('semantic_delivery_and_accounting_exact',all( ...
    T.deliveryExact==1)&&all(T.accountingExact==1)&&all( ...
    T.collisionRecipients==0)&&all(T.duplicateForwards==0)&&all( ...
    T.forbiddenReads==0),sprintf( ...
    'attempt range %.0f--%.0f; integer byte/airtime exact', ...
    min(T.attempts),max(T.attempts)));
scope=R.developmentOnly&&~R.confirmatoryEvidence&& ...
    ~R.managementRelayingValidated&&~R.repeatedOnlineRenewalValidated&& ...
    ~R.freshSeedEvidence&&~R.robustnessClaimPermitted&& ...
    ~R.submissionClaimPermitted;
add('primitive_scope_only',scope, ...
    'routing primitive closes; closed-loop and renewal claims stay false');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23am: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function row=emptyRow()

row=struct('kind',"",'sender',NaN,'packetBytes',NaN, ...
    'recipientCount',NaN,'currentRecipientHash',NaN, ...
    'recipientHashExact',NaN,'localOnly',NaN, ...
    'parentUndefinedRouteHash',0,'noRouteInstantiated',0, ...
    'currentPlanHash',NaN,'planExact',NaN,'reliabilityExact',NaN, ...
    'simulatorVersionHash',0,'deliveryExact',NaN,'attempts',NaN, ...
    'physicalBytes',NaN,'offeredAirtimeSec',NaN, ...
    'accountingExact',NaN,'collisionRecipients',0, ...
    'duplicateForwards',0,'forbiddenReads',0);

end


function runRequiredTests()

names={'test_exp23am_semantic_sentinel_contracts', ...
    'test_exp23al_routed_accounting_contracts', ...
    'test_slotted_management_flood_contracts', ...
    'test_receiver_lifted_control_routing_contracts'};
for k=1:numel(names), runScriptIsolated(names{k}); end

end


function snapshotSource(target,R)

root=projectRoot(); files={ ...
    'docs/EXP23AM_SEMANTIC_LOCAL_SENTINEL_PLAN.md', ...
    'docs/EXP23AL_ROUTED_INTEGER_ACCOUNTING_PLAN.md', ...
    'results/exp23al_routed_accounting_confirmation/2026-09-06_071620/routed_accounting_verdict.json', ...
    'results/exp23al_routed_accounting_confirmation/2026-09-06_071620/validation_gates.csv', ...
    'network/buildSlottedManagementFloodPlan.m', ...
    'network/repeatedHopManagementFloodReliabilityCertificate.m', ...
    'network/dimensionRepeatedHopManagementFlood.m', ...
    'network/simulateRepeatedHopManagementFlood.m', ...
    'network/receiverLiftedClosureControlRecipients.m', ...
    'utils/exp23amSemanticSentinelRegistry.m', ...
    'tests/test_exp23am_semantic_sentinel_contracts.m', ...
    'tests/test_slotted_management_flood_contracts.m', ...
    'tests/test_receiver_lifted_control_routing_contracts.m', ...
    'experiments/exp23am_semantic_local_sentinel.m'};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
for k=1:numel(files)
    source=fullfile(root,files{k});
    if ~isfile(source), error('exp23am: missing source %s.',source); end
    name=replace(files{k},{'/' '\'},'__');
    copyfile(source,fullfile(freeze,name));
end
writeJson(fullfile(target,'scope_snapshot.json'),struct( ...
    'registryVersion',R.version,'claimScope','routing primitive only'));

end


function writeJson(path,value)

fid=fopen(path,'w'); if fid<0, error('exp23am: cannot write.'); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));

end


function value=ternary(condition,a,b)

if condition, value=a; else, value=b; end

end
