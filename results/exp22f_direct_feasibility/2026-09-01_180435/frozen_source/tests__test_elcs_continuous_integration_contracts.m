%% TEST_ELCS_CONTINUOUS_INTEGRATION_CONTRACTS ELCS-F physical timeline.

startup;
fprintf('\n============================================================\n');
fprintf('test_elcs_continuous_integration_contracts\n');
fprintf('============================================================\n\n');
checks=cell(0,2);
R=exp22dElcsClosedLoopRegistry();
checks(end+1,:)={numel(R.seeds)==30 && numel(R.cells)==2 && ...
    numel(R.arms)==2 && R.expectedRuns==120 && ...
    ~R.policyOptimizationAllowed && ~R.newMethodPromotionAllowed && ...
    ~R.submissionClaimPermitted, ...
    'EXP22D registry freezes 120 integration-only fresh-seed rows'};
Rrepair=exp22eElcsClosedLoopRegistry();
checks(end+1,:)={numel(Rrepair.seeds)==30 && ...
    Rrepair.expectedRuns==120 && ...
    isempty(intersect(R.seeds,Rrepair.seeds)) && ...
    Rrepair.fallbackAttemptCapPerNodeFrame==1 && ...
    strcmp(Rrepair.parentKernelGates,'17/17'), ...
    'EXP22E closed-loop rerun uses disjoint seeds after valid kernel repair'};

%% Exact kernel-to-continuous mapping with distinct control/DATA airtime.
N=5;
theta=0.25e-3;
ppm=40;
B=continuousTdmaGuardBound(theta,ppm,5.0);
C=elcsKernelConfig(N,60);
C.guardSec=B.safeGuardSec;
T=generateElcsTrace(16043001,C);
K=simulateElcsScheduling(C,T);
Q=buildElcsContinuousSchedule(C,T,K.elapsedSec);

checks(end+1,:)={abs(Q.airtimeSec-8*C.dataBytes/C.phyRateBps)<1e-15 && ...
    abs(Q.controlAirtimeSec-8*C.controlBytes/C.phyRateBps)<1e-15 && ...
    Q.controlAirtimeSec<Q.airtimeSec, ...
    'control and DATA use their declared common-PHY payload airtimes'};
checks(end+1,:)={nnz(Q.controlKind=="status")==K.statusAttempts && ...
    nnz(Q.controlKind=="grant")==K.grantAttempts && ...
    nnz(Q.dataKind=="scheduled")==K.scheduledAttempts && ...
    nnz(Q.dataKind=="fallback")==K.fallbackAttempts, ...
    'every full-horizon kernel attempt maps once with its plane/kind'};
checks(end+1,:)={Q.expectedManagementAttempts==K.controlAttempts && ...
    Q.expectedManagementRecipientAttempts==K.managementRecipientAttempts && ...
    Q.expectedManagementRecipientSuccess==K.managementRecipientSuccess && ...
    Q.expectedManagementRecipientErasure==K.managementRecipientErasure && ...
    Q.expectedManagementRecipientCollision==K.managementRecipientCollision, ...
    'management attempt and recipient accounting equals the kernel'};
checks(end+1,:)={Q.expectedDataRecipientSuccess== ...
        K.scheduledRecipientSuccess+K.fallbackRecipientSuccess && ...
    Q.expectedDataRecipientErasure== ...
        K.scheduledRecipientErasure+K.fallbackRecipientErasure && ...
    Q.expectedDataRecipientCollision== ...
        K.scheduledRecipientCollision+K.fallbackRecipientCollision && ...
    Q.futureRandomReads==0 && Q.receiverTruthDecisionReads==0, ...
    'DATA outcome projection closes without forbidden information reads'};
checks(end+1,:)={crossPlaneClear(Q) && all(Q.dataCompletesByHorizon), ...
    'native STATUS, GRANT, fallback and scheduled regions are disjoint'};

%% Affine clocks preserve the same logical experiment and exact metadata.
zero=clockSpec(N,theta,ppm,B,zeros(N,1),zeros(N,1));
offset=linspace(-theta,theta,N)';
drift=linspace(-ppm,ppm,N)';
impaired=clockSpec(N,theta,ppm,B,offset,drift);
Q0=applyDstrAffineClockSchedule(Q,zero);
Qa=applyDstrAffineClockSchedule(Q,impaired);
checks(end+1,:)={Qa.logicalOpportunityHashExact== ...
        Q0.logicalOpportunityHashExact && ...
    isequal(sortrows([Qa.dataFrame Qa.dataSlot Qa.dataNode]), ...
        sortrows([Q0.dataFrame Q0.dataSlot Q0.dataNode])) && ...
    isequal(sortrows([Qa.controlFrame double(Qa.controlSlot) Qa.controlNode]), ...
        sortrows([Q0.controlFrame double(Q0.controlSlot) Q0.controlNode])), ...
    'zero/impaired clocks retain identical outcome-blind logical opportunities'};
checks(end+1,:)={numel(Qa.dataKind)==numel(Qa.dataStartTime) && ...
    numel(Qa.controlKind)==numel(Qa.controlStartTime) && ...
    nnz(Qa.dataKind=="fallback")==nnz(Q0.dataKind=="fallback") && ...
    nnz(Qa.controlKind=="grant")==nnz(Q0.controlKind=="grant"), ...
    'affine transformation preserves fallback/scheduled and STATUS/GRANT labels'};
checks(end+1,:)={Qa.clockTimingConflictFree==1 && ...
    Qa.clockMinimumIntergroupGapSec>=-1e-12 && ...
    Qa.clockMaximumIntragroupSkewSec<Qa.airtimeSec && ...
    Qa.clockEquationMaxResidualSec<1e-12 && crossPlaneClear(Qa), ...
    'mission guard certifies the composed physical timeline'};

%% Shared event engine consumes the transformed schedule exactly.
cfg=eventCfg(C,Qa,theta,ppm);
trace=generateSharedMediumTrace(cfg);
net=initSharedMediumState(cfg,cfg.swarm.A);
net=fillQueues(net,Qa,cfg);
[net,events]=advanceSharedMedium(net,0,cfg.swarm.T,cfg,trace);
S=net.serviceScheduler;
checks(end+1,:)={S.dstrDataOpportunities==numel(Qa.dataStartTime) && ...
    S.dstrDataAttempts==numel(Qa.dataStartTime) && ...
    S.dstrDataSkippedNoQueue==0 && ...
    S.dstrManagementAttempts==Qa.expectedManagementAttempts && ...
    abs(S.dstrManagementAirtime-Qa.expectedManagementAttempts* ...
        Qa.controlAirtimeSec)<1e-12, ...
    'event engine consumes all due attempts and charges control airtime'};
checks(end+1,:)={S.dstrDataOutcomeMismatchCount==0 && ...
    net.stats.collisionFrames==Qa.expectedCompletedDataCollisionFrames && ...
    S.dstrDataRecipientSuccessObserved== ...
        Qa.expectedCompletedDataRecipientSuccess && ...
    S.dstrDataRecipientErasureObserved== ...
        Qa.expectedCompletedDataRecipientErasure && ...
    S.dstrDataRecipientCollisionObserved== ...
        Qa.expectedCompletedDataRecipientCollision && ...
    S.dstrCrossPlaneOverlapCount==0 && ~isempty(events), ...
    'physical DATA masks and fallback collisions replay exactly'};

split=0.413*cfg.swarm.T;
net2=initSharedMediumState(cfg,cfg.swarm.A);
net2=fillQueues(net2,Qa,cfg);
[net2,e1]=advanceSharedMedium(net2,0,split,cfg,trace);
[net2,e2]=advanceSharedMedium(net2,split,cfg.swarm.T,cfg,trace);
checks(end+1,:)={net2.serviceScheduler.dstrDataCursor==S.dstrDataCursor && ...
    net2.serviceScheduler.dstrControlCursor==S.dstrControlCursor && ...
    configHash(net2.stats)==configHash(net.stats) && ...
    configHash([e1(:);e2(:)])==configHash(events), ...
    'split calls equal one-shot replay bit-for-bit'};

%% Short closed-loop smoke test: deliveries reach the formation controller.
base=applyExp21CCell('n5-stressed',16043002);
base.swarm.T=0.30;
base.shared.evalStart=0;
base.sixdof.enable=false;
[closedCfg,closedQ]=closedLoopCfg(base,theta,ppm);
closedTrace=generateSharedMediumTrace(closedCfg);
meta=struct('stage','contract','scenario','n5-short', ...
    'scenarioLabel','N5 short','family','ELCS contract', ...
    'arm','elcs-contract','pointIndex',1,'parameterValue',closedQ.guardSec);
details=struct('kind','contract','route','none','ackDesign','none', ...
    'accessDesign','edge-leased-certified-scheduling', ...
    'schedulerMode','continuous-elcs-replay','periodicRateHz',50, ...
    'distributedFlag',1,'idealFlag',0);
[closedRow,closed]=runExp22dElcsClosedLoopCell( ...
    closedCfg,'periodic','ELCS contract',meta,closedTrace,details);
checks(end+1,:)={closed.serviceScheduler.dstrInitialized && ...
    closed.netStats.dataFramesAttempted>0 && ...
    closed.serviceScheduler.dstrManagementAttempts>0 && ...
    closed.serviceScheduler.dstrCrossPlaneOverlapCount==0 && ...
    closed.invariantViolations==0 && ...
    closed.netStats.collisionFrames== ...
        closedQ.expectedCompletedDataCollisionFrames && ...
    closedRow.ELCS_MANAGEMENT_ACCOUNTING_CLOSE==1 && ...
    closedRow.ELCS_DATA_COLLISION_WITNESS_MATCH==1 && ...
    closedRow.ELCS_LOGICAL_OPPORTUNITY_HASH_EXACT== ...
        closedQ.logicalOpportunityHashExact, ...
    'closed-loop formation consumes ELCS-F deliveries with exact accounting'};

Rf=exp22fFeasibilityRegistry();
staticArm=Rf.arms(strcmp({Rf.arms.id},'periodic-static-p10'));
[staticCfg,staticMethod,staticLabel,staticDetails]= ...
    applyExp22fStaticArm(base,staticArm,Rf);
staticTrace=generateSharedMediumTrace(staticCfg);
staticMeta=struct('stage','contract','scenario','n5-short', ...
    'scenarioLabel','N5 short','family','EXP22F contract', ...
    'arm',staticArm.id,'pointIndex',1, ...
    'parameterValue',staticArm.periodicRateHz);
[staticRow,staticOut]=runExp22fFeasibilityCell( ...
    staticCfg,staticMethod,staticLabel,staticMeta,staticTrace, ...
    staticDetails,staticArm.family);
checks(end+1,:)={numel(Rf.arms)==10 && Rf.expectedRuns==600 && ...
    staticRow.REPLAY_FLAG==0 && ...
    staticRow.ENDOGENOUS_COLLISION_FRAMES==0 && ...
    staticRow.INVARIANT_VIOLATIONS==0 && ...
    staticRow.CONTINUOUS_MAX_CLOCK_RESIDUAL<=1e-12 && ...
    abs(staticRow.TOTAL_OFFERED_UTIL- ...
        staticOut.netStats.dataAirtime/staticCfg.swarm.T)<1e-12, ...
    'EXP22F static frontier arm uses paired affine clock and full charge'};

flags=cellfun(@logical,checks(:,1));
for k=1:size(checks,1)
    if flags(k), tag='ok'; else, tag='FAIL'; end
    fprintf('    %-4s %s\n',tag,checks{k,2});
end
if ~all(flags)
    error('test_elcs_continuous_integration_contracts: %d of %d failed.', ...
        nnz(~flags),numel(flags));
end
fprintf('\ntest_elcs_continuous_integration_contracts: PASS (%d checks)\n', ...
    numel(flags));


function S=clockSpec(N,theta,ppm,B,offset,drift)

S=struct('clockOffsetSec',reshape(offset,N,1), ...
    'clockDriftPpm',reshape(drift,N,1), ...
    'maxOffsetSec',theta,'maxDriftPpm',ppm, ...
    'leadTimeSec',B.maxBoundaryErrorSec, ...
    'safeGuardSec',B.safeGuardSec);

end


function clear=crossPlaneClear(Q)

clear=true;
for k=1:numel(Q.dataStartTime)
    overlap=Q.dataStartTime(k)<Q.controlGroupEndTime-1e-12 & ...
        Q.controlGroupStartTime<Q.dataStartTime(k)+Q.airtimeSec-1e-12;
    if any(overlap), clear=false; return; end
end

end


function cfg=eventCfg(C,Q,theta,ppm)

N=C.N;
cfg=struct();
cfg.swarm=struct('N',N,'T',Q.horizonSec,'A',C.neighborGraph);
cfg.net=struct('seed',16043001);
cfg.mac=struct('type','tdma','slotTime',0.1e-3,'queueCapacity',4096, ...
    'dataBytes',C.dataBytes,'ackBaseBytes',4,'ackEntryBytes',2, ...
    'phyRateBps',C.phyRateBps,'ackDeadline',0.01,'pAccess',1, ...
    'historySize',4096,'residualLoss',0,'dataResidualLoss',0, ...
    'ackResidualLoss',0,'lossModel','iid','separateAckTrace',false, ...
    'maxRetries',0,'backgroundLoad',0, ...
    'interferenceMatrix',C.interferenceMatrix, ...
    'carrierSenseMatrix',true(N),'applyDeliveriesInline',false);
cfg.aoiEvent=struct('posThreshold',0.05,'velThreshold',0.10, ...
    'aoiThreshold',0.12,'maxSilence',0.50);
cfg.shared=struct('feedbackMode','none');
cfg.shared.serviceScheduler=struct('mode','continuous-elcs-replay', ...
    'logDecisions',true,'clockOffsetMaxSec',theta, ...
    'clockDriftMaxPpm',ppm,'continuousGuardTime',Q.guardSec, ...
    'continuousSyncPeriod',inf,'continuousExactAirtime',true, ...
    'dstrSchedule',Q);
cfg.exp21c=struct('version','EXP22-ELCS-CONTINUOUS-CONTRACT-v1');
cfg.mac=sharedMediumConfig(cfg);
cfg.shared.serviceScheduler=serviceSchedulerConfig(cfg);

end


function net=fillQueues(net,Q,cfg)

for node=1:net.N
    count=nnz(Q.dataNode==node);
    q=repmat(net.frameTemplate,count,1);
    for k=1:count
        f=net.frameTemplate;
        f.id=net.nextFrameId;
        net.nextFrameId=net.nextFrameId+1;
        f.type='data';
        f.dataMode='broadcast';
        f.sender=node;
        f.seq=k;
        f.genTime=0;
        f.pos=[node 0 0];
        f.vel=[0 0 0];
        f.dataReceiverMask=reshape(logical(cfg.swarm.A(:,node)),1,[]);
        f.receiverMask=f.dataReceiverMask;
        f.bytes=cfg.mac.dataBytes;
        f.enqueueTime=0;
        q(k)=f;
    end
    net.queues{node}=q;
end

end


function [cfg,Q]=closedLoopCfg(base,theta,ppm)

cfg=base;
N=cfg.swarm.N;
cfg.net.commPeriod=1/50;
cfg.mac.type='tdma';
cfg.mac.pAccess=1;
cfg.mac.maxRetries=0;
cfg.mac.dataBytes=96;
cfg.mac.phyRateBps=250e3;
cfg.mac.backgroundLoad=0;
cfg.shared.feedbackMode='none';
C=elcsKernelConfig(N,40);
C.dataBytes=cfg.mac.dataBytes;
C.phyRateBps=cfg.mac.phyRateBps;
C.neighborGraph=logical(cfg.swarm.A);
C.managementReach=true(N)-eye(N)>0;
C.interferenceMatrix=logical(cfg.mac.interferenceMatrix);
C.conflictGraph=buildSenderConflictGraph( ...
    C.neighborGraph,C.interferenceMatrix);
B=continuousTdmaGuardBound(theta,ppm,cfg.swarm.T);
C.guardSec=B.safeGuardSec;
T=generateElcsTrace(cfg.net.seed,C);
nativeQ=buildElcsContinuousSchedule(C,T,cfg.swarm.T);
spec=struct('clockOffsetSec',zeros(N,1),'clockDriftPpm',zeros(N,1), ...
    'maxOffsetSec',theta,'maxDriftPpm',ppm, ...
    'leadTimeSec',B.maxBoundaryErrorSec,'safeGuardSec',B.safeGuardSec);
Q=applyDstrAffineClockSchedule(nativeQ,spec);
cfg.shared.serviceScheduler=struct( ...
    'mode','continuous-elcs-replay','logDecisions',true, ...
    'continuousGuardTime',Q.guardSec,'continuousSyncPeriod',inf, ...
    'continuousExactAirtime',true,'dstrSchedule',Q);
cfg.mac=sharedMediumConfig(cfg);
cfg.shared.serviceScheduler=serviceSchedulerConfig(cfg);
cfg.exp20a.originalMacType='tdma';

end
