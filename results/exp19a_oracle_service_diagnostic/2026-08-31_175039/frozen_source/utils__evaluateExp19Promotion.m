function D=evaluateExp19Promotion(S,R,integrityPass)
%EVALUATEEXP19PROMOTION Apply the frozen EXP19A development decision rules.

required={'scenario','arm','meanRMSE','safeFailures','meanOfferedUtil', ...
    'priorityDiffersFifo','fifoComparableDecisions'};
if ~istable(S) || ~all(ismember(required,S.Properties.VariableNames))
    error('evaluateExp19Promotion: summary schema is incomplete.');
end

B=rowFor(S,R.boundaryCell,R.baselineArm);
F=rowFor(S,R.failureCell,R.baselineArm);
oracleRows=repmat(emptyOracle(),numel(R.oracleArms),1);
for k=1:numel(R.oracleArms)
    id=R.oracleArms{k};
    O1=rowFor(S,R.boundaryCell,id);
    O2=rowFor(S,R.failureCell,id);
    gate1=O1.meanRMSE<B.meanRMSE-1e-12 && ...
        O1.meanOfferedUtil<B.meanOfferedUtil-1e-12 && ...
        O1.safeFailures<=B.safeFailures;
    gate2=O2.safeFailures<F.safeFailures && ...
        O2.meanOfferedUtil<=F.meanOfferedUtil+1e-12;
    comparable=sum(S.fifoComparableDecisions( ...
        string(S.arm)==string(id)));
    differs=sum(S.priorityDiffersFifo(string(S.arm)==string(id)));
    fraction=differs/max(comparable,1);
    oracleRows(k)=struct('arm',id, ...
        'boundaryRmseDifference',O1.meanRMSE-B.meanRMSE, ...
        'boundaryOfferedDifference', ...
        O1.meanOfferedUtil-B.meanOfferedUtil, ...
        'boundaryFailureDifference',O1.safeFailures-B.safeFailures, ...
        'failureCellFailureDifference',O2.safeFailures-F.safeFailures, ...
        'failureCellOfferedDifference', ...
        O2.meanOfferedUtil-F.meanOfferedUtil, ...
        'boundaryParetoGate',double(gate1), ...
        'failureReductionGate',double(gate2), ...
        'priorityDiffersFifoFraction',fraction, ...
        'priorityActionGate',double(fraction>= ...
        R.minimumPriorityDifferenceFraction-1e-12));
end
oracle=struct2table(oracleRows);

periodicRows=repmat(emptyPeriodic(),0,1);
for k=1:numel(R.oracleArms)
    id=R.oracleArms{k};
    O=rowFor(S,R.boundaryCell,id);
    for q=1:numel(R.periodicArms)
        pid=R.periodicArms{q};
        P=rowFor(S,R.boundaryCell,pid);
        reproduces=P.meanRMSE<=O.meanRMSE+1e-12 && ...
            P.meanOfferedUtil<=O.meanOfferedUtil+1e-12 && ...
            P.safeFailures<=O.safeFailures;
        periodicRows(end+1,1)=struct('oracleArm',id, ...
            'periodicArm',pid,'rmseDifference', ...
            P.meanRMSE-O.meanRMSE,'offeredDifference', ...
            P.meanOfferedUtil-O.meanOfferedUtil, ...
            'failureDifference',P.safeFailures-O.safeFailures, ...
            'reproducesOracle',double(reproduces)); %#ok<AGROW>
    end
end
periodic=struct2table(periodicRows);

g1=any(oracle.boundaryParetoGate==1);
g2=any(oracle.failureReductionGate==1);
qualified=string(oracle.arm(oracle.boundaryParetoGate==1));
if isempty(qualified)
    g3=false;
else
    reproduced=false;
    for k=1:numel(qualified)
        reproduced=reproduced || any(periodic.oracleArm==qualified(k) & ...
            periodic.reproducesOracle==1);
    end
    g3=~reproduced;
end
g4=any(oracle.priorityActionGate==1);
g5=logical(integrityPass);
names={'boundary_oracle_pareto_headroom'; ...
    'n10_moderate_failure_reduction'; ...
    'not_reproduced_by_periodic_tdma'; ...
    'semantic_priority_changes_fifo';'all_integrity_gates'};
passed=double([g1;g2;g3;g4;g5]);
detail={ ...
    'an oracle lowers mean RMSE and offered utilization with no extra failures'; ...
    'an oracle reduces failures without increasing mean offered utilization'; ...
    'no periodic TDMA arm Pareto-reproduces a boundary-qualified oracle'; ...
    sprintf('an oracle differs from FIFO in at least %.0f%% of comparable decisions', ...
    100*R.minimumPriorityDifferenceFraction); ...
    'all declared EXP19A integrity gates pass'};
gates=table(names,passed,detail, ...
    'VariableNames',{'gate','passed','detail'});
D=struct('oracle',oracle,'periodic',periodic,'gates',gates, ...
    'promote',all(passed==1));

end


function r=rowFor(S,scenario,arm)

idx=string(S.scenario)==string(scenario) & string(S.arm)==string(arm);
if nnz(idx)~=1
    error('evaluateExp19Promotion: row %s/%s is not unique.',scenario,arm);
end
r=S(idx,:);

end


function r=emptyOracle()

r=struct('arm','','boundaryRmseDifference',NaN, ...
    'boundaryOfferedDifference',NaN,'boundaryFailureDifference',NaN, ...
    'failureCellFailureDifference',NaN, ...
    'failureCellOfferedDifference',NaN,'boundaryParetoGate',NaN, ...
    'failureReductionGate',NaN,'priorityDiffersFifoFraction',NaN, ...
    'priorityActionGate',NaN);

end


function r=emptyPeriodic()

r=struct('oracleArm','','periodicArm','','rmseDifference',NaN, ...
    'offeredDifference',NaN,'failureDifference',NaN, ...
    'reproducesOracle',NaN);

end
