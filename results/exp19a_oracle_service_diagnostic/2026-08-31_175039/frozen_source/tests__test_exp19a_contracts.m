%% TEST_EXP19A_CONTRACTS Frozen registry and arm-semantics gates.

startup;
fprintf('\n============================================================\n');
fprintf('test_exp19a_contracts\n');
fprintf('============================================================\n\n');
checks=cell(0,2);
R=exp19aRegistry();

checks(end+1,:)={isequal(R.seeds,(16026001:16026030)') && ...
    numel(R.cells)==6 && numel(R.arms)==9 && R.expectedRuns==1620, ...
    'registry fixes 30 seeds, six contexts and nine arms'};
checks(end+1,:)={isequal({R.cells.macType}, ...
    {'aloha','aloha','csma','csma','aloha','aloha'}), ...
    'context access types match the mechanism-selected protocol'};
checks(end+1,:)={max(abs(R.periodicRatesHz- ...
    [6.25 1/0.12 10 12.5]))<1e-12 && ...
    ~R.confirmatory && ~R.manuscriptClaimPermitted && ...
    ~R.hardwarePolicyValidationPermitted, ...
    'periodic frontier and development-only claim boundary are frozen'};

base=applyExp19ACell('n5-moderate-bg0',16025999);
out=cell(numel(R.arms),1);
for k=1:numel(R.arms)
    [cfg,method,~,details]=applyExp19AArm(base,R.arms(k));
    out{k}=struct('cfg',cfg,'method',method,'details',details);
end
frame=out{strcmp({R.arms.id},'frame-piggyback')};
candidate=out{strcmp({R.arms.id},'capacity-gated-selector')};
tdma=out{strcmp({R.arms.id},'collision-free-tdma-piggyback')};
deficit=out{strcmp({R.arms.id}, ...
    'oracle-deficit-maxweight-piggyback')};
urgency=out{strcmp({R.arms.id}, ...
    'oracle-urgency-maxweight-piggyback')};

L=max(1,ceil((8*base.mac.dataBytes/base.mac.phyRateBps)/ ...
    base.mac.slotTime));
expectedP=1/(base.swarm.N*(2*L-1));
checks(end+1,:)={strcmp(frame.method,'causal-broadcast') && ...
    strcmp(frame.cfg.shared.feedbackMode,'piggyback') && ...
    abs(frame.cfg.mac.pAccess-expectedP)<1e-12 && ...
    strcmp(frame.details.schedulerMode,'native'), ...
    'frame-piggyback retains the strongest original-access baseline'};
checks(end+1,:)={strcmp(candidate.method,'context-aware-broadcast') && ...
    strcmp(candidate.details.route,'capacity-gated-selector') && ...
    strcmp(candidate.details.schedulerMode,'native'), ...
    'capacity-gated selector is retained only as a negative control'};
checks(end+1,:)={strcmp(tdma.cfg.mac.type,'tdma') && ...
    strcmp(tdma.cfg.shared.serviceScheduler.mode,'round-robin') && ...
    strcmp(tdma.cfg.shared.feedbackMode,'piggyback'), ...
    'collision-free reference changes service while retaining piggyback'};
checks(end+1,:)={deficit.cfg.shared.serviceScheduler.oracle && ...
    ~deficit.cfg.shared.serviceScheduler.receiverTruthOracle && ...
    urgency.cfg.shared.serviceScheduler.oracle && ...
    urgency.cfg.shared.serviceScheduler.receiverTruthOracle, ...
    'deficit and urgency oracle information contracts are distinct'};

periodic=ismember(string({R.arms.id}),string(R.periodicArms));
periodicOk=true;
for k=find(periodic)
    q=out{k};
    periodicOk=periodicOk && strcmp(q.method,'periodic') && ...
        strcmp(q.cfg.mac.type,'tdma') && ...
        strcmp(q.cfg.shared.feedbackMode,'none') && ...
        abs(1/q.cfg.net.commPeriod-R.arms(k).periodicRateHz)<1e-12;
end
checks(end+1,:)={periodicOk, ...
    'all four periodic TDMA frontier rates execute their exact contracts'};
checks(end+1,:)={isequal(fieldnames(exp19aEmptyRow()), ...
    fieldnames(exp19aEmptyRow())), ...
    'EXP19A tidy-row schema is stable'};

flags=cellfun(@logical,checks(:,1));
for k=1:size(checks,1)
    if flags(k), tag='ok'; else, tag='FAIL'; end
    fprintf('    %-4s %s\n',tag,checks{k,2});
end
if ~all(flags)
    error('test_exp19a_contracts: %d of %d checks failed.', ...
        nnz(~flags),numel(flags));
end
fprintf('\ntest_exp19a_contracts: PASS (%d checks)\n',numel(flags));
