function signature = sharedMediumChannelSignature(mac,N)
%SHAREDMEDIUMCHANNELSIGNATURE Hash the channel semantics attached to a trace.

modelId = double(strcmp(mac.lossModel,'gilbert-elliott'));
values = [modelId; double(mac.separateAckTrace); ...
    vectorMap(mac.dataResidualLoss,N); ...
    vectorMap(mac.ackResidualLoss,N); ...
    vectorMap(mac.burst.dataGoodLoss,N); ...
    vectorMap(mac.burst.dataBadLoss,N); ...
    vectorMap(mac.burst.dataGoodToBad,N); ...
    vectorMap(mac.burst.dataBadToGood,N); ...
    vectorMap(mac.burst.ackGoodLoss,N); ...
    vectorMap(mac.burst.ackBadLoss,N); ...
    vectorMap(mac.burst.ackGoodToBad,N); ...
    vectorMap(mac.burst.ackBadToGood,N)];
signature = realizationHash(values);

end


function y = vectorMap(x,N)

if isscalar(x)
    y = repmat(x,N,N);
else
    y = x;
end
y = y(:);

end
