function O=simulateSlottedManagementFlood( ...
    plan,linkUniform,erasureProbability,packetBytes,phyRateBps,guardSec)
%SIMULATESLOTTEDMANAGEMENTFLOOD Causal receive-before-forward replay.

% A planned relay transmits iff it possessed the packet at the start of its
% assigned slot. Link draws are read only for intended child links of active
% transmitters. The tree gives each node one parent and hence suppresses
% duplicate forwards by construction.

required={'N','source','directReach','physicalInterference', ...
    'children','transmitterSlot', ...
    'senderConflictGraph','recipientMask','reservedSlotCount', ...
    'plannedTransmitterCount','slotColoringProper','admissible','hashExact'};
if ~isstruct(plan)||~isscalar(plan)||~all(isfield(plan,required))|| ...
        ~plan.admissible||~plan.slotColoringProper
    error('simulateSlottedManagementFlood: admissible plan required.');
end
N=plan.N; U=double(linkUniform);
if ~isequal(size(U),[N N])||any(~isfinite(U),'all')|| ...
        any(U<0|U>1,'all')||~isscalar(erasureProbability)|| ...
        ~isfinite(erasureProbability)||erasureProbability<0|| ...
        erasureProbability>1||~isscalar(packetBytes)|| ...
        ~isfinite(packetBytes)||packetBytes<1||packetBytes~=floor(packetBytes)|| ...
        ~isscalar(phyRateBps)||~isfinite(phyRateBps)||phyRateBps<=0|| ...
        ~isscalar(guardSec)||~isfinite(guardSec)||guardSec<0
    error('simulateSlottedManagementFlood: invalid physical input.');
end

known=false(N,1); known(plan.source)=true;
transmitted=false(N,1); receivedSlot=nan(N,1); receivedSlot(plan.source)=0;
attempts=0; bytes=0; offeredAirtime=0; busySlots=0;
linkReads=0; collisionRecipients=0; successfulLinks=0; erasedLinks=0;
slotTx=false(plan.reservedSlotCount,N);
slotDelivery=false(plan.reservedSlotCount,N);
for slotIndex=1:plan.reservedSlotCount
    scheduled=find(plan.transmitterSlot==slotIndex);
    active=scheduled(known(scheduled));
    slotTx(slotIndex,active)=true;
    if isempty(active), continue; end
    busySlots=busySlots+1; attempts=attempts+numel(active);
    bytes=bytes+numel(active)*packetBytes;
    offeredAirtime=offeredAirtime+ ...
        numel(active)*8*packetBytes/phyRateBps;
    transmitted(active)=true;
    newKnown=false(N,1);
    for sender=reshape(active,1,[])
        children=find(plan.children(:,sender));
        for receiver=reshape(children,1,[])
            other=active(active~=sender);
            detectable=reshape(plan.physicalInterference( ...
                receiver,other)|plan.directReach(receiver,other),[],1);
            collision=any(other==receiver|detectable);
            if collision
                collisionRecipients=collisionRecipients+1;
                continue;
            end
            linkReads=linkReads+1;
            if U(receiver,sender)>erasureProbability
                newKnown(receiver)=true; successfulLinks=successfulLinks+1;
                if isnan(receivedSlot(receiver))
                    receivedSlot(receiver)=slotIndex;
                end
                slotDelivery(slotIndex,receiver)=true;
            else
                erasedLinks=erasedLinks+1;
            end
        end
    end
    known=known|newKnown;
end
delivery=known&plan.recipientMask;
packetAirtime=8*packetBytes/phyRateBps;
O=struct('version','SLOTTED-MANAGEMENT-FLOOD-REPLAY-v2', ...
    'planHash',plan.hashExact,'deliveryMask',delivery, ...
    'allRecipientsDelivered',double(all(known(plan.recipientMask))), ...
    'knownMask',known,'transmittedMask',transmitted, ...
    'receivedSlot',receivedSlot,'attempts',attempts,'bytes',bytes, ...
    'packetAirtimeSec',packetAirtime, ...
    'offeredAirtimeSec',offeredAirtime, ...
    'channelBusyAirtimeSec',busySlots*packetAirtime, ...
    'reservedDurationSec',plan.reservedSlotCount*(packetAirtime+guardSec), ...
    'busySlots',busySlots,'plannedAttemptBound', ...
    plan.plannedTransmitterCount,'attemptBoundSatisfied', ...
    double(attempts<=plan.plannedTransmitterCount), ...
    'successfulLinks',successfulLinks,'erasedLinks',erasedLinks, ...
    'collisionRecipients',collisionRecipients,'linkRandomReads',linkReads, ...
    'duplicateForwardCount',0,'futureRandomReads',0, ...
    'receiverTruthDecisionReads',0,'slotTransmissionMask',slotTx, ...
    'slotDeliveryMask',slotDelivery, ...
    'hashExact',realizationHash([plan.hashExact;U(:); ...
    erasureProbability;packetBytes;phyRateBps;guardSec;double(known); ...
    double(transmitted);replaceNaN(receivedSlot,-1);attempts;bytes; ...
    collisionRecipients;linkReads;double(slotTx(:)); ...
    double(slotDelivery(:))]));

end


function value=replaceNaN(value,replacement)
value(isnan(value))=replacement;
end
