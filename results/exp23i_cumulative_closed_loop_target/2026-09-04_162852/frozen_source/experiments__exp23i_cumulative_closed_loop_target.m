function exp23i_cumulative_closed_loop_target(resumeDir)
%EXP23I_CUMULATIVE_CLOSED_LOOP_TARGET Frozen failed-cell repair test.

if nargin<1, resumeDir=''; end
startup;
close all;
R=exp23iCumulativeClosedLoopRegistry();
[registryHash,registryLeaves]=configHash(R);
experimentName='exp23i_cumulative_closed_loop_target';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(experimentName, ...
        ['Fresh targeted closed-loop falsification of cumulative witness ' ...
        'receipts at the EXP23G N5/IID-15 failure cell.']);
    writeJson(fullfile(expRun.dir,'target_registry.json'),R);
    writeJson(fullfile(expRun.dir,'target_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'policyOptimizationAllowed',false, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=4;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runGroup(R.seeds(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  seeds %2d--%2d / %2d; rows %3d / %3d\n', ...
        index(1),index(end),numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T);
writetable(S,fullfile(expRun.dir,'summary.csv'));
D=periodicContrasts(T,R);
writetable(D,fullfile(expRun.dir,'periodic_contrasts.csv'));
E=redesignEffect(T,R);
writetable(E,fullfile(expRun.dir,'redesign_effect.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));

safetyNames=["candidate_safety" "candidate_terminal_liveness"];
safetyGate=ismember(string(gates.gate),safetyNames);
structuralPass=all(gates.passed(~safetyGate)==1);
safetyPass=all(gates.passed(safetyGate)==1);
mechanismPass=logical(E.mechanismReliefPassed(1));
cumulativeRow=D(string(D.candidateArm)==string(R.cumulativeArm),:);
epsilonKill=logical(cumulativeRow.epsilonDominates(1));
confidenceKill=logical(cumulativeRow.epsilonConfidenceSupported(1));
if ~structuralPass
    status='ELCS_W_CUMULATIVE_CLOSED_LOOP_STUDY_INVALID';
    next='repair_target_infrastructure';
elseif ~safetyPass
    status='ELCS_W_CUMULATIVE_CLOSED_LOOP_SAFETY_FAIL';
    next='redesign_cumulative_state_or_fallback';
elseif ~mechanismPass
    status='ELCS_W_CUMULATIVE_MECHANISM_RELIEF_INSUFFICIENT';
    next='return_to_protocol_design';
elseif epsilonKill
    status='ELCS_W_CUMULATIVE_STILL_EPSILON_DOMINATED';
    next='return_to_protocol_design';
else
    status='ELCS_W_CUMULATIVE_TARGET_SURVIVES';
    next='freeze_full_background_confirmation';
end
verdict=struct('status',status,'validationGatesPassed',sum(gates.passed), ...
    'validationGatesTotal',height(gates),'rows',height(T), ...
    'structuralIntegrityPassed',structuralPass, ...
    'candidateSafetyAndLivenessPassed',safetyPass, ...
    'mechanismReliefPassed',mechanismPass, ...
    'epsilonDominanceFound',epsilonKill, ...
    'confidenceSupportedEpsilonDominanceFound',confidenceKill, ...
    'next',next,'fullBackgroundConfirmationPermitted', ...
    structuralPass && safetyPass && mechanismPass && ~epsilonKill, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'target_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','D','E','gates', ...
    'verdict','R');

fprintf('\nEXP23I targeted cumulative closed-loop gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf(['\nEXP23I REDESIGN: management %.2f%%; retry %.2f%%; ' ...
    'RMSE %.2f%%\n'],100*E.relativeManagementDelta, ...
    100*E.relativeRetryDelta,100*E.relativeRmseDelta);
fprintf('EXP23I PERIODIC vs CUMULATIVE: RMSE %.2f%%; cost %.2f%%\n', ...
    100*cumulativeRow.relativePeriodicRmse, ...
    100*cumulativeRow.relativePeriodicCost);
fprintf('EXP23I DECISION: %s\n',status);
finishExperiment(expRun);
if ~structuralPass
    error('exp23i: targeted closed-loop study structurally invalid.');
end

end


function rows=runGroup(seedValue,R)

c=R.cells(1);
condition=R.conditions(1);
base=applyExp21dClosedLoopCell(c.id,seedValue);
base.mac.backgroundLoad=condition.targetLoad;
base.mac=sharedMediumConfig(base);
trace=generateSharedMediumTrace(base);
N=base.swarm.N;
CR=exp23cWitnessClosedLoopRegistry();
clockArm=CR.arms(strcmp({CR.arms.id},CR.clockArm));
offset=(2*reshape(trace.exp21cClockOffsetU(1,:),[],1)-1)* ...
    R.maxOffsetSec;
drift=(2*reshape(trace.exp21cClockDriftU,[],1)-1)*R.maxDriftPpm;
clockSpec=struct('clockOffsetSec',offset,'clockDriftPpm',drift, ...
    'leadTimeSec',R.clockLeadTimeSec);

rows=repmat(exp23fWitnessBackgroundEmptyRow(),numel(R.arms),1);
for k=1:numel(R.arms)
    arm=R.arms(k);
    if strcmp(arm.family,'periodic-static')
        rate=c.lowerCostRateHz;
        localArm=struct('id',arm.id,'label',arm.label, ...
            'family','periodic-static','periodicRateHz',rate);
        [cfg,method,label,details]=applyExp22fStaticArm(base,localArm,R);
    else
        C=elcsWitnessKernelConfig(N,R.elcsMaxFrames);
        C.guardSec=R.missionSafeGuardSec;
        C.dataBytes=base.mac.dataBytes;
        C.phyRateBps=base.mac.phyRateBps;
        C.neighborGraph=logical(base.swarm.A);
        C.managementReach=C.neighborGraph;
        C.interferenceMatrix=logical(base.mac.interferenceMatrix);
        C.conflictGraph=buildSenderConflictGraph( ...
            C.neighborGraph,C.interferenceMatrix);
        C.cumulativeReceiptRetry=logical(arm.cumulativeReceiptRetry);
        elcsTrace=generateElcsWitnessTrace(seedValue,C);
        [elcsTrace,backgroundCertificate]= ...
            applySharedBackgroundToElcsWitnessTrace( ...
            elcsTrace,C,trace,clockSpec,condition.targetLoad);
        nativeQ=buildElcsWitnessContinuousSchedule(C,elcsTrace,base.swarm.T);
        nativeQ.backgroundOverlay=backgroundCertificate;
        nativeQ.hashExact=realizationHash([ ...
            nativeQ.hashExact;backgroundCertificate.hashExact]);
        [cfg,method,~,details]=applyExp23cWitnessClockArm( ...
            base,clockArm,nativeQ,trace,CR);
        label=arm.label;
        details.kind='candidate-elcs-w';
        details.retryMode=ternary(C.cumulativeReceiptRetry, ...
            'cumulative-same-sequence','same-frame-new-sequence');
        rate=50;
    end
    meta=struct('stage',R.stage,'scenario',c.id, ...
        'scenarioLabel',c.label,'family','EXP23I targeted repair', ...
        'arm',arm.id,'pointIndex',k,'parameterValue',rate);
    rows(k)=runExp23fWitnessBackgroundCell( ...
        cfg,method,label,meta,trace,details,arm.family,condition);
end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.scenario)+'|'+ ...
    string(T.loadCondition)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isscalar(unique(string(T.scenario))) && ...
    strcmp(unique(string(T.loadCondition)),string(R.conditions.id)) && ...
    isequal(sort(unique(string(T.arm))), ...
    sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '60 seeds, one failed cell and three paired arms exact');

paired=true;
for seed=R.seeds'
    index=T.seed==seed;
    fraction=T.REALIZED_BACKGROUND_FRACTION(index);
    busy=T.BACKGROUND_BUSY_TIME(index);
    paired=paired && nnz(index)==numel(R.arms) && ...
        isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
        isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
        isscalar(unique(T.BACKGROUND_RANDOM_FIELD_HASH_EXACT(index))) && ...
        max(fraction)-min(fraction)<=R.realizedFractionPairTolerance && ...
        max(busy)-min(busy)<=1e-9;
end
add('paired_absolute_realizations',paired, ...
    'channel, estimator, clock and occupied busy time pair by seed');

candidate=string(T.ENGINE_FAMILY)=="candidate-elcs-w";
legacy=string(T.arm)==string(R.legacyArm);
cumulative=string(T.arm)==string(R.cumulativeArm);
periodic=string(T.arm)==string(R.periodicArm);
candidatePair=true;
for seed=R.seeds'
    index=T.seed==seed & candidate;
    candidatePair=candidatePair && nnz(index)==2 && ...
        isscalar(unique(T.ELCSW_KERNEL_TRACE_HASH_EXACT(index))) && ...
        isscalar(unique(T.ELCSW_BACKGROUND_TRACE_HASH_EXACT(index)));
end
add('candidate_trace_overlay_pairing',candidatePair, ...
    'legacy and cumulative kernels receive identical absolute draws');
add('retry_mode_declaration_exact',all( ...
    T.ELCSW_CUMULATIVE_RECEIPT_RETRY(legacy)==0) && all( ...
    T.ELCSW_CUMULATIVE_RECEIPT_RETRY(cumulative)==1), ...
    'only the cumulative arm retains same-sequence receipts');
add('periodic_boundary_and_timing',all(abs( ...
    T.PERIODIC_RATE_HZ(periodic)-R.cells.lowerCostRateHz)<1e-12) && ...
    all(T.ENDOGENOUS_COLLISION_FRAMES(periodic)==0) && all( ...
    T.CONTINUOUS_MAX_CLOCK_RESIDUAL(periodic)<=2e-12), ...
    'EXP23D lower-cost boundary remains continuously guarded');
certificate=all(T.ELCSW_BACKGROUND_OVERLAY_APPLIED(candidate)==1) && ...
    all(T.ELCSW_BACKGROUND_TRACE_HASH_EXACT(candidate)== ...
    T.TRACE_HASH_EXACT(candidate)) && all(abs( ...
    T.ELCSW_BACKGROUND_LOAD(candidate)-0.15)<=1e-12);
add('candidate_background_certificate',certificate, ...
    'both ELCS-W arms compose the declared shared occupancy trace');
add('background_stimulus_activation',all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS(candidate)>0) && all( ...
    T.BACKGROUND_BUSY_TIME>0), ...
    'IID-15 occupancy intersects potential ELCS-W transmissions');
add('one_hop_witness_cover',all( ...
    T.ELCSW_ALL_EDGES_COVERED(candidate)==1) && all( ...
    T.ELCSW_HIDDEN_CONFLICT_EDGES(candidate)>0) && all( ...
    T.ELCSW_MAX_WITNESS_LOAD(candidate)<=10), ...
    'hidden conflicts retain bounded one-hop witnesses');
add('absolute_control_bounds',all( ...
    T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)<=1+1e-12) && all( ...
    T.ELCSW_BYTE_BOUND_RATIO(candidate)<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)), ...
    max(T.ELCSW_BYTE_BOUND_RATIO(candidate))));
replay=all(T.ELCSW_DATA_SKIPPED_NO_QUEUE(candidate)==0) && ...
    all(T.ELCSW_DATA_OUTCOME_MISMATCHES(candidate)==0) && ...
    all(T.ELCSW_DATA_COLLISION_WITNESS_MATCH(candidate)==1) && ...
    all(T.ELCSW_CROSS_PLANE_OVERLAPS(candidate)==0) && ...
    all(T.ELCSW_CLOCK_TIMING_CONFLICT_FREE(candidate)==1);
add('exact_elcs_w_replay',replay, ...
    'queue, outcome, clock and control/DATA contracts close');
management=all(T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE(candidate)==1) && ...
    all(T.ELCSW_MANAGEMENT_ATTEMPTS(candidate)== ...
    T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS(candidate)) && all(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME(candidate))<=1e-12) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
    T.ELCSW_CONTROL_BYTES_AIRTIME(candidate))<=1e-12);
add('variable_payload_management_accounting',management, ...
    'attempt, recipient, byte and airtime accounting close exactly');
add('candidate_safety',all( ...
    T.ELCSW_FALSE_VALID_EDGE_FRAMES(candidate)==0) && all( ...
    T.ELCSW_SCHEDULED_COLLISION_FRAMES(candidate)==0) && all( ...
    T.ELCSW_CERTIFICATE_WITHOUT_FRESH_CLAIMS(candidate)==0) && all( ...
    T.SAFEFAIL(candidate)==0) && all(T.DIVERGED(candidate)==0), ...
    'zero certificate, collision, safety and divergence failures');
add('candidate_terminal_liveness',all( ...
    T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED(candidate)==1) && all( ...
    T.ELCSW_FINAL_OPEN_CLAIM_TRANSACTIONS(cumulative)==0), ...
    'both ELCS-W modes certify; cumulative transactions close');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
account=all(abs(T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && all( ...
    T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && all( ...
    T.CHANNEL_UTIL<=T.TOTAL_OFFERED_UTIL+ ...
    T.REALIZED_BACKGROUND_FRACTION+1e-9);
add('recipient_airtime_and_busy_union',account, ...
    'offered airtime, recipient partitions and busy union close');
add('causal_and_protocol_invariants',all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && all(T.INVARIANT_VIOLATIONS==0), ...
    'zero future/random truth reads and invariant violations');
retained=all(ismember(T.SAFEFAIL,[0 1])) && ...
    all(T.SAFEFAIL>=T.DIVERGED) && all(ismember( ...
    T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED(candidate),[0 1]));
add('all_failures_retained',retained, ...
    'unsafe, divergent and terminal-uncertified outcomes remain visible');
add('target_scope_only',~R.policyOptimizationAllowed && ...
    ~R.broadRobustnessClaimPermitted && ~R.newMethodPromotionAllowed && ...
    ~R.submissionClaimPermitted, ...
    'no tuning, broad robustness, promotion or submission decision');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredIntegrityContracts
    error('exp23i: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function D=periodicContrasts(T,R)

P=selectRows(T,R.periodicArm);
arms={R.legacyArm,R.cumulativeArm};
rows=cell(numel(arms),20);
for k=1:numel(arms)
    C=selectRows(T,arms{k});
    rmse=pairedBootstrapCI(P.RMSE,C.RMSE,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+2*k,numel(R.seeds));
    cost=pairedBootstrapCI(P.TOTAL_OFFERED_UTIL, ...
        C.TOTAL_OFFERED_UTIL,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+2*k+1,numel(R.seeds));
    cr=mean(C.RMSE); pr=mean(P.RMSE);
    cc=mean(C.TOTAL_OFFERED_UTIL); pc=mean(P.TOTAL_OFFERED_UTIL);
    epsilon=pr<=(1+R.epsilonRmse)*cr && ...
        pc<=(1-R.requiredCostImprovement)*cc;
    confidence=rmse.hi<=R.epsilonRmse*cr && ...
        cost.hi<=-R.requiredCostImprovement*cc;
    rows(k,:)={string(arms{k}),height(C),cr,pr,cc,pc, ...
        pr/cr-1,pc/cc-1,rmse.meanD,rmse.lo,rmse.hi, ...
        cost.meanD,cost.lo,cost.hi, ...
        mean(C.ELCSW_MANAGEMENT_AIRTIME), ...
        mean(C.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS), ...
        mean(C.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED), ...
        sum(C.SAFEFAIL),double(epsilon),double(confidence)};
end
D=cell2table(rows,'VariableNames',{'candidateArm','nPairs', ...
    'candidateMeanRMSE','periodicMeanRMSE','candidateMeanCost', ...
    'periodicMeanCost','relativePeriodicRmse','relativePeriodicCost', ...
    'rmseDelta','rmseCiLo','rmseCiHi','costDelta','costCiLo', ...
    'costCiHi','candidateMeanManagementAirtime', ...
    'candidateMeanRetryClaims','terminalCertificationRate', ...
    'candidateSafeFailures','epsilonDominates', ...
    'epsilonConfidenceSupported'});

end


function E=redesignEffect(T,R)

C=selectRows(T,R.cumulativeArm);
L=selectRows(T,R.legacyArm);
mgmt=pairedBootstrapCI(C.ELCSW_MANAGEMENT_AIRTIME, ...
    L.ELCSW_MANAGEMENT_AIRTIME,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+20,numel(R.seeds));
retry=pairedBootstrapCI(C.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS, ...
    L.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+21,numel(R.seeds));
cost=pairedBootstrapCI(C.TOTAL_OFFERED_UTIL, ...
    L.TOTAL_OFFERED_UTIL,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+22,numel(R.seeds));
rmse=pairedBootstrapCI(C.RMSE,L.RMSE,R.bootstrapReplicates, ...
    R.bootstrapSeedBase+23,numel(R.seeds));
relativeManagement=mean(C.ELCSW_MANAGEMENT_AIRTIME)/ ...
    mean(L.ELCSW_MANAGEMENT_AIRTIME)-1;
mechanism=relativeManagement<=-R.requiredManagementReduction && ...
    mgmt.hi<0;
E=table(numel(R.seeds),mean(L.ELCSW_MANAGEMENT_AIRTIME), ...
    mean(C.ELCSW_MANAGEMENT_AIRTIME),relativeManagement, ...
    mgmt.meanD,mgmt.lo,mgmt.hi, ...
    mean(L.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS), ...
    mean(C.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS), ...
    mean(C.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS)/ ...
    mean(L.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS)-1, ...
    retry.meanD,retry.lo,retry.hi,mean(L.TOTAL_OFFERED_UTIL), ...
    mean(C.TOTAL_OFFERED_UTIL), ...
    mean(C.TOTAL_OFFERED_UTIL)/mean(L.TOTAL_OFFERED_UTIL)-1, ...
    cost.meanD,cost.lo,cost.hi,mean(L.RMSE),mean(C.RMSE), ...
    mean(C.RMSE)/mean(L.RMSE)-1,rmse.meanD,rmse.lo,rmse.hi, ...
    double(mechanism),'VariableNames',{'nPairs', ...
    'legacyMeanManagementAirtime','cumulativeMeanManagementAirtime', ...
    'relativeManagementDelta','managementDelta','managementCiLo', ...
    'managementCiHi','legacyMeanRetryClaims','cumulativeMeanRetryClaims', ...
    'relativeRetryDelta','retryDelta','retryCiLo','retryCiHi', ...
    'legacyMeanCost','cumulativeMeanCost','relativeCostDelta', ...
    'costDelta','costCiLo','costCiHi','legacyMeanRMSE', ...
    'cumulativeMeanRMSE','relativeRmseDelta','rmseDelta','rmseCiLo', ...
    'rmseCiHi','mechanismReliefPassed'});

end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'scenario','scenarioLabel','loadCondition', ...
    'loadConditionLabel','arm','methodLabel','ENGINE_FAMILY'}));
S.nRuns=splitapply(@numel,T.RMSE,group);
S.meanRealizedBackgroundFraction=splitapply( ...
    @mean,T.REALIZED_BACKGROUND_FRACTION,group);
S.meanRMSE=splitapply(@mean,T.RMSE,group);
S.meanTrueAoI=splitapply(@mean,T.MEAN_TRUE_AOI,group);
S.meanTotalOfferedUtil=splitapply(@mean,T.TOTAL_OFFERED_UTIL,group);
S.meanChannelUtil=splitapply(@mean,T.CHANNEL_UTIL,group);
S.meanGoodputHz=splitapply(@mean,T.DATA_GOODPUT_HZ,group);
S.meanManagementAirtime=splitapply( ...
    @finiteMean,T.ELCSW_MANAGEMENT_AIRTIME,group);
S.meanPhysicalRetryClaims=splitapply( ...
    @finiteMean,T.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS,group);
S.physicalTerminalCertificationRate=splitapply( ...
    @finiteMean,T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);

end


function T=selectRows(T,arm)
T=T(string(T.arm)==string(arm),:);
T=sortrows(T,'seed');
end


function y=finiteMean(x)
x=x(isfinite(x));
if isempty(x), y=NaN; else, y=mean(x); end
end


function [rows,completed]=loadCheckpoint(runDir,R)

completed=false(size(R.seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23fWitnessBackgroundEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string');
rows=table2struct(T);
for q=1:numel(R.seeds)
    index=T.seed==R.seeds(q);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23i: partial checkpoint seed group.'); end
end

end


