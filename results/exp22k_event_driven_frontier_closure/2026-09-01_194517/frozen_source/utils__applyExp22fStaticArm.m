function [cfg,method,label,details]=applyExp22fStaticArm(base,arm,R)
%APPLYEXP22FSTATICARM Full-mission guarded static-TDMA frontier arm.

if nargin<3 || isempty(R), R=exp22fFeasibilityRegistry(); end
if ~strcmp(arm.family,'periodic-static') || ...
        ~any(strcmp({R.arms.id},char(arm.id)))
    error('applyExp22fStaticArm: arm is not a registered periodic point.');
end
cfg=base;
method='periodic';
label=char(arm.label);
cfg.net.commPeriod=1/arm.periodicRateHz;
cfg.mac.type='tdma';
cfg.mac.pAccess=1;
cfg.mac.maxRetries=0;
cfg.shared.feedbackMode='none';
cfg.shared.serviceScheduler=struct( ...
    'mode','continuous-local-static-tdma','logDecisions',true, ...
    'tieBreak','fifo-node','reservationFrameSlots',cfg.swarm.N, ...
    'clockOffsetMaxSec',R.maxOffsetSec, ...
    'clockDriftMaxPpm',R.maxDriftPpm, ...
    'continuousGuardTime',R.missionSafeGuardSec, ...
    'continuousSyncPeriod',inf, ...
    'continuousEpochLeadTime',R.clockLeadTimeSec, ...
    'continuousExactAirtime',true);
cfg.mac=sharedMediumConfig(cfg);
cfg.shared.serviceScheduler=serviceSchedulerConfig(cfg);
cfg.exp20a.originalMacType='tdma';
cfg.exp22f=struct('version',R.version,'arm',char(arm.id), ...
    'family',char(arm.family),'submissionClaimPermitted',false);
details=struct('kind','periodic-frontier','route','none', ...
    'ackDesign','none','accessDesign','full-mission-static-tdma', ...
    'schedulerMode','continuous-local-static-tdma', ...
    'periodicRateHz',arm.periodicRateHz, ...
    'distributedFlag',0,'idealFlag',0);

end
