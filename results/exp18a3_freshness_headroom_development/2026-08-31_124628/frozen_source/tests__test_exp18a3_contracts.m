%% TEST_EXP18A3_CONTRACTS Freshness-headroom amendment checks.

startup;

fprintf('\n============================================================\n');
fprintf('test_exp18a3_contracts\n');
fprintf('============================================================\n\n');

checks=cell(0,2);
R=exp18a3Registry();
checks(end+1,:)={R.expectedRuns==400 && ~R.confirmatory && ...
    R.maxJointlyWorseFeasibleCells==1 && ...
    R.requireExactCsmaPiggybackAlias && ...
    R.requireFeasibleAlohaAckActivity, ...
    'v3 keeps 400 development rows and registers stricter route gates'};

base=applyExp18Cell('n5-moderate-bg0',R.seeds(1));
base.mac.type='aloha'; base.mac.pAccess=1/base.swarm.N;
[cfg,method,label,details,cert]=applyExp18A3Arm(base);
checks(end+1,:)={cert.feasible && ...
    cfg.shared.contextAware.freshnessHeadroomEnabled && ...
    strcmp(details.route,'context-aware-v3') && ...
    strcmp(method,'context-aware-broadcast'), ...
    'v3 enables headroom only after capacity feasibility'};

base.swarm.T=0.8; base.shared.evalStart=0; base.sixdof.enable=false;
trace=generateSharedMediumTrace(base);
[cfg,method,label,details,cert]=applyExp18A3Arm(base);
meta=struct('stage','development-amendment-3', ...
    'scenario','n5-moderate-bg0','scenarioLabel','N5 Moderate bg0', ...
    'family','EXP18A3 test','arm',R.arm.id,'pointIndex',1, ...
    'parameterValue',0,'role','core','channel','moderate', ...
    'modifier','nominal','basePAccess',1/5);
row=runExp18A3Cell(cfg,method,label,meta,trace,details,cert);
checks(end+1,:)={row.freshnessHeadroomEnabled==1 && ...
    isequal(fieldnames(row),fieldnames(exp18a3EmptyRow())) && ...
    row.CONTEXT_ACK_EVALUATED==row.CONTEXT_ACK_PERMITTED+ ...
    row.CONTEXT_ACK_BLOCKED_FEASIBILITY+row.CONTEXT_ACK_BLOCKED_VALUE, ...
    'v3 trajectory closes decision accounting and exact row schema'};

flags=cellfun(@logical,checks(:,1));
for k=1:size(checks,1)
    if flags(k), tag='ok'; else, tag='FAIL'; end
    fprintf('    %-4s %s\n',tag,checks{k,2});
end
if ~all(flags)
    error('test_exp18a3_contracts: %d of %d checks failed.', ...
        nnz(~flags),numel(flags));
end
fprintf('\ntest_exp18a3_contracts: PASS (%d checks)\n',numel(flags));
