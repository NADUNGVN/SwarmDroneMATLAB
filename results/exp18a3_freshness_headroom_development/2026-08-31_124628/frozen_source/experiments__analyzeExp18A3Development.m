function analysis=analyzeExp18A3Development(runDir)
%ANALYZEEXP18A3DEVELOPMENT Evaluate freshness-headroom route contracts.

R=exp18a3Registry();
T=readtable(fullfile(runDir,'tidy.csv'),'TextType','string');
reference=readtable(fullfile(R.referenceRun,'tidy.csv'),'TextType','string');
rows=repmat(emptyComparison(),0,1);

for c=R.cells
    for m=1:numel(R.macTypes)
        mac=string(R.macTypes{m});
        Q=T(T.scenario==string(c.id) & T.macType==mac,:);
        C=aggregate(Q);
        LQ=reference(reference.scenario==string(c.id) & ...
            reference.macType==mac & reference.arm=="legacy-selector",:);
        PQ=reference(reference.scenario==string(c.id) & ...
            reference.macType==mac & reference.arm=="frame-piggyback",:);
        AQ=reference(reference.scenario==string(c.id) & ...
            reference.macType==mac & reference.arm=="frame-adaptive",:);
        L=aggregate(LQ); P=aggregate(PQ); A=aggregate(AQ);
        row=emptyComparison();
        row.context=c.id; row.role=c.role; row.N=c.N;
        row.macType=char(mac); row.serviceFeasible=Q.serviceCertificateFeasible(1);
        row.serviceRatio=Q.serviceRatio(1);
        row.candidateRMSE=C.rmse; row.candidateOffered=C.offered;
        row.deltaRmseVsPiggy=C.rmse-P.rmse;
        row.deltaOfferedVsPiggy=C.offered-P.offered;
        row.deltaRmseVsAdaptive=C.rmse-A.rmse;
        row.deltaOfferedVsAdaptive=C.offered-A.offered;
        row.candidateFailures=C.failures; row.piggyFailures=P.failures;
        row.adaptiveFailures=A.failures; row.legacyFailures=L.failures;
        row.failureNonincrease=C.failures<=P.failures && ...
            C.failures<=A.failures;
        row.jointlyWorseBoth=C.rmse>max(P.rmse,A.rmse) && ...
            C.offered>max(P.offered,A.offered);
        row.collisionFrameReductionVsLegacy= ...
            (L.collisionFrames-C.collisionFrames)/ ...
            max(abs(L.collisionFrames),eps);
        row.meanStandaloneAck=C.standalone;
        row.valueBlocks=C.valueBlocks;
        row.feasibilityBlocks=C.feasibilityBlocks;
        row.maxPiggyAliasDifference=aliasDifference(Q,PQ);
        rows(end+1,1)=row; %#ok<AGROW>
    end
end

C=struct2table(rows);
writetable(C,fullfile(runDir,'development_comparisons.csv'));
core=C(string(C.role)=="core",:);
feasible=core(core.serviceFeasible==1,:);
infeasible=C(C.serviceFeasible==0,:);
coverage=height(feasible)>=R.minimumFeasibleCoreMacCells && ...
    numel(unique(feasible.N))==2 && ...
    numel(unique(string(feasible.macType)))==2;
failureNonincrease=all(feasible.failureNonincrease==1);
jointlyWorseCount=sum(feasible.jointlyWorseBoth);
notJointlyWorse=jointlyWorseCount<=R.maxJointlyWorseFeasibleCells;
abstentionExact=all(infeasible.meanStandaloneAck==0);
csma=feasible(string(feasible.macType)=="csma",:);
csmaAlias=height(csma)>=1 && all(csma.meanStandaloneAck==0) && ...
    all(csma.maxPiggyAliasDifference==0);
aloha=feasible(string(feasible.macType)=="aloha",:);
alohaActive=height(aloha)>=1 && all(aloha.meanStandaloneAck>0) && ...
    all(aloha.failureNonincrease==1) && all(aloha.jointlyWorseBoth==0);
n10Aloha=core(core.N==10 & string(core.macType)=="aloha",:);
collisionRepair=height(n10Aloha)==4 && ...
    all(n10Aloha.collisionFrameReductionVsLegacy>= ...
    R.minimumCollisionFrameReduction-1e-12);
reverse=T(contains(T.scenario,"reverse"),:);
mismatch=~isempty(reverse) && ...
    all(reverse.calibrationSource=="nominal-moderate-mismatch");

gateNames={'feasible_coverage','feasible_failure_nonincrease', ...
    'feasible_not_jointly_worse','infeasible_exact_abstention', ...
    'feasible_csma_exact_piggyback_alias','feasible_aloha_active_quality', ...
    'n10_aloha_collision_frame_repair','reverse_mismatch_reported'}';
gatePassed=double([coverage;failureNonincrease;notJointlyWorse; ...
    abstentionExact;csmaAlias;alohaActive;collisionRepair;mismatch]);
gateDetail={ ...
    sprintf('%d feasible core cells with both N and access types',height(feasible)); ...
    'feasible candidate failures do not exceed either fixed route'; ...
    sprintf('%d jointly-worse feasible cells (maximum %d)', ...
        jointlyWorseCount,R.maxJointlyWorseFeasibleCells); ...
    sprintf('%d infeasible context--MAC cells emit zero standalone ACKs', ...
        height(infeasible)); ...
    sprintf('%d feasible CSMA cells emit zero ACK and alias piggyback exactly', ...
        height(csma)); ...
    sprintf('%d feasible ALOHA cells retain ACK activity without joint loss', ...
        height(aloha)); ...
    sprintf('N10 ALOHA absolute collisions reduce by >= %.0f%%', ...
        100*R.minimumCollisionFrameReduction); ...
    'reverse boundary retains nominal ACK calibration mismatch'};
gates=table(gateNames,gatePassed,gateDetail, ...
    'VariableNames',{'gate','passed','detail'});
writetable(gates,fullfile(runDir,'development_decision_gates.csv'));

promote=all(gatePassed==1);
verdict=struct('status',ternary(promote, ...
    'CANDIDATE_READY_FOR_FRESH_SEED_PREREGISTRATION', ...
    'REJECT_OR_REVISE_FRESHNESS_HEADROOM'), ...
    'developmentOnly',true,'confirmatoryClaimPermitted',false, ...
    'gatesPassed',sum(gatePassed),'gatesTotal',numel(gatePassed), ...
    'feasibleCoreMacCells',height(feasible), ...
    'futureHoldoutOpened',false,'hardwareClaimPermitted',false);
writeJson(fullfile(runDir,'development_verdict.json'),verdict);
analysis=struct('comparisons',C,'gates',gates,'verdict',verdict);

end


function a=aggregate(Q)

if isempty(Q), error('analyzeExp18A3Development: missing comparison rows.'); end
a=struct('rmse',mean(Q.RMSE),'offered',mean(Q.OFFERED_UTIL), ...
    'failures',sum(Q.SAFEFAIL),'collisionFrames',mean(Q.COLLISION_FRAMES), ...
    'standalone',mean(Q.ACK_STANDALONE), ...
    'valueBlocks',sum(Q.CONTEXT_ACK_BLOCKED_VALUE), ...
    'feasibilityBlocks',sum(Q.CONTEXT_ACK_BLOCKED_FEASIBILITY));

end


function d=aliasDifference(A,B)

fields={'RMSE','MINSEP','SAFEFAIL','DIVERGED','CONTROL_EFFORT', ...
    'MEAN_TRUE_AOI','MEAN_EST_AOI','DATA_GENERATED','DATA_ATTEMPTED', ...
    'DATA_RECIPIENT_SUCCESS','COLLISION_FRAMES','QUEUE_DROPS', ...
    'OFFERED_UTIL','DATA_AIRTIME','ACK_AIRTIME','ACK_STANDALONE', ...
    'RECIPIENT_GOODPUT_HZ'};
[~,ia]=sort(A.seed); A=A(ia,:);
[~,ib]=sort(B.seed); B=B(ib,:);
if height(A)~=height(B) || any(A.seed~=B.seed)
    d=inf;
    return;
end
d=0;
for k=1:numel(fields)
    d=max(d,max(abs(A.(fields{k})-B.(fields{k}))));
end

end


function r=emptyComparison()

r=struct('context','','role','','N',NaN,'macType','', ...
    'serviceFeasible',NaN,'serviceRatio',NaN, ...
    'candidateRMSE',NaN,'candidateOffered',NaN, ...
    'deltaRmseVsPiggy',NaN,'deltaOfferedVsPiggy',NaN, ...
    'deltaRmseVsAdaptive',NaN,'deltaOfferedVsAdaptive',NaN, ...
    'candidateFailures',NaN,'piggyFailures',NaN, ...
    'adaptiveFailures',NaN,'legacyFailures',NaN, ...
    'failureNonincrease',false,'jointlyWorseBoth',false, ...
    'collisionFrameReductionVsLegacy',NaN,'meanStandaloneAck',NaN, ...
    'valueBlocks',NaN,'feasibilityBlocks',NaN, ...
    'maxPiggyAliasDifference',NaN);

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('analyzeExp18A3Development: cannot write %s.',path); end
cleaner=onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));

end


function y=ternary(flag,a,b)

if flag, y=a; else, y=b; end

end
