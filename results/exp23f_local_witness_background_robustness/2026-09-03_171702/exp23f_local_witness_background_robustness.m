function exp23f_local_witness_background_robustness(resumeDir)
%EXP23F_LOCAL_WITNESS_BACKGROUND_ROBUSTNESS Frozen occupancy/burst screen.

if nargin<1, resumeDir=''; end
startup;
close all;
R=exp23fWitnessBackgroundRobustnessRegistry();
[registryHash,registryLeaves]=configHash(R);
experimentName='exp23f_local_witness_background_robustness';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(experimentName, ...
        ['ELCS-W versus periodic under shared IID and Markov-bursty ' ...
        'exogenous channel occupancy.']);
    writeJson(fullfile(expRun.dir,'background_registry.json'),R);
    writeJson(fullfile(expRun.dir,'background_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'policyOptimizationAllowed',false, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
[seeds,cells,conditions]=groups(R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=4;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runGroup(seeds(index(q)),cells(index(q)), ...
            conditions(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  groups %3d--%3d / %3d; rows %3d / %3d\n', ...
        index(1),index(end),numel(seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T);
writetable(S,fullfile(expRun.dir,'summary.csv'));
D=robustnessTable(T,R);
writetable(D,fullfile(expRun.dir,'background_contrasts.csv'));
gates=integrityGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'integrity_gates.csv'));
integrityPass=all(gates.passed==1);
safetyFailure=any(D.physicalTerminalCertificationRate<1) || ...
    any(D.falseValidEdgeFrames>0) || any(D.scheduledCollisionFrames>0) || ...
    any(D.candidateSafeFailures>0) || any(D.candidateDivergences>0);
epsilonKill=any(D.epsilonDominates==1);
confidenceKill=any(D.epsilonConfidenceSupported==1);
if ~integrityPass
    status='ELCS_W_BACKGROUND_ROBUSTNESS_STUDY_INVALID';
    next='repair_background_composition';
elseif safetyFailure
    status='ELCS_W_BACKGROUND_ROBUSTNESS_SAFETY_FAIL';
    next='redesign_retry_or_fallback';
elseif epsilonKill
    status='ELCS_W_BACKGROUND_EPSILON_DOMINATED_RETURN_TO_DESIGN';
    next='redesign_load_response_or_overhead';
else
    status='ELCS_W_BACKGROUND_ROBUSTNESS_SCREEN_SURVIVES';
    next='bursty_link_loss_and_topology_dynamics';
end
verdict=struct('status',status, ...
    'integrityGatesPassed',sum(gates.passed), ...
    'integrityGatesTotal',height(gates),'rows',height(T), ...
    'terminalOrSafetyFailureFound',safetyFailure, ...
    'epsilonDominanceFound',epsilonKill, ...
    'confidenceSupportedEpsilonDominanceFound',confidenceKill, ...
    'next',next,'nextRobustnessContinuationPermitted', ...
    integrityPass && ~safetyFailure && ~epsilonKill, ...
    'newMethodPromotionAllowed',false,'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'background_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','D','gates','verdict','R');

fprintf('\nEXP23F background-load robustness integrity gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23F DECISION: %s\n',status);
finishExperiment(expRun);
if ~integrityPass, error('exp23f: background robustness invalid.'); end

end


function rows=runGroup(seedValue,cellIndex,conditionIndex,R)

c=R.cells(cellIndex);
condition=R.conditions(conditionIndex);
base=applyExp21dClosedLoopCell(c.id,seedValue);
base.mac.backgroundLoad=condition.targetLoad;
base.mac=sharedMediumConfig(base);
trace=generateSharedMediumTrace(base);
if strcmp(condition.model,'markov')
    trace=applyMarkovBackgroundStateTrace( ...
        trace,condition.offToOn,condition.onToOff);
end
N=base.swarm.N;
C=elcsWitnessKernelConfig(N,R.elcsMaxFrames);
C.guardSec=R.missionSafeGuardSec;
C.dataBytes=base.mac.dataBytes;
C.phyRateBps=base.mac.phyRateBps;
C.neighborGraph=logical(base.swarm.A);
C.managementReach=C.neighborGraph;
C.interferenceMatrix=logical(base.mac.interferenceMatrix);
C.conflictGraph=buildSenderConflictGraph( ...
    C.neighborGraph,C.interferenceMatrix);
elcsTrace=generateElcsWitnessTrace(seedValue,C);
offset=(2*reshape(trace.exp21cClockOffsetU(1,:),[],1)-1)* ...
    R.maxOffsetSec;
drift=(2*reshape(trace.exp21cClockDriftU,[],1)-1)*R.maxDriftPpm;
clockSpec=struct('clockOffsetSec',offset,'clockDriftPpm',drift, ...
    'leadTimeSec',R.clockLeadTimeSec);
[elcsTrace,backgroundCertificate]= ...
    applySharedBackgroundToElcsWitnessTrace( ...
    elcsTrace,C,trace,clockSpec,condition.targetLoad);
nativeQ=buildElcsWitnessContinuousSchedule(C,elcsTrace,base.swarm.T);
nativeQ.backgroundOverlay=backgroundCertificate;
nativeQ.hashExact=realizationHash([ ...
    nativeQ.hashExact;backgroundCertificate.hashExact]);
CR=exp23cWitnessClosedLoopRegistry();
candidateArm=CR.arms(strcmp({CR.arms.id},CR.clockArm));

rows=repmat(exp23fWitnessBackgroundEmptyRow(),numel(R.arms),1);
for k=1:numel(R.arms)
    arm=R.arms(k);
    if strcmp(arm.family,'periodic-static')
        rate=c.lowerCostRateHz;
        localArm=struct('id',arm.id,'label',arm.label, ...
            'family','periodic-static','periodicRateHz',rate);
        [cfg,method,label,details]=applyExp22fStaticArm(base,localArm,R);
    else
        [cfg,method,~,details]=applyExp23cWitnessClockArm( ...
            base,candidateArm,nativeQ,trace,CR);
        label=arm.label;
        details.kind='candidate-elcs-w';
        rate=50;
    end
    meta=struct('stage',R.stage,'scenario',c.id, ...
        'scenarioLabel',c.label,'family','EXP23F background robustness', ...
        'arm',arm.id,'pointIndex',k,'parameterValue',rate);
    rows(k)=runExp23fWitnessBackgroundCell( ...
        cfg,method,label,meta,trace,details,arm.family,condition);
end

end


function gates=integrityGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.scenario)+'|'+ ...
    string(T.loadCondition)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(sort(unique(string(T.scenario))), ...
        sort(reshape(string({R.cells.id}),[],1))) && ...
    isequal(sort(unique(string(T.loadCondition))), ...
        sort(reshape(string({R.conditions.id}),[],1))) && ...
    isequal(sort(unique(string(T.arm))), ...
        sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '30 seeds, two cells, four load conditions and two arms exact');
paired=true; nested=true;
for seed=R.seeds'
    for c=R.cells
        fieldHash=zeros(numel(R.conditions),1);
        for q=1:numel(R.conditions)
            condition=R.conditions(q);
            index=T.seed==seed & string(T.scenario)==string(c.id) & ...
                string(T.loadCondition)==string(condition.id);
            paired=paired && nnz(index)==numel(R.arms) && ...
                isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
                isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
                isscalar(unique(T.REALIZED_BACKGROUND_FRACTION(index))) && ...
                isscalar(unique(T.BACKGROUND_TRANSITION_COUNT(index)));
            fieldHash(q)=T.BACKGROUND_RANDOM_FIELD_HASH_EXACT(find(index,1));
        end
        nested=nested && isscalar(unique(fieldHash));
    end
end
add('paired_shared_realizations',paired, ...
    'each cell/condition pairs channel, estimator, clock and occupancy');
add('nested_background_random_field',nested, ...
    'IID and Markov conditions derive from one absolute uniform field');

periodic=string(T.ENGINE_FAMILY)=="periodic-static";
candidate=string(T.ENGINE_FAMILY)=="candidate-elcs-w";
rates=true;
for c=R.cells
    index=periodic & string(T.scenario)==string(c.id);
    rates=rates && all(abs(T.PERIODIC_RATE_HZ(index)- ...
        c.lowerCostRateHz)<1e-12);
end
add('periodic_boundary_and_timing',rates && all( ...
    T.ENDOGENOUS_COLLISION_FRAMES(periodic)==0) && all( ...
    T.CONTINUOUS_MAX_CLOCK_RESIDUAL(periodic)<=2e-12), ...
    'EXP23D rates remain guarded without endogenous collision');
backgroundPair=true;
for seed=R.seeds'
    for c=R.cells
        for condition=R.conditions
            index=T.seed==seed & string(T.scenario)==string(c.id) & ...
                string(T.loadCondition)==string(condition.id);
            values=T.BACKGROUND_BUSY_TIME(index);
            backgroundPair=backgroundPair && max(values)-min(values)<=1e-9;
        end
    end
end
add('exact_background_busy_time_pairing',backgroundPair, ...
    'both engines charge the same absolute occupied time');
certificate=all(T.ELCSW_BACKGROUND_OVERLAY_APPLIED(candidate)==1) && ...
    all(T.ELCSW_BACKGROUND_TRACE_HASH_EXACT(candidate)== ...
        T.TRACE_HASH_EXACT(candidate)) && ...
    all(abs(T.ELCSW_BACKGROUND_LOAD(candidate)- ...
        T.TARGET_BACKGROUND_LOAD(candidate))<=1e-12);
add('candidate_background_certificate',certificate, ...
    'ELCS-W control/DATA overlay matches shared trace and declared load');
loadActive=candidate & T.TARGET_BACKGROUND_LOAD>0;
clean=candidate & T.TARGET_BACKGROUND_LOAD==0;
add('background_stimulus_activation',all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS(loadActive)>0) && all( ...
    T.ELCSW_BACKGROUND_POTENTIAL_HITS(clean)==0) && all( ...
    T.BACKGROUND_BUSY_TIME(loadActive)>0) && all( ...
    T.BACKGROUND_BUSY_TIME(clean)==0), ...
    'nonzero load hits ELCS-W attempts; clean remains exactly empty');
markov15=string(T.loadCondition)=="markov-load15";
iid15=string(T.loadCondition)=="iid-load15";
correlated=mean(T.BACKGROUND_MEAN_ON_RUN_SEC(markov15))> ...
    10*mean(T.BACKGROUND_MEAN_ON_RUN_SEC(iid15)) && ...
    mean(T.BACKGROUND_TRANSITION_COUNT(markov15))< ...
    mean(T.BACKGROUND_TRANSITION_COUNT(iid15));
add('markov_burst_correlation_stimulus',correlated,sprintf( ...
    'mean on-run IID/Markov %.4g/%.4g s', ...
    mean(T.BACKGROUND_MEAN_ON_RUN_SEC(iid15)), ...
    mean(T.BACKGROUND_MEAN_ON_RUN_SEC(markov15))));
add('one_hop_witness_cover',all( ...
    T.ELCSW_ALL_EDGES_COVERED(candidate)==1) && all( ...
    T.ELCSW_HIDDEN_CONFLICT_EDGES(candidate)>0) && all( ...
    T.ELCSW_MAX_WITNESS_LOAD(candidate)<=10), ...
    'all hidden conflicts retain bounded local witnesses');
add('absolute_control_bounds',all( ...
    T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)<=1+1e-12) && all( ...
    T.ELCSW_BYTE_BOUND_RATIO(candidate)<=1+1e-12),sprintf( ...
    'max attempt/byte ratios %.6f/%.6f', ...
    max(T.ELCSW_ATTEMPT_BOUND_RATIO(candidate)), ...
    max(T.ELCSW_BYTE_BOUND_RATIO(candidate))));
replay=all(T.ELCSW_DATA_SKIPPED_NO_QUEUE(candidate)==0) && ...
    all(T.ELCSW_DATA_OUTCOME_MISMATCHES(candidate)==0) && ...
    all(T.ELCSW_DATA_COLLISION_WITNESS_MATCH(candidate)==1) && ...
    all(T.ELCSW_CROSS_PLANE_OVERLAPS(candidate)==0) && ...
    all(T.ELCSW_CLOCK_TIMING_CONFLICT_FREE(candidate)==1);
add('exact_elcs_w_replay',replay, ...
    'queue, outcome, clock and control/DATA plane contracts close');
management=all(T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE(candidate)==1) && ...
    all(T.ELCSW_MANAGEMENT_ATTEMPTS(candidate)== ...
        T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS(candidate)) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
        T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME(candidate))<=1e-12) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME(candidate)- ...
        T.ELCSW_CONTROL_BYTES_AIRTIME(candidate))<=1e-12);
add('variable_payload_management_accounting',management, ...
    'attempt, recipient, byte and airtime accounting close exactly');
retryStim=true;
for c=R.cells
    for condition=R.conditions(2:end)
        index=candidate & string(T.scenario)==string(c.id) & ...
            string(T.loadCondition)==string(condition.id);
        retryStim=retryStim && sum( ...
            T.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS(index))>0;
    end
end
add('load_induced_retry_stimulus',retryStim && all( ...
    T.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS(clean)==0), ...
    'every loaded cell activates retry; clean does not');
costEligible=true;
for c=R.cells
    for condition=R.conditions
        A=selectRows(T,c.id,condition.id,R.periodicArm);
        E=selectRows(T,c.id,condition.id,R.elcsWArm);
        costEligible=costEligible && mean(A.TOTAL_OFFERED_UTIL)<= ...
            (1-R.requiredCostImprovement)*mean(E.TOTAL_OFFERED_UTIL)+1e-12;
    end
end
add('periodic_cost_eligibility',costEligible, ...
    'periodic is at least 1% cheaper in every load contrast');
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.TOTAL_MANAGEMENT_AIRTIME)/12;
account=all(abs(T.TOTAL_OFFERED_UTIL-charge)<=1e-12) && ...
    all(T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
        T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS) && ...
    all(T.CHANNEL_UTIL<=T.TOTAL_OFFERED_UTIL+ ...
        T.REALIZED_BACKGROUND_FRACTION+1e-9);
add('recipient_airtime_and_busy_union',account, ...
    'focal offered airtime, recipients and exogenous busy union close');
add('causal_and_protocol_invariants', ...
    all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && ...
    all(T.INVARIANT_VIOLATIONS==0), ...
    'zero future/random truth reads and protocol invariant violations');
retained=all(ismember(T.SAFEFAIL,[0 1])) && ...
    all(T.SAFEFAIL>=T.DIVERGED) && ...
    all(ismember(T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED(candidate),[0 1]));
add('all_robustness_failures_retained',retained, ...
    'unsafe, divergent and terminal-uncertified outcomes remain observable');
add('background_screen_scope_only',~R.policyOptimizationAllowed && ...
    ~R.broadRobustnessClaimPermitted && ~R.newMethodPromotionAllowed && ...
    ~R.submissionClaimPermitted, ...
    'no tuning, broad robustness, promotion or submission decision');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredIntegrityContracts
    error('exp23f: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function D=robustnessTable(T,R)

rows=cell(0,27); q=0;
for c=R.cells
    for condition=R.conditions
        E=selectRows(T,c.id,condition.id,R.elcsWArm);
        A=selectRows(T,c.id,condition.id,R.periodicArm);
        q=q+1;
        rmse=pairedBootstrapCI(A.RMSE,E.RMSE,10000, ...
            R.bootstrapSeedBase+2*q,30);
        cost=pairedBootstrapCI(A.TOTAL_OFFERED_UTIL, ...
            E.TOTAL_OFFERED_UTIL,10000,R.bootstrapSeedBase+1+2*q,30);
        er=mean(E.RMSE); ec=mean(E.TOTAL_OFFERED_UTIL);
        ar=mean(A.RMSE); ac=mean(A.TOTAL_OFFERED_UTIL);
        epsilon=ar<=(1+R.epsilonRmse)*er && ...
            ac<=(1-R.requiredCostImprovement)*ec;
        confidence=rmse.hi<=R.epsilonRmse*er && ...
            cost.hi<=-R.requiredCostImprovement*ec;
        rows(end+1,:)={string(c.id),string(condition.id),height(E), ...
            mean(E.REALIZED_BACKGROUND_FRACTION), ...
            mean(E.BACKGROUND_MEAN_ON_RUN_SEC), ...
            mean(E.BACKGROUND_TRANSITION_COUNT),er,ar,ec,ac, ...
            ar/er-1,ac/ec-1,rmse.meanD,rmse.lo,rmse.hi, ...
            cost.meanD,cost.lo,cost.hi, ...
            mean(E.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED), ...
            mean(E.ELCSW_PHYSICAL_UNCERTIFIED_NODE_FRAMES), ...
            mean(E.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS), ...
            sum(E.ELCSW_FALSE_VALID_EDGE_FRAMES), ...
            sum(E.ELCSW_SCHEDULED_COLLISION_FRAMES), ...
            sum(E.SAFEFAIL),sum(E.DIVERGED),double(epsilon), ...
            double(confidence)}; %#ok<AGROW>
    end
end
D=cell2table(rows,'VariableNames',{'scenario','loadCondition','nPairs', ...
    'meanRealizedBackgroundFraction','meanOnRunSec','meanTransitions', ...
    'candidateMeanRMSE','periodicMeanRMSE','candidateMeanCost', ...
    'periodicMeanCost','relativePeriodicRmse','relativePeriodicCost', ...
    'rmseDelta','rmseCiLo','rmseCiHi','costDelta','costCiLo','costCiHi', ...
    'physicalTerminalCertificationRate','meanUncertifiedNodeFrames', ...
    'meanPhysicalRetryClaims','falseValidEdgeFrames', ...
    'scheduledCollisionFrames','candidateSafeFailures', ...
    'candidateDivergences','epsilonDominates', ...
    'epsilonConfidenceSupported'});

end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'scenario','scenarioLabel','loadCondition', ...
    'loadConditionLabel','backgroundModel','arm','methodLabel', ...
    'ENGINE_FAMILY'}));
S.nRuns=splitapply(@numel,T.RMSE,group);
S.meanRealizedBackgroundFraction=splitapply( ...
    @mean,T.REALIZED_BACKGROUND_FRACTION,group);
S.meanOnRunSec=splitapply(@mean,T.BACKGROUND_MEAN_ON_RUN_SEC,group);
S.meanRMSE=splitapply(@mean,T.RMSE,group);
S.meanTrueAoI=splitapply(@mean,T.MEAN_TRUE_AOI,group);
S.meanTotalOfferedUtil=splitapply(@mean,T.TOTAL_OFFERED_UTIL,group);
S.meanChannelUtil=splitapply(@mean,T.CHANNEL_UTIL,group);
S.meanGoodputHz=splitapply(@mean,T.DATA_GOODPUT_HZ,group);
S.meanPhysicalRetryClaims=splitapply( ...
    @finiteMean,T.ELCSW_PHYSICAL_RETRY_CLAIM_ATTEMPTS,group);
S.physicalTerminalCertificationRate=splitapply( ...
    @finiteMean,T.ELCSW_PHYSICAL_FINAL_ALL_CERTIFIED,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);

end


function T=selectRows(T,scenario,condition,arm)
T=T(string(T.scenario)==string(scenario) & ...
    string(T.loadCondition)==string(condition) & ...
    string(T.arm)==string(arm),:);
T=sortrows(T,'seed');
end


function y=finiteMean(x)
x=x(isfinite(x));
if isempty(x), y=NaN; else, y=mean(x); end
end


function [seeds,cells,conditions]=groups(R)
nCells=numel(R.cells); nConditions=numel(R.conditions);
seeds=repelem(R.seeds,nCells*nConditions);
cells=repmat(repelem((1:nCells)',nConditions),numel(R.seeds),1);
conditions=repmat((1:nConditions)',numel(R.seeds)*nCells,1);
end


function [rows,completed]=loadCheckpoint(runDir,R)

[seeds,cells,conditions]=groups(R);
completed=false(size(seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23fWitnessBackgroundEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string');
rows=table2struct(T);
for q=1:numel(seeds)
    c=R.cells(cells(q)); condition=R.conditions(conditions(q));
    index=T.seed==seeds(q) & string(T.scenario)==string(c.id) & ...
        string(T.loadCondition)==string(condition.id);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23f: partial checkpoint group.'); end
end

end


