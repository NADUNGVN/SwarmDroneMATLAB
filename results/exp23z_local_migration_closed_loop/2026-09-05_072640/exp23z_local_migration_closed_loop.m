function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('exp23z: cannot write JSON artifact.'); end
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));

end
