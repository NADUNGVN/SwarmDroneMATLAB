function exp23z_local_migration_closed_loop()
%EXP23Z_LOCAL_MIGRATION_CLOSED_LOOP Graph-input executor development study.

startup; close all;
run('tests/test_local_union_geometry_binding_contracts.m');
run('tests/test_exp23z_local_migration_closed_loop_contracts.m');
R=exp23zLocalMigrationClosedLoopRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23z_local_migration_closed_loop', ...
    'N10 graph-input local migration closed-loop development.');
writeJson(fullfile(expRun.dir,'closed_loop_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23zLocalMigrationClosedLoopEmptyRow(),0,1);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
for s=1:numel(R.seeds)
    batch=runExp23zLocalMigrationClosedLoopSeed(R.seeds(s),R);
    rows=[rows;batch(:)]; %#ok<AGROW>
    writetable(struct2table(rows),checkpoint);
    fprintf('  seed %2d / %2d; rows %3d / %3d\n', ...
        s,numel(R.seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T,R);
writetable(S,fullfile(expRun.dir,'summary.csv'));
C=pairedContrasts(T,R);
writetable(C,fullfile(expRun.dir,'paired_contrasts.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'LOCAL_MIGRATION_GRAPH_INPUT_CLOSED_LOOP_VALID', ...
    'LOCAL_MIGRATION_GRAPH_INPUT_CLOSED_LOOP_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'developmentOnly',true,'geometryCoupledToPlant',false, ...
    'freshSeedEvidence',false,'submissionClaimPermitted',false, ...
    'next','online_state_tube_coupling_before_confirmation');
writeJson(fullfile(expRun.dir,'closed_loop_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','C','gates','verdict','R');

fprintf('\nEXP23Z graph-input closed-loop gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-39s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S(:,{'arm','meanRMSE','meanCost','safeFailureRate', ...
    'reacquisitionRate'}));
disp(C);
fprintf('EXP23Z DECISION: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23z: graph-input closed-loop integration invalid.'); end

end


function S=summaryTable(T,R)

rows=cell(numel(R.arms),10);
for k=1:numel(R.arms)
    index=string(T.arm)==string(R.arms(k).id);
    rows(k,:)={string(R.arms(k).id),nnz(index),mean(T.RMSE(index)), ...
        mean(T.TOTAL_COST(index)),mean(T.MINSEP(index)), ...
        mean(T.SAFEFAIL(index)),mean(T.COLLISION_FRAMES(index)), ...
        mean(T.reacquired(index),'omitnan'), ...
        mean(T.firstReacquiredFrame(index),'omitnan'), ...
        mean(T.MANAGEMENT_AIRTIME(index))};
end
S=cell2table(rows,'VariableNames',{'arm','nRuns','meanRMSE','meanCost', ...
    'meanMinSep','safeFailureRate','meanCollisionFrames', ...
    'reacquisitionRate','meanFirstReacquiredFrame', ...
    'meanManagementAirtime'});

end


function C=pairedContrasts(T,R)

pairs={ ...
    'migration-zero','periodic-zero'; ...
    'migration-iid20','periodic-iid20'; ...
    'migration-iid20-revoke-blackout','migration-iid20'; ...
    'migration-iid20-response-blackout','migration-iid20'};
rows=cell(size(pairs,1),11);
for k=1:size(pairs,1)
    A=sortrows(T(string(T.arm)==string(pairs{k,1}),:),'seed');
    B=sortrows(T(string(T.arm)==string(pairs{k,2}),:),'seed');
    if ~isequal(A.seed,B.seed), error('exp23z: paired seeds differ.'); end
    rmse=pairedBootstrapCI(A.RMSE,B.RMSE,R.bootstrapReplicates, ...
        R.bootstrapSeedBase+2*k,numel(R.seeds));
    cost=pairedBootstrapCI(A.TOTAL_COST,B.TOTAL_COST, ...
        R.bootstrapReplicates,R.bootstrapSeedBase+2*k+1,numel(R.seeds));
    rows(k,:)={string(pairs{k,1}),string(pairs{k,2}),height(A), ...
        mean(A.RMSE)/mean(B.RMSE)-1,rmse.meanD,rmse.lo,rmse.hi, ...
        mean(A.TOTAL_COST)/mean(B.TOTAL_COST)-1, ...
        cost.meanD,cost.lo,cost.hi};
end
C=cell2table(rows,'VariableNames',{'candidate','reference','nPairs', ...
    'relativeRmse','rmseDelta','rmseCiLo','rmseCiHi', ...
    'relativeCost','costDelta','costCiLo','costCiHi'});

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash)&&registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
root=projectRoot();
x=jsondecode(fileread(fullfile(root,'results', ...
    'exp23x_local_union_migration_kernel',R.parentKernelRun, ...
    'migration_verdict.json')));
y=jsondecode(fileread(fullfile(root,'results', ...
    'exp23y_migration_common_phy',R.parentCommonPhyRun, ...
    'timing_verdict.json')));
add('parent_evidence_valid',strcmp(x.status,R.parentKernelStatus)&& ...
    strcmp(y.status,R.parentCommonPhyStatus), ...
    'EXP23X kernel and EXP23Y common-PHY parents valid');
key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds)&&isequal( ...
    sort(unique(string(T.arm))),sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '20 seeds and six paired arms exact');
paired=true;
for seed=R.seeds'
    z=T.seed==seed & string(T.condition)=="zero";
    i=T.seed==seed & string(T.condition)=="iid20";
    paired=paired&&isscalar(unique(T.traceHash(z)))&& ...
        isscalar(unique(T.traceHash(i)))&& ...
        isscalar(unique(T.geometryHash(T.seed==seed)))&& ...
        isscalar(unique(T.interferenceEventHash(T.seed==seed)));
end
add('paired_realizations',paired, ...
    'channel field pairs within condition; geometry/event pair by seed');
candidate=string(T.kind)=="migration";
add('geometry_selector_stimulus',all(T.graphAdmissible(candidate)==1)&& ...
    all(T.graphLocalOnly(candidate)==1)&& ...
    all(T.graphAddedEdges(candidate)==1)&& ...
    all(T.graphRemovedEdges(candidate)==0)&& ...
    all(T.oldSlot(candidate)==7)&&all(T.newSlot(candidate)==9), ...
    'one incident edge forces UAV 10 from slot 7 to slot 9');
add('geometry_scope_boundary',all(T.geometryCoupledToPlant==0)&& ...
    R.developmentOnly&&~R.geometryCoupledToPlant&& ...
    ~R.freshSeedEvidence&&~R.submissionClaimPermitted, ...
    'graph-input executor cannot claim online plant-tube coupling');
add('causal_instrumentation',all(T.futureRandomReads==0)&& ...
    all(T.receiverTruthReads==0), ...
    'zero future-random and receiver-truth decision reads');
add('clock_timing_valid',all(T.clockConflictFree(candidate)==1)&& ...
    all(T.clockResidual(candidate)<2e-12), ...
    'all migration schedules remain safe under paired affine clocks');
replay=all(T.dataOutcomeMismatches(candidate)==0)&& ...
    all(T.dataSkippedNoQueue(candidate)==0)&& ...
    all(T.crossPlaneOverlaps(candidate)==0)&& ...
    all(T.expectedDataSuccess(candidate)==T.observedDataSuccess(candidate))&& ...
    all(T.expectedDataErasure(candidate)==T.observedDataErasure(candidate))&& ...
    all(T.expectedDataCollision(candidate)==T.observedDataCollision(candidate));
add('exact_closed_loop_replay',replay, ...
    'DATA receiver outcomes and continuous replay close exactly');
control=all(T.controlAttempts(candidate)==T.expectedControlAttempts(candidate))&& ...
    all(abs(T.controlAirtime(candidate)- ...
    T.expectedControlAirtime(candidate))<1e-12)&& ...
    all(abs(T.controlAirtime(candidate)- ...
    T.controlBytes(candidate)*8/250e3)<1e-12);
add('control_airtime_accounting',control, ...
    'management attempts, bytes and exact airtime close');
add('supported_collision_safety',all(T.COLLISION_FRAMES==0)&& ...
    all(T.expectedDataCollision(candidate)==0), ...
    'all periodic and supported migration runs are collision-free');
normal=ismember(string(T.arm),["migration-zero" "migration-iid20" ...
    "migration-iid20-revoke-blackout"]);
add('normal_reacquisition',all(T.reacquired(normal)==1)&& ...
    all(T.finalSuppressed(normal)==0)&& ...
    all(T.firstReacquiredFrame(normal)>=T.eligibleFrame(normal)), ...
    sprintf('%d/%d normal migration rows reacquire', ...
    sum(T.reacquired(normal)),nnz(normal)));
blocked=string(T.arm)=="migration-iid20-response-blackout";
add('response_blackout_fail_silent',all(T.reacquired(blocked)==0)&& ...
    all(T.finalSuppressed(blocked)==1), ...
    'permanent RESPONSE blackout remains silent');
equivalent=true;
for seed=R.seeds'
    a=T.seed==seed & string(T.arm)=="migration-iid20";
    b=T.seed==seed & string(T.arm)== ...
        "migration-iid20-revoke-blackout";
    equivalent=equivalent&&T.suppressionHash(a)==T.suppressionHash(b)&& ...
        T.reacquisitionHash(a)==T.reacquisitionHash(b);
end
add('revoke_loss_independence',equivalent, ...
    'REVOKE delivery cannot alter local suppression or reuse history');
add('closed_loop_safety',all(T.SAFEFAIL==0)&&all(T.DIVERGED==0), ...
    'zero safety and divergence failures in the development matrix');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23z: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function value=ternary(condition,a,b)
if condition, value=a; else, value=b; end
end


