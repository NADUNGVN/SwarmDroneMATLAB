    parent.gatesPassed==R.parentGatesPassed&& ...
    parent.gatesTotal==R.parentGatesTotal&& ...
    parent.multiOriginRoutingDiagnosticValidated&& ...
    isfinite(registryHash)&&registryLeaves>0&&isfinite(sourceHash)&& ...
    sourceLeaves>0,sprintf('parent %d/%d; registry/source %d/%d leaves', ...
    parent.gatesPassed,parent.gatesTotal,registryLeaves,sourceLeaves));
