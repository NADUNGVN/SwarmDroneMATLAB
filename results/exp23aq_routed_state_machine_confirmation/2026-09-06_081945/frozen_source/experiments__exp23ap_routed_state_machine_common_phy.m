    R.transactionFailureUpperBound*(1-R.transactionFailureUpperBound)/ ...
    height(T))+1/height(T);
add('normal_completion_bound_sanity',empirical<= ...
    R.transactionFailureUpperBound+tolerance,sprintf( ...
    '%d/%d failures = %.6g; bound+tolerance %.6g', ...
    failures,height(T),empirical,R.transactionFailureUpperBound+tolerance));
add('barrier_activation_and_coloring_safety',all( ...
    T.prematureActivationFrames==0)&&all(T.scheduledCollisionFrames==0)&& ...
    all(T.finalActiveColoringProper==1)&&all( ...
    T.motionAuthorized<=T.barrierClosed), ...
    'zero premature activation/collision; every active coloring is proper');
add('route_causality_collision_and_isolation',all( ...
    T.routeCollisionRecipients==0)&&all(T.crossPacketStateWrites==0)&& ...
    all(T.forbiddenReads==0)&&all(F.routeCollisionRecipients==0)&& ...
    all(F.crossPacketStateWrites==0)&&all(F.forbiddenReads==0), ...
    'zero route collision, cross-packet write, or forbidden read');
add('conditional_integer_phy_accounting',all( ...
    T.integerAccountingExact==1)&&all(T.physicalControlAttempts<= ...
    T.attemptBound)&&all(mod(T.physicalControlBytes,1)==0),sprintf( ...
    'attempt range %.0f--%.0f; maximum bytes %.0f', ...
    min(T.physicalControlAttempts),max(T.physicalControlAttempts), ...
    max(T.physicalControlBytes)));
add('kernel_continuous_replay_identity',all(T.scheduleBuilt==1)&&all( ...
    T.kernelContinuousReplayExact==1)&&all( ...
    T.continuousAccountingExact==1)&&all( ...
    F.kernelContinuousReplayExact==1), ...
    'state hash, attempts, bytes, and airtime replay exactly');
add('continuous_nonoverlap_and_horizon',all( ...
    T.controlDataNonOverlap==1)&&all( ...
    T.continuousDurationSec<=R.postRequestTimeBudgetSec)&&all( ...
    F.continuousDurationSec<=R.postRequestTimeBudgetSec)&&all( ...
    strlength(T.scheduleError)==0),sprintf( ...
    'maximum schedule duration %.6f/%.3f s', ...
    max([T.continuousDurationSec;F.continuousDurationSec]), ...
    R.postRequestTimeBudgetSec));
add('conservative_duration_envelope',all(T.continuousDurationSec<= ...
    R.conservativeTransactionTimeSec+1e-12)&&all( ...
    F.continuousDurationSec<=R.conservativeTransactionTimeSec+1e-12), ...
    sprintf('maximum %.6f <= frozen %.6f s', ...
    max([T.continuousDurationSec;F.continuousDurationSec]), ...
    R.conservativeTransactionTimeSec));
add('affine_clock_accounting_preserved',all( ...
    T.clockSchedulePreserved==1), ...
    sprintf('%d/%d clock-impaired schedules preserve accounting', ...
    nnz(T.clockSchedulePreserved),height(T)));
add('dynamic_bundle_slot_envelopes',height(E)== ...
    R.expectedBundleEnvelopeRows&&all(E.envelopeSatisfied==1)&&all( ...
    T.dynamicBundleEnvelopeExact==1)&&all( ...
    F.dynamicBundleEnvelopeExact==1),sprintf( ...
    'maximum headroom %.0f slots; minimum %.0f', ...
    max(E.slotHeadroom),min(E.slotHeadroom)));
prepare=F(F.fault=="prepare-blackout",:);
add('prepare_blackout_fails_safe',height(prepare)==1&& ...
    ~prepare.barrierClosed&&~prepare.motionAuthorized&& ...
    ~prepare.commitReady&&~prepare.allAffectedReactivated&& ...
    prepare.prepareBudgetExhausted&&prepare.logicalClaimPackets==0&& ...
    prepare.logicalResponsePackets==0&&prepare.logicalCommitPackets==0, ...
    'no barrier, motion, evidence, response, commit, or reactivation');
response=F(F.fault=="response-blackout",:);
add('response_blackout_fails_safe',height(response)==1&& ...
    response.barrierClosed&&response.motionAuthorized&& ...
    ~response.commitReady&&~response.allAffectedReactivated&& ...
    response.logicalCommitPackets==0, ...
    'barrier closes but certification and commit remain blocked');
commit=F(F.fault=="commit-blackout",:);
add('commit_blackout_fails_safe',height(commit)==1&& ...
    commit.barrierClosed&&commit.motionAuthorized&&commit.commitReady&& ...
    ~commit.allAffectedReactivated&&commit.commitBudgetExhausted&& ...
    commit.logicalCommitPackets==R.commitAttempts, ...
    'certification succeeds but remote reactivation remains blocked');
add('implementation_version_identity',all(T.traceVersionHash== ...
    realizationHash(R.traceVersion))&&all(T.kernelVersionHash== ...
    realizationHash(R.kernelVersion))&&all(T.continuousVersionHash== ...
    realizationHash(R.continuousVersion))&&all(T.scheduleBuilt==1), ...
    'routed trace, state kernel, and continuous builder versions fixed');
add('analytical_reliability_scope',B.horizonFeasible&& ...
    B.unionFailureUpperBound<=1e-3&& ...
    R.conservativeTransactionTimeSec<=R.postRequestTimeBudgetSec, ...
    sprintf('failure %.9g and time %.6f s remain jointly feasible', ...
    B.unionFailureUpperBound,R.conservativeTransactionTimeSec));
add('development_scope_preserved',R.developmentOnly&& ...
    ~R.confirmatoryEvidence&&~R.managementRelayingValidated&& ...
    ~R.closedLoopManagementRelayingValidated&& ...
    ~R.repeatedOnlineRenewalValidated&&~R.freshSeedEvidence&& ...
    ~R.robustnessClaimPermitted&&~R.submissionClaimPermitted, ...
    'only a passing verdict may promote management-relaying validation');
if numel(name)~=R.requiredValidationContracts
    error('exp23ap: validation gate count differs from registry.');
end
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});

    function add(label,value,message)
        name{end+1,1}=label; pass(end+1,1)=logical(value);
        detail{end+1,1}=message;
    end

end


