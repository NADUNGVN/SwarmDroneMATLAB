function exp23ap_routed_state_machine_common_phy(R)
%EXP23AP_ROUTED_STATE_MACHINE_COMMON_PHY Validate routed protocol execution.

if nargin<1, R=exp23apRoutedStateMachineRegistry(); end
startup; close all; runRequiredTests(R);
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment(R.experimentName, ...
    ['Frozen routed receiver-state migration and continuous common-PHY ' ...
    'development diagnostic.']);
writeJson(fullfile(expRun.dir,'routed_state_registry.json'),R);
[sourceHash,sourceLeaves]=snapshotSource(expRun.dir,R);

[M,C,route,P,parentSelected,parentEnvelope]=fixture(R);
routeCertificate=receiverLiftedRoutedClosureReliabilityCertificate( ...
    M,C,R.evidencePrefixAttempts,route);
[normal,envelopeNormal]=normalRuns(M,C,route,P,parentEnvelope,R);
writetable(normal,fullfile(expRun.dir,'normal_routed_transactions.csv'));
[faults,envelopeFault]=faultRuns(M,C,route,P,parentEnvelope,R);
writetable(faults,fullfile(expRun.dir,'routed_fault_trajectories.csv'));
envelopes=bundleEnvelopes(parentEnvelope,envelopeNormal,envelopeFault);
writetable(envelopes,fullfile(expRun.dir,'dynamic_bundle_envelopes.csv'));
writeJson(fullfile(expRun.dir,'routed_transaction_certificate.json'), ...
    routeCertificate);

gates=validationGates(normal,faults,envelopes,routeCertificate, ...
    parentSelected,R,registryHash,registryLeaves,sourceHash,sourceLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
valid=all(gates.passed==1); status=ternary(valid,R.validStatus,R.invalidStatus);
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'normalRuns',height(normal), ...
    'normalCompletions',sum(normal.allAffectedReactivated), ...
    'normalFailures',nnz(~normal.allAffectedReactivated), ...
    'faultRows',height(faults), ...
    'maximumContinuousDurationSec',max([normal.continuousDurationSec; ...
    faults.continuousDurationSec]), ...
    'transactionFailureUpperBound', ...
    routeCertificate.unionFailureUpperBound, ...
    'multiOriginRoutingDiagnosticValidated',true, ...
    'managementRelayingValidated',valid, ...
    'closedLoopManagementRelayingValidated',false, ...
    'repeatedOnlineRenewalValidated',false,'freshSeedEvidence',false, ...
    'robustnessClaimPermitted',false,'submissionClaimPermitted',false, ...
    'next',ternary(valid,'routed_common_phy_plant_closed_loop', ...
    'repair_routed_state_machine_without_relaxing_registered_gates'));
writeJson(fullfile(expRun.dir,'routed_state_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'normal','faults','envelopes', ...
    'routeCertificate','parentSelected','parentEnvelope','M','C','route', ...
    'P','gates','verdict','R');

fprintf('\n%s validation gates\n',R.version);
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(envelopes);
fprintf('%s DECISION: %s\n',R.version,status);
finishExperiment(expRun);
if ~valid
    error('exp23ap: routed state-machine diagnostic invalid.');
end

end


function [M,C,route,P,parentSelected,parentEnvelope]=fixture(R)

BASE=exp23aiIntegerAccountingRegistry();
[~,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,BASE);
M=context.geometry.migration;
C=struct('maxFrames',R.maxFrames,'prepareFrame',1, ...
    'transactionVersion',BASE.transactionVersion, ...
    'prepareDenseRetryFrames',R.prepareAttempts, ...
    'prepareMaxBackoffFrames',1, ...
    'prepareRetryAttemptLimit',R.prepareAttempts, ...
    'claimEligibilityDelayFrames',BASE.claimEligibilityDelayFrames, ...
    'lockProofRepeatFrames',R.evidencePrefixAttempts, ...
    'claimBackoffEnabled',true,'claimDenseRetryFrames',R.claimAttempts, ...
    'claimMaxBackoffFrames',1,'claimRetryAttemptLimit',R.claimAttempts, ...
    'commitRetryAttemptLimit',R.commitAttempts, ...
    'phyRateBps',R.phyRateBps);
route=struct('directReach',logical(context.neighborGraph), ...
    'physicalInterference',context.geometry.oldPhysicalGraph| ...
    context.geometry.proposedPhysicalGraph, ...
    'linkErasureProbability',R.linkErasureProbability, ...
    'repetitionsPerHop',R.repetitionsPerHop, ...
    'safeGuardSec',R.safeGuardSec);
P=struct('guardSec',R.safeGuardSec,'dataBytes',R.dataBytes, ...
    'horizonSec',R.postRequestTimeBudgetSec);
parent=load(fullfile(projectRoot(),'results', ...
    'exp23ao_multi_origin_routing',R.parentRun,'workspace.mat'), ...
    'selected','bundleTable');
parentSelected=parent.selected; parentEnvelope=parent.bundleTable;

end


function [T,envelope]=normalRuns(M,C,route,P,parentEnvelope,R)

rows=repmat(normalEmptyRow(),R.normalTrials,1);
envelope=zeros(R.normalTrials,height(parentEnvelope));
for index=1:R.normalTrials
    seed=R.normalSeeds(index); row=normalEmptyRow(); row.seed=seed;
    trace=generateReceiverLiftedRoutedClosureTrace(seed,M,C,route);
    K=simulateReceiverLiftedRoutedClosureMigration(M,C,trace,route);
    row.traceHash=trace.hashExact; row.stateHash=K.stateHashExact;
    row.barrierClosed=K.barrierClosed;
    row.motionAuthorized=K.motionAuthorized;
    row.commitReady=K.commitReady;
    row.allAffectedReactivated=K.allAffectedReactivated;
    row.finalSuppressedCount=K.finalSuppressedCount;
    row.prematureActivationFrames=K.prematureActivationFrames;
    row.scheduledCollisionFrames=K.scheduledCollisionFrames;
    row.finalActiveColoringProper=K.finalActiveColoringProper;
    row.routeCollisionRecipients=K.routeCollisionRecipients;
    row.crossPacketStateWrites=K.crossPacketStateWrites;
    row.forbiddenReads=K.futureRandomReads+K.receiverTruthDecisionReads;
    row.logicalPacketCount=K.logicalPacketCount;
    row.routedPacketCount=K.routedPacketCount;
    row.localOnlyPacketCount=K.localOnlyPacketCount;
    row.physicalControlAttempts=K.physicalControlAttempts;
    row.physicalControlBytes=K.physicalControlBytes;
    row.physicalControlAirtimeSec=K.physicalControlAirtimeSec;
    row.attemptBound=sum(arrayfun(@(x) x.replay.plannedAttemptBound, ...
        K.bundleLog([K.bundleLog.routedPacketCount]>0)));
    row.integerAccountingExact=double(K.physicalControlAttempts== ...
        sum(struct2array(K.physicalAttemptsByKind))&& ...
        K.physicalControlBytes==sum(struct2array(K.physicalBytesByKind))&& ...
        K.physicalControlAirtimeSec== ...
        8*K.physicalControlBytes/R.phyRateBps&& ...
        K.physicalControlAttempts<=row.attemptBound);
    [envelope(index,:),row.dynamicBundleEnvelopeExact]= ...
        observedEnvelope(K.bundleLog,parentEnvelope);
    try
        Q=buildReceiverLiftedRoutedClosureContinuousSchedule( ...
            M,C,trace,P,route);
        row.scheduleBuilt=1; row.continuousHash=Q.hashExact;
        row.continuousVersionHash=realizationHash(Q.version);
        row.kernelContinuousReplayExact=double( ...
            Q.kernel.stateHashExact==K.stateHashExact);
        row.continuousDurationSec=Q.frameEndTime(end);
        row.firstConvergenceTimeSec=Q.firstConvergenceTimeSec;
        row.continuousAccountingExact=double( ...
            Q.expectedManagementAttempts==K.physicalControlAttempts&& ...
            Q.expectedManagementBytes==K.physicalControlBytes&& ...
            Q.expectedManagementAirtime==K.physicalControlAirtimeSec);
        Q=bindReplayDataOutcomes( ...
            Q,M.dataNeighborGraph,Q.kernel.debug.actualGraph);
        clockStream=RandStream('mt19937ar','Seed',seed+3000000);
        clock=struct('clockOffsetSec',(2*rand(clockStream,M.N,1)-1)* ...
            R.safeClockMaxOffsetSec,'clockDriftPpm', ...
            (2*rand(clockStream,M.N,1)-1)*R.safeClockMaxDriftPpm, ...
            'maxOffsetSec',R.safeClockMaxOffsetSec, ...
            'maxDriftPpm',R.safeClockMaxDriftPpm, ...
            'leadTimeSec',R.clockLeadTimeSec, ...
            'safeGuardSec',R.safeGuardSec);
        A=applyDstrAffineClockSchedule(Q,clock);
        row.clockSchedulePreserved=double(A.expectedManagementAttempts== ...
            Q.expectedManagementAttempts&&A.expectedManagementBytes== ...
            Q.expectedManagementBytes&& ...
            A.expectedManagementRecipientCollision==0);
        row.controlDataNonOverlap=noOverlap(A);
    catch ME
        row.scheduleError=string(ME.message);
    end
    row.traceVersionHash=realizationHash(trace.version);
    row.kernelVersionHash=realizationHash(K.version);
    rows(index)=row;
    if mod(index,50)==0
        fprintf('  routed normal %d/%d complete; failures=%d\n', ...
            index,R.normalTrials,nnz(~[rows(1:index).allAffectedReactivated]));
    end
end
T=struct2table(rows);

end


function [T,envelope]=faultRuns(M,C,route,P,parentEnvelope,R)

rows=repmat(faultEmptyRow(),numel(R.faults),1);
envelope=zeros(numel(R.faults),height(parentEnvelope));
base=generateReceiverLiftedRoutedClosureTrace(R.faultSeed,M,C,route);
kinds=fieldnames(base.linkUniform);
for k=1:numel(kinds), base.linkUniform.(kinds{k})(:)=1; end
for index=1:numel(R.faults)
    fault=R.faults{index}; trace=base;
    switch fault
        case 'prepare-blackout'
            trace.linkUniform.prepare(:)=0;
        case 'response-blackout'
            trace.linkUniform.response(:)=0;
        case 'commit-blackout'
            trace.linkUniform.commit(:)=0;
        otherwise
            error('exp23ap: unknown registered fault.');
    end
    trace.hashExact=receiverLiftedRoutedClosureTraceHash(trace);
    K=simulateReceiverLiftedRoutedClosureMigration(M,C,trace,route);
    Q=buildReceiverLiftedRoutedClosureContinuousSchedule(M,C,trace,P,route);
    row=faultEmptyRow(); row.fault=string(fault); row.seed=R.faultSeed;
    row.barrierClosed=K.barrierClosed;
    row.motionAuthorized=K.motionAuthorized; row.commitReady=K.commitReady;
    row.allAffectedReactivated=K.allAffectedReactivated;
    row.prepareBudgetExhausted=K.prepareBudgetExhausted;
    row.commitBudgetExhausted=K.commitBudgetExhausted;
    row.logicalClaimPackets=K.logicalPackets.claim;
    row.logicalResponsePackets=K.logicalPackets.response;
    row.logicalCommitPackets=K.logicalPackets.commit;
    row.routeCollisionRecipients=K.routeCollisionRecipients;
    row.crossPacketStateWrites=K.crossPacketStateWrites;
    row.forbiddenReads=K.futureRandomReads+K.receiverTruthDecisionReads;
    row.physicalControlAttempts=K.physicalControlAttempts;
    row.physicalControlBytes=K.physicalControlBytes;
    row.continuousDurationSec=Q.frameEndTime(end);
    row.kernelContinuousReplayExact=double( ...
        Q.kernel.stateHashExact==K.stateHashExact&& ...
        Q.expectedManagementAttempts==K.physicalControlAttempts&& ...
        Q.expectedManagementBytes==K.physicalControlBytes);
    [envelope(index,:),row.dynamicBundleEnvelopeExact]= ...
        observedEnvelope(K.bundleLog,parentEnvelope);
    rows(index)=row;
end
T=struct2table(rows);

end


function [observed,exact]=observedEnvelope(logs,parent)

observed=zeros(1,height(parent));
for k=1:numel(logs)
    if logs(k).routedPacketCount==0, continue; end
    index=find(parent.bundle==logs(k).phase);
    if numel(index)~=1
        error('exp23ap: dynamic bundle is outside the registry.');
    end
    observed(index)=max(observed(index),logs(k).reservedSlotCount);
end
exact=double(all(observed<=parent.compactSlotCount'));

end


function T=bundleEnvelopes(parent,normal,fault)

maximum=max([normal;fault],[],1)';
T=table(parent.bundle,parent.compactSlotCount,maximum, ...
    parent.compactSlotCount-maximum, ...
    double(maximum<=parent.compactSlotCount), ...
    'VariableNames',{'bundle','registeredSlotEnvelope', ...
    'maximumObservedSlots','slotHeadroom','envelopeSatisfied'});

end


function exact=noOverlap(Q)

exact=1;
for frame=1:numel(Q.frameStartTime)
    control=Q.controlFrame==frame; data=Q.dataFrame==frame;
    if any(control)&&any(data)&&max(Q.controlStartTime(control)+ ...
            Q.controlAttemptAirtimeSec(control))> ...
            min(Q.dataStartTime(data))+1e-12
        exact=0; return;
    end
end

end


function gates=validationGates(T,F,E,B,parentSelected,R, ...
    registryHash,registryLeaves,sourceHash,sourceLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
