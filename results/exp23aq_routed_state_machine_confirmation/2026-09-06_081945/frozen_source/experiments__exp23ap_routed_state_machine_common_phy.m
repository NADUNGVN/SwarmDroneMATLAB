    B.hashExact==parentSelected.certificate.hashExact,sprintf( ...
    'r=%d, allocation [%d %d %d %d], failure %.9g', ...
    R.repetitionsPerHop,R.prepareAttempts,R.claimAttempts, ...
    R.evidencePrefixAttempts,R.commitAttempts,B.unionFailureUpperBound));
