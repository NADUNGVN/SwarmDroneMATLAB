    parentSelected.repetitionsPerHop==R.repetitionsPerHop&& ...
    parentSelected.prepareAttempts==R.prepareAttempts&& ...
    parentSelected.claimAttempts==R.claimAttempts&& ...
    parentSelected.evidencePrefixAttempts==R.evidencePrefixAttempts&& ...
    parentSelected.commitAttempts==R.commitAttempts&& ...
    parentSelected.maxFrames==R.maxFrames&& ...
