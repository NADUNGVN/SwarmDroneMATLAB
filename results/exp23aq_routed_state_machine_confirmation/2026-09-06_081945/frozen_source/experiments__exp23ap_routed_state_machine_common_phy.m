function [sourceHash,sourceLeaves]=snapshotSource(target,R)

root=projectRoot(); files={R.planFile, ...
    'docs/EXP23AO_MULTI_ORIGIN_ROUTING_RESULTS_2026-09-06.md', ...
    ['results/exp23ao_multi_origin_routing/' R.parentRun ...
    '/multi_origin_verdict.json'], ...
    ['results/exp23ao_multi_origin_routing/' R.parentRun ...
    '/selected_transaction_certificate.json'], ...
    'network/buildSenderConflictGraph.m', ...
    'network/buildSlottedManagementFloodPlan.m', ...
    'network/receiverLiftedClosureControlRecipients.m', ...
    'network/buildMultiOriginRoutedControlSchedule.m', ...
    'network/simulateMultiOriginRoutedControl.m', ...
    'network/receiverLiftedRoutedClosureReliabilityCertificate.m', ...
    'network/generateReceiverLiftedRoutedClosureTrace.m', ...
    'network/receiverLiftedRoutedClosureTraceHash.m', ...
    'network/simulateReceiverLiftedRoutedClosureMigration.m', ...
    'network/buildReceiverLiftedRoutedClosureContinuousSchedule.m', ...
    'network/bindReplayDataOutcomes.m', ...
    'network/applyDstrAffineClockSchedule.m',R.registryFile,R.testFile, ...
    'tests/test_receiver_lifted_routed_closure_kernel_contracts.m', ...
    'experiments/exp23ap_routed_state_machine_common_phy.m',R.entryFile};
freeze=fullfile(target,'frozen_source'); mkdir(freeze);
records=repmat(struct('name','','content',''),numel(files),1);
for k=1:numel(files)
    source=fullfile(root,files{k});
    if ~isfile(source), error('exp23ap: missing source %s.',source); end
    name=replace(files{k},{'/' '\'},'__');
    copyfile(source,fullfile(freeze,name));
    records(k).name=name; records(k).content=fileread(source);
end
[sourceHash,sourceLeaves]=configHash(records);
manifest=struct('algorithm','configHash over ordered path/content records', ...
    'sourceHash',sourceHash,'sourceLeaves',sourceLeaves, ...
    'fileCount',numel(files),'files',{files});
writeJson(fullfile(target,'source_manifest.json'),manifest);

end


function writeJson(path,value)

fid=fopen(path,'w');
if fid<0, error('exp23ap: cannot write %s.',path); end
cleanup=onCleanup(@() fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true)); clear cleanup;

end


function value=ternary(condition,a,b)

