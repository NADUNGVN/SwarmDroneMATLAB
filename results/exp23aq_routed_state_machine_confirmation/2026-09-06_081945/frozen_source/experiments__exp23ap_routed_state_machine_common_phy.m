    superseded=jsondecode(fileread(fullfile(projectRoot(),'results', ...
        'exp23ap_routed_state_machine_common_phy',R.supersededRun, ...
        'superseded_verdict.json')));
    add('superseded_version_gate_exposed',strcmp( ...
        superseded.scientificStatus,R.supersededStatus)&&strcmp( ...
        superseded.reasonCode,R.supersededReasonCode),sprintf( ...
        'EXP23AP %s is retained but not promoted',R.supersededRun));
end
add('registered_tests_and_seed_partition',height(T)==R.normalTrials&& ...
    isequal(T.seed,R.normalSeeds)&&numel(unique(T.seed))==height(T)&& ...
    height(F)==R.expectedFaultRows&&all(F.seed==R.faultSeed)&& ...
    ~ismember(R.faultSeed,T.seed),sprintf( ...
    '%d unique normal seeds and %d isolated fault rows',height(T),height(F)));
