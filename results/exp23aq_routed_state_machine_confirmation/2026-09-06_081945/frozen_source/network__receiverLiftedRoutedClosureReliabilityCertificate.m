function B=receiverLiftedRoutedClosureReliabilityCertificate( ...
    M,C,evidencePrefixAttempts,routeSpec)
%RECEIVERLIFTEDROUTEDCLOSURERELIABILITYCERTIFICATE Cross-layer union bound.
%
% Each receiver-level erasure in the phase-reserved closure certificate is
% replaced by its routed path probability 1-(1-p^r)^h. Independence is
% required across repeated attempts of the same packet/link path. Arbitrary
% correlation among different receiver obligations within an attempt is
% permitted because the transaction combines obligations by a union bound.

if ~isstruct(M)||~isscalar(M)||~isfield(M,'admissible')||~M.admissible
    error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
        'admissible migration required.']);
end
requiredC={'maxFrames','prepareFrame','prepareDenseRetryFrames', ...
    'prepareMaxBackoffFrames','prepareRetryAttemptLimit', ...
    'claimEligibilityDelayFrames','lockProofRepeatFrames', ...
    'claimBackoffEnabled','claimDenseRetryFrames', ...
    'claimMaxBackoffFrames','claimRetryAttemptLimit', ...
    'commitRetryAttemptLimit'};
if ~all(isfield(C,requiredC))||~isscalar(evidencePrefixAttempts)|| ...
        ~isfinite(evidencePrefixAttempts)||evidencePrefixAttempts<1|| ...
        evidencePrefixAttempts~=floor(evidencePrefixAttempts)
    error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
        'invalid kernel configuration.']);
end
requiredRoute={'directReach','physicalInterference', ...
    'linkErasureProbability','repetitionsPerHop'};
if ~isstruct(routeSpec)||~isscalar(routeSpec)|| ...
        ~all(isfield(routeSpec,requiredRoute))
    error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
        'invalid route specification.']);
end
N=M.N; direct=logical(routeSpec.directReach);
physical=logical(routeSpec.physicalInterference);
if ~isequal(size(direct),[N N])||~isequal(size(physical),[N N])
    error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
        'route graph size mismatch.']);
end

P=struct('maxFrames',C.maxFrames,'eligibleFrame',C.prepareFrame, ...
    'claimBackoffEnabled',true, ...
    'claimDenseRetryFrames',C.prepareDenseRetryFrames, ...
    'claimMaxBackoffFrames',C.prepareMaxBackoffFrames, ...
    'claimRetryAttemptLimit',C.prepareRetryAttemptLimit);
[~,preparePolicy]=localUnionMigrationClaimSchedule(P);
latestPrepareFrame=preparePolicy.lastOpportunityFrame;
worstEligibleFrame=latestPrepareFrame+1+C.claimEligibilityDelayFrames;
claimPolicy=struct('opportunityCount',0,'lastOpportunityFrame',NaN, ...
    'scheduleHashExact',NaN); claimDue=false(C.maxFrames,1);
if worstEligibleFrame<=C.maxFrames
    Q=C; Q.eligibleFrame=worstEligibleFrame;
    [claimDue,claimPolicy]=localUnionMigrationClaimSchedule(Q);
end
claimFrames=find(claimDue); claimCount=numel(claimFrames);
responseSuffixAttempts=max(0,claimCount-evidencePrefixAttempts);
if claimCount>=evidencePrefixAttempts
    evidenceLastFrame=claimFrames(evidencePrefixAttempts);
else
    evidenceLastFrame=inf;
end
proofLastFrame=min(C.maxFrames, ...
    worstEligibleFrame+C.lockProofRepeatFrames-1);
evidenceProofFrames=max(0,proofLastFrame-worstEligibleFrame+1);
commitFramesReserved=0;
if ~isempty(claimFrames)
    commitFramesReserved=C.maxFrames-claimFrames(end)+1;
end
horizonFeasible=preparePolicy.opportunityCount== ...
    C.prepareRetryAttemptLimit&&claimCount==C.claimRetryAttemptLimit&& ...
    responseSuffixAttempts>=1&&evidenceLastFrame<=proofLastFrame&& ...
    commitFramesReserved>=C.commitRetryAttemptLimit;

affected=logical(M.affectedMask(:)); remote=M.affectedNodes;
remote(remote==M.initiator)=[];
prepareRounds=preparePolicy.opportunityCount;
prepareFailure=0; prepareNodeFailure=zeros(numel(remote),1);
endpointFailure=zeros(0,1); endpointKind=strings(0,1);
endpointSender=zeros(0,1); endpointReceiver=zeros(0,1);
endpointDepth=zeros(0,1); endpointRouteHash=zeros(0,1);
for remoteIndex=1:numel(remote)
    node=remote(remoteIndex);
    pPrepare=failureTo('prepare',M.initiator,node);
    pQuiet=failureTo('quiescent',node,M.initiator);
    failure=pPrepare^prepareRounds;
    for firstSuccess=1:prepareRounds
        failure=failure+pPrepare^(firstSuccess-1)*(1-pPrepare)* ...
            pQuiet^(prepareRounds-firstSuccess+1);
    end
    prepareNodeFailure(remoteIndex)=failure;
    prepareFailure=prepareFailure+failure;
end
prepareFailure=min(1,prepareFailure);

claimObligations=0; proofObligations=0; responseObligations=0;
evidenceFailure=0; responseFailure=0;
for edge=1:M.incidentUnionEdgeCount
    witness=M.incidentEdgeWitness(edge);
    endpoints=[M.incidentEdgeA(edge) M.incidentEdgeB(edge)];
    for endpoint=endpoints
        if endpoint==witness, continue; end
        if affected(endpoint)
            pEndpoint=failureTo('claim',endpoint,witness);
            evidenceFailure=evidenceFailure+ ...
                pEndpoint^evidencePrefixAttempts;
            claimObligations=claimObligations+1;
        else
            pEndpoint=failureTo('lock-proof',endpoint,witness);
            evidenceFailure=evidenceFailure+ ...
                pEndpoint^evidenceProofFrames;
            proofObligations=proofObligations+1;
        end
    end
    if witness~=M.initiator
        pResponse=failureTo('response',witness,M.initiator);
        responseFailure=responseFailure+ ...
            pResponse^responseSuffixAttempts;
        responseObligations=responseObligations+1;
    end
end
evidenceFailure=min(1,evidenceFailure);
responseFailure=min(1,responseFailure);

commitFailure=0;
for node=reshape(remote,1,[])
    pCommit=failureTo('commit',M.initiator,node);
    commitFailure=commitFailure+pCommit^C.commitRetryAttemptLimit;
end
commitFailure=min(1,commitFailure);
if horizonFeasible
    unionFailure=min(1,prepareFailure+evidenceFailure+ ...
        responseFailure+commitFailure);
else
    unionFailure=1;
end
maximumEndpointErasure=max([0;endpointFailure]);
B=struct('version','RECEIVER-LIFTED-ROUTED-RELIABILITY-v1', ...
    'assumption',["independent physical-link erasures across repeated " ...
    "attempts; cross-obligation correlation allowed by union bound"], ...
    'horizonFeasible',double(horizonFeasible), ...
    'latestPrepareFrame',latestPrepareFrame, ...
    'worstEligibleFrame',worstEligibleFrame, ...
    'prepareOpportunityCount',preparePolicy.opportunityCount, ...
    'claimOpportunityCount',claimCount, ...
    'evidencePrefixAttempts',evidencePrefixAttempts, ...
    'evidenceProofFrames',evidenceProofFrames, ...
    'responseSuffixAttempts',responseSuffixAttempts, ...
    'commitFramesReserved',commitFramesReserved, ...
    'remoteAffectedCount',numel(remote), ...
    'prepareNodeFailureUpperBound',prepareNodeFailure, ...
    'claimObligations',claimObligations, ...
    'proofObligations',proofObligations, ...
    'responseObligations',responseObligations, ...
    'prepareFailureUpperBound',prepareFailure, ...
    'evidenceFailureUpperBound',evidenceFailure, ...
    'responseFailureUpperBound',responseFailure, ...
    'commitFailureUpperBound',commitFailure, ...
    'unionFailureUpperBound',unionFailure, ...
    'completionProbabilityLowerBound',1-unionFailure, ...
    'maximumEndpointErasureProbability',maximumEndpointErasure, ...
    'minimumEndpointDeliveryProbability',1-maximumEndpointErasure, ...
    'endpointKind',endpointKind,'endpointSender',endpointSender, ...
    'endpointReceiver',endpointReceiver,'endpointDepth',endpointDepth, ...
    'endpointErasureProbability',endpointFailure, ...
    'endpointRouteHash',endpointRouteHash, ...
    'prepareScheduleHashExact',preparePolicy.scheduleHashExact, ...
    'claimScheduleHashExact',claimPolicy.scheduleHashExact, ...
    'hashExact',realizationHash([preparePolicy.scheduleHashExact; ...
    claimPolicy.scheduleHashExact;evidencePrefixAttempts; ...
    numel(remote);claimObligations;proofObligations; ...
    responseObligations;prepareFailure;evidenceFailure; ...
    responseFailure;commitFailure;unionFailure;maximumEndpointErasure; ...
    endpointSender;endpointReceiver;endpointDepth;endpointFailure; ...
    endpointRouteHash]));

    function failure=failureTo(kind,sender,receiver)
        if sender==receiver, failure=0; return; end
        if isfield(routeSpec,'endpointModel')
            model=routeSpec.endpointModel;
            cacheIndex=find(string(model.kind)==string(kind)& ...
                model.sender==sender&model.receiver==receiver);
            if numel(cacheIndex)~=1
                error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
                    'endpoint cache miss.']);
            end
            failure=model.erasureProbability(cacheIndex);
            depth=model.depth(cacheIndex);
            routeHash=model.routeHash(cacheIndex);
        else
            recipients=receiverLiftedClosureControlRecipients( ...
                M,kind,sender);
            if ~recipients(receiver)
                error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
                    'receiver is not a semantic destination.']);
            end
            plan=buildSlottedManagementFloodPlan( ...
                direct,physical,sender,recipients,N-1);
            pLink=kindValue(routeSpec.linkErasureProbability,kind);
            repetitions=kindValue(routeSpec.repetitionsPerHop,kind);
            if pLink<0||pLink>1||repetitions<1|| ...
                    repetitions~=floor(repetitions)
                error(['receiverLiftedRoutedClosureReliabilityCertificate: ' ...
                    'invalid kind-specific route value.']);
            end
            edgeSuccess=1-pLink^repetitions;
            depth=plan.depth(receiver); routeHash=plan.hashExact;
            failure=1-edgeSuccess^depth;
        end
        endpointFailure(end+1,1)=failure;
        endpointKind(end+1,1)=string(kind);
        endpointSender(end+1,1)=sender;
        endpointReceiver(end+1,1)=receiver;
        endpointDepth(end+1,1)=depth;
        endpointRouteHash(end+1,1)=routeHash;
    end

end


function value=kindValue(spec,kind)

if isnumeric(spec)&&isscalar(spec)&&isfinite(spec)
    value=double(spec); return;
end
if ~isstruct(spec)||~isscalar(spec)
    error('receiverLiftedRoutedClosureReliabilityCertificate: kind value.');
end
field=strrep(char(kind),'-','');
if ~isfield(spec,field)||~isscalar(spec.(field))|| ...
        ~isfinite(spec.(field))
    error(['receiverLiftedRoutedClosureReliabilityCertificate: missing ' ...
        'route kind %s.'],field);
end
value=double(spec.(field));

end
