function exp23c_local_witness_closed_loop_integration(resumeDir)
%EXP23C_LOCAL_WITNESS_CLOSED_LOOP_INTEGRATION Frozen ELCS-W composition.

if nargin<1, resumeDir=''; end
startup;
close all;
R=exp23cWitnessClosedLoopRegistry();
[registryHash,registryLeaves]=configHash(R);
experimentName='exp23c_local_witness_closed_loop_integration';
if isempty(resumeDir)
    runRequiredTests();
    expRun=startExperiment(experimentName, ...
        ['ELCS-W local-witness common-PHY closed-loop composition with ' ...
        'paired zero and bounded affine clocks.']);
    writeJson(fullfile(expRun.dir,'elcs_w_registry.json'),R);
    writeJson(fullfile(expRun.dir,'elcs_w_opened.json'),struct( ...
        'openedAt',char(datetime('now','Format','yyyy-MM-dd HH:mm:ss')), ...
        'registryHash',registryHash,'registryLeaves',registryLeaves, ...
        'policyOptimizationAllowed',false, ...
        'submissionClaimPermitted',false));
    snapshotSource(expRun.dir);
else
    expRun=resumeRun(resumeDir,registryHash,registryLeaves,experimentName);
end

[rows,completed]=loadCheckpoint(expRun.dir,R);
[seeds,cells]=groups(R);
pending=find(~completed);
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
batchSize=4;
for first=1:batchSize:numel(pending)
    last=min(first+batchSize-1,numel(pending));
    index=pending(first:last);
    batch=cell(numel(index),1);
    for q=1:numel(index)
        batch{q}=runGroup(seeds(index(q)),cells(index(q)),R);
    end
    for q=1:numel(batch), rows=[rows;batch{q}(:)]; end %#ok<AGROW>
    writeTableAtomic(struct2table(rows),checkpoint);
    fprintf('  groups %2d--%2d / %2d; rows %3d / %3d\n', ...
        index(1),index(end),numel(seeds),numel(rows),R.expectedRuns);
end

T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T);
writetable(S,fullfile(expRun.dir,'summary.csv'));
P=pairedComparison(T,R);
writetable(P,fullfile(expRun.dir,'paired_clock_comparison.csv'));
gates=integrationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'integration_gates.csv'));
pass=all(gates.passed==1);
status=ternary(pass,'ELCS_W_CLOSED_LOOP_VALID', ...
    'ELCS_W_CLOSED_LOOP_INVALID');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'frontierComparisonPermitted',pass, ...
    'newMethodPromotionAllowed',false, ...
    'submissionClaimPermitted',false);
writeJson(fullfile(expRun.dir,'integration_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'T','S','P','gates','verdict','R');

fprintf('\nEXP23C ELCS-W closed-loop integration gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nEXP23C VERDICT: %s\n',status);
finishExperiment(expRun);
if ~pass, error('exp23c: ELCS-W closed-loop integration invalid.'); end

end


function rows=runGroup(seedValue,cellIndex,R)

c=R.cells(cellIndex);
base=applyExp21dClosedLoopCell(c.id,seedValue);
if abs(base.swarm.T-R.clockResetHorizonSec)>1e-12
    error('exp23c: cell horizon differs from frozen clock horizon.');
end
if base.mac.dataBytes~=96 || base.mac.phyRateBps~=250e3
    error('exp23c: cell differs from frozen common PHY.');
end
trace=generateSharedMediumTrace(base);
N=base.swarm.N;
C=elcsWitnessKernelConfig(N,R.maxFrames);
C.guardSec=R.missionSafeGuardSec;
C.dataBytes=base.mac.dataBytes;
C.phyRateBps=base.mac.phyRateBps;
C.neighborGraph=logical(base.swarm.A);
C.managementReach=C.neighborGraph;
C.interferenceMatrix=logical(base.mac.interferenceMatrix);
C.conflictGraph=buildSenderConflictGraph( ...
    C.neighborGraph,C.interferenceMatrix);
elcsTrace=generateElcsWitnessTrace(seedValue,C);
nativeQ=buildElcsWitnessContinuousSchedule(C,elcsTrace,base.swarm.T);

rows=repmat(exp23cWitnessClosedLoopEmptyRow(),numel(R.arms),1);
for k=1:numel(R.arms)
    arm=R.arms(k);
    [cfg,method,label,details]=applyExp23cWitnessClockArm( ...
        base,arm,nativeQ,trace,R);
    meta=struct('stage',R.stage,'scenario',c.id, ...
        'scenarioLabel',c.label,'family', ...
        'EXP23C ELCS-W closed-loop integration', ...
        'arm',arm.id,'pointIndex',k, ...
        'parameterValue',nativeQ.guardSec);
    rows(k)=runExp23cWitnessClosedLoopCell( ...
        cfg,method,label,meta,trace,details);
end

end


function gates=integrationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
add('registry_frozen',isfinite(registryHash) && registryLeaves>0, ...
    sprintf('hash %.0f over %d leaves',registryHash,registryLeaves));
key=string(T.seed)+'|'+string(T.scenario)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns && ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds) && ...
    isequal(sort(unique(string(T.scenario))), ...
        sort(reshape(string({R.cells.id}),[],1))) && ...
    isequal(sort(unique(string(T.arm))), ...
        sort(reshape(string({R.arms.id}),[],1)));
add('exact_seed_cell_arm_coverage',coverage, ...
    '30 fresh seeds, two cells and two arms exact');

paired=true;
for seed=R.seeds'
    for c=R.cells
        index=T.seed==seed & string(T.scenario)==string(c.id);
        paired=paired && nnz(index)==2 && ...
            isscalar(unique(T.TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.EXP21C_TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.ESTIMATOR_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCSW_KERNEL_TRACE_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCSW_KERNEL_CONFIG_HASH(index))) && ...
            isscalar(unique(T.ELCSW_WITNESS_MAP_HASH(index))) && ...
            isscalar(unique(T.ELCSW_CLOCK_BASE_SCHEDULE_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCSW_LOGICAL_OPPORTUNITY_HASH_EXACT(index))) && ...
            isscalar(unique(T.ELCSW_DATA_OPPORTUNITIES(index))) && ...
            isscalar(unique(T.ELCSW_MANAGEMENT_ATTEMPTS(index))) && ...
            isscalar(unique(T.ELCSW_PHYSICAL_CONTROL_BYTES(index)));
    end
end
add('paired_absolute_realizations',paired, ...
    'channel, estimator, witness kernel and logical opportunities paired');

localCover=all(T.ELCSW_ALL_EDGES_COVERED==1) && ...
    all(T.ELCSW_HIDDEN_CONFLICT_EDGES>0) && ...
    all(T.ELCSW_MAX_WITNESS_LOAD<=floor((96-16)/8));
add('one_hop_witness_cover',localCover,sprintf( ...
    '%d hidden conflict-edge instances; max witness load %.0f', ...
    sum(T.ELCSW_HIDDEN_CONFLICT_EDGES),max(T.ELCSW_MAX_WITNESS_LOAD)));

clock=string(T.arm)==string(R.clockArm);
zero=string(T.arm)==string(R.zeroArm);
declared=all(T.ELCSW_CLOCK_APPLIED(clock)==1) && ...
    all(T.ELCSW_CLOCK_APPLIED(zero)==0) && ...
    all(T.ELCSW_CLOCK_REALIZED_MAX_OFFSET_SEC(clock)<= ...
        R.maxOffsetSec+1e-15) && ...
    all(T.ELCSW_CLOCK_REALIZED_MAX_DRIFT_PPM(clock)<= ...
        R.maxDriftPpm+1e-12);
add('clock_impairment_declared',declared, ...
    'only affine arm consumes the paired bounded clock realization');
timing=all(T.ELCSW_CLOCK_TIMING_CONFLICT_FREE==1) && ...
    all(T.ELCSW_CLOCK_MIN_INTERGROUP_GAP_SEC>=-1e-12) && ...
    all(T.ELCSW_CLOCK_MAX_INTRAGROUP_SKEW_SEC<8*96/250e3) && ...
    all(T.ELCSW_CLOCK_EQUATION_MAX_RESIDUAL_SEC<=1e-12) && ...
    all(T.CONTINUOUS_MAX_CLOCK_RESIDUAL<=1e-12);
add('affine_clock_and_guard_certificate',timing,sprintf( ...
    'max residual %.3g s; min gap %.3g s', ...
    max(T.ELCSW_CLOCK_EQUATION_MAX_RESIDUAL_SEC), ...
    min(T.ELCSW_CLOCK_MIN_INTERGROUP_GAP_SEC)));

kernel=all(T.ELCSW_FINAL_ALL_CERTIFIED==1) && ...
    all(T.ELCSW_FALSE_VALID_EDGE_FRAMES==0) && ...
    all(T.ELCSW_SCHEDULED_COLLISION_FRAMES==0) && ...
    all(T.ELCSW_CERTIFICATE_WITHOUT_FRESH_CLAIMS==0);
add('witness_kernel_safety',kernel,sprintf( ...
    '%d false-valid, %d scheduled-collision, %d unsupported cert', ...
    sum(T.ELCSW_FALSE_VALID_EDGE_FRAMES), ...
    sum(T.ELCSW_SCHEDULED_COLLISION_FRAMES), ...
    sum(T.ELCSW_CERTIFICATE_WITHOUT_FRESH_CLAIMS)));
renewal=all(T.ELCSW_FIRST_ALL_CERTIFIED_FRAME==1) && ...
    all(T.ELCSW_RETRY_CLAIM_ATTEMPTS==0) && ...
    all(T.ELCSW_CONTROL_ATTEMPTS==T.ELCSW_NOMINAL_ATTEMPT_BOUND) && ...
    all(T.ELCSW_CONTROL_BYTES==T.ELCSW_NOMINAL_BYTE_BOUND) && ...
    all(T.ELCSW_ATTEMPT_BOUND_RATIO<=1+1e-12) && ...
    all(T.ELCSW_BYTE_BOUND_RATIO<=1+1e-12);
add('zero_loss_renewal_contract',renewal,sprintf( ...
    'max retry %.0f; max attempt/byte ratios %.6f/%.6f', ...
    max(T.ELCSW_RETRY_CLAIM_ATTEMPTS),max(T.ELCSW_ATTEMPT_BOUND_RATIO), ...
    max(T.ELCSW_BYTE_BOUND_RATIO)));
add('causal_information_contract',all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.RECEIVER_TRUTH_READS==0) && all(T.LOCAL_SCHEDULE_ONLY==1), ...
    'zero future-random and receiver-truth decision reads');
add('all_elcs_w_opportunities_served',all( ...
    T.ELCSW_DATA_SKIPPED_NO_QUEUE==0) && all( ...
    T.ELCSW_DATA_ATTEMPTS==T.ELCSW_DATA_OPPORTUNITIES) && all( ...
    T.ELCSW_DATA_OPPORTUNITIES==T.ELCSW_SCHEDULED_OPPORTUNITIES+ ...
        T.ELCSW_FALLBACK_OPPORTUNITIES), ...
    sprintf('%d skipped opportunities',sum(T.ELCSW_DATA_SKIPPED_NO_QUEUE)));
outcomes=all(T.ELCSW_DATA_OUTCOME_MISMATCHES==0) && ...
    all(T.ELCSW_OBSERVED_DATA_RECIPIENT_SUCCESS== ...
        T.ELCSW_EXPECTED_DATA_RECIPIENT_SUCCESS) && ...
    all(T.ELCSW_OBSERVED_DATA_RECIPIENT_ERASURE== ...
        T.ELCSW_EXPECTED_DATA_RECIPIENT_ERASURE) && ...
    all(T.ELCSW_OBSERVED_DATA_RECIPIENT_COLLISION== ...
        T.ELCSW_EXPECTED_DATA_RECIPIENT_COLLISION) && ...
    all(T.ELCSW_DATA_COLLISION_WITNESS_MATCH==1);
add('exact_data_outcome_replay',outcomes, ...
    'success, erasure and collision masks match the witness schedule');

management=all(T.ELCSW_MANAGEMENT_ACCOUNTING_CLOSE==1) && ...
    all(T.ELCSW_MANAGEMENT_ATTEMPTS== ...
        T.ELCSW_EXPECTED_MANAGEMENT_ATTEMPTS) && ...
    all(T.ELCSW_MANAGEMENT_RECIPIENT_ATTEMPTS== ...
        T.ELCSW_EXPECTED_MANAGEMENT_RECIPIENT_ATTEMPTS) && ...
    all(T.ELCSW_MANAGEMENT_RECIPIENT_SUCCESS== ...
        T.ELCSW_EXPECTED_MANAGEMENT_RECIPIENT_SUCCESS) && ...
    all(T.ELCSW_MANAGEMENT_RECIPIENT_ERASURE== ...
        T.ELCSW_EXPECTED_MANAGEMENT_RECIPIENT_ERASURE) && ...
    all(T.ELCSW_MANAGEMENT_RECIPIENT_COLLISION== ...
        T.ELCSW_EXPECTED_MANAGEMENT_RECIPIENT_COLLISION) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME- ...
        T.ELCSW_EXPECTED_MANAGEMENT_AIRTIME)<=1e-12) && ...
    all(abs(T.ELCSW_MANAGEMENT_AIRTIME- ...
        T.ELCSW_CONTROL_BYTES_AIRTIME)<=1e-12);
add('variable_payload_management_accounting',management,sprintf( ...
    'max byte-to-airtime residual %.3g s',max(abs( ...
    T.ELCSW_MANAGEMENT_AIRTIME-T.ELCSW_CONTROL_BYTES_AIRTIME))));
add('cross_plane_nonoverlap',all(T.ELCSW_CROSS_PLANE_OVERLAPS==0), ...
    sprintf('%d overlap witnesses',sum(T.ELCSW_CROSS_PLANE_OVERLAPS)));
recipient=all(T.DATA_RECIPIENT_SUCCESS+T.DATA_RECIPIENT_LOSS+ ...
    T.TERMINAL_DATA_INFLIGHT==T.DATA_RECIPIENT_ATTEMPTS);
charge=(T.DATA_AIRTIME+T.ACK_AIRTIME+T.ELCSW_MANAGEMENT_AIRTIME)/12;
add('recipient_and_airtime_accounting',recipient && ...
    all(abs(T.OFFERED_UTIL-charge)<=1e-9) && ...
    all(T.CHANNEL_UTIL<=T.OFFERED_UTIL+1e-9), ...
    'recipient partition and DATA/ACK/control utilization close');
add('protocol_invariants',all(T.INVARIANT_VIOLATIONS==0), ...
    sprintf('%d invariant violations',sum(T.INVARIANT_VIOLATIONS)));
retained=all(ismember(T.SAFEFAIL,[0 1])) && ...
    all(T.SAFEFAIL>=T.DIVERGED) && ...
    all(ismember(T.ELCSW_FINAL_ALL_CERTIFIED,[0 1]));
add('all_failures_retained',retained,sprintf( ...
    '%d unsafe, %d divergent and %d uncertified retained', ...
    sum(T.SAFEFAIL),sum(T.DIVERGED),sum(T.ELCSW_FINAL_ALL_CERTIFIED==0)));
add('integration_scope_only',~R.policyOptimizationAllowed && ...
    ~R.newMethodPromotionAllowed && ~R.submissionClaimPermitted && ...
    ~R.frontierComparisonPermitted, ...
    'no tuning, promotion, frontier claim or submission decision');
gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredIntegrationContracts
    error('exp23c: registry contract count differs from implemented gates.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p);
        detail{end+1,1}=d;
    end

end


function S=summaryTable(T)

U=T; U.RMSE(logical(U.DIVERGED))=NaN;
[group,S]=findgroups(U(:,{'scenario','scenarioLabel','arm', ...
    'methodLabel','armKind'}));
S.nRuns=splitapply(@numel,U.RMSE,group);
S.meanRMSE=splitapply(@finiteMean,U.RMSE,group);
S.meanTrueAoI=splitapply(@finiteMean,U.MEAN_TRUE_AOI,group);
S.meanOfferedUtil=splitapply(@finiteMean,U.OFFERED_UTIL,group);
S.meanChannelUtil=splitapply(@finiteMean,U.CHANNEL_UTIL,group);
S.meanGoodputHz=splitapply(@finiteMean,U.DATA_GOODPUT_HZ,group);
S.meanManagementUtil=splitapply( ...
    @(x) finiteMean(x/12),U.ELCSW_MANAGEMENT_AIRTIME,group);
S.meanControlBytes=splitapply( ...
    @finiteMean,U.ELCSW_PHYSICAL_CONTROL_BYTES,group);
S.meanFallbackOpportunities=splitapply( ...
    @finiteMean,U.ELCSW_FALLBACK_OPPORTUNITIES,group);
S.safeFailures=splitapply(@sum,U.SAFEFAIL,group);

end


function P=pairedComparison(T,R)

metrics={'RMSE','MEAN_TRUE_AOI','OFFERED_UTIL','CHANNEL_UTIL', ...
    'DATA_GOODPUT_HZ'};
rows=cell(0,8); q=0;
for c=R.cells
    A=selectRows(T,c.id,R.clockArm);
    B=selectRows(T,c.id,R.zeroArm);
    for m=1:numel(metrics)
        q=q+1;
        boot=pairedBootstrapCI(A.(metrics{m}),B.(metrics{m}), ...
            10000,16059900+q,30);
        relative=boot.meanD/max(abs(mean(B.(metrics{m}))),eps);
        rows(end+1,:)={string(c.id),string(metrics{m}),boot.nPairs, ...
            boot.meanD,boot.lo,boot.hi,relative, ...
            string(R.clockArm)+" minus "+string(R.zeroArm)}; %#ok<AGROW>
    end
end
P=cell2table(rows,'VariableNames',{'scenario','metric','nPairs', ...
    'meanDelta','ciLo','ciHi','relativeDelta','contrast'});

end


function T=selectRows(T,scenario,arm)
T=T(string(T.scenario)==string(scenario) & string(T.arm)==string(arm),:);
T=sortrows(T,'seed');
end


function y=finiteMean(x)
x=x(isfinite(x));
if isempty(x), y=NaN; else, y=mean(x); end
end


function [seeds,cells]=groups(R)
seeds=repelem(R.seeds,numel(R.cells));
cells=repmat((1:numel(R.cells))',numel(R.seeds),1);
end


function [rows,completed]=loadCheckpoint(runDir,R)

[seeds,cells]=groups(R);
completed=false(size(seeds));
path=fullfile(runDir,'trajectory_checkpoint.csv');
if ~isfile(path)
    rows=repmat(exp23cWitnessClosedLoopEmptyRow(),0,1);
    return;
end
T=readtable(path,'TextType','string');
rows=table2struct(T);
for q=1:numel(seeds)
    c=R.cells(cells(q));
    index=T.seed==seeds(q) & string(T.scenario)==string(c.id);
    if nnz(index)==numel(R.arms), completed(q)=true;
    elseif any(index), error('exp23c: partial checkpoint group.'); end
end

end


