%% TEST_EXP23AG_RADIAL_CLOSURE_CONTRACTS Registry and theorem witness.
startup;
fprintf('\n============================================================\n');
fprintf('test_exp23ag_radial_closure_contracts\n');
fprintf('============================================================\n\n');

R=exp23agRadialClosureRegistry(); checks=0;
assert(R.expectedRuns==300&&numel(R.seeds)==50&&numel(R.arms)==6&& ...
    R.requiredValidationContracts==25&& ...
    isempty(intersect(R.seeds,R.calibrationSeeds))&& ...
    ~ismember(R.smokeSeed,R.seeds)&& ...
    ~ismember(R.diagnosticWitnessSeed,R.seeds));
fprintf('    ok   300-row fresh matrix excludes design/calibration seeds\n');
checks=checks+1;

parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23af_online_swept_receiver_closure',R.parentOnlineRun, ...
    'online_closure_verdict.json')));
diagnosis=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23af_radial_contract_diagnostic',R.parentRadialDiagnosticRun, ...
    'radial_diagnostic_verdict.json')));
assert(strcmp(parent.status,R.parentOnlineStatus)&& ...
    parent.gatesPassed==23&&parent.gatesTotal==24&& ...
    strcmp(diagnosis.status,R.parentRadialDiagnosticStatus)&& ...
    diagnosis.posthocDiagnosis&&~diagnosis.registeredConfirmation);
fprintf('    ok   failed parent and posthoc diagnosis remain explicit\n');
checks=checks+1;

rows=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,R);
T=struct2table(rows); closure=string(T.kind)=="closure";
noEmergency=string(T.arm)== ...
    "closure-response-blackout-no-emergency";
protected=closure&~noEmergency;
assert(any(T.criticalCapsuleBoundSatisfied(protected)==0)&& ...
    all(T.radialConstructionPremise(protected)==1)&& ...
    all(T.radialTheoremCertified(protected)==1)&& ...
    all(T.actualPhysicalSubset(protected)==1)&& ...
    T.radialTheoremCertified(noEmergency)==0);
fprintf('    ok   theorem witness separates vector error from radial safety\n');
checks=checks+1;

assert(all(T.prefixStateExact(closure)==1)&& ...
    all(T.emergencyMappingExact(protected)==1)&& ...
    all(T.kernelCollisionFrames(protected)==0)&& ...
    all(T.observedCollisionFrames(protected)==0)&& ...
    all(T.futureRandomReads(closure)==0)&& ...
    all(T.receiverTruthReads(closure)==0));
fprintf('    ok   causal replay and protected service remain intact\n');
checks=checks+1;

assert(R.registeredFreshRadialSeeds&&~R.freshRadialContractEvidence&& ...
    ~R.repeatedOnlineRenewalValidated&& ...
    ~R.managementRelayingValidated&&~R.freshSeedEvidence&& ...
    ~R.robustnessClaimPermitted&&~R.submissionClaimPermitted);
fprintf('    ok   no downstream claim is promoted before registered execution\n');
checks=checks+1;

fprintf('\ntest_exp23ag_radial_closure_contracts: PASS (%d checks)\n',checks);
