function G=buildCausalSweptReceiverClosure(observedRelativePosition, ...
    proposedRelativePosition,trackingRadius,interferenceRadius, ...
    dataNeighborGraph,managementReach,initiator,config)
%BUILDCAUSALSWEPTRECEIVERCLOSURE Online state/public-command closure binding.

% The retiring graph is the zero-length capsule at the current observed
% relative position. The proposed graph is the full public command sweep.
% No future plant state or channel outcome enters either construction.

p0=double(observedRelativePosition);
p1=double(proposedRelativePosition);
old=buildSweptBroadcastConflictSupergraph( ...
    p0,p0,trackingRadius,interferenceRadius,dataNeighborGraph);
proposed=buildSweptBroadcastConflictSupergraph( ...
    p0,p1,trackingRadius,interferenceRadius,dataNeighborGraph);
if isfield(config,'retiringSlot')&&~isempty(config.retiringSlot)
    oldSlot=reshape(double(config.retiringSlot),[],1);
else
    oldSlot=elcsWitnessPriorityColor(old.senderConflictGraph);
end
M=buildReceiverLiftedDependencyMigration(old.senderConflictGraph, ...
    proposed.senderConflictGraph,oldSlot,initiator,managementReach,config);
M.dataNeighborGraph=logical(dataNeighborGraph);
G=struct('version','CAUSAL-SWEPT-RECEIVER-CLOSURE-v1', ...
    'N',size(p0,1),'initiator',initiator, ...
    'observedRelativePosition',p0,'proposedRelativePosition',p1, ...
    'trackingRadius',trackingRadius, ...
    'interferenceRadius',interferenceRadius, ...
    'oldBroadcastGraph',old,'proposedBroadcastGraph',proposed, ...
    'oldPhysicalGraph',old.potentialInterferenceGraph, ...
    'proposedPhysicalGraph',proposed.potentialInterferenceGraph, ...
    'migration',M,'causalStateOnly',true,'publicCommandOnly',true, ...
    'futureActualReads',0,'futureRandomReads',0, ...
    'receiverTruthDecisionReads',0);
G.hashExact=realizationHash([old.hashExact;proposed.hashExact; ...
    M.hashExact;initiator;double(managementReach(:))]);

end
