%% TEST_RECEIVER_CLOSURE_EMERGENCY_DATA_CONTRACTS
startup;

R=exp23aeClosureCommonPhyRegistry();
[M,C,T]=fixture(R);
controlSlot=8*R.maxControlPacketBytes/R.phyRateBps+R.safeGuardSec;
dataSlot=8*R.dataBytes/R.phyRateBps+R.safeGuardSec;
frameDuration=(2*M.N+1)*controlSlot+M.config.maxDataSlots*dataSlot;
P=struct('guardSec',R.safeGuardSec,'dataBytes',R.dataBytes, ...
    'horizonSec',C.maxFrames*frameDuration+.1);
baseQ=buildReceiverLiftedClosureContinuousSchedule(M,C,T,P);
Q=addReceiverClosureEmergencyData(baseQ,M,M.config.maxDataSlots);
emergency=Q.dataKind=="emergency";
assert(Q.emergencyData.enabled&&nnz(emergency)>0&& ...
    all(Q.dataSlot(emergency)==M.config.maxDataSlots)&& ...
    strcmp(Q.emergencyData.mode,'round-robin'));
assert(~any(M.oldSlot==M.config.maxDataSlots)&& ...
    ~any(M.candidateSlot==M.config.maxDataSlots));
assert(numel(unique(Q.dataFrame(emergency)))==nnz(emergency));
assert(all(ismember(Q.dataNode(emergency),M.affectedNodes)));
served=Q.emergencyData.nodeOpportunities(M.affectedNodes);
assert(all(served>0)&&max(served)-min(served)<=1);

affected=reshape(M.affectedNodes,[],1);
protected=(M.N+1:M.N+numel(affected))';
Qp=addReceiverClosureEmergencyData(baseQ,M,protected);
parallelEmergency=Qp.dataKind=="emergency";
assert(Qp.emergencyData.enabled&&strcmp(Qp.emergencyData.mode,'parallel')&& ...
    Qp.emergencyData.maximumNominalServiceGapFrames==1&& ...
    all(Qp.emergencyData.slots==protected));
for frame=1:numel(Qp.frameStartTime)
    suppressed=logical(Qp.kernel.debug.suppressed(frame,affected));
    selected=find(parallelEmergency&Qp.dataFrame==frame);
    assert(numel(selected)==nnz(suppressed));
    assert(all(Qp.dataNode(selected)==affected(suppressed)));
    assert(all(Qp.dataSlot(selected)==protected(suppressed)));
end
assert(all(Qp.emergencyData.nodeOpportunities(affected)>0));

fprintf('test_receiver_closure_emergency_data_contracts: PASS\n');


