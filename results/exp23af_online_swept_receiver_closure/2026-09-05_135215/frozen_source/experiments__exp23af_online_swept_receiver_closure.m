function exp23af_online_swept_receiver_closure()
%EXP23AF_ONLINE_SWEPT_RECEIVER_CLOSURE Registered plant/tube integration.

startup; close all; runRequiredTests();
R=exp23afOnlineClosureRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23af_online_swept_receiver_closure', ...
    'Causal online swept receiver-closure and protected DATA validation.');
writeJson(fullfile(expRun.dir,'online_closure_registry.json'),R);
snapshotSource(expRun.dir);

rows=repmat(exp23afOnlineClosureEmptyRow(),R.expectedRuns,1); q=0;
checkpoint=fullfile(expRun.dir,'trajectory_checkpoint.csv');
for seedIndex=1:numel(R.seeds)
    seedRows=runExp23afOnlineClosureSeed(R.seeds(seedIndex),R);
    rows(q+(1:numel(seedRows)))=seedRows; q=q+numel(seedRows);
    if mod(seedIndex,5)==0
        writetable(struct2table(rows(1:q)),checkpoint);
        fprintf('  seed %2d / %2d; rows %3d / %3d\n', ...
            seedIndex,numel(R.seeds),q,R.expectedRuns);
    end
end
T=struct2table(rows);
writetable(T,fullfile(expRun.dir,'trajectory_tidy.csv'));
S=summaryTable(T); writetable(S,fullfile(expRun.dir,'summary.csv'));
P=pairedContrasts(T,R);
writetable(P,fullfile(expRun.dir,'paired_contrasts.csv'));
PS=pairedSummary(P);
writetable(PS,fullfile(expRun.dir,'paired_summary.csv'));
gates=validationGates(T,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));
valid=all(gates.passed==1);
status=ternary(valid,'ONLINE_SWEPT_RECEIVER_CLOSURE_VALID', ...
    'ONLINE_SWEPT_RECEIVER_CLOSURE_INVALID');
next=ternary(valid,'routed_multihop_management_then_online_renewal', ...
    'repair_online_tube_or_transaction_without_relaxing_gates');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'rows',height(T), ...
    'developmentOnly',true,'onlinePlantCouplingValidated',valid, ...
    'managementRelayingValidated',false,'freshSeedEvidence',false, ...
    'robustnessClaimPermitted',false,'submissionClaimPermitted',false, ...
    'next',next);
writeJson(fullfile(expRun.dir,'online_closure_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'), ...
    'T','S','P','PS','gates','verdict','R');

fprintf('\nEXP23AF online swept receiver-closure gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-43s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
disp(S);
disp(PS);
fprintf('EXP23AF DECISION: %s\n',status);
finishExperiment(expRun);
if ~valid, error('exp23af: online swept receiver closure invalid.'); end

end


function gates=validationGates(T,R,registryHash,registryLeaves)

name=cell(0,1); pass=false(0,1); detail=cell(0,1);
closure=string(T.kind)=="closure";
normal=string(T.arm)=="closure-iid20-emergency";
response=string(T.arm)=="closure-response-blackout-emergency";
noEmergency=string(T.arm)=="closure-response-blackout-no-emergency";
prepare=string(T.arm)=="closure-prepare-blackout-emergency";
commit=string(T.arm)=="closure-commit-blackout-emergency";
protected=closure&~noEmergency;

add('registry_frozen',isfinite(registryHash)&&registryLeaves>0&& ...
    ~ismember(R.smokeSeed,R.seeds)&&R.expectedRuns==120, ...
    sprintf('hash %.0f over %d leaves; smoke seed excluded', ...
    registryHash,registryLeaves));
ae=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ae_receiver_lifted_closure_common_phy',R.parentCommonPhyRun, ...
    'common_phy_verdict.json')));
ab=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ab_bounded_retry_development',R.parentRetryRun, ...
    'bounded_retry_verdict.json')));
parents=strcmp(ae.status,R.parentCommonPhyStatus)&& ...
    ae.gatesPassed==ae.gatesTotal&& ...
    strcmp(ab.status,R.parentRetryStatus)&&ab.gatesPassed==ab.gatesTotal;
add('parents_locked',parents,'EXP23AE 22/22 and EXP23AB 24/24 retained');

key=string(T.seed)+'|'+string(T.arm);
add('matrix_complete_unique',height(T)==R.expectedRuns&& ...
    numel(unique(key))==height(T),sprintf('%d/%d unique rows', ...
    numel(unique(key)),R.expectedRuns));
coverage=isequal(unique(T.seed),R.seeds)&& ...
    isequal(sort(unique(string(T.arm))), ...
    sort(reshape(string({R.arms.id}),[],1)));
add('exact_matrix_coverage',coverage, ...
    '20 untouched registered seeds and six arms exact');
add('seed_trace_pairing',perSeedUnique(T,R,'traceHash'), ...
    'one exogenous PHY trace is shared across all six arms per seed');

prefix=all(T.prefixStateExact(closure)==1)&& ...
    perSeedUnique(T(closure,:),R,'decisionStateHash')&& ...
    perSeedUnique(T(closure,:),R,'prefixScheduleHash')&& ...
    all(T.prefixScheduleHash(closure)==T.probePrefixScheduleHash(closure));
add('online_prefix_exact',prefix, ...
    'decision state and pre-PREPARE schedule are arm-independent');
geometry=perSeedUnique(T(closure,:),R,'geometryHash')&& ...
    perSeedUnique(T(closure,:),R,'selectorHash');
add('causal_geometry_pairing',geometry, ...
    'one observed-state swept certificate is paired across closure arms');
add('receiver_lifted_stimulus',all(T.graphAdmissible(closure)==1)&& ...
    all(T.changedSenderEdges(closure)>=1)&& ...
    all(T.nonincidentSenderEdges(closure)>=1)&& ...
    all(T.changedSlotCount(closure)>=1), ...
    sprintf('minimum nonincident edges %d; minimum affected %d', ...
    min(T.nonincidentSenderEdges(closure)),min(T.affectedCount(closure))));
add('union_packet_and_protected_slots',all( ...
    T.candidateProper(closure)==1)&&all(T.prepareBytes(closure)<= ...
    R.maxControlPacketBytes)&&all(T.maxResponseBytes(closure)<= ...
    R.maxControlPacketBytes)&&all(T.protectedSlotFree(closure)==1), ...
    'union coloring, MTU, and protected-slot separation hold');

add('motion_gate_exact',all(T.motionGateExact(closure)==1), ...
    'command starts exactly at authorized graph activation only');
add('prepare_blackout_blocks_motion',all(T.barrierClosed(prepare)==0)&& ...
    all(T.motionAuthorized(prepare)==0)&& ...
    all(T.prepareBudgetExhausted(prepare)==1), ...
    'missing PREPARE leaves barrier open and command unapplied');
add('normal_reacquisition',all(T.motionAuthorized(normal)==1)&& ...
    all(T.allReactivated(normal)==1)&& ...
    all(T.finalSuppressedCount(normal)==0), ...
    sprintf('%d/%d normal runs fully reactivate', ...
    nnz(T.allReactivated(normal)),nnz(normal)));
add('response_blackout_fail_silent',all( ...
    T.motionAuthorized(response)==1)&&all(T.allReactivated(response)==0)&& ...
    all(T.finalSuppressedCount(response)==T.affectedCount(response)), ...
    'certified graph activates while all affected closure states stay silent');
add('commit_blackout_partial_safe',all(T.motionAuthorized(commit)==1)&& ...
    all(T.allReactivated(commit)==0)&&all( ...
    T.finalSuppressedCount(commit)>0)&&all( ...
    T.kernelCollisionFrames(commit)==0), ...
    'lost COMMIT leaves partial suppression without kernel collision');

emergency=all(T.emergencyParallelMode(protected)==1)&& ...
    all(T.emergencyMappingExact(protected)==1)&&all( ...
    T.emergencySuppressedDemand(protected)== ...
    T.emergencyOpportunities(protected))&&all( ...
    T.emergencyRecipientCollision(protected)==0);
add('parallel_emergency_mapping',emergency, ...
    'every suppressed sender receives one distinct protected slot per frame');
add('protected_capsule_bound',all( ...
    T.capsuleBoundSatisfied(protected)==1),sprintf( ...
    'maximum realized/bound ratio %.6f', ...
    max(T.capsuleMaximumRatio(protected))));
add('protected_actual_graph_subset',all( ...
    T.actualPhysicalSubset(protected)==1)&&all( ...
    T.actualSenderSubset(protected)==1)&&all( ...
    T.actualSubsetCheckSamples(protected)>0), ...
    'realized physical and sender graphs stay inside swept union');

protectedRmse=armValues(T,R, ...
    'closure-response-blackout-emergency','MISSION_RMSE');
unprotectedRmse=armValues(T,R, ...
    'closure-response-blackout-no-emergency','MISSION_RMSE');
negative=all(T.emergencyOpportunities(noEmergency)==0)&& ...
    all(T.capsuleBoundSatisfied(noEmergency)==0)&& ...
    all(T.capsuleMaximumRatio(noEmergency)>1)&& ...
    all(unprotectedRmse-protectedRmse>0);
add('no_emergency_negative_visible',negative,sprintf( ...
    'paired mission-RMSE penalty %.6f m; minimum tube ratio %.3f', ...
    mean(unprotectedRmse-protectedRmse), ...
    min(T.capsuleMaximumRatio(noEmergency))));

add('supported_collision_safety',all( ...
    T.kernelCollisionFrames(protected)==0)&&all( ...
    T.expectedCollisionRecipients(protected)==0)&&all( ...
    T.observedCollisionFrames(protected)==0)&&all( ...
    T.emergencyRecipientCollision(protected)==0), ...
    'all protected online cells are collision-free');
replay=all(T.dataOutcomeMismatches(closure)==0)&& ...
    all(T.dataSkippedNoQueue(closure)==0)&& ...
    all(T.crossPlaneOverlaps(closure)==0)&&all( ...
    T.expectedDataSuccess(closure)==T.observedDataSuccess(closure))&&all( ...
    T.expectedDataErasure(closure)==T.observedDataErasure(closure));
add('receiver_outcome_replay_exact',replay, ...
    'success/erasure outcomes replay with no queue skip or plane overlap');
accounting=all(T.controlAttempts(closure)== ...
    T.expectedControlAttempts(closure))&&all(abs( ...
    T.controlAirtime(closure)-T.expectedControlAirtime(closure))<1e-15);
add('management_accounting_exact',accounting, ...
    'management attempts and airtime equal registered schedule');
add('affine_timing_safe',all(T.clockConflictFree(closure)==1)&& ...
    all(T.clockResidual(closure)<1e-12)&& ...
    R.missionSec<=R.clockResetHorizonSec, ...
    sprintf('maximum equation residual %.3g s',max(T.clockResidual(closure))));
add('closed_loop_safety',all(T.SAFEFAIL==0)&&all(T.DIVERGED==0)&& ...
    all(isfinite(T.MISSION_RMSE))&&all(isfinite(T.MINSEP)),sprintf( ...
    'minimum realized separation %.6f m',min(T.MINSEP)));
scope=~R.managementRelayingValidated&&~R.freshSeedEvidence&& ...
    ~R.robustnessClaimPermitted&&~R.submissionClaimPermitted;
add('causality_and_scope',all(T.futureRandomReads(closure)==0)&& ...
    all(T.receiverTruthReads(closure)==0)&&scope, ...
    'forbidden reads are zero; routing, robustness, and submission stay false');

gates=table(string(name),double(pass),string(detail), ...
    'VariableNames',{'gate','passed','detail'});
if height(gates)~=R.requiredValidationContracts
    error('exp23af: registry gate count differs from implementation.');
end

    function add(n,p,d)
        name{end+1,1}=n; pass(end+1,1)=logical(p); detail{end+1,1}=d;
    end
end


function exact=perSeedUnique(T,R,field)

exact=true;
for seed=R.seeds'
    value=T.(field)(T.seed==seed);
    exact=exact&&~isempty(value)&&isscalar(unique(value));
end

end


function value=armValues(T,R,arm,field)

value=nan(numel(R.seeds),1);
for k=1:numel(R.seeds)
    index=T.seed==R.seeds(k)&string(T.arm)==string(arm);
    if nnz(index)~=1, error('exp23af: missing paired arm row.'); end
    value(k)=T.(field)(index);
end

end


function S=summaryTable(T)

[group,S]=findgroups(T(:,{'arm','kind','fault','emergencyEnabled'}));
S.nRuns=splitapply(@numel,T.MISSION_RMSE,group);
S.motionAuthorizationRate=splitapply(@omitMean,T.motionAuthorized,group);
S.reactivationRate=splitapply(@omitMean,T.allReactivated,group);
S.meanFinalSuppressed=splitapply(@omitMean,T.finalSuppressedCount,group);
S.meanMissionRmse=splitapply(@omitMean,T.MISSION_RMSE,group);
S.meanFormationRmse=splitapply(@omitMean,T.RMSE,group);
S.minimumSeparation=splitapply(@min,T.MINSEP,group);
S.safeFailures=splitapply(@sum,T.SAFEFAIL,group);
S.maximumCapsuleRatio=splitapply(@omitMax,T.capsuleMaximumRatio,group);
S.physicalSubsetRate=splitapply(@omitMean,T.actualPhysicalSubset,group);
S.senderSubsetRate=splitapply(@omitMean,T.actualSenderSubset,group);
S.meanControlBytes=splitapply(@omitMean,T.controlBytes,group);
S.meanDataAirtime=splitapply(@omitMean,T.DATA_AIRTIME,group);
S.meanManagementAirtime=splitapply(@omitMean,T.MANAGEMENT_AIRTIME,group);
S.meanTotalCost=splitapply(@omitMean,T.TOTAL_COST,group);

end


function P=pairedContrasts(T,R)

pairs={ ...
    'response_no_emergency_minus_protected', ...
    'closure-response-blackout-no-emergency', ...
    'closure-response-blackout-emergency'; ...
    'normal_closure_minus_periodic', ...
    'closure-iid20-emergency','periodic-iid20'};
P=table();
for pairIndex=1:size(pairs,1)
    label=string(pairs{pairIndex,1}); a=pairs{pairIndex,2};
    b=pairs{pairIndex,3}; n=numel(R.seeds);
    block=table(R.seeds,repmat(label,n,1), ...
        armValues(T,R,a,'MISSION_RMSE')-armValues(T,R,b,'MISSION_RMSE'), ...
        armValues(T,R,a,'MINSEP')-armValues(T,R,b,'MINSEP'), ...
        armValues(T,R,a,'TOTAL_COST')-armValues(T,R,b,'TOTAL_COST'), ...
        armValues(T,R,a,'DATA_AIRTIME')-armValues(T,R,b,'DATA_AIRTIME'), ...
        'VariableNames',{'seed','contrast','deltaMissionRmse', ...
        'deltaMinimumSeparation','deltaTotalCost','deltaDataAirtime'});
    P=[P;block]; %#ok<AGROW>
end

end


function S=pairedSummary(P)

[group,S]=findgroups(P(:,{'contrast'}));
S.nPairs=splitapply(@numel,P.seed,group);
S.meanDeltaMissionRmse=splitapply(@mean,P.deltaMissionRmse,group);
S.minimumDeltaMissionRmse=splitapply(@min,P.deltaMissionRmse,group);
S.maximumDeltaMissionRmse=splitapply(@max,P.deltaMissionRmse,group);
S.meanDeltaMinimumSeparation=splitapply( ...
    @mean,P.deltaMinimumSeparation,group);
S.meanDeltaTotalCost=splitapply(@mean,P.deltaTotalCost,group);
S.meanDeltaDataAirtime=splitapply(@mean,P.deltaDataAirtime,group);

end


function value=omitMean(x)
value=mean(x,'omitnan');
end


function value=omitMax(x)
if all(isnan(x)), value=NaN; else, value=max(x,[],'omitnan'); end
end


function runRequiredTests()

