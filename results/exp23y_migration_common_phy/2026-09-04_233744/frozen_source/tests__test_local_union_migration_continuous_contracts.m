% TEST_LOCAL_UNION_MIGRATION_CONTINUOUS_CONTRACTS Common-PHY mapping.
startup;
fprintf('\n============================================================\n');
fprintf('test_local_union_migration_continuous_contracts\n');
fprintf('============================================================\n\n');

[M,C,T,P]=fixture(); checks=0;
Q=buildLocalUnionMigrationContinuousSchedule(M,C,T,P);
assert(Q.expectedManagementAttempts==Q.kernel.controlAttempts && ...
    sum(Q.controlAttemptBytes)==Q.kernel.controlBytes && ...
    abs(Q.expectedManagementAirtime-Q.kernel.controlAirtimeSec)<1e-12 && ...
    Q.expectedDataCollisionFrames==0);
fprintf('    ok   kernel attempts, bytes, airtime and collisions map exactly\n');
checks=checks+1;

assert(nnz(Q.controlKind=="revoke")==1 && ...
    nnz(Q.controlKind=="claim")==Q.kernel.claimAttempts && ...
    nnz(Q.controlKind=="lock-proof")==Q.kernel.lockProofAttempts && ...
    nnz(Q.controlKind=="response")==Q.kernel.responseAttempts && ...
    all(Q.controlAttemptBytes(Q.controlKind=="revoke")==24) && ...
    all(Q.controlAttemptBytes(Q.controlKind=="claim")==28) && ...
    all(Q.controlAttemptBytes(Q.controlKind=="lock-proof")==28));
fprintf('    ok   REVOKE, CLAIM, LOCK-PROOF and RESPONSE payloads are explicit\n');
checks=checks+1;

after=Q.controlKind=="lock-proof" & ...
    Q.controlFrame>Q.kernel.firstReacquiredFrame;
assert(any(after) && numel(unique(Q.controlFrame(after)))>0);
fprintf('    ok   fixed proof window remains independent after reactivation\n');
checks=checks+1;

node=M.transitionNode; before=Q.dataNode==node & ...
    Q.dataFrame<C.transitionFrame; during=Q.dataNode==node & ...
    Q.dataFrame>=C.transitionFrame & ...
    Q.dataFrame<Q.kernel.firstReacquiredFrame; after=Q.dataNode==node & ...
    Q.dataFrame>=Q.kernel.firstReacquiredFrame;
assert(all(Q.dataSlot(before)==M.oldSlot(node)) && ~any(during) && ...
    all(Q.dataSlot(after)==M.newSlot));
fprintf('    ok   DATA switches old-slot to silence to certified new-slot\n');
checks=checks+1;

N=M.N; stream=RandStream('mt19937ar','Seed',90331);
offset=(2*rand(stream,N,1)-1)*0.25e-3;
drift=(2*rand(stream,N,1)-1)*40;
B=continuousTdmaGuardBound(0.25e-3,40,30);
spec=struct('clockOffsetSec',offset,'clockDriftPpm',drift, ...
    'maxOffsetSec',0.25e-3,'maxDriftPpm',40,'leadTimeSec',0.01, ...
    'safeGuardSec',B.safeGuardSec);
A=applyDstrAffineClockSchedule(Q,spec);
assert(A.clockTimingConflictFree && A.clockEquationMaxResidualSec<1e-12 && ...
    sum(A.controlAttemptBytes)==sum(Q.controlAttemptBytes) && ...
    numel(A.dataStartTime)==numel(Q.dataStartTime));
fprintf('    ok   affine-clock guard preserves every logical opportunity\n');
checks=checks+1;

outside=T; outside.actualGraph(C.newGraphActivationFrame:end,1,3)=true;
outside.actualGraph(C.newGraphActivationFrame:end,3,1)=true;
outside.hashExact=localUnionMigrationTraceHash(outside);
X=buildLocalUnionMigrationContinuousSchedule(M,C,outside,P);
XA=applyDstrAffineClockSchedule(X,spec);
collisionFrames=numel(unique( ...
    XA.dataFrame(any(XA.dataCollisionMask,2))));
assert(collisionFrames==X.kernel.scheduledCollisionFrames && ...
    XA.expectedDataCollisionFrames==2*collisionFrames);
fprintf('    ok   collision frames remain distinct from colliding attempts\n');
checks=checks+1;

fprintf('\ntest_local_union_migration_continuous_contracts: PASS (%d checks)\n', ...
    checks);


function [M,C,T,P]=fixture()

N=5; node=5; G0=false(N);
for k=1:N-1, G0(k,k+1)=true; G0(k+1,k)=true; end
G1=G0; G1(4,5)=false; G1(5,4)=false;
G1(3,5)=true; G1(5,3)=true;
slot=elcsWitnessPriorityColor(G0); reach=true(N); reach(1:N+1:end)=false;
packet=struct('maxDataSlots',N,'claimBytes',28, ...
    'certificateHeaderBytes',16,'certificateEntryBytes',10, ...
    'maxControlPacketBytes',96,'revokeBytes',24);
M=buildLocalUnionGraphMigration(G0,G1,slot,node,reach,packet);
C=struct('maxFrames',30,'transitionFrame',8,'eligibleFrame',12, ...
    'newGraphActivationFrame',9,'lockProofRepeatFrames',12, ...
    'phyRateBps',250e3,'claimErasureProbability',0.2, ...
    'lockProofErasureProbability',0.2,'responseErasureProbability',0.2, ...
    'revokeErasureProbability',0.2);
T=generateLocalUnionMigrationTrace(16085000,M,C);
B=continuousTdmaGuardBound(0.25e-3,40,30);
controlSlot=8*packet.maxControlPacketBytes/C.phyRateBps+B.safeGuardSec;
dataSlot=8*64/C.phyRateBps+B.safeGuardSec;
frameDuration=2*N*controlSlot+N*dataSlot;
P=struct('guardSec',B.safeGuardSec,'dataBytes',64, ...
    'horizonSec',C.maxFrames*frameDuration+0.1);

end
