function B=buildReachableBroadcastConflictSupergraph( ...
    state,horizonSec,interferenceRadius,dataNeighborGraph,mandatoryConflictGraph)
%BUILDREACHABLEBROADCASTCONFLICTSUPERGRAPH Lift tubes to sender conflicts.
%
% dataNeighborGraph(receiver,sender) declares intended DATA recipients.
% The physical potential-interference graph comes from reachable tubes.
% Sender conflicts are then computed at every intended receiver, including
% hidden-terminal conflicts between transmitters that are not close enough
% to decode one another.

N=size(state.p,1);
if ~isequal(size(dataNeighborGraph),[N N])
    error('buildReachableBroadcastConflictSupergraph: invalid neighbor graph.');
end
neighbor=logical(dataNeighborGraph);
neighbor(1:N+1:end)=false;
if nargin<5 || isempty(mandatoryConflictGraph)
    mandatoryConflictGraph=false(N);
end
if ~isequal(size(mandatoryConflictGraph),[N N]) || ...
        any(diag(mandatoryConflictGraph)) || ...
        ~isequal(logical(mandatoryConflictGraph), ...
        logical(mandatoryConflictGraph)')
    error(['buildReachableBroadcastConflictSupergraph: invalid ' ...
        'mandatory conflict graph.']);
end

P=buildReachableConflictSupergraph( ...
    state,horizonSec,interferenceRadius,false(N));
conflict=buildSenderConflictGraph(neighbor,P.potentialGraph) | ...
    logical(mandatoryConflictGraph);
conflict(1:N+1:end)=false;
B=struct('version','REACHABLE-BROADCAST-CONFLICT-SUPERGRAPH-v1', ...
    'N',N,'horizonSec',horizonSec, ...
    'interferenceRadius',interferenceRadius, ...
    'dataNeighborGraph',neighbor, ...
    'potentialInterferenceGraph',P.potentialGraph, ...
    'senderConflictGraph',conflict, ...
    'potentialGraph',conflict, ...
    'mandatoryConflictGraph',logical(mandatoryConflictGraph), ...
    'physicalGeometry',P,'physicalEdgeCount',P.edgeCount, ...
    'edgeCount',nnz(triu(conflict,1)), ...
    'hashExact',realizationHash([P.hashExact;double(neighbor(:)); ...
    double(mandatoryConflictGraph(:));double(conflict(:))]));

end
