function [reach,edgeCount,diameter,hash]=topologyFixture(N)

cfg=applyTopologyConfig(defaultConfig(),N,'ring2');
reach=logical(cfg.swarm.A);
reach(logical(cfg.swarm.pin(:)),1)=true;
reach=reach|reach'; reach(1:N+1:end)=false;
D=distances(graph(reach)); finite=D(isfinite(D));
edgeCount=nnz(triu(reach,1)); diameter=max(finite);
hash=realizationHash([N;double(reach(:));double(cfg.swarm.pin(:))]);

end


function interference=interferenceFixture(N,mode)

switch char(mode)
    case 'spatial-reuse-lower-bound'
        interference=false(N);
    case 'complete-interference-upper-bound'
        interference=~eye(N);
    otherwise
        error('exp23aj: unknown interference mode.');
end

end


function [parentUnique,causalSlotOrder]=planInvariants(P)

nodes=find(P.activeNodeMask); nodes(nodes==P.source)=[];
parentUnique=double(all(P.parent(nodes)>0)&all( ...
    sum(P.children(nodes,:),2)==1));
causal=true;
for receiver=nodes'
    if P.transmitterMask(receiver)
        causal=causal&&P.transmitterSlot(P.parent(receiver))< ...
            P.transmitterSlot(receiver);
    end
end
causalSlotOrder=double(causal);

end


function [attempts,B]=dimensionWholeFlood(P,p,target)

for candidate=1:100
    C=slottedManagementFloodReliabilityCertificate(P,p,candidate);
    if C.multicastFailureUnionUpperBound<target
        attempts=candidate; B=C; return;
    end
end
error('exp23aj: whole-flood comparator cannot meet target.');

end


function packets=semanticPackets(M)

packets=struct('kind',{},'sender',{},'bytes',{}); q=0;
append('prepare',M.initiator,M.prepareBytes);
for sender=reshape(M.affectedNodes,1,[])
    if sender~=M.initiator
        append('quiescent',sender,M.config.quietBytes);
    end
    append('claim',sender,M.config.claimBytes);
end
affected=logical(M.affectedMask);
outside=unique([M.incidentEdgeA(~affected(M.incidentEdgeA)); ...
    M.incidentEdgeB(~affected(M.incidentEdgeB))]);
for sender=reshape(outside,1,[])
    append('lock-proof',sender,M.config.lockProofBytes);
end
for sender=reshape(unique(M.incidentEdgeWitness),1,[])
    packetBytes=M.config.certificateHeaderBytes+ ...
        nnz(M.incidentEdgeWitness==sender)*M.config.certificateEntryBytes;
    append('response',sender,packetBytes);
end
append('commit',M.initiator,M.config.commitBytes);

    function append(kind,sender,bytes)
        q=q+1; packets(q)=struct('kind',kind,'sender',sender,'bytes',bytes);
    end
end


function expected=expectedSemanticRecipients(M,kind,sender)

expected=false(M.N,1); kind=lower(strrep(char(kind),'_','-'));
switch kind
    case {'prepare','commit'}
        expected(M.affectedNodes)=true;
    case {'quiet','quiescent','response'}
        expected(M.initiator)=true;
    case {'claim','lock-proof','lockproof'}
        edge=M.incidentEdgeA==sender|M.incidentEdgeB==sender;
        expected(unique(M.incidentEdgeWitness(edge)))=true;
    case 'revoke'
        expected=logical(M.oldGraph(:,sender));
    otherwise
