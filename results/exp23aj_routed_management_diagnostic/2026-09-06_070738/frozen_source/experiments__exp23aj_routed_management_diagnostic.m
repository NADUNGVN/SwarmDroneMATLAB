function exp23aj_routed_management_diagnostic()
%EXP23AJ_ROUTED_MANAGEMENT_DIAGNOSTIC Physical multi-hop primitive audit.

startup; close all; runRequiredTests();
R=exp23ajRoutedManagementRegistry();
[registryHash,registryLeaves]=configHash(R);
expRun=startExperiment('exp23aj_routed_management_diagnostic', ...
    ['Frozen routed-management primitive, reliability, accounting, and ' ...
    'semantic-multicast diagnostic.']);
writeJson(fullfile(expRun.dir,'routed_management_registry.json'),R);
snapshotSource(expRun.dir);

S=structuralRoutes(R);
writetable(S,fullfile(expRun.dir,'structural_routes.csv'));
M=monteCarloRoutes(S,R);
writetable(M,fullfile(expRun.dir,'monte_carlo_replay.csv'));
E=semanticRoutes(R);
writetable(E,fullfile(expRun.dir,'semantic_routes.csv'));
gates=validationGates(S,M,E,R,registryHash,registryLeaves);
writetable(gates,fullfile(expRun.dir,'validation_gates.csv'));

valid=all(gates.passed==1);
status=ternary(valid,'ROUTED_MANAGEMENT_PRIMITIVE_DIAGNOSTIC_VALID', ...
    'ROUTED_MANAGEMENT_PRIMITIVE_DIAGNOSTIC_INVALID');
next=ternary(valid,'multi_origin_common_phy_routing_integration', ...
    'repair_routing_primitive_without_relaxing_registered_gates');
verdict=struct('status',status,'gatesPassed',sum(gates.passed), ...
    'gatesTotal',height(gates),'structuralRows',height(S), ...
    'monteCarloRows',height(M),'semanticRows',height(E), ...
    'routingPrimitiveValidated',valid, ...
    'semanticMulticastDiagnosticValidated',valid, ...
    'closedLoopManagementRelayingValidated',false, ...
    'managementRelayingValidated',false, ...
    'repeatedOnlineRenewalValidated',false, ...
    'freshSeedEvidence',false,'robustnessClaimPermitted',false, ...
    'submissionClaimPermitted',false,'next',next);
writeJson(fullfile(expRun.dir,'routed_management_verdict.json'),verdict);
save(fullfile(expRun.dir,'workspace.mat'),'S','M','E','gates', ...
    'verdict','R');

fprintf('\nEXP23AJ routed-management gates\n');
for k=1:height(gates)
    fprintf('  [%-4s] %-46s %s\n', ...
        ternary(gates.passed(k)==1,'PASS','FAIL'), ...
        char(gates.gate(k)),char(gates.detail(k)));
end
fprintf('\nStructural worst cases by size and interference\n');
disp(groupsummary(S,{'N','interferenceMode'},'max', ...
    {'maximumRecipientDepth','maximumPhysicalAttempts', ...
    'reservedSlotCount','reservedDurationSec'}));
disp(M); 
fprintf('EXP23AJ DECISION: %s\n',status);
finishExperiment(expRun);
if ~valid
    error('exp23aj: routed-management diagnostic invalid.');
end

end


function T=structuralRoutes(R)

rows=repmat(structuralEmptyRow(),R.expectedStructuralRows,1); q=0;
for N=R.swarmSizes
    [reach,directEdges,diameter,topologyHash]=topologyFixture(N);
    for modeIndex=1:numel(R.interferenceModes)
        mode=R.interferenceModes{modeIndex};
        interference=interferenceFixture(N,mode);
        for source=1:N
            recipients=setdiff(1:N,source);
            P=buildSlottedManagementFloodPlan(reach,interference, ...
                source,recipients,R.maxHopsFactor*(N-1));
            [parentUnique,causalSlotOrder]=planInvariants(P);
            for p=R.linkErasureProbability
                q=q+1; row=structuralEmptyRow();
                D=dimensionRepeatedHopManagementFlood(P,p, ...
                    R.maximumLogicalPacketFailure, ...
                    R.maxRepetitionsPerHop);
                B=D.certificate;
                [wholeAttempts,whole]=dimensionWholeFlood(P,p, ...
                    R.maximumLogicalPacketFailure);
                repetitions=D.selectedRepetitions;
                U=ones(N,N,repetitions);
                O=simulateRepeatedHopManagementFlood(P,U,p,repetitions, ...
                    R.maximumPacketBytes,R.phyRateBps,R.safeGuardSec);
                failedU=U;
                sourceChildren=find(P.children(:,source));
                failedU(sourceChildren,source,:)=0;
                F=simulateRepeatedHopManagementFlood(P,failedU,p, ...
                    repetitions,R.maximumPacketBytes,R.phyRateBps, ...
                    R.safeGuardSec);
                previousFailure=1;
                if repetitions>1
                    previous=repeatedHopManagementFloodReliabilityCertificate( ...
                        P,p,repetitions-1);
                    previousFailure=previous.multicastFailureExact;
                end

                row.N=N; row.interferenceMode=string(mode);
                row.source=source; row.directEdgeCount=directEdges;
                row.directGraphDiameter=diameter;
                row.topologyHash=topologyHash; row.planHash=P.hashExact;
                row.routeAdmissible=P.admissible;
                row.unreachableRecipientCount=P.unreachableRecipientCount;
                row.treeEdgeCount=P.treeEdgeCount;
                row.maximumRecipientDepth=P.maximumRecipientDepth;
                row.plannedTransmitterCount=P.plannedTransmitterCount;
                row.baseReservedSlotCount=P.reservedSlotCount;
                row.parentUnique=parentUnique;
                row.slotColoringProper=P.slotColoringProper;
                row.causalSlotOrder=causalSlotOrder;
                row.linkErasureProbability=p;
                row.selectedRepetitions=repetitions;
                row.previousRepetitionFailure=previousFailure;
                row.edgeFailureProbability=B.edgeFailureProbability;
                row.minimumRecipientDelivery=min( ...
                    B.recipientDeliveryProbability);
                row.multicastFailureExact=B.multicastFailureExact;
                row.multicastFailureUnionUpperBound= ...
                    B.multicastFailureUnionUpperBound;
                row.maximumPhysicalAttempts=B.maximumPhysicalAttemptBound;
                row.maximumPhysicalBytes=B.maximumPhysicalAttemptBound* ...
                    R.maximumPacketBytes;
                row.reservedSlotCount=B.reservedSlotCount;
                row.reservedDurationSec=B.reservedSlotCount*( ...
                    8*R.maximumPacketBytes/R.phyRateBps+R.safeGuardSec);
                row.wholeFloodAttempts=wholeAttempts;
                row.wholeFloodFailure=whole.multicastFailureUnionUpperBound;
                row.wholeFloodMaximumPhysicalAttempts= ...
                    whole.maximumPhysicalAttemptBound;
                row.wholeFloodReservedSlotCount= ...
                    wholeAttempts*P.reservedSlotCount;
                row.hopLocalSlotSavings=row.wholeFloodReservedSlotCount- ...
                    row.reservedSlotCount;
                row.logicalCliqueAttemptUndercountFactor= ...
                    B.maximumPhysicalAttemptBound;
                row.noLossAllRecipientsDelivered=O.allRecipientsDelivered;
                row.replayAttempts=O.attempts; row.replayBytes=O.bytes;
                row.replayOfferedAirtimeSec=O.offeredAirtimeSec;
                row.replayReservedDurationSec=O.reservedDurationSec;
                row.replayCollisionRecipients=O.collisionRecipients;
                row.replayDuplicateForwards=O.duplicateForwardCount;
                row.replayFutureRandomReads=O.futureRandomReads;
                row.replayReceiverTruthReads=O.receiverTruthDecisionReads;
                row.integerAccountingExact=double(O.attempts== ...
                    B.maximumPhysicalAttemptBound&&O.bytes== ...
                    B.maximumPhysicalAttemptBound*R.maximumPacketBytes);
                row.airtimeAccountingExact=double( ...
                    O.offeredAirtimeSec==8*O.bytes/R.phyRateBps&& ...
                    O.reservedDurationSec==row.reservedDurationSec);
                row.upstreamErasureCausalSilence=double( ...
                    ~F.allRecipientsDelivered&&nnz(F.knownMask)==1&& ...
                    F.attempts==repetitions&& ...
                    F.linkRandomReads==numel(sourceChildren)*repetitions);
                row.failedReplayAttempts=F.attempts;
                rows(q)=row;
            end
        end
        fprintf('  structural N=%d, %-35s complete\n',N,mode);
    end
end
if q~=R.expectedStructuralRows
    error('exp23aj: structural row count mismatch.');
end
T=struct2table(rows);

end


function T=monteCarloRoutes(S,R)

rows=repmat(monteCarloEmptyRow(),R.expectedMonteCarloRows,1); q=0;
for N=R.swarmSizes
    [reach,~,~,~]=topologyFixture(N);
    for modeIndex=1:numel(R.interferenceModes)
        q=q+1; mode=R.interferenceModes{modeIndex};
        cellRows=S(S.N==N&string(S.interferenceMode)==string(mode)& ...
            abs(S.linkErasureProbability-R.monteCarloLoss)<1e-15,:);
        score=[cellRows.reservedSlotCount, ...
            cellRows.maximumPhysicalAttempts, ...
            cellRows.maximumRecipientDepth,cellRows.source];
        [~,order]=sortrows(score,[-1 -2 -3 4]);
        source=cellRows.source(order(1));
        interference=interferenceFixture(N,mode);
        P=buildSlottedManagementFloodPlan(reach,interference,source, ...
            setdiff(1:N,source),N-1);
        B=repeatedHopManagementFloodReliabilityCertificate(P, ...
            R.monteCarloLoss,R.monteCarloRepetitionsPerHop);
        stream=RandStream('mt19937ar','Seed',R.monteCarloSeeds(q));
        failures=0; attempts=0; maximumAttempts=0; collisions=0;
        duplicates=0; forbiddenReads=0;
        for trial=1:R.monteCarloTrials
            U=rand(stream,N,N,R.monteCarloRepetitionsPerHop);
            O=simulateRepeatedHopManagementFlood(P,U, ...
                R.monteCarloLoss,R.monteCarloRepetitionsPerHop, ...
                R.maximumPacketBytes,R.phyRateBps,R.safeGuardSec);
            failures=failures+~O.allRecipientsDelivered;
            attempts=attempts+O.attempts;
            maximumAttempts=max(maximumAttempts,O.attempts);
            collisions=collisions+O.collisionRecipients;
            duplicates=duplicates+O.duplicateForwardCount;
            forbiddenReads=forbiddenReads+O.futureRandomReads+ ...
                O.receiverTruthDecisionReads;
        end
        empirical=failures/R.monteCarloTrials;
        tolerance=R.monteCarloStandardErrorMultiplier*sqrt( ...
            B.multicastFailureExact*(1-B.multicastFailureExact)/ ...
            R.monteCarloTrials)+1/R.monteCarloTrials;
        row=monteCarloEmptyRow();
        row.N=N; row.interferenceMode=string(mode); row.source=source;
        row.seed=R.monteCarloSeeds(q); row.planHash=P.hashExact;
        row.trials=R.monteCarloTrials; row.failures=failures;
        row.linkErasureProbability=R.monteCarloLoss;
        row.repetitionsPerHop=R.monteCarloRepetitionsPerHop;
        row.failureProbabilityExact=B.multicastFailureExact;
        row.failureProbabilityEmpirical=empirical;
        row.absoluteError=abs(empirical-B.multicastFailureExact);
        row.registeredTolerance=tolerance;
        row.probabilityAgreement=double(row.absoluteError<=tolerance);
        row.meanPhysicalAttempts=attempts/R.monteCarloTrials;
        row.maximumObservedAttempts=maximumAttempts;
        row.analyticalAttemptBound=B.maximumPhysicalAttemptBound;
        row.attemptBoundSatisfied=double(maximumAttempts<= ...
            B.maximumPhysicalAttemptBound);
        row.collisionRecipients=collisions;
        row.duplicateForwards=duplicates;
        row.forbiddenReads=forbiddenReads;
        rows(q)=row;
        fprintf(['  Monte Carlo N=%d, %-35s source=%d: ' ...
            '%d/%d failures\n'],N,mode,source,failures,R.monteCarloTrials);
    end
end
T=struct2table(rows);

end


function T=semanticRoutes(R)

PARENT=exp23aiIntegerAccountingRegistry();
[~,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,PARENT);
migration=context.geometry.migration;
reach=logical(context.neighborGraph);
interference=context.geometry.oldPhysicalGraph| ...
    context.geometry.proposedPhysicalGraph;
packets=semanticPackets(migration);
rows=repmat(semanticEmptyRow(),numel(packets),1);
for k=1:numel(packets)
    packet=packets(k); row=semanticEmptyRow();
    recipients=receiverLiftedClosureControlRecipients( ...
        migration,packet.kind,packet.sender);
    expected=expectedSemanticRecipients(migration,packet.kind,packet.sender);
    row.kind=string(packet.kind); row.sender=packet.sender;
    row.packetBytes=packet.bytes; row.recipientCount=nnz(recipients);
    row.recipientHash=realizationHash(double(recipients));
    row.recipientContractExact=double(isequal(recipients,expected));
    row.selfOnly=double(~any(recipients));
    if ~any(recipients)
        row.routeAdmissible=1; row.minimumRepetitionExact=1;
        row.multicastFailureExact=0; row.allRecipientsDelivered=1;
        row.accountingExact=1; row.semanticNoWorseThanAllNodes=1;
        rows(k)=row; continue;
    end

    plan=buildSlottedManagementFloodPlan(reach,interference, ...
        packet.sender,recipients,migration.N-1);
    D=dimensionRepeatedHopManagementFlood(plan,R.monteCarloLoss, ...
        R.maximumLogicalPacketFailure,R.maxRepetitionsPerHop);
    full=buildSlottedManagementFloodPlan(reach,interference, ...
        packet.sender,setdiff(1:migration.N,packet.sender),migration.N-1);
    fullD=dimensionRepeatedHopManagementFlood(full,R.monteCarloLoss, ...
        R.maximumLogicalPacketFailure,R.maxRepetitionsPerHop);
    repetitions=D.selectedRepetitions; B=D.certificate;
    O=simulateRepeatedHopManagementFlood(plan, ...
        ones(migration.N,migration.N,repetitions),R.monteCarloLoss, ...
        repetitions,packet.bytes,R.phyRateBps,R.safeGuardSec);
    previousFailure=1;
    if repetitions>1
        previous=repeatedHopManagementFloodReliabilityCertificate( ...
            plan,R.monteCarloLoss,repetitions-1);
        previousFailure=previous.multicastFailureExact;
    end
    row.routeAdmissible=plan.admissible;
    row.planHash=plan.hashExact; row.treeEdgeCount=plan.treeEdgeCount;
    row.maximumRecipientDepth=plan.maximumRecipientDepth;
    row.plannedTransmitterCount=plan.plannedTransmitterCount;
    row.baseReservedSlotCount=plan.reservedSlotCount;
    row.selectedRepetitions=repetitions;
    row.minimumRepetitionExact=double(previousFailure>= ...
        R.maximumLogicalPacketFailure);
    row.multicastFailureExact=B.multicastFailureExact;
    row.maximumPhysicalAttempts=B.maximumPhysicalAttemptBound;
    row.maximumPhysicalBytes=B.maximumPhysicalAttemptBound*packet.bytes;
    row.reservedSlotCount=B.reservedSlotCount;
    row.reservedDurationSec=B.reservedSlotCount*( ...
        8*packet.bytes/R.phyRateBps+R.safeGuardSec);
    row.observedAttempts=O.attempts; row.observedBytes=O.bytes;
    row.observedAirtimeSec=O.offeredAirtimeSec;
    row.allRecipientsDelivered=O.allRecipientsDelivered;
    row.collisionRecipients=O.collisionRecipients;
    row.duplicateForwards=O.duplicateForwardCount;
    row.forbiddenReads=O.futureRandomReads+O.receiverTruthDecisionReads;
    row.accountingExact=double(O.attempts== ...
        B.maximumPhysicalAttemptBound&&O.bytes== ...
        B.maximumPhysicalAttemptBound*packet.bytes&& ...
        O.offeredAirtimeSec==8*O.bytes/R.phyRateBps);
    row.allNodeMaximumPhysicalAttempts= ...
        fullD.certificate.maximumPhysicalAttemptBound;
    row.allNodeReservedSlotCount=fullD.certificate.reservedSlotCount;
    row.savedPhysicalAttempts=row.allNodeMaximumPhysicalAttempts- ...
        row.maximumPhysicalAttempts;
    row.savedReservedSlots=row.allNodeReservedSlotCount- ...
        row.reservedSlotCount;
    row.semanticNoWorseThanAllNodes=double( ...
        row.savedPhysicalAttempts>=0&&row.savedReservedSlots>=0);
    row.logicalCliqueAttemptUndercountFactor=row.maximumPhysicalAttempts;
    rows(k)=row;
end
if numel(rows)~=R.expectedSemanticRows
    error('exp23aj: semantic row count differs from registry.');
end
T=struct2table(rows);

end


