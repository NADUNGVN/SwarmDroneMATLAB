function O=simulateRepeatedHopManagementFlood( ...
    plan,linkUniform,erasureProbability,repetitionsPerHop, ...
    packetBytes,phyRateBps,guardSec)
%SIMULATEREPEATEDHOPMANAGEMENTFLOOD Causal repeated-hop tree replay.
%
% linkUniform(receiver,sender,repetition) supplies the independent link
% draw for one reserved repetition.  A relay transmits in all repetitions
% of its assigned base slot iff it knew the packet at the start of that
% base slot.  Therefore an erased upstream hop suppresses every causal
% descendant, and no future link draw can enable a relay prematurely.

required={'N','source','children','transmitterSlot','depth', ...
    'senderConflictGraph','recipientMask','reservedSlotCount', ...
    'plannedTransmitterCount','slotColoringProper','admissible','hashExact'};
if ~isstruct(plan)||~isscalar(plan)||~all(isfield(plan,required))|| ...
        ~plan.admissible||~plan.slotColoringProper
    error('simulateRepeatedHopManagementFlood: admissible plan required.');
end
N=plan.N; U=double(linkUniform);
if repetitionsPerHop==1&&isequal(size(U),[N N])
    U=reshape(U,N,N,1);
end
if ~isequal(size(U),[N N repetitionsPerHop])|| ...
        any(~isfinite(U),'all')||any(U<0|U>1,'all')|| ...
        ~isscalar(erasureProbability)||~isfinite(erasureProbability)|| ...
        erasureProbability<0||erasureProbability>1|| ...
        ~isscalar(repetitionsPerHop)||~isfinite(repetitionsPerHop)|| ...
        repetitionsPerHop<1||repetitionsPerHop~=floor(repetitionsPerHop)|| ...
        ~isscalar(packetBytes)||~isfinite(packetBytes)||packetBytes<1|| ...
        packetBytes~=floor(packetBytes)||~isscalar(phyRateBps)|| ...
        ~isfinite(phyRateBps)||phyRateBps<=0||~isscalar(guardSec)|| ...
        ~isfinite(guardSec)||guardSec<0
    error('simulateRepeatedHopManagementFlood: invalid physical input.');
end

totalSlots=plan.reservedSlotCount*repetitionsPerHop;
known=false(N,1); known(plan.source)=true;
transmitted=false(N,1); receivedSlot=nan(N,1); receivedSlot(plan.source)=0;
attempts=0; bytes=0; offeredAirtime=0; busySlots=0;
linkReads=0; collisionRecipients=0; successfulLinks=0; erasedLinks=0;
slotTx=false(totalSlots,N); slotDelivery=false(totalSlots,N);
for baseSlot=1:plan.reservedSlotCount
    scheduled=find(plan.transmitterSlot==baseSlot);
    active=scheduled(known(scheduled));
    for repetition=1:repetitionsPerHop
        slotIndex=(baseSlot-1)*repetitionsPerHop+repetition;
        slotTx(slotIndex,active)=true;
        if isempty(active), continue; end
        busySlots=busySlots+1; attempts=attempts+numel(active);
        bytes=bytes+numel(active)*packetBytes;
        offeredAirtime=offeredAirtime+ ...
            numel(active)*8*packetBytes/phyRateBps;
        transmitted(active)=true;
        newKnown=false(N,1);
        for sender=reshape(active,1,[])
            children=find(plan.children(:,sender));
            for receiver=reshape(children,1,[])
                interferers=active(active~=sender& ...
                    plan.senderConflictGraph(active,sender));
                collision=~isempty(interferers);
                if collision
                    collisionRecipients=collisionRecipients+1;
                    continue;
                end
                linkReads=linkReads+1;
                if U(receiver,sender,repetition)>erasureProbability
                    successfulLinks=successfulLinks+1;
                    if ~known(receiver)&&~newKnown(receiver)
                        receivedSlot(receiver)=slotIndex;
                        slotDelivery(slotIndex,receiver)=true;
                    end
                    newKnown(receiver)=true;
                else
                    erasedLinks=erasedLinks+1;
                end
            end
        end
        known=known|newKnown;
    end
end

delivery=known&plan.recipientMask;
packetAirtime=8*packetBytes/phyRateBps;
O=struct('version','REPEATED-HOP-MANAGEMENT-FLOOD-REPLAY-v1', ...
    'planHash',plan.hashExact,'repetitionsPerHop',repetitionsPerHop, ...
    'deliveryMask',delivery, ...
    'allRecipientsDelivered',double(all(known(plan.recipientMask))), ...
    'knownMask',known,'transmittedMask',transmitted, ...
    'receivedSlot',receivedSlot,'attempts',attempts,'bytes',bytes, ...
    'packetAirtimeSec',packetAirtime,'offeredAirtimeSec',offeredAirtime, ...
    'channelBusyAirtimeSec',busySlots*packetAirtime, ...
    'reservedDurationSec',totalSlots*(packetAirtime+guardSec), ...
    'busySlots',busySlots,'plannedAttemptBound', ...
    repetitionsPerHop*plan.plannedTransmitterCount, ...
    'attemptBoundSatisfied',double(attempts<= ...
    repetitionsPerHop*plan.plannedTransmitterCount), ...
    'successfulLinks',successfulLinks,'erasedLinks',erasedLinks, ...
    'collisionRecipients',collisionRecipients,'linkRandomReads',linkReads, ...
    'duplicateForwardCount',0,'futureRandomReads',0, ...
    'receiverTruthDecisionReads',0,'slotTransmissionMask',slotTx, ...
    'slotDeliveryMask',slotDelivery, ...
    'hashExact',realizationHash([plan.hashExact;U(:); ...
    erasureProbability;repetitionsPerHop;packetBytes;phyRateBps;guardSec; ...
    double(known);double(transmitted);replaceNaN(receivedSlot,-1); ...
    attempts;bytes;collisionRecipients;linkReads;double(slotTx(:)); ...
    double(slotDelivery(:))]));

end


function value=replaceNaN(value,replacement)
value(isnan(value))=replacement;
end
