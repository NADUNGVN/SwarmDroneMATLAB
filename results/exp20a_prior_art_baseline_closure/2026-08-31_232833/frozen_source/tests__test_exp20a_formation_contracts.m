%% TEST_EXP20A_FORMATION_CONTRACTS Prior-art projection and accounting gates.

startup;
fprintf('\n============================================================\n');
fprintf('test_exp20a_formation_contracts\n');
fprintf('============================================================\n\n');

R=exp20aRegistry();
checks=cell(0,2);
checks(end+1,:)={R.expectedFormationRuns==2520 && ...
    R.expectedNativeRuns==1800, ...
    'frozen registry contains 2520 formation and 1800 native runs'};
checks(end+1,:)={numel(unique(R.formationSeeds))==30 && ...
    numel(unique(R.nativeSeeds))==30 && ...
    isempty(intersect(R.formationSeeds,R.nativeSeeds)), ...
    'panel seed blocks are unique and disjoint'};

base=applyExp20ACell(R.cells(1).id,R.formationSeeds(1));
base.swarm.T=0.4;
trace=generateSharedMediumTrace(base);
ids={'dtsa-common-view','dtsa-private-view','chen-age-gain-private', ...
    'zmac-like-hybrid','delta-public-projection', ...
    'delta-private-projection'};
rows=repmat(exp20aFormationEmptyRow(),numel(ids),1);
for k=1:numel(ids)
    arm=R.formationArms(strcmp({R.formationArms.id},ids{k}));
    [cfg,method,label,details]=applyExp20AArm(base,arm);
    meta=struct('stage','contract-smoke','scenario',R.cells(1).id, ...
        'scenarioLabel',R.cells(1).label,'family','EXP20A contract', ...
        'arm',arm.id,'pointIndex',k,'parameterValue',arm.periodicRateHz);
    rows(k)=runExp20AFormationCell( ...
        cfg,method,label,meta,trace,details);
end
T=struct2table(rows);

checks(end+1,:)={numel(unique(T.TRACE_HASH_EXACT))==1 && ...
    numel(unique(T.CHANNEL_STATE_HASH))==1, ...
    'all prior-art arms use one paired absolute channel trace'};
common=T(string(T.arm)=='dtsa-common-view',:);
private=T(string(T.arm)=='dtsa-private-view',:);
checks(end+1,:)={common.DTSA_DECISIONS>0 && ...
    common.ENDOGENOUS_COLLISION_FRAMES==0 && ...
    private.DTSA_DISAGREEMENTS>0, ...
    'DTSA common view is scheduled and private-view disagreement is logged'};
age=T(string(T.arm)=='chen-age-gain-private',:);
checks(end+1,:)={age.AGE_GAIN_ELIGIBLE>0 && ...
    age.MECHANISM_ACTIVATIONS>0 && age.RECEIVER_TRUTH_READS==0, ...
    'age-gain thinning activates without receiver-truth reads'};
zmac=T(string(T.arm)=='zmac-like-hybrid',:);
checks(end+1,:)={zmac.ZMAC_OWNER_ATTEMPTS>0 && ...
    zmac.ZMAC_CONTENTION_ATTEMPTS>0, ...
    'Z-MAC-like owner and contention paths both activate'};
pub=T(string(T.arm)=='delta-public-projection',:);
priv=T(string(T.arm)=='delta-private-projection',:);
checks(end+1,:)={pub.PUBLIC_FEEDBACK_COUNT>0 && ...
    pub.PUBLIC_FEEDBACK_AIRTIME>0 && ...
    pub.CHARGED_OFFERED_UTIL>pub.OFFERED_UTIL && ...
    priv.PUBLIC_FEEDBACK_COUNT==0 && priv.ACK_ENTRIES_PIGGYBACKED>0, ...
    'DELTA public minislot and private piggyback feedback are both charged'};
checks(end+1,:)={all(T.SERVICE_DECISION_LOG_VALID==1) && ...
    all(T.FUTURE_RANDOM_READS==0) && ...
    all(T.INVARIANT_VIOLATIONS==0), ...
    'decision logs, future-read guards and causal invariants pass'};

flags=cellfun(@logical,checks(:,1));
for k=1:size(checks,1)
    if flags(k), tag='ok'; else, tag='FAIL'; end
    fprintf('    %-4s %s\n',tag,checks{k,2});
end
if ~all(flags)
    error('test_exp20a_formation_contracts: %d of %d checks failed.', ...
        nnz(~flags),numel(flags));
end
fprintf('\ntest_exp20a_formation_contracts: PASS (%d checks)\n',numel(flags));

