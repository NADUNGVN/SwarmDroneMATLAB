q = struct( ...
    'candidateOrdinal', {}, ...
    'time',             {}, ...
    'node',             {}, ...
    'nEntries',         {}, ...
    'targetSenders',    {}, ...
    'seqs',             {}, ...
    'genTimes',         {}, ...
    'pendingAge',       {}, ...
    'localBusy',        {}, ...
    'forced',           {}, ...
    'queueDepth',       {}, ...
    'preNetworkHash',   {}, ...
    'preContextHash',   {}, ...
    'policyAllowed',    {}, ...
    'physicalAdmitted', {}, ...
    'isTarget',         {}, ...
    'intervention',     {}, ...
    'suppressedEntries',{});

end


