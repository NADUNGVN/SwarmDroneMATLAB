%% TEST_SLOTTED_MANAGEMENT_FLOOD_CONTRACTS Routing primitive.
startup;

% Four-node directed line: loss at the first hop prevents every causal relay.
N=4; reach=false(N); reach(2,1)=true; reach(3,2)=true; reach(4,3)=true;
physical=reach|reach'; recipients=[2 3 4];
P=buildSlottedManagementFloodPlan(reach,physical,1,recipients,3);
assert(P.admissible&&P.maximumRecipientDepth==3&& ...
    P.plannedTransmitterCount==3&&P.reservedSlotCount==3&& ...
    P.slotColoringProper&&isequal(P.parent,[0;1;2;3]));
U=ones(N); O=simulateSlottedManagementFlood(P,U,.2,40,250e3,.001);
assert(O.allRecipientsDelivered&&O.attempts==3&&O.bytes==120&& ...
    O.collisionRecipients==0&&O.duplicateForwardCount==0&& ...
    O.attemptBoundSatisfied&&O.linkRandomReads==3);
B=slottedManagementFloodReliabilityCertificate(P,.2,5);
assert(max(abs(B.singleFloodDeliveryProbability-[.8;.64;.512]))<1e-12&& ...
    abs(B.multicastFailureUnionUpperBound- ...
    sum((1-[.8;.64;.512]).^5))<1e-12&& ...
    B.maximumPhysicalAttemptBound==15);
R=repeatedHopManagementFloodReliabilityCertificate(P,.2,6);
edgeSuccess=1-.2^6;
assert(max(abs(R.recipientDeliveryProbability- ...
    edgeSuccess.^(1:3)'))<1e-12&& ...
    abs(R.multicastFailureExact-(1-edgeSuccess^3))<1e-12&& ...
    R.multicastFailureExact<=R.multicastFailureUnionUpperBound&& ...
    R.maximumPhysicalAttemptBound==18&&R.reservedSlotCount==18);
D=dimensionRepeatedHopManagementFlood(P,.2,1e-3,20);
assert(D.admissible&&D.selectedRepetitions==5&& ...
    D.certificate.multicastFailureExact<1e-3&& ...
    repeatedHopManagementFloodReliabilityCertificate( ...
    P,.2,D.selectedRepetitions-1).multicastFailureExact>=1e-3);
UR=ones(N,N,6);
OR=simulateRepeatedHopManagementFlood(P,UR,.2,6,40,250e3,.001);
assert(OR.allRecipientsDelivered&&OR.attempts==18&&OR.bytes==720&& ...
    OR.collisionRecipients==0&&OR.linkRandomReads==18&& ...
    OR.offeredAirtimeSec==8*OR.bytes/250e3&& ...
    OR.reservedDurationSec==18*(40*8/250e3+.001));
U(2,1)=0; L=simulateSlottedManagementFlood(P,U,.2,40,250e3,.001);
assert(~L.allRecipientsDelivered&&L.attempts==1&& ...
    ~any(L.knownMask(2:4))&&L.linkRandomReads==1);
UR=ones(N,N,6); UR(2,1,:)=0;
LR=simulateRepeatedHopManagementFlood(P,UR,.2,6,40,250e3,.001);
assert(~LR.allRecipientsDelivered&&LR.attempts==6&& ...
    ~any(LR.knownMask(2:4))&&LR.linkRandomReads==6&& ...
    LR.offeredAirtimeSec==8*LR.bytes/250e3);

% Two depth-one relays are hidden interferers at each other's child. Their
% receiver-lifted conflict forces distinct forwarding slots.
N=5; reach=false(N); reach(2,1)=true; reach(3,1)=true;
reach(4,2)=true; reach(5,3)=true;
physical=false(N); physical(4,3)=true; physical(3,4)=true;
physical(5,2)=true; physical(2,5)=true;
H=buildSlottedManagementFloodPlan(reach,physical,1,[4 5],2);
assert(H.admissible&&H.senderConflictGraph(2,3)&& ...
    H.transmitterSlot(2)~=H.transmitterSlot(3)&& ...
    H.reservedSlotCount==3&&H.slotColoringProper);
Q=simulateSlottedManagementFlood(H,ones(N),.2,64,250e3,.001);
assert(Q.allRecipientsDelivered&&Q.collisionRecipients==0&&Q.attempts==3);
Q1=simulateRepeatedHopManagementFlood( ...
    H,ones(N),.2,1,64,250e3,.001);
assert(Q1.allRecipientsDelivered&&Q1.attempts==3&& ...
    Q1.bytes==192&&Q1.offeredAirtimeSec==8*Q1.bytes/250e3);
QR=simulateRepeatedHopManagementFlood( ...
    H,ones(N,N,3),.2,3,64,250e3,.001);
assert(QR.allRecipientsDelivered&&QR.collisionRecipients==0&& ...
    QR.attempts==9&&QR.reservedDurationSec== ...
    9*(64*8/250e3+.001));

% Hop limit exposes an unreachable recipient instead of silently granting
% logical clique reachability.
D=buildSlottedManagementFloodPlan(reach,physical,1,[4 5],1);
assert(~D.admissible&&D.unreachableRecipientCount==2);

fprintf('test_slotted_management_flood_contracts: PASS\n');
