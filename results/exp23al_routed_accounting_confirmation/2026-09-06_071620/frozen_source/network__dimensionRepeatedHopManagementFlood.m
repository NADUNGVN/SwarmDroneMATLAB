function D=dimensionRepeatedHopManagementFlood( ...
    plan,linkErasureProbability,maximumMulticastFailure,maxRepetitions)
%DIMENSIONREPEATEDHOPMANAGEMENTFLOOD Smallest certified hop repetition.

if ~isscalar(maximumMulticastFailure)|| ...
        ~isfinite(maximumMulticastFailure)||maximumMulticastFailure<=0|| ...
        maximumMulticastFailure>=1||~isscalar(maxRepetitions)|| ...
        ~isfinite(maxRepetitions)||maxRepetitions<1|| ...
        maxRepetitions~=floor(maxRepetitions)
    error('dimensionRepeatedHopManagementFlood: invalid target.');
end

certificate=[]; selected=NaN;
for repetitions=1:maxRepetitions
    candidate=repeatedHopManagementFloodReliabilityCertificate( ...
        plan,linkErasureProbability,repetitions);
    if candidate.multicastFailureExact<maximumMulticastFailure
        selected=repetitions; certificate=candidate; break;
    end
end
admissible=isfinite(selected);
if ~admissible
    certificate=repeatedHopManagementFloodReliabilityCertificate( ...
        plan,linkErasureProbability,maxRepetitions);
end
D=struct('version','REPEATED-HOP-MANAGEMENT-DIMENSION-v1', ...
    'planHash',plan.hashExact,'linkErasureProbability', ...
    linkErasureProbability,'maximumMulticastFailure', ...
    maximumMulticastFailure,'maxRepetitions',maxRepetitions, ...
    'selectedRepetitions',selected,'admissible',double(admissible), ...
    'certificate',certificate,'hashExact',realizationHash([ ...
    plan.hashExact;linkErasureProbability;maximumMulticastFailure; ...
    maxRepetitions;replaceNaN(selected,-1);double(admissible); ...
    certificate.hashExact]));

end


function value=replaceNaN(value,replacement)
value(isnan(value))=replacement;
end
