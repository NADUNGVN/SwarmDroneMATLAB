function cells=makeNativeCells()

Ns=[5 10 20];
rhos=[0.20 0.50];
epsilons=[0.05 0.20];
cells=repmat(struct('id','','N',0,'rho',0,'epsilon',0),0,1);
for N=Ns
    for rho=rhos
        for epsilon=epsilons
            c=struct();
            c.id=sprintf('n%d-rho%02d-eps%02d',N,round(100*rho), ...
                round(100*epsilon));
            c.N=N;
            c.rho=rho;
            c.epsilon=epsilon;
            cells(end+1,1)=c; %#ok<AGROW>
        end
    end
end

