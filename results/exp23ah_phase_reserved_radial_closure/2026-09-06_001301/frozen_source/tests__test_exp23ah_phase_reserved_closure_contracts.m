%% TEST_EXP23AH_PHASE_RESERVED_CLOSURE_CONTRACTS Registry and smoke proof.
startup;
fprintf('\n============================================================\n');
fprintf('test_exp23ah_phase_reserved_closure_contracts\n');
fprintf('============================================================\n\n');

R=exp23ahPhaseReservedClosureRegistry(); checks=0;
used=[R.smokeSeed;R.calibrationSeeds;R.radialValidationSeeds];
assert(R.expectedRuns==300&&numel(R.seeds)==50&&numel(R.arms)==6&& ...
    R.requiredValidationContracts==27&&isempty(intersect(R.seeds,used))&& ...
    R.prepareRetryAttemptLimit+R.claimRetryAttemptLimit+ ...
    R.commitRetryAttemptLimit==28&&R.evidencePrefixClaimAttempts==8);
fprintf('    ok   300-row phase-reserved fresh matrix is disjoint\n');
checks=checks+1;

parent=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ag_fresh_radial_receiver_closure',R.parentFreshRadialRun, ...
    'radial_closure_verdict.json')));
diagnosis=jsondecode(fileread(fullfile(projectRoot(),'results', ...
    'exp23ah_phase_reserved_diagnostic',R.parentPhaseDiagnosticRun, ...
    'phase_reserved_verdict.json')));
assert(strcmp(parent.status,R.parentFreshRadialStatus)&& ...
    parent.gatesPassed==22&&parent.gatesTotal==25&& ...
    strcmp(diagnosis.status,R.parentPhaseDiagnosticStatus)&& ...
    diagnosis.calibrationSeedsOnly&&~diagnosis.freshConfirmation);
fprintf('    ok   failed parent and calibration diagnosis remain explicit\n');
checks=checks+1;

[rows,context]=runExp23afOnlineClosureSeed(R.diagnosticWitnessSeed,R);
T=struct2table(rows); closure=string(T.kind)=="closure";
normal=string(T.arm)=="closure-iid20-emergency";
response=string(T.arm)=="closure-response-blackout-emergency";
noEmergency=string(T.arm)== ...
    "closure-response-blackout-no-emergency";
prepare=string(T.arm)=="closure-prepare-blackout-emergency";
commit=string(T.arm)=="closure-commit-blackout-emergency";
protected=closure&~noEmergency;

B=context.reliabilityCertificate;
assert(B.horizonFeasible&&B.prepareOpportunityCount==7&& ...
    B.claimOpportunityCount==15&&B.evidencePrefixAttempts==8&& ...
    B.responseSuffixAttempts==7&&B.commitFramesReserved==6&& ...
    B.unionFailureUpperBound<R.maxTransactionFailureProbability&& ...
    all(T.transactionFailureUpperBound(closure)==B.unionFailureUpperBound)&& ...
    all(T.reliabilityCertificateHash(closure)==B.hashExact));
fprintf('    ok   analytical phase reserve closes below 10^-3\n');
checks=checks+1;

assert(all(T.kernelVersionHash(closure)== ...
    realizationHash(R.closureKernelVersion))&& ...
    all(T.controlAttemptBoundRatio(closure)<=1)&& ...
    all(T.controlByteBoundRatio(closure)<=1)&& ...
    all(T.kernelActualSubsetOld(closure)==1)&& ...
    all(T.kernelActualSubsetUnion(closure)==1)&& ...
    all(T.kernelFinalColoringProper(closure)==1)&& ...
    all(T.prematureActivationFrames(closure)==0));
fprintf('    ok   persistent-QUIET v2 kernel preserves structural bounds\n');
checks=checks+1;

assert(T.allReactivated(normal)==1&&T.motionAuthorized(normal)==1&& ...
    T.motionAuthorized(prepare)==0&&T.barrierClosed(prepare)==0&& ...
    T.motionAuthorized(response)==1&&T.commitReady(response)==0&& ...
    T.finalSuppressedCount(response)==T.affectedCount(response)&& ...
    T.motionAuthorized(commit)==1&&T.commitReady(commit)==1&& ...
    T.reactivatedCount(commit)==1&& ...
    T.finalSuppressedCount(commit)==T.affectedCount(commit)-1);
fprintf('    ok   normal and blackout terminal semantics are exact\n');
checks=checks+1;

assert(all(T.radialConstructionPremise(protected)==1)&& ...
    all(T.radialTheoremCertified(protected)==1)&& ...
    all(T.actualPhysicalSubset(protected)==1)&& ...
    all(T.actualSenderSubset(protected)==1)&& ...
    all(T.emergencyMappingExact(protected)==1)&& ...
    all(T.observedCollisionFrames(protected)==0));
assert(T.radialTheoremCertified(noEmergency)==0&& ...
    T.MISSION_RMSE(noEmergency)>T.MISSION_RMSE(response));
fprintf('    ok   protected radial theorem and negative removal separate\n');
checks=checks+1;

assert(all(T.prefixStateExact(closure)==1)&& ...
    all(T.dataOutcomeMismatches(closure)==0)&& ...
    all(T.futureRandomReads(closure)==0)&& ...
    all(T.receiverTruthReads(closure)==0)&&all(T.SAFEFAIL(protected)==0)&& ...
    R.freshRadialContractEvidence&&~R.freshPhaseReservedEvidence&& ...
    ~R.repeatedOnlineRenewalValidated&& ...
    ~R.managementRelayingValidated&&~R.submissionClaimPermitted);
fprintf('    ok   replay/causality pass without downstream promotion\n');
checks=checks+1;

fprintf('\ntest_exp23ah_phase_reserved_closure_contracts: PASS (%d checks)\n', ...
    checks);
