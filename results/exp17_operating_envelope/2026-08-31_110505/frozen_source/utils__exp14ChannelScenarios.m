function scenarios = exp14ChannelScenarios()
%EXP14CHANNELSCENARIOS Frozen time-varying channel cells for EXP14.
%
% Each DATA and standalone-ACK directed link is an independently initialized
% stationary two-state Gilbert-Elliott chain.  DATA and ACK have equal
% marginals in the primary cells but use independent uniforms and states.

ids = {'clean','moderate','stressed'};
labels = {'Clean','Moderate','Stressed'};
goodLoss = [0.00 0.03 0.05];
badLoss = [0.20 0.70 0.85];
goodToBad = [0.001 0.004 0.009];
badToGood = [0.039 0.036 0.021];

for k = numel(ids):-1:1
    stationaryBad = goodToBad(k)/(goodToBad(k)+badToGood(k));
    scenarios(k) = struct( ...
        'id',ids{k}, ...
        'label',labels{k}, ...
        'dataGoodLoss',goodLoss(k), ...
        'dataBadLoss',badLoss(k), ...
        'dataGoodToBad',goodToBad(k), ...
        'dataBadToGood',badToGood(k), ...
        'ackGoodLoss',goodLoss(k), ...
        'ackBadLoss',badLoss(k), ...
        'ackGoodToBad',goodToBad(k), ...
        'ackBadToGood',badToGood(k), ...
        'stationaryBadProbability',stationaryBad, ...
        'meanBadDurationSec',1e-3/badToGood(k), ...
        'stationaryMeanLoss', ...
        (1-stationaryBad)*goodLoss(k)+stationaryBad*badLoss(k));
end

end
