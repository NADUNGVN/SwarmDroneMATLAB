function C=elcsKernelConfig(N,maxFrames)
%ELCSKERNELCONFIG Conservative untuned ELCS-F kernel defaults.

if nargin<2, maxFrames=160; end
graph=true(N)-eye(N)>0;
B=continuousTdmaGuardBound(0.25e-3,40,0.5);
C=struct('N',N,'maxFrames',maxFrames,'frameLength',N, ...
    'controlSlots',N,'fallbackSlots',2,'leaseFrames',20, ...
    'refreshLeadFrames',6,'leaseFenceFrames',1, ...
    'statusPeriodFrames',2,'fallbackAccessProbability',1/N, ...
    'deterministicControlSlots',true, ...
    'dataBytes',96,'controlBytes',32,'phyRateBps',250e3, ...
    'guardSec',B.safeGuardSec,'dataErasureProbability',0, ...
    'managementErasureProbability',0,'neighborGraph',graph, ...
    'managementReach',graph,'interferenceMatrix',graph, ...
    'conflictGraph',graph,'stateLossEnabled',false, ...
    'stateLossFrame',max(2,floor(maxFrames/2)), ...
    'stateLossNode',min(2,N),'reconfigurationEnabled',false, ...
    'reconfigurationFrame',max(2,floor(maxFrames/2)), ...
    'reconfigurationNode',min(2,N), ...
    'reconfigurationSlot',N);

end
