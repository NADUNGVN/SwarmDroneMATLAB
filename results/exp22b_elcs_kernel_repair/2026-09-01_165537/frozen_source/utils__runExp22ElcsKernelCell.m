function row=runExp22ElcsKernelCell( ...
    seedValue,cellSpec,condition,C,T,conditionMeta)
%RUNEXP22ELCSKERNELCELL Execute and flatten one ELCS-F kernel row.

out=simulateElcsScheduling(C,T);
row=exp22ElcsKernelEmptyRow();
row.seed=seedValue;
row.scenario=char(cellSpec.id);
row.scenarioLabel=char(cellSpec.label);
row.condition=char(condition.id);
row.conditionLabel=char(condition.label);
row.conditionKind=char(condition.kind);
row.N=C.N;
row.BASE_TRACE_HASH_EXACT=conditionMeta.baseTraceHashExact;
row.CONDITION_TRACE_HASH_EXACT=conditionMeta.conditionTraceHashExact;
row.CONFIG_HASH=out.configHash;
row.REALIZATION_HASH=out.realizationHash;
row.SCHEDULE_STATE_HASH=out.scheduleStateHash;
row.BLACKOUT_OWNER=conditionMeta.blackoutOwner;
row.BLACKOUT_CLIENT=conditionMeta.blackoutClient;
if isfinite(conditionMeta.blackoutOwner)
    owner=conditionMeta.blackoutOwner;
    client=conditionMeta.blackoutClient;
    row.BLACKOUT_OWNER_LOCK_EXPIRY=out.ownerLockExpiry(owner,client);
    row.BLACKOUT_CLIENT_GRANT_EXPIRY=out.grantExpiry(client,owner);
    row.BLACKOUT_CLIENT_FINAL_ACTIVE=double(out.active(client));
end
fields={ ...
    'FINAL_ALL_CERTIFIED','finalAllCertified'; ...
    'FINAL_SCHEDULED_COLLISION_FREE','finalScheduledCollisionFree'; ...
    'FIRST_ALL_CERTIFIED_FRAME','firstAllCertifiedFrame'; ...
    'CERTIFIED_NODE_FRAME_FRACTION','certifiedNodeFrameFraction'; ...
    'FALSE_VALID_EDGE_FRAMES','falseValidEdgeFrames'; ...
    'OWNER_LOCK_VIOLATIONS','ownerLockViolations'; ...
    'STALE_GRANT_ACCEPTS','staleGrantAccepts'; ...
    'FUTURE_GRANT_ACCEPTS','futureGrantAccepts'; ...
    'RECONFIGURATION_APPLIED_FRAME','reconfigurationAppliedFrame'; ...
    'RECONFIGURATION_RELEASE_FENCE','reconfigurationReleaseFence'; ...
    'RECOVERY_FRAME','recoveryFrame'; ...
    'AUTOMATIC_RECOLOR_COUNT','automaticRecolorCount'; ...
    'STATUS_ATTEMPTS','statusAttempts'; ...
    'GRANT_ATTEMPTS','grantAttempts'; ...
    'GRANT_ENTRIES_ATTEMPTED','grantEntriesAttempted'; ...
    'CONTROL_ATTEMPTS','controlAttempts'; ...
    'MANAGEMENT_RECIPIENT_ATTEMPTS','managementRecipientAttempts'; ...
    'MANAGEMENT_RECIPIENT_SUCCESS','managementRecipientSuccess'; ...
    'MANAGEMENT_RECIPIENT_ERASURE','managementRecipientErasure'; ...
    'MANAGEMENT_RECIPIENT_COLLISION','managementRecipientCollision'; ...
    'SCHEDULED_ATTEMPTS','scheduledAttempts'; ...
    'FALLBACK_ATTEMPTS','fallbackAttempts'; ...
    'SCHEDULED_RECIPIENT_ATTEMPTS','scheduledRecipientAttempts'; ...
    'SCHEDULED_RECIPIENT_SUCCESS','scheduledRecipientSuccess'; ...
    'SCHEDULED_RECIPIENT_ERASURE','scheduledRecipientErasure'; ...
    'SCHEDULED_RECIPIENT_COLLISION','scheduledRecipientCollision'; ...
    'FALLBACK_RECIPIENT_ATTEMPTS','fallbackRecipientAttempts'; ...
    'FALLBACK_RECIPIENT_SUCCESS','fallbackRecipientSuccess'; ...
    'FALLBACK_RECIPIENT_ERASURE','fallbackRecipientErasure'; ...
    'FALLBACK_RECIPIENT_COLLISION','fallbackRecipientCollision'; ...
    'SCHEDULED_COLLISION_FRAMES','scheduledCollisionFrames'; ...
    'FALLBACK_COLLISION_FRAMES','fallbackCollisionFrames'; ...
    'OFFERED_UTILIZATION','offeredUtilization'; ...
    'CHANNEL_UTILIZATION','channelUtilization'; ...
    'ACCOUNTING_CLOSES','accountingCloses'; ...
    'FUTURE_RANDOM_READS','futureRandomReads'; ...
    'RECEIVER_TRUTH_READS','receiverTruthDecisionReads'};
for k=1:size(fields,1)
    row.(fields{k,1})=double(out.(fields{k,2}));
end

end
