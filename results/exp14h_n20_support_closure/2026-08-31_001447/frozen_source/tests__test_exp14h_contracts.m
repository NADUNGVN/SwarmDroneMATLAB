%% TEST_EXP14H_CONTRACTS N20-only support closure without outcome tuning.

startup;
R=exp14hRegistry();
[h,n]=configHash(R);
assert(h==142973713 && n==25 && R.expectedPilotRuns==240 && ...
    R.maximumReplayPairs==20, ...
    'EXP14H registry hash, leaves and dimensions must be frozen.');
known=[exp14Registry().seeds; exp14cRegistry().seeds; ...
    exp14dRegistry().seeds; exp14eRegistry().seeds; ...
    exp14fRegistry().seeds; exp14gRegistry().seeds];
assert(numel(unique(R.seeds))==240 && isempty(intersect(R.seeds,known)), ...
    'EXP14H seeds must be unique and disjoint from all prior studies.');
assert(R.minimumEventsPerCell==12 && R.targetEventsPerCell==20 && ...
    R.eligibleStart==8 && R.localHorizon==0.75 && ...
    ~R.selectionUsesOutcome && ~R.predictorFittingPermitted, ...
    'EXP14H must inherit the failed EXP14G support and claim boundaries.');
[cfg,method]=applyExp14HCell(0);
assert(cfg.swarm.N==20 && strcmp(cfg.swarm.topology,'ring2') && ...
    strcmp(method,'mac-aware-broadcast') && ...
    strcmp(cfg.shared.ackBranchReplay.mode,'observe'), ...
    'EXP14H must change only the N20 pilot seed block.');

fprintf(['test_exp14h_contracts: PASS ' ...
    '(registry, disjoint seeds, unchanged N20 estimand)\n']);
