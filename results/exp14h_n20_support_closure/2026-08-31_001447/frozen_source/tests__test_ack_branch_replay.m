%% TEST_ACK_BRANCH_REPLAY Causal prehistory and targeted suppression contract.

startup;
R=exp14fRegistry();
base=applyExp14FCell('n5-csma',16019999);
base.swarm.T=3.0;
base.shared.evalStart=0;
[base,method]=applyExp14FArm(base,R.arms(1));
trace=generateSharedMediumTrace(base);

% Logging-only observe mode must be physically inert.
off=base;
outOff=simSwarmSharedMedium(off,method,trace);
observe=base;
observe.shared.ackBranchReplay=replayConfig('observe',0);
outObserve=simSwarmSharedMedium(observe,method,trace);
assert(isequal(outOff.P,outObserve.P) && isequal(outOff.V,outObserve.V) && ...
    isequal(outOff.A,outObserve.A) && ...
    isequaln(outOff.trueAoI,outObserve.trueAoI) && ...
    isequal(outOff.netStats,outObserve.netStats) && ...
    isequal(outOff.policy,outObserve.policy), ...
    'Observe mode changed a physical or control outcome.');
assert(~outOff.ackBranchReplay.enabled && isempty(outOff.ackAdmissionLog) && ...
    outObserve.ackBranchReplay.enabled && ...
    ~isempty(outObserve.ackAdmissionLog), ...
    'Branch replay must default off and observe permitted ACK decisions.');

admitted=find([outObserve.ackAdmissionLog.physicalAdmitted],1);
assert(~isempty(admitted),'Development smoke run produced no ACK admission.');
pilot=outObserve.ackAdmissionLog(admitted);
ordinal=pilot.candidateOrdinal;

% Explicit admit-target is an identity branch.
actual=base;
actual.shared.ackBranchReplay=replayConfig('admit-target',ordinal);
outActual=simSwarmSharedMedium(actual,method,trace);
targetA=find([outActual.ackAdmissionLog.isTarget]);
assert(isscalar(targetA) && ...
    outActual.ackAdmissionLog(targetA).physicalAdmitted && ...
    strcmp(outActual.ackAdmissionLog(targetA).intervention,'admit-target'), ...
    'Admit-target did not reach and admit exactly one target.');
assert(isequal(outObserve.P,outActual.P) && ...
    isequal(outObserve.V,outActual.V) && ...
    isequal(outObserve.netStats,outActual.netStats), ...
    'Admit-target must be physically identical to observe mode.');

% Suppress only the target obligation from standalone aggregates.
shadow=base;
shadow.shared.ackBranchReplay=replayConfig('suppress-target',ordinal);
outShadow=simSwarmSharedMedium(shadow,method,trace);
targetS=find([outShadow.ackAdmissionLog.isTarget]);
assert(isscalar(targetS),'Suppress branch did not reach exactly one target.');
a=outActual.ackAdmissionLog(targetA);
s=outShadow.ackAdmissionLog(targetS);
assert(a.time==s.time && a.node==s.node && a.nEntries==s.nEntries && ...
    isequal(a.targetSenders,s.targetSenders) && ...
    isequal(a.seqs,s.seqs) && isequal(a.genTimes,s.genTimes), ...
    'Target identity differs before the branch intervention.');
assert(a.preNetworkHash==s.preNetworkHash && ...
    a.preContextHash==s.preContextHash, ...
    'Actual and shadow do not share the complete pre-decision state hash.');
assert(~s.physicalAdmitted && s.suppressedEntries==s.nEntries && ...
    strcmp(s.intervention,'suppress-target'), ...
    'Suppress-target did not remove the focal obligation.');

before=outActual.t<=a.time+1e-12;
assert(isequal(outActual.P(before,:,:),outShadow.P(before,:,:)) && ...
    isequal(outActual.V(before,:,:),outShadow.V(before,:,:)) && ...
    isequaln(outActual.trueAoI(before,:,:),outShadow.trueAoI(before,:,:)), ...
    'Branches diverged before the registered decision time.');

windowEnd=min(a.time+actual.shared.ackBranchReplay.localHorizon,base.swarm.T);
for k=1:a.nEntries
    idx=[outShadow.ackValueLog.sourceReceiver]==a.node & ...
        [outShadow.ackValueLog.targetSender]==a.targetSenders(k) & ...
        [outShadow.ackValueLog.genTime]>=a.genTimes(k)-1e-12 & ...
        [outShadow.ackValueLog.time]>=a.time-1e-12 & ...
        [outShadow.ackValueLog.time]<=windowEnd+1e-12;
    if any(idx)
        assert(all(string({outShadow.ackValueLog(idx).transport})=="data"), ...
            'A protected target crossed through standalone ACK in the window.');
    end
end
assert(outShadow.ackBranchState.targetReached && ...
    outShadow.ackBranchState.suppressedEntryCount>=s.nEntries, ...
    'Suppression state did not retain its target accounting.');

bad=base;
bad.shared.ackBranchReplay=struct('enabled',true, ...
    'schema','ACK-BRANCH-REPLAY-v1','mode','suppress-target', ...
    'targetOrdinal',0,'localHorizon',0.75);
rejected=false;
try
    simSwarmSharedMedium(bad,method,trace);
catch
    rejected=true;
end
assert(rejected,'Malformed replay targets must fail at the boundary.');

fprintf(['test_ack_branch_replay: PASS ' ...
    '(inert observe, identical prehistory, targeted suppression)\n']);


function cfg=replayConfig(mode,ordinal)

cfg=struct('enabled',true,'schema','ACK-BRANCH-REPLAY-v1', ...
    'mode',mode,'targetOrdinal',ordinal,'localHorizon',0.75);

end
